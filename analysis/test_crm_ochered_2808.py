# -*- coding: utf-8 -*-
"""ПОСЛЕДНИЙ РУБЕЖ ПЕРЕД CRM: город без филиала направления в очередь не идёт.

Повод — боевая очередь `data/crm_queue.jsonl`: из шести настоящих сбоев (не считая
двадцати пяти на тестовом номере) все шесть — «город не найден в направлении».
Форс согласования при отсутствии филиала стоит выше по коду и работает, но только
когда направление известно; что проходит мимо, попадает в CRM и падает там.

Для владельца такой сбой выглядит как молчаливая потеря: запись в очереди есть,
заявки в CRM нет, а причина видна только в поле errors. Теперь запись остаётся в
журнале с пометкой `no_filial`, и человек видит, что нужно согласование.
"""
import json, os, sys, tempfile
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "brain"))
import server as s

ok = fail = 0


def проверить(имя, условие, факт=""):
    global ok, fail
    print(("  OK  " if условие else "  FAIL") + "  " + имя + ("" if условие else "  → " + str(факт)))
    if условие:
        ok += 1
    else:
        fail += 1


def поставить(город, направление):
    """Кладём лид во ВРЕМЕННУЮ очередь — боевой журнал тест не трогает."""
    прежний = s._CRM_QUEUE
    tmp = tempfile.mktemp(suffix=".jsonl")
    s._CRM_QUEUE = tmp
    try:
        s._crm_queue_put("ключ-" + город, направление, {"city": город, "phone": "0000000000"})
        строки = [json.loads(l) for l in open(tmp, encoding="utf-8")]
        return строки[-1] if строки else {}
    finally:
        s._CRM_QUEUE = прежний
        if os.path.exists(tmp):
            os.unlink(tmp)


print("── ГОРОДА БЕЗ ФИЛИАЛА НАПРАВЛЕНИЯ (боевые случаи из очереди) ────")
for город, направление in (("Рыбинск", "bt"), ("Кисловодск", "bt"), ("Воронеж", "bt")):
    r = поставить(город, направление)
    проверить("%s / %s не уходит в CRM" % (город, направление),
              r.get("status") == "no_filial", r.get("status"))
    проверить("%s / %s — причина записана" % (город, направление),
              "согласование" in (r.get("note") or ""), r.get("note"))

print("── ГОРОДА С ФИЛИАЛОМ ИДУТ КАК ПРЕЖДЕ ────────────────────────────")
for город, направление in (("Москва", "kp"), ("Санкт-Петербург", "kp"),
                           ("Москва", "bt"), ("Рыбинск", "kp")):
    r = поставить(город, направление)
    проверить("%s / %s ставится в очередь" % (город, направление),
              r.get("status") == "pending", r.get("status"))

print("── ЗАПИСЬ НЕ ВОСКРЕСНЕТ ─────────────────────────────────────────")
# ⚠ иначе расширение возьмёт её как pending и получит ту же ошибку из CRM
проверить("no_filial в списке закрытых статусов", "no_filial" in s._CRM_ЗАКРЫТЫЕ,
          s._CRM_ЗАКРЫТЫЕ)

print("── ЛИД НЕ ТЕРЯЕТСЯ ──────────────────────────────────────────────")
r = поставить("Рыбинск", "bt")
проверить("данные лида сохранены в записи", (r.get("lead") or {}).get("city") == "Рыбинск", r.get("lead"))

print()
print("итог: ok=%d fail=%d" % (ok, fail))
sys.exit(1 if fail else 0)
