# ─────────── УНИКАЛЬНОСТЬ ТЕКСТОВ: одна фраза — одно намерение ──────────────
pool = {}
dup = []


def add(text, owner):
    t = " ".join((text or "").split()).lower().rstrip(".!")
    if not t:
        return
    if t in pool and pool[t] != owner:
        dup.append((t[:48], pool[t], owner))
    pool.setdefault(t, owner)


for k, v in esc.REPLIES.items():
    add(v, "эскалация:" + k)
for k, v in p.JUNK_REPLIES.items():
    add(v, "мусор:" + k)
for v in p.STATUS_BRIDGE_VARIANTS:
    add(v, "статус-мост")
for v in p.ASK_NUMBER_VARIANTS:
    add(v, "спросить номер")
add(p.SOGLAS_REPLY, "согласование")
add(p._REFUSE_HOLD, "отказ-удержание")
add(p.CALL_REPLY, "созвон")
add(p.TROLL_EXIT_REPLY, "выход из троллинга")
add(p.DEFLECT_REPLY, "дубль-рассылка")
for k, lst in p.REFUSE_VARIANTS.items():
    if k in p.REFUSE_FINAL:
        for v in lst:
            add(v, "отказ-окончательный:" + k)
chk("уникальность фолбэков", dup, [])

