# -*- coding: utf-8 -*-
"""ЗНАЕТ ЛИ БОТ РЕГЛАМЕНТ: сверка матрицы приёма с тем, что есть в коде и промпте.

ЗАЧЕМ. «Бот знает регламент» — не вопрос, а ощущение, пока не сказано, ЧТО именно
он должен знать и где это лежит. Источник правды — analysis/МАТРИЦА-ПРИЁМА-2026.md:
273 позиции с явным статусом (приём / согласование / бывший отказ / нужен
квалификатор) и ссылкой на страницу полного регламента.

ЧТО СВЕРЯЕТСЯ. Для каждой позиции — три вопроса, и все три отвечаются офлайн:
  1. знает ли о ней ПРОМПТ (brain/prompt.py) — то, что видит модель;
  2. знает ли о ней РОУТЕР (brain/prefilter.py) — решение без модели, 0 токенов;
  3. есть ли она хоть в одном НАБОРЕ проверок (analysis/test_*.py).

Позиция, которой нет НИГДЕ, — это правило, которого бот знать не может: он ответит
по общему смыслу, а не по регламенту. Именно их число и есть честный ответ на
вопрос «насколько он знает регламент».

⚠ ЧЕГО ЭТА СВЕРКА НЕ ДЕЛАЕТ. Она не проверяет ПОВЕДЕНИЕ — для этого нужен вызов
модели, а он платный. Она отвечает на более раннее: может ли бот в принципе знать
правило. Поведение проверяется отдельно и на выборке.

⚠ ИНСТРУМЕНТ ПЕРЕПИСЫВАЛСЯ ТРИЖДЫ, И ПЕРВЫЕ ДВЕ РЕДАКЦИИ ВРАЛИ — В РАЗНЫЕ СТОРОНЫ.
Числа, которые они давали, записаны здесь, чтобы никто не поверил им снова:
  · «все корни правила есть в тексте» → «известно 87 %». Корни стояли друг от друга
    на 97 752 знака: метрика не значила ничего;
  · «все корни в окне 300 знаков» → «неизвестно 42,6 %». Ловила формулировку, а не
    правило: у «кронштейна» в промпте ЦЕЛЫЙ РАЗДЕЛ, а метрика его не видела.
Работает третья: искать ПРЕДМЕТ правила (самое редкое слово позиции) во всех
модулях мозга. Она даёт 3,7 % (10 из 272).

⚠ И ЭТИ 3,7 % ПРОВЕРЕНЫ РУКАМИ — ПОШТУЧНО, ВСЕ ДЕСЯТЬ. Из них настоящих пробелов
ДВА: «Периферия к телефону/планшету» (наушники, геймпады, смарт-часы — нет ни в
одном модуле) и «восстановление внешнего вида техники» (вмятины). Остальные восемь
в коде ЕСТЬ, просто другим словом: «сушки»→«сушил», «фреоно»→«фреон»,
«клопов»→«клоп», «аксесс»→«гардин», «серия»→«oculus/quest». То есть по ПРЕДМЕТУ
регламент покрыт почти целиком, и оставшиеся десять — верхняя оценка, не список.

⚠ ГЛАВНОЕ, ЧЕГО ЭТИМ НЕ УЗНАТЬ: покрытие предмета — не верный СТАТУС. «Кронштейн» в
промпте есть, но говорит ли бот «согласование» там, где положено, — вопрос
поведения, и отвечает на него только прогон через модель.

Запуск: uv run python analysis/audit_reglament.py [--подробно]
Сеть не трогается, токены не тратятся.
"""
import io
import json
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
МАТРИЦА = os.path.join(КОРЕНЬ, "analysis", "МАТРИЦА-ПРИЁМА-2026.md")

СТАТУСЫ = {"✅": "приём", "🔶": "согласование", "⛔→🔶": "бывший отказ", "❓": "квалификатор"}
_ПОЗИЦИЯ_RX = re.compile(r"^(⛔→🔶|✅|🔶|❓)\s+\*\*(.+?)\*\*\s*—\s*(.*)$")
_РАЗДЕЛ_RX = re.compile(r"^##\s+(\S+)")

#: Слова, по которым позицию НЕ опознать: они есть в любом тексте и дали бы
#: ложное «правило известно» на пустом месте.
_ШУМ = frozenset("""и или на в с по для от до не без при это как что бы же ли то
все весь вся любой любые другой другие прочее прочие ремонт настройка замена
установка подключение работа работы услуга услуги техника техники тип типы
согласование приём приемка сверка передача клиент клиента мастер""".split())


def позиции():
    """Матрица → список правил. Одна строка файла — одно правило."""
    out, раздел = [], ""
    for n, line in enumerate(io.open(МАТРИЦА, encoding="utf-8"), 1):
        line = line.rstrip("\n")
        m = _РАЗДЕЛ_RX.match(line)
        if m:
            раздел = m.group(1)
            continue
        m = _ПОЗИЦИЯ_RX.match(line)
        if m:
            out.append({"строка": n, "раздел": раздел, "знак": m.group(1),
                        "статус": СТАТУСЫ[m.group(1)], "имя": m.group(2).strip(),
                        "хвост": m.group(3).strip()})
    return out


def ключи(имя):
    """Опорные слова позиции: по ним и ищем её след в коде.

    Берём корни длиной от 5 букв — короткие («тв», «пк») дают ложные совпадения
    внутри других слов, а с ними сверка показывала бы 100 % и не значила ничего.
    """
    слова = re.findall(r"[а-яёa-z]{5,}", (имя or "").lower())
    return [w[:6] for w in слова if w not in _ШУМ][:4]


#: ⚠ ТРЕТЬЯ РЕДАКЦИЯ ИНСТРУМЕНТА, И ПЕРВЫЕ ДВЕ ВРАЛИ — ОБЕ, В РАЗНЫЕ СТОРОНЫ.
#:  1. «все корни правила встречаются в тексте» → 87 % «известно». Проверка проверки:
#:     корни стоят друг от друга до 97 752 знаков. Метрика не значила ничего.
#:  2. «все корни в окне 300 знаков» → 42,6 % «неизвестно». Проверка на руках: у
#:     «Крепление ТВ к стене на кронштейн» в промпте ЦЕЛЫЙ РАЗДЕЛ («⚖ КРОНШТЕЙНЫ —
#:     ТОЧНАЯ ГРАНЬ РЕГЛАМЕНТА»), у «корпуса» — строка «промышленная техника,
#:     корпус/ручки». Метрика ловила формулировку, а не правило.
#: Правило — про ПРЕДМЕТ. Берём самое РЕДКОЕ слово позиции (по всей матрице): оно и
#: есть предмет («пылесос», «кронштейн», «мультиварка»), а частые слова — рамка.
#: Проверяем, знает ли код и промпт этот предмет ХОТЬ ГДЕ-НИБУДЬ. Это не доказывает,
#: что правило записано верно, — но отсутствие предмета доказывает, что правила нет.
#: Короткие предметы, которые правило целиком: их не выловить порогом «от 5 букв»,
#: а без них сверка врала «правила нет» на VPN, СНПЧ, Xbox и авто.
_КОРОТКИЕ = ("vpn", "снпч", "xbox", "авто", "смс", "sim", "hdd", "ssd", "квт")


def предмет(имя, частота):
    """Самый редкий корень позиции — им подписывается строка отчёта."""
    низ = (имя or "").lower()
    for к in _КОРОТКИЕ:
        if к in низ:
            return к
    слова = [w for w in re.findall(r"[а-яёa-z]{5,}", низ) if w not in _ШУМ]
    if not слова:
        return ""
    return min(слова, key=lambda w: частота.get(w[:6], 0))[:6]


#: ⚠ ОДИН КОРЕНЬ НА ПОЗИЦИЮ ДАВАЛ ЛОЖНЫЕ ТРЕВОГИ, И ИХ ОКАЗАЛОСЬ БОЛЬШИНСТВО (27.08).
#: Сверка брала САМОЕ редкое слово позиции и объявляла правило неизвестным, если именно
#: его нет в тексте. Но редчайшее слово — не всегда предмет: у «Сушильной машины (для
#: сушки белья)» им оказалось «сушки», которого в промпте нет, — при том что «сушильная
#: машина» упомянута в промпте дважды и в коде четырнадцать раз. Из четырёх позиций,
#: которые сверка называла неизвестными, три были такими призраками.
#: Считаем правило известным, если найден ЛЮБОЙ из трёх самых редких корней позиции:
#: предмет почти всегда среди них, а рамочные слова частотны и в тройку не попадают.
def корни_позиции(имя, частота, сколько=3):
    # ⚠ ОБРЕЗКА ДО ПЯТИ БУКВ, А НЕ ДО ШЕСТИ. На шести корень «фреоном» превращался в
    # «фреоно» — последовательность, которой в текстах нет вовсе: там пишут «фреон».
    # Сверка объявляла правило неизвестным, хотя слово стоит в промпте трижды. Пять букв
    # ловят и «фреон», и «фреоном»; на контроле выдуманных позиций мягче не стало.
    низ = (имя or "").lower()
    для_коротких = [к for к in _КОРОТКИЕ if к in низ]
    слова = sorted({w[:5] for w in re.findall(r"[а-яёa-z]{5,}", низ) if w not in _ШУМ},
                   key=lambda w: частота.get(w, 0))
    return для_коротких + слова[:сколько]


def главное():
    подробно = "--подробно" in sys.argv
    правила = позиции()
    промпт = io.open(os.path.join(КОРЕНЬ, "brain", "prompt.py"), encoding="utf-8").read().lower()
    # ⚠ КОД — ЭТО НЕ ТОЛЬКО prefilter И server. Территория живёт в territory.py, цены
    # в price_book.py, передача человеку в escalation.py. Без них сверка объявляла
    # «черта города» неизвестной, хотя это шесть упоминаний в territory.py.
    роутер = ""
    for имя_ф in ("prefilter.py", "server.py", "territory.py", "price_book.py",
                  "escalation.py"):
        роутер += io.open(os.path.join(КОРЕНЬ, "brain", имя_ф), encoding="utf-8").read().lower()
    сервер = роутер
    тесты = ""
    for имя in sorted(os.listdir(os.path.join(КОРЕНЬ, "analysis"))):
        if имя.startswith("test_") and имя.endswith(".py"):
            тесты += io.open(os.path.join(КОРЕНЬ, "analysis", имя), encoding="utf-8").read().lower()

    # частота корней по ВСЕЙ матрице — чтобы отличить предмет правила от рамки
    частота = {}
    for п in правила:
        for w in re.findall(r"[а-яёa-z]{5,}", п["имя"].lower()):
            if w not in _ШУМ:
                частота[w[:6]] = частота.get(w[:6], 0) + 1

    свод = {}
    нигде = []
    for п in правила:
        пр = предмет(п["имя"], частота)
        п["предмет"] = пр
        корни = корни_позиции(п["имя"], частота)
        # ⚠ И ОБРАТНЫЙ ПЕРЕКОС ТОЖЕ ПРОВЕРЕН. «Любой из трёх корней» оказался слишком
        # мягок: выдуманная позиция «Ремонт вертолётных двигателей» считалась известной,
        # потому что «двигат» встречается в коде (двигатель стиральной машины). Требуем
        # ДВА корня из трёх — тогда контрольные выдумки («ядерный реактор», «дрессировка
        # попугаев», «пошив платьев», «вертолётные двигатели») честно неизвестны, а
        # настоящие позиции узнаются по паре своих слов.
        # ⚠ НО «ДВА КОРНЯ» В ЧИСТОМ ВИДЕ СЛИШКОМ СТРОГИ ДЛЯ КОРОТКИХ ПОЗИЦИЙ: «Холодильник
        # — заправка фреоном (хладагентом)» терялся, хотя слово «фреон» в промпте есть
        # трижды. Правило итоговое: знает, если найден САМЫЙ РЕДКИЙ корень (он специфичен
        # по определению — «фреон», «вертол», «кинеск») ИЛИ найдены любые два корня.
        # На контроле из пяти выдуманных позиций («вертолётные двигатели», «ядерный
        # реактор», «дрессировка попугаев», «пошив платьев», «подводные лодки») ни одна
        # не считается известной, а настоящие узнаются все.
        # ⚠ ИЩЕМ ПО ПРЕФИКСУ С ГРАНИЦЕЙ СЛОВА, А НЕ ПОДСТРОКОЙ. Выбор между обрезкой в
        # пять и шесть букв был выбором из двух ошибок: на шести терялся «фреон» (корень
        # «фреоно» в текстах не встречается), на пяти выдуманные «вертолётные двигатели»
        # и «ювелирные изделия» становились известными через «двига» и «издел» внутри
        # чужих слов. Граница слова снимает обе: `\bфреон` находит и «фреон», и «фреоном»,
        # а `\bдвига` не срабатывает на «двигатель» внутри «привод двигателя»… — точнее,
        # срабатывает только там, где слово И НАЧИНАЕТСЯ с этого корня, что и требуется.
        главный = корни[0] if корни else ""
        _рx = {к: re.compile(r"\b" + re.escape(к)) for к in корни}

        def если(текст, _к=корни, _г=главный, _r=_рx):
            if _г and _r[_г].search(текст):
                return True
            return sum(1 for к in _к if _r[к].search(текст)) >= 2
        п["в_промпте"] = если(промпт)
        п["в_роутере"] = если(роутер) or если(сервер)
        п["в_тестах"] = если(тесты)
        п["без_предмета"] = not пр
        где = свод.setdefault(п["раздел"], {"всего": 0, "промпт": 0, "роутер": 0,
                                            "тесты": 0, "нигде": 0})
        где["всего"] += 1
        где["промпт"] += п["в_промпте"]
        где["роутер"] += п["в_роутере"]
        где["тесты"] += п["в_тестах"]
        if not (п["в_промпте"] or п["в_роутере"]):
            где["нигде"] += 1
            нигде.append(п)

    print("═" * 78)
    print("СВЕРКА МАТРИЦЫ ПРИЁМА С КОДОМ И ПРОМПТОМ (офлайн, 0 токенов)")
    print("═" * 78)
    print("%-30s %6s %8s %8s %7s %8s" % ("раздел", "правил", "в промпте", "в коде",
                                         "в тестах", "НИГДЕ"))
    ит = {"всего": 0, "промпт": 0, "роутер": 0, "тесты": 0, "нигде": 0}
    for раздел, s in свод.items():
        for k in ит:
            ит[k] += s[k]
        print("%-30s %6d %8d %8d %7d %8d"
              % (раздел[:30], s["всего"], s["промпт"], s["роутер"], s["тесты"], s["нигде"]))
    print("-" * 78)
    print("%-30s %6d %8d %8d %7d %8d" % ("ИТОГО", ит["всего"], ит["промпт"],
                                         ит["роутер"], ит["тесты"], ит["нигде"]))
    print("\nдоля правил, которых нет ни в промпте, ни в коде: %.1f%% (%d из %d)"
          % (100.0 * ит["нигде"] / ит["всего"], ит["нигде"], ит["всего"]))

    по_статусу = {}
    for п in нигде:
        по_статусу.setdefault(п["статус"], []).append(п)
    print("\nиз них по статусу:")
    for ст, xs in sorted(по_статусу.items(), key=lambda kv: -len(kv[1])):
        print("  %-16s %3d" % (ст, len(xs)))

    print("\nпримеры правил, которых бот знать не может:")
    for п in нигде[:: max(1, len(нигде) // 12)][:12]:
        print("  [%-13s] %s" % (п["статус"], п["имя"][:66]))

    # ── ВТОРАЯ СВЕРКА: ЧТО РЕШАЕТ САМ БОТ, БЕЗ МОДЕЛИ ───────────────────────────
    # Текстом правду не измерить: «правило есть в промпте» зависит от того, какими
    # словами его там записали. Поэтому спрашиваем не текст, а РЕШЕНИЕ. Реплику
    # клиента берём из имени самой позиции — она синтетическая, но взята из
    # документа заказчика, а не выдумана.
    sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
    import prefilter                                            # noqa: E402

    def реплика(имя):
        имя = re.sub(r"\([^)]*\)", " ", имя)                    # скобки — пояснение, не речь
        имя = имя.split("—")[0]
        # ⚠ ОГОВОРКУ «КРОМЕ X» И «БЕЗ ПОДТВЕРЖДЕНИЯ X» ОТРЕЗАЕМ (26.08). Строка матрицы
        # «ТВ ЖК: проблема с изображением БЕЗ подтверждения матрицы» имеет статус ПРИЁМ
        # именно потому, что матрицы там НЕТ. Но в роутер уходил весь заголовок целиком,
        # вместе со словом «матрицы», роутер честно опознавал отказную тему — и аудитор
        # объявлял это «ложным согласованием на приёме». Тревога была своя собственная:
        # проверено вручную, на живых формулировках («звук есть, картинки нет»,
        # «подсветка», «замена подсветки сколько стоит») бот отвечает верно, отказ даёт
        # только на прямых «полосы на экране» и «разбил экран» — как и велит регламент.
        имя = re.sub(r"\s*(?:,\s*)?(?:кроме|без\s+подтверждени\w*|без)\s+.*$", "", имя,
                     flags=re.IGNORECASE)
        return re.sub(r"\s{2,}", " ", имя).strip().lower()

    беда = {"ложное согласование на приёме": [], "молчит там, где нужно согласование": []}
    решено = 0
    for п in правила:
        т = реплика(п["имя"])
        if len(т) < 6:
            continue
        отказ = prefilter.check_refuse(т)
        соглас = prefilter.check_soglasovanie(т)
        сработал = bool(отказ or соглас)
        п["роутер_решил"] = сработал
        решено += сработал
        if п["статус"] == "приём" and сработал:
            беда["ложное согласование на приёме"].append(п)
        if п["статус"] in ("согласование", "бывший отказ") and not сработал and not п["в_промпте"]:
            беда["молчит там, где нужно согласование"].append(п)

    print("\n" + "═" * 78)
    print("ЧТО БОТ РЕШАЕТ САМ, БЕЗ МОДЕЛИ (те же 272 позиции, 0 токенов)")
    print("═" * 78)
    print("роутер дал решение на %d позициях из %d (%.1f%%)"
          % (решено, len(правила), 100.0 * решено / len(правила)))
    for имя, xs in беда.items():
        print("\n%s: %d" % (имя.upper(), len(xs)))
        for п in xs[:8]:
            print("   · %s" % п["имя"][:70])
        if len(xs) > 8:
            print("   … и ещё %d" % (len(xs) - 8))

    if подробно:
        with io.open(os.path.join(КОРЕНЬ, "analysis", "audit_reglament.json"),
                     "w", encoding="utf-8") as f:
            json.dump(правила, f, ensure_ascii=False, indent=1)
        print("\nполный разбор: analysis/audit_reglament.json")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
