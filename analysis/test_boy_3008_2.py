# -*- coding: utf-8 -*-
"""ДВА БОЕВЫХ ДЕФЕКТА ПОСЛЕ ВКЛЮЧЕНИЯ БОТА (30.08, вечер, скрин владельца).

1. «ПОДТВЕРЖУ БЛИЖЕ К ДЕЛУ» БЕЗ ПРОСЬБЫ (повтор запрета владельца 26.08: «если
   клиент не просит прозвон — не нужно это писать вообще»). Клиент ответил на вопрос
   адреса «…домофон работает» — и слово «домофон» в _CALL_OK_BASE_RX сочлось темой
   звонка: гард отпустил модельное «Подтвержу ближе к делу». Классика «гард ловит
   слово, не смысл». Плюс сам снимающий регекс знал только «наберу перед выездом» —
   форм «подтвержу…» из собственного пула бота в нём не было.

2. ВТОРАЯ ЗАЯВКА ЗА ДЕНЬ. Дубль-ключ (телефон:дата, намеренное решение 18.08 против
   гонки филиалов) возвращал МОЛЧА, а lead_ready оставался — LeadChat закрывал диалог
   заметкой «заявка передана», при том что заявки НЕТ: CRM не создаёт вторую, пока
   первая в «Ожидает» (слова владельца). Теперь исход честный: lead_ready снимается,
   диалог уходит человеку с причиной «дополните существующую карточку вручную» и
   сутью новой задачи.

Запуск: uv run python analysis/test_boy_3008_2.py
Офлайн, 0 токенов.
"""
import io
import os
import sys
import time

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import crm  # noqa: E402
import server as s  # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── 1. «ПОДТВЕРЖУ» ТОЛЬКО ПО ПРОСЬБЕ ─────────────────────────────")
chk("«домофон работает» — НЕ тема звонка",
    not s._call_ok("89001112240, ул Радищева 41, кв 12, 4 этаж, домофон работает"))
chk("«домофон не работает, позвоните» — тема звонка",
    s._call_ok("домофон не работает, позвоните перед выездом"))
chk("«сломан домофон» — тема звонка", s._call_ok("сломан домофон, наберите"))
chk("гард знает форму «Подтвержу ближе к делу»",
    bool(s._CALLBEFORE_RX.search("Подтвержу ближе к делу")))
chk("…и «Как буду выезжать, подтвержу»",
    bool(s._CALLBEFORE_RX.search("Как буду выезжать, подтвержу")))
chk("…и «Подтвержу перед выездом»",
    bool(s._CALLBEFORE_RX.search("Подтвержу перед выездом")))

# боевая реплика полным конвейером
kr = {"visitor": "Т", "city": "Пенза", "direction": "kp", "partner": "7"}
msgs = [{"role": "client",
         "text": "89001112240, ул Радищева 41, кв 12, 4 этаж, домофон работает"}]
итог, _, _, _ = s._postprocess_reply(
    "буду у вас сегодня к 13:00-13:30, до встречи. Подтвержу ближе к делу",
    msgs, kr, {}, False)
chk("боевая реплика: «подтвержу» снято", "одтвержу" not in итог, итог[:80])
# ⚠ БЕЗ ДОСЛОВНЫХ ЦИФР: «сегодня к 13:00-13:30» достижимо лишь до полудня по Пензе —
# вечером слой честных часов ЗАМЕНЯЕТ окно («через час-полтора»), и дословная
# проверка флапала по времени суток. Суть сторожа — окно уцелело, а не его цифры.
chk("слот при этом уцелел",
    bool(s._CLOCK_RX.search(итог)) or "через час" in итог or "полтора" in итог, итог[:80])
msgs2 = [{"role": "client", "text": "домофон не работает, позвоните перед выездом. Ленина 5"}]
итог2, _, _, _ = s._postprocess_reply(
    "буду у вас сегодня к 13:00-13:30, до встречи. Подтвержу ближе к делу",
    msgs2, kr, {}, False)
chk("при просьбе звонка — сохранено", "одтвержу" in итог2, итог2[:80])

print("── 2. ВТОРАЯ ЗАЯВКА ЗА ДЕНЬ ─────────────────────────────────────")
_mode, _брошен = crm.mode, s._ход_брошен
crm.mode = lambda: "queue"
s._ход_брошен = lambda: False
try:
    digits = "9001112241"
    s._CRM_DONE.add("%s:%s" % (digits, time.strftime("%Y-%m-%d")))
    result = {"reply": "буду у вас к 13:00",
              "state": {"phone": digits, "problem_line": "Принтер снова полосит"},
              "category": "кп", "lead_ready": True, "lead": {"вид": "полная"}}
    s._maybe_autocreate(result, {"city": "Пенза", "direction": "kp"}, {},
                        [{"role": "client", "text": "снова принтер полосит. 8%s" % digits}])
    chk("lead_ready снят — диалог НЕ закроется «переданной» заявкой",
        result["lead_ready"] is False)
    chk("диалог уходит человеку", result.get("handoff") is True)
    _пр = (result.get("escalation") or {}).get("reason", "")
    chk("причина объясняет, что делать", "дополните" in _пр.lower() and "вручную" in _пр.lower(), _пр[:80])
    chk("суть новой задачи в причине", "полосит" in _пр.lower())
finally:
    crm.mode, s._ход_брошен = _mode, _брошен

print("── 3. «ТОЛЬКО НА ВЫЕЗД» БЕЗ ТАВТОЛОГИИ ─────────────────────────")
# Боевой повтор 30.08 (два диалога): один вопрос «могу к вам подъехать?» заставлял
# вставщик добавлять «только на выезд» КАЖДЫМ следующим ходом — он смотрел всю речь
# клиента и не видел прежних реплик бота. Теперь — только последнюю реплику.
_кр = {"visitor": "Т", "city": "Новосибирск", "direction": "kp", "partner": "723"}
_м1 = [{"role": "client", "text": "Могу я к вам подъехать?"}]
_р1, _, _, _ = s._postprocess_reply("Проще будет, если я сам заеду к вам", _м1, _кр, {}, False)
chk("на вопрос о привозе — ответ есть", "выезжа" in _р1.lower() or "не беру" in _р1.lower(), _р1[:60])
_м2 = _м1 + [{"role": "operator", "text": "Я только на выезд работаю, мастерской у меня нет"},
             {"role": "client", "text": "Понял"}]
_р2, _, _, _ = s._postprocess_reply("Принял. Как будет удобно, пишите, подъеду", _м2, _кр, {}, False)
chk("на «Понял» повтора НЕТ", "только на выезд" not in _р2.lower()
    and "не беру" not in _р2.lower(), _р2[:70])

print("── ПЕРВАЯ ЗАЯВКА ДНЯ НЕ ЗАДЕТА ──────────────────────────────────")
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
chk("дубль-ключ телефон:дата жив (решение 18.08)",
    'key = "%s:%s" % (digits[-10:], time.strftime("%Y-%m-%d"))' in _ИСХ)
chk("ключ по-прежнему БЕЗ направления", "КЛЮЧ БЕЗ НАПРАВЛЕНИЯ (18.08)" in _ИСХ)


print("── ТРИ СКРИНА ВЕЧЕРА 30.08 (воронка времени) ────────────────────")
# 1) Самара: клиент согласился на слот — заглушка отсрочки запрещена, идёт шаг к данным
_кр1 = {"visitor": "Т", "city": "Самара", "direction": "kp", "partner": "7"}
_м1 = [{"role": "client", "text": "а в среднем сколько это может стоить"},
       {"role": "operator", "text": "Через час-полтора удобно? И номер подскажите"},
       {"role": "client", "text": "ок да удобно"}]
_р1, _, _, _ = s._postprocess_reply("Хорошо. Номер телефона подскажите, пожалуйста",
                                   _м1, _кр1, {}, False)
chk("согласие ≠ отсрочка: заглушки «пишите, подъеду» нет",
    "пишите, подъеду" not in _р1, _р1[:70])
chk("после согласия — шаг к данным (номер или адрес)",
    "номер" in _р1.lower() or "адрес" in _р1.lower(), _р1[:70])
# 2) Севастополь: адрес неизвестен — слот не предлагается (финальный рубеж)
_м2 = [{"role": "client", "text": "здравствуйте"},
       {"role": "client", "text": "выезжаете по городу?"}]
_р2, _, _, _ = s._postprocess_reply("Здравствуйте, да, выезжаю по городу.",
                                   _м2, dict(_кр1, city="Севастополь"), {}, True)
chk("слот без адреса вырезан финальным рубежом", "час-полтора" not in _р2, _р2[:80])
# после фикса «проблема первична» ход без названной проблемы спрашивает ДЕЛО,
# а не адрес — это ещё строже прежнего ожидания
chk("ход не пустой: вопрос о деле или адресе",
    "?" in _р2 and ("вопрос" in _р2.lower() or "случил" in _р2.lower()
                    or "куда" in _р2.lower() or "адрес" in _р2.lower()), _р2[:70])
# 3) Кострома: увод согласования — слот не клеится
_м3 = [{"role": "client", "text": "Сколько стоит заменить матрицу на TCL 55C6K?"}]
_р3, _, _, _ = s._postprocess_reply(
    "Здравствуйте, по этому гляну по месту и отвечу отдельно.",
    _м3, {"visitor": "Т", "city": "Кострома", "direction": "kp",
          "partner": "723", "white": True}, {}, True)
chk("слот после увода согласования снят",
    "час" not in _р3.lower() and "удобно вам будет" not in _р3.lower(), _р3[:90])
chk("увод согласования уцелел", "отвечу отдельно" in _р3)
# слот с известным адресом жив
_м4 = [{"role": "client", "text": "Ленина 5 кв 2, настроить тв"}]
_р4, _, _, _ = s._postprocess_reply("Хорошо, настрою.", _м4,
                                   dict(_кр1, city="Севастополь"), {}, True)
# ⚠ БЕЗ ДОСЛОВНОЙ ФОРМЫ ОКНА (31.08): «через час-полтора» бот предлагает, только пока
# рабочий день в разгаре, а вечером и ночью честные часы дают другую форму — «сегодня
# к 10:00-10:30». Сторож ловил форму, а охранять должен факт: окно уцелело.
chk("с адресом слот живёт как раньше",
    bool(s._CLOCK_RX.search(_р4)) or "час-полтора" in _р4, _р4[:90])

print("── СКРИНЫ НОЧИ 30.08: ПРОБЛЕМА ПЕРВИЧНА + УНИКАЛЬНОСТЬ ─────────")
# «можете подсказать пожалуйста» — проблема НЕ названа: ни адреса, ни окна,
# только вопрос о деле (боевой скрин: бот просил адрес до единого слова о проблеме)
_кп = {"visitor": "Анна", "city": "СПб", "direction": "kp", "partner": "7"}
_мп = [{"role": "client", "text": "здравствуйте,можете подсказать пожалуйста"}]
_рп, _, _, _ = s._postprocess_reply("Здравствуйте, слушаю вас", _мп, _кп, {}, True)
chk("проблема не названа: адрес не спрашивается",
    "адрес" not in _рп.lower() and "квартир" not in _рп.lower(), _рп[:70])
chk("…и окно не предлагается", "час" not in _рп.lower(), _рп[:70])
chk("…идёт вопрос о деле", "?" in _рп)
# проблема названа — воронка работает как раньше
_мп2 = [{"role": "client", "text": "здравствуйте, сломался холодильник, не морозит"}]
_рп2, _, _, _ = s._postprocess_reply("Здравствуйте, помогу.", _мп2,
                                    dict(_кп, direction="bt"), {}, True)
chk("проблема названа: воронка идёт к данным",
    "адрес" in _рп2.lower() or "куда" in _рп2.lower(), _рп2[:70])
# уникальность: один клиент в 10 диалогах — дописки почти все разные (зерно+chat_id)
# chat_id как в бою — 12 hex от LeadChat; хэш по модулю пула из 12 даёт по дню
# рождения ~7 уникальных на 10 — это ротация, а не совпадение шаблонов
import hashlib as _hl
_отв = set()
for _c in range(10):
    _kn = {"visitor": "Анна", "title": "Ремонт", "persona": "",
           "chat_id": _hl.sha256(str(_c).encode()).hexdigest()[:12]}
    _r, _, _, _ = s._postprocess_reply("Здравствуйте, слушаю вас", _мп, _кп, _kn, True)
    _отв.add(_r)
chk("один клиент × 10 диалогов → ≥6 уникальных дописок (зерно с chat_id)",
    len(_отв) >= 6, str(len(_отв)))
# а БЕЗ chat_id (до фикса) было бы 1: сторож самого механизма
_отв0 = set()
for _c in range(6):
    _kn0 = {"visitor": "Анна", "title": "Ремонт", "persona": "", "chat_id": ""}
    _r0, _, _, _ = s._postprocess_reply("Здравствуйте, слушаю вас", _мп, _кп, _kn0, True)
    _отв0.add(_r0)
chk("пустой chat_id стабилен (обратная совместимость)", len(_отв0) == 1)
chk("пул вопросов о проблеме ≥ 12", len(s._Q_PROBLEM) >= 12)

print("=" * 50)
print("Боевые дефекты 30.08 (вечер): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
