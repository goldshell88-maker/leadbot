"""ТРИ ПОЗИЦИИ МАТРИЦЫ, ПО КОТОРЫМ РОУТЕР МОЛЧАЛ (сверка регламента 27–28.08).

Молчание роутера не нейтрально: решение уходит модели. А мелкой кухонной техники не
было и в промпте — ни мультиварки, ни блендера, ни мясорубки, ни чайника, ни кофеварки
(проверено счётом вхождений). В корпусе такие обращения редки — 3 на 40 тысяч, — но
они есть: «Кофеварка Редмонд спустя 1,5 года зависла». Регламент по ним требует
согласования, значит решает роутер, за ноль токенов.

⚠ ГРАНИЦЫ ВЫВЕРЕНЫ ПО КОРПУСУ. «Сломалась ножка у шкафа» — мебель, обычная работа
МНЧ: из 19 живых обращений про ручки и ножки большинство именно мебельные, и утащить
их в согласование значило бы потерять законные заявки.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "brain"))
import prefilter

ok = fail = 0


def проверить(имя, условие, факт=""):
    global ok, fail
    print(("  OK  " if условие else "  FAIL") + "  " + имя + ("" if условие else "  → " + str(факт)))
    if условие:
        ok += 1
    else:
        fail += 1


def тема(текст):
    r = prefilter.check_soglasovanie(текст)
    return (r or {}).get("sub") if isinstance(r, dict) else None


print("── СОГЛАСОВАНИЕ: мелкая кухонная техника ────────────────────────")
for реплика in ("Мультиварка не включается, ремонтируете?",
                "Кофеварка Редмонд спустя 1,5 года зависла",
                "Блендер сломался, можете посмотреть?",
                "Электромясорубка не крутит",
                "Электрочайник перестал греть",
                "Тостер не работает"):
    проверить(реплика[:44], тема(реплика) == "мелкая кухонная техника", тема(реплика))

print("── СОГЛАСОВАНИЕ: ручки и ножки ТЕХНИКИ ──────────────────────────")
for реплика in ("Нужно заменить ручку на холодильнике",
                "Отломалась ножка у стиральной машины, замените?",
                "У духовки ручка сломалась"):
    проверить(реплика[:44], тема(реплика) == "ручки/ножки техники", тема(реплика))

print("── СОГЛАСОВАНИЕ: плёнка и царапины экрана ───────────────────────")
for реплика in ("На мониторе нужна поляризационная плёнка",
                "На экране монитора царапины, уберёте?",
                "Поляризационная плёнка на телевизоре"):
    проверить(реплика[:44], тема(реплика) == "плёнка/царапины экрана", тема(реплика))

print("── ГРАНИЦЫ: это обычная работа, не согласование ──────────────────")
for реплика in ("Сломалась ножка у шкафа",
                "Ручка двери отвалилась",
                "Стиральная машина не отжимает",
                "Холодильник не морозит",
                "Нужно повесить телевизор на стену",
                "Собрать кухонный гарнитур",
                "Кухонный шкаф собрать надо"):
    проверить(реплика[:44], тема(реплика) is None, тема(реплика))

print("── СОГЛАСОВАНИЕ: авто (матрица: сверка-передача) ────────────────")
# Найдено разбором боевых передач: «Можно будет перепаять деталь, на авто магнитоле?»
# — модель позвала человека сама, но заслона не было, и в другой раз она могла взяться.
for реплика in ("Можно будет перепаять деталь на авто магнитоле?",
                "Ремонт автомагнитолы делаете?",
                "Магнитола в машине не включается",
                "Автомобильный усилитель не работает"):
    проверить(реплика[:44], тема(реплика) == "авто", тема(реплика))

print("── ГРАНИЦА: автоматы это ПРИЁМ, а не авто ───────────────────────")
for реплика in ("Поставить автомат в щиток", "Автоматы выбивает",
                "Проложить кабель и автомат", "Автоматические ворота не работают"):
    проверить("не авто: %s" % реплика[:34], тема(реплика) != "авто", тема(реплика))

print()
print("итог: ok=%d fail=%d" % (ok, fail))
sys.exit(1 if fail else 0)
