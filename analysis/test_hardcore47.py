def check(reply, must, must_not):
    low = (reply or "").lower()
    ok = True
    if must and not re.search(must, low):
        ok = False
    if must_not and re.search(must_not, low):
        ok = False
    return ok


def main():
    results = []
    total = passed = 0
    for sid, direction, turns, checks in SCENARIOS:
        kn = dict(KN, direction=direction)
        hist, replies = [], []
        for t in turns:
            hist.append({"role": "client", "text": t})
            r = ask(hist, kn)
            reply = (r.get("reply") or "").strip()
            replies.append({"client": t, "bot": reply, "handoff": bool(r.get("handoff"))})
            hist.append({"role": "bot", "text": reply or "(молчание)"})
        verdicts = []
        for turn_i, must, must_not, what in checks:
            ok = check(replies[turn_i]["bot"], must, must_not)
            total += 1
            passed += int(ok)
            verdicts.append({"turn": turn_i, "what": what, "ok": ok})
            print("%s [%s] %s" % ("✓" if ok else "✗", sid, what))
        results.append({"id": sid, "rows": replies, "verdicts": verdicts})
        for row in replies:
            print("   К: %s" % row["client"][:90])
            print("   Б: %s" % (row["bot"][:150] or "(молчит — оператору)"))
        print()

    # --- вариативность между диалогами: одна заявка 4 раза ---
    print("=== ПЛАСТИНКА: одна заявка 4 раза подряд ===")
    variants = []
    for i in range(4):
        r = ask([{"role": "client", "text":
                  "Стиральная машина не отжимает. Сколько будет стоить ремонт?"}],
                dict(KN, direction="bt", visitor="Клиент%d" % i))
        variants.append((r.get("reply") or "").strip())
        print("  %d) %s" % (i + 1, variants[-1][:140]))
    norm = [re.sub(r"\s+", " ", v.lower()) for v in variants]
    uniq = len(set(norm))
    # совпадение «ядра увода»: одинаковых дословных пар быть не должно
    var_ok = uniq >= 3
    total += 1
    passed += int(var_ok)
    print("%s разных формулировок: %d из 4" % ("✓" if var_ok else "✗", uniq))
    results.append({"id": "пластинка ×4", "rows": [{"client": "(одна заявка 4 раза)",
                    "bot": " || ".join(v[:90] for v in variants)}],
                    "verdicts": [{"turn": 0, "what": "формулировки различаются (≥3 из 4)",
                                  "ok": var_ok}]})

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_hardcore47_results.jsonl")
    with open(out, "w", encoding="utf-8") as f:
        for row in results:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print("=" * 55)
    print("ХАРДКОР-47: %d/%d прошло" % (passed, total))


if __name__ == "__main__":
    main()
