def ask(history, known):
    """run_relay с ретраями на перегруз API (529)."""
    for att in range(5):
        try:
            return server.run_relay(history, known=known)
        except Exception as e:
            if "529" in str(e) or "overload" in str(e).lower() or "429" in str(e):
                time.sleep(15 * (att + 1))
                continue
            raise
    raise RuntimeError("API перегружен, 5 попыток")


