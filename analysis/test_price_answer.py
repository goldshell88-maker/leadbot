# -*- coding: utf-8 -*-
"""На ПЕРВЫЙ вопрос о цене бот уводит на осмотр, а не отмалчивается.

ПОВОД — просьба владельца 26.08: «чтобы бот качественно и на любой вопрос правильно
ответил». Стресс-набор показал, что на самый частый вопрос он не отвечает вовсе:

    К: Здравствуйте, сколько установка windows 11?
    Б: Модель ноутбука подскажете?

Ни цифры, ни увода — просто встречный вопрос. Клиент спросил и не получил ничего.

⚠ ЦИФРУ НА ПЕРВОМ ВОПРОСЕ НЕ ДАЁМ — И ЭТО СОШЛОСЬ У ПЛЕЙБУКА С ЗАМЕРОМ. Раздел 10:
«ЭТАП 1 — увод БЕЗ цифры; ЭТАП 2 — floor направления; ЭТАП 3 — точная сумма». Живой
корпус Авито говорит то же: на ПЕРВОМ ходе ответ цифрой даёт 20,7 % [15,9–26,5] против
20,2 % [18,4–22,1] у ухода — разницы нет; выигрыш появляется только со ВТОРОГО хода
(27,6 % [23,2–32,5] против 20,9 % [18,7–23,4]).

⚠ ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ФАЙЛА ТРЕБОВАЛА ЦИФРУ СРАЗУ, И ЭТО БЫЛО ОШИБКОЙ. Стресс-набор
показал цену такой торопливости: «заменить буксу в кране ванной, сколько?» → «Ванна от
8000» — прайс нашёл слово «ванной» и назвал стоимость установки ванны за замену буксы.
Цифра не та и не вовремя.

⚠ СТУПЕНИ 2 И 3 ЗДЕСЬ НЕ ПРОВЕРЯЮТСЯ НАМЕРЕННО. Их ведёт модель по готовой ступени из
промпта, и там же записано, что на втором шаге нужен floor НАПРАВЛЕНИЯ, а сумма из
прайса — только на третьем. Дублировать это кодом значит завести второй источник правды
о цене и однажды разойтись с первым.

⚠ ДВЕ ОШИБКИ РОДИЛИСЬ ИЗ ОДНОГО ДЕТЕКТОРА. Он требовал глагола рядом со «сколько»
(«сколько СТОИТ»), а живые пишут короче — «сколько установка windows 11?», «ну хотя бы
порядок скажите, примерно сколько?». Из-за этого бот не видел вопроса и (1) не отвечал
на него вовсе, (2) вырезал СВОЮ ЖЕ верную цену как «незваную».

Запуск: uv run python analysis/test_price_answer.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import price_book                                       # noqa: E402
import server as s                                      # noqa: E402

KR = {"visitor": "", "city": "Москва", "direction": "кп", "title": ""}
ошибки = []


def проверь(имя, условие, чем=""):
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:80]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


def ход(клиент, модель, первый=True):
    out, *_ = s._postprocess_reply(модель, [{"role": "client", "text": клиент}],
                                   dict(KR), {}, первый)
    return out or ""


print("короткий вопрос о цене распознаётся")
for т in ("сколько установка windows 11?", "сколько замена розетки?",
          "сколько стоит ремонт?", "по деньгам что?", "почём выйдет?"):
    проверь("вопрос о цене: %s" % т, s._клиент_спросил_цену(т))
for т in ("ну хотя бы порядок скажите, примерно сколько?", "хотя бы примерно"):
    проверь("второй нажим тоже вопрос о цене: %s" % т[:38], s._клиент_спросил_цену(т))
for т in ("сколько ждать мастера?", "сколько вас ждать?", "телевизор не включается",
          "во сколько приедете?"):
    проверь("НЕ про цену: %s" % т, not s._клиент_спросил_цену(т), т)

print("встречный вопрос на первом ходе — законный шаг, не удлиняем")
# ⚠ ЗДЕСЬ БЫЛА ПРОВЕРКА «БОТ ОБЯЗАН УВЕСТИ НА ОСМОТР», И Я ЕЁ УБРАЛ. Стресс показал
# «сколько установка windows 11?» → «Модель ноутбука подскажете?», и я счёл это
# молчанием. Оказалось наоборот: без модели цену и не назвать, а плейбук на ПЕРВОМ
# вопросе цифры не велит. Настоящего тупика не бывает — воронка сама дописывает шаг.
# Дописка увода стоила длины: медиана 76 → 84 знака, доля длиннее 90 — 32 % → 43 %,
# при том что по замеру ответ цифрой и уход от неё на первом ходе равны.
_a2 = ход("Здравствуйте, сколько установка windows 11?", "Модель ноутбука подскажете?")
проверь("встречный вопрос сохранён", "модель" in _a2.lower(), _a2)
проверь("лишнего увода не дописано", not s._УВОД_НА_ОСМОТР_RX.search(_a2), _a2)
проверь("цифры на первом вопросе нет", not s._ЦИФРА_ЦЕНЫ_RX.search(_a2), _a2)

print("свою цену бот больше не вырезает")
_b = ход("сколько установка windows?", "Установка Windows от 2000, точнее на месте")
проверь("цена модели осталась", "2000" in _b, _b)
проверь("увод не дописан поверх цены", not s._УВОД_НА_ОСМОТР_RX.search(_b.split("2000")[-1]), _b)

print("прайс не подставляет цену МЕСТА вместо работы")
_c = ход("нужно заменить буксу в кране ванной. Сколько будет стоить?",
         "Здравствуйте, берусь. Кран однорычажный или с буксами обычными?")
проверь("цена установки ванны не названа", "8000" not in _c, _c)

print("без вопроса о цене ничего не дописываем")
_d = ход("Здравствуйте, розетка не работает", "Здравствуйте, помогу. Что случилось?")
проверь("увода нет", not s._УВОД_НА_ОСМОТР_RX.search(_d), _d)
проверь("цифры нет", not s._ЦИФРА_ЦЕНЫ_RX.search(_d), _d)

print("прайс на месте")
проверь("windows в прайсе", price_book.price_for("windows") is not None)
проверь("розетка в прайсе", price_book.price_for("розетка") is not None)

print()
if ошибки:
    print("ПРОВАЛЕНО: %d" % len(ошибки))
    for e in ошибки:
        print("  -", e)
    sys.exit(1)
print("Все проверки пройдены")
