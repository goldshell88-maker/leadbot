def run_phrases():
    import server
    import re as _re
    ban = _re.compile(r"без\s+(?:вашего\s+)?соглас\w*\s+(?:цену\s+)?не\s+(?:сделаю|подниму|увеличу|буду)", _re.I)
    ok = 0
    for src, keep in NOCONSENT:
        out = server._humanize(src)
        got_clean = not ban.search(out)
        # разрешённые формулы должны остаться дословно, запрещённые — исчезнуть
        good = got_clean and (out.strip() == src.strip() if keep else True)
        if good:
            ok += 1
        else:
            print("  ПРОВАЛ запрет-фразы: %r -> %r" % (src, out))
    for src, want in DASH:
        got = server._no_dash(src)
        if got == want:
            ok += 1
        else:
            print("  ПРОВАЛ дефис: %r -> %r (ждали %r)" % (src, got, want))
    n = len(NOCONSENT) + len(DASH)
    print("%-12s %d/%d" % ("запреты:", ok, n))
    return ok, n


