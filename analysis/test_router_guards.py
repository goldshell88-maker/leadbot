def run_voice():
    """ГОЛОСОВОЕ БЕЗ ТЕКСТА — ЧЕСТНЫЙ ОТВЕТ БЕЗ ВЫЗОВА МОДЕЛИ (правка 24.08).

    Аудио бот не понимает: во всём мозге ноль строк про распознавание речи, до него
    доезжает только подпись вложения «📎 Голосовое сообщение». Худший исход не в том,
    что он не расслышал, а в том, что он ОТВЕЧАЕТ ПО СМЫСЛУ, которого не слышал —
    переспрашивает «что случилось» или придумывает диагноз.

    ⚠ СМЕШАННЫЙ СЛУЧАЙ РОУТЕР НЕ ТРОГАЕТ: если рядом с голосовым есть текст, разговор
    идёт по тексту, а про голосовое модель скажет сама (правило в плейбуке рядом с
    видео). Перехватить такой ход шаблоном значило бы потерять сказанное.
    """
    ok = n = 0
    ТОЛЬКО_ГОЛОС = ("📎 Голосовое сообщение", "📎 Голосовое сообщение\n",
                    "📎 голосовое сообщение", "📎 Voice message", "📎 Аудиосообщение",
                    "📎 Голосовое сообщение\n📎 Голосовое сообщение")
    СМЕШАННОЕ = ("📎 Голосовое сообщение\nне морозит холодильник",
                 "не морозит, я голосовое отправлял",
                 "📎 Голосовое сообщение\n📎 Вложение\nЛенина 5")
    НЕ_ГОЛОС = ("не морозит", "🖼 https://example.com/a.jpg", "📎 Вложение",
                "📎 Документ.pdf", "", "   ")
    for т, ждём in ((ТОЛЬКО_ГОЛОС, True), (СМЕШАННОЕ, False), (НЕ_ГОЛОС, False)):
        for текст in т:
            n += 1
            if p.voice_only(текст) == ждём:
                ok += 1
            else:
                print("  ПРОВАЛ voice_only(%r) = %s, ждали %s" % (текст[:34], not ждём, ждём))

    # ...и поведение целиком: ход отвечается роутером, модель не зовётся, человека не зовём
    import server as s_mod
    import claude_api as _ca
    _настоящий = _ca.messages

    def _взорвись(*a, **k):
        raise AssertionError("модель звали на голосовом без текста — это лишние деньги")

    _ca.messages = _взорвись
    try:
        r = s_mod.run_relay([{"role": "client", "text": "📎 Голосовое сообщение"}],
                            known={"city": "Москва", "direction": "bt"})
        n += 1
        if "не открывается" in (r.get("reply_text") or "").lower():
            ok += 1
        else:
            print("  ПРОВАЛ voice: ответ не про голосовое — %r" % (r.get("reply_text") or "")[:60])
        # ⚠ ЧЕЛОВЕКА ЗОВЁМ, И ЭТО ПРАВКА ПО ЗАМЕРУ, А НЕ ПО ВКУСУ. Утром здесь стояло
        # обратное утверждение — «звать незачем, клиент сейчас напишет текстом», — и это
        # было допущение. Запрос к боевой базе в тот же день его опроверг: из 258
        # голосовых без текста ответ текстом в следующие десять минут пришёл только на
        # 124 (48%). Больше половины клиентов не пишут, и без человека диалог умирает.
        # Очередь этим не зальёт: голосовых 4-23 в сутки.
        n += 1
        if r.get("notify_human"):
            ok += 1
        else:
            print("  ПРОВАЛ voice: человека не позвали — половина таких клиентов "
                  "текстом не пишет, диалог умрёт молча")
        n += 1
        if (r.get("escalation") or {}).get("reason") == "voice":
            ok += 1
        else:
            print("  ПРОВАЛ voice: причина не названа — очередь получит «тема не распознана»")
        n += 1
        if (r.get("escalation") or {}).get("deadline_min") == 15:
            ok += 1
        else:
            print("  ПРОВАЛ voice: срок реакции не 15 минут — клиент ждёт ответа по существу")
        n += 1
        if "номер" in (r.get("reply_text") or "").lower():
            ok += 1
        else:
            print("  ПРОВАЛ voice: не предложили оставить номер как второй путь")
    except AssertionError as e:
        n += 3
        print("  ПРОВАЛ voice: %s" % e)
    finally:
        _ca.messages = _настоящий
    return ok, n


