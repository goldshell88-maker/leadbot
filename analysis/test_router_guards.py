def run_debounce():
    """Дебаунс серии сообщений (для автоматического канала #6).

    Замер корпуса: 34.1% вызовов модели лишние — клиент дописывает мысль частями, а мы отвечаем
    на каждый кусок. Это и деньги (до 31 800 ₽/мес при 868 диалогах), и маркер бота: живой мастер
    не отвечает на полфразы. ⚠ ПЕРЕВЁРНУТО 21.08 (правила базы №59 и №67): прямой вопрос ТОЖЕ
    ждёт, просто короче прочих (15–20 с). Мгновенный ответ на вопрос выдаёт автомат надёжнее
    любой формулировки — живой не успевает прочитать и ответить за секунду. Полный разбор
    величин: analysis/test_batch5_silence.py.
    """
    import server
    cases = [
        ("здравствуйте", 0, True),                       # короткое начало — ждём продолжения
        ("Bosch", 5, True),                              # обрывок
        ("стиралка не отжимает, и ещё", 0, True),        # обрыв на союзе
        ("а", 0, True),
        ("сколько будет стоить?", 0, True),              # вопрос ждёт короче, но ждёт
        ("Когда сможете подъехать?", 30, False),         # 30 с прошло — вопрос уже отпущен
        ("здравствуйте", 50, False),                     # уже подождали достаточно
        ("Не работает стиральная машина Bosch, не отжимает бельё.", 30, False),
        ("", 0, False),                                  # пусто — ждать нечего
    ]
    ok = 0
    for text, elapsed, want_wait in cases:
        got = server.debounce_wait(text, elapsed) > 0
        if got == want_wait:
            ok += 1
        else:
            print("  ПРОВАЛ дебаунс %-42r прошло=%ds ждали=%s получили=%s"
                  % (text[:42], elapsed, want_wait, got))
    print("%-12s %d/%d" % ("дебаунс:", ok, len(cases)))
    return ok, len(cases)


