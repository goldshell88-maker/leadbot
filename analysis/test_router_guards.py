    # слово «удобно» — оно приходило из фразы «Когда вам было бы удобно?», вписанной
    # прямо в `_ensure_close`. Фраза была третьим источником открытого вопроса,
    # запрещённого разбором заказчика 02.08, и её убрали: теперь дожим ПРЕДЛАГАЕТ
    # окно, а без окна (город неизвестен либо нужна сверка) тянет к адресу, от
    # которого час и считается.
