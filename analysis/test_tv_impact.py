import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter as p                                   # noqa: E402

ошибки = []


def проверь(имя, условие, чем=""):
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:60]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


def матрица(t):
    return (p.check_refuse(t) or {}).get("sub") == "матрица"


print("отказываем: телевизор пострадал физически")
ОТКАЗ = [
    "Возможно ли спасти телевизор? На него упал шкаф",
    "возможно ли отремонтировать ТВ, ребенок бросил игрушку в него",
    "попала вода в телевизор, можно починить?",
    "Телевизор залили водой, не включается",
    "Сломался телевизор при переезде, экран не показывает, поди ударился",
    "Дети разбили дисплей на телевизоре",
    "Нужен ремонт телевизора, ударили экраном",
    "телевизор уронили, теперь половина показывает",
]
for т in ОТКАЗ:
    проверь("отказ: %s" % т[:52], матрица(т))

print("берём: телевизор целый, работа обычная")
БЕРЁМ = [
    "Телевизор не включается, что делать?",
    "Телевизор LG не переключает каналы",
    "Настроить каналы на телевизоре",
    "Повесить телевизор на стену",
    "Купил телевизор, надо подключить",
    "Уронил пульт от телевизора, теперь не работает",
    "Уронили подставку от телевизора, надо закрепить",
    "Телевизор показывает, но нет звука",
]
for т in БЕРЁМ:
    проверь("берём: %s" % т[:52], not матрица(т), (p.check_refuse(т) or {}).get("sub"))

# ⚠ МОНИТОР — НЕ ТЕЛЕВИЗОР. Отказ по матрице регламент объявил только для ЖК ТВ;
# матрица монитора и моноблока — обычная работа КП, и разбитый монитор мы берём.
проверь("разбитый монитор берём (это работа КП)",
        not матрица("Интересует ремонт монитора, ребенок бросил в экран бутылку"))

print("прежние отказы по матрице никуда не делись")
for т in ("Разбит экран телевизора", "Замена матрицы на телевизоре",
          "Телевизор с серым экраном и полосами"):
    проверь("остался отказ: %s" % т[:46], матрица(т))

print("ноутбук с разбитым экраном по-прежнему берём (это работа КП)")
проверь("ноутбук не под отказом матрицы",
        not матрица("Разбит экран на ноутбуке, замените?"),
        (p.check_refuse("Разбит экран на ноутбуке, замените?") or {}).get("sub"))

print()
if ошибки:
    print("ПРОВАЛЕНО: %d" % len(ошибки))
    for e in ошибки:
        print("  -", e)
    sys.exit(1)
print("Все проверки пройдены")
