# -*- coding: utf-8 -*-
"""ПАЧКА 4, часть 1 — ПРИВАТНОСТЬ (Э4, 21.08). Найдено разбором слепых зон 21.08,
проверено вручную: в brain/rag_examples.json лежали 14 «голых» 10-значных телефонов
и 276 адресов ЖИВЫХ клиентов, и rag.note_for подставлял их в system-промпт КАЖДОГО
хода — то есть чужие ПДн уезжали в модель на каждом обращении.

Прежняя маска ловила только «+7…/8…» — номер, записанный десятью цифрами подряд
(«9001112244»), проходил насквозь. Адреса не маскировались вовсе: «<адрес>» стоял
всего в 37 примерах из 4140.

Проверяем ТРИ рубежа:
  1. сам файл примеров чист — ни одного 10-значного номера, ни одного адреса
     с номером дома/квартиры в поле запроса;
  2. маскировщик режет оба формата (это защита на будущее: примеры пополняются);
  3. rag.note_for на запрос с адресом и номером не отдаёт ни цифр телефона,
     ни номера дома из чужих примеров.

Запуск: uv run python analysis/test_batch4_privacy.py   (0 токенов)
"""
import io
import json
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import rag  # noqa: E402

ok = bad = 0


def chk(label, cond):
    global ok, bad
    if cond:
        ok += 1
    else:
        bad += 1
        print("✗", label)


ТЕЛЕФОН = re.compile(r"(?<!\d)\d{10,11}(?!\d)")
АДРЕС = re.compile(
    r"(?<![а-яёА-ЯЁa-zA-Z])"
    r"(?:ул\.?|улиц\w*|пр-т|проспект|пер\.?|переул\w*|бульвар|шоссе|мкр|микрорайон|"
    r"д\.?|дом|кв\.?|квартир\w*|подъезд|подьезд|под\.|пд|этаж)\s*\.?\s*\d{1,4}",
    re.IGNORECASE)

# ── 1. файл примеров ─────────────────────────────────────────────────────────
data = json.load(io.open(os.path.join(КОРЕНЬ, "brain", "rag_examples.json"), encoding="utf-8"))
примеры = data if isinstance(data, list) else (data.get("examples") or data.get("pairs") or [])
chk("примеры загрузились", len(примеры) > 100)

с_телефоном = [e for e in примеры if ТЕЛЕФОН.search(str(e.get("q", "")) + " " + str(e.get("a", "")))]
с_адресом = [e for e in примеры if АДРЕС.search(str(e.get("q", "")) + " " + str(e.get("a", "")))]
chk("в примерах не осталось телефонов (было 14): %d" % len(с_телефоном), not с_телефоном)
chk("в примерах не осталось адресов с номерами (было 276): %d" % len(с_адресом), not с_адресом)

# ── 2. маскировщик ───────────────────────────────────────────────────────────
for сырое, что in [
    ("9001112244", "голые 10 цифр"),
    ("89001112244", "11 цифр с восьмёркой"),
    ("+7 900 111-22-44", "формат с плюсом"),
    ("мой номер 9001112245, звоните", "номер в тексте"),
]:
    chk("маска телефона: %s" % что, not ТЕЛЕФОН.search(rag.mask_pii(сырое)))

for сырое, что in [
    ("Крупской 14/2, подьезд3", "улица без слова «улица»"),
    ("улица 7-й Гвардейской 15", "улица с номером дома"),
    ("ул Плехановская 38 кв 17, подъезд 2, этаж 5", "полный адрес"),
    ("10 микрорайон дом 19 кв 131", "микрорайон"),
]:
    chk("маска адреса: %s" % что, not АДРЕС.search(rag.mask_pii(сырое)))

chk("маска не портит деловой текст",
    "стиральная машина не сливает" in rag.mask_pii("стиральная машина не сливает"))
chk("маска бережёт цену", "2000" in rag.mask_pii("замена термопасты 2000"))

# ── 3. выдача RAG ────────────────────────────────────────────────────────────
выдача = rag.note_for("мой номер 9001112244, адрес Ленина 38 кв 17, подъезд 2") or ""
chk("в подсказке RAG нет телефонов", not ТЕЛЕФОН.search(выдача))
chk("в подсказке RAG нет чужих адресов", not АДРЕС.search(выдача))

print("\nИТОГО: %d ок, %d провал" % (ok, bad))
sys.exit(1 if bad else 0)
