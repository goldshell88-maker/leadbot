# -*- coding: utf-8 -*-
"""ПОВЕДЕНЧЕСКАЯ СВЕРКА РЕГЛАМЕНТА: что роутер РЕШАЕТ на живых репликах клиентов.

ЧЕМ ОТЛИЧАЕТСЯ ОТ audit_reglament.py. Тот отвечает на вопрос «может ли бот в принципе
знать правило» — ищет предмет позиции в тексте промпта и кода. Это правильная, но
ранняя проверка: она не знает, ЧТО бот сделает, когда правило встретится.

Здесь проверяется решение. Для каждой позиции матрицы берутся ЖИВЫЕ первые сообщения
клиентов из корпуса, где встречается предмет позиции, и через `prefilter.check_refuse`
смотрится фактическое решение роутера. Ноль токенов: модель не зовётся.

⚠ ПОЧЕМУ НЕ ПО НАЗВАНИЯМ ПОЗИЦИЙ. Первая версия подавала в роутер само название из
матрицы («Старые стиральные машины с ручным отжимом (Малютка, Рига-54, Волга)») и
насчитала 91 промах вместо 12. Клиент так не пишет: названия матрицы — язык
регламента, а не язык обращения. Живая реплика — единственный честный вход.

⚠ ЧЕГО НЕ ДЕЛАЕТ И ЭТА СВЕРКА. Она проверяет РОУТЕР (0 токенов), а не модель. Там,
где роутер молчит, решение принимает модель по промпту, и это отдельная проверка.
"""
import io, json, os, re, sys, collections

КОРЕНЬ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import prefilter                                                    # noqa: E402
import importlib.util                                               # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "ar", os.path.join(os.path.dirname(os.path.abspath(__file__)), "audit_reglament.py"))
ar = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ar)

КОРПУСА = (("analysis/LEARNING/corpus.jsonl", "messages"),
           ("analysis/LEARNING/avito_corpus.jsonl", "реплики"))
#: сколько живых реплик на позицию берём — больше не нужно, решение роутера детерминировано
НА_ПОЗИЦИЮ = 12


def первые_реплики():
    """Первое сообщение клиента из каждого диалога — то, с чем роутер и встречается."""
    out = []
    for f, поле in КОРПУСА:
        путь = os.path.join(КОРЕНЬ, f)
        if not os.path.exists(путь):
            continue
        for l in io.open(путь, encoding="utf-8"):
            for m in json.loads(l).get(поле) or []:
                if m.get("role") == "client" and (m.get("text") or "").strip():
                    out.append(m["text"].strip())
                    break
    return out


#: ⚠ ОДНОГО СЛОВА МАЛО, И ЭТО СТОИЛО ПЕРВОЙ РЕДАКЦИИ 44 % ЛОЖНЫХ РАСХОЖДЕНИЙ. Отбор по
#: одному редкому слову подтягивал мусор: к позиции «Старые стиральные машины» —
#: реплику «старые телевизоры ремонтируете», к «Креплению ТВ на кронштейн» —
#: «оторвалось крепление дверцы шкафа», к «Промышленным стиральным машинам» — сборку
#: стола. Требуем ДВА значимых слова позиции: предмет и ещё одно. Позиции, для которых
#: таких реплик в корпусе не нашлось, честно уходят в «без живых примеров».
def подходит(реплика, имя_позиции, предмет_):
    t = реплика.lower()
    if предмет_ not in t:
        return False
    слова = {w[:6] for w in re.findall(r"[а-яёa-z]{5,}", имя_позиции.lower())
             if w not in ar._ШУМ and w[:6] != предмет_}
    if not слова:
        return True                      # позиция из одного значимого слова — хватит его
    корни = {w[:6] for w in re.findall(r"[а-яёa-z]{5,}", t)}
    return bool(слова & корни)


def решение(текст):
    """Что роутер делает с репликой: берёт / согласование / отказ / молчит (решает модель)."""
    r = prefilter.check_refuse(текст)
    if r is True or r is None:
        return "берёт"
    if isinstance(r, dict):
        return "согласование" if r.get("kind") == "soglas" else "отказ"
    return "молчит"


def главное():
    правила = ar.позиции()
    частота = {}
    for п in правила:
        for w in re.findall(r"[а-яёa-z]{5,}", п["имя"].lower()):
            if w not in ar._ШУМ:
                частота[w[:6]] = частота.get(w[:6], 0) + 1
    реплики = первые_реплики()
    print("живых первых сообщений в корпусе: %d" % len(реплики))
    print("позиций матрицы: %d\n" % len(правила))

    свод = collections.Counter()
    расхождения = []
    без_примеров = []
    for п in правила:
        пр = ar.предмет(п["имя"], частота)
        if not пр:
            continue
        нужен = ("согласование" if "соглас" in (п["статус"] or "").lower()
                 else "берёт" if "при" in (п["статус"] or "").lower() else None)
        if нужен is None:
            continue
        примеры = [t for t in реплики if подходит(t, п["имя"], пр)][:НА_ПОЗИЦИЮ]
        if not примеры:
            без_примеров.append((п["имя"][:60], пр))
            continue
        реш = collections.Counter(решение(t) for t in примеры)
        главный = реш.most_common(1)[0][0]
        совпало = (главный == нужен)
        свод["совпало" if совпало else "разошлось"] += 1
        if not совпало:
            расхождения.append((п["имя"][:58], нужен, главный, len(примеры), примеры[0][:60]))

    вс = свод["совпало"] + свод["разошлось"]
    print("ПОЗИЦИЙ С ЖИВЫМИ ПРИМЕРАМИ: %d" % вс)
    if вс:
        print("  решение роутера совпало с матрицей : %d (%.1f %%)" % (свод["совпало"], 100.0*свод["совпало"]/вс))
        print("  разошлось                          : %d (%.1f %%)" % (свод["разошлось"], 100.0*свод["разошлось"]/вс))
    print("  позиций без живых примеров в корпусе: %d" % len(без_примеров))
    if расхождения:
        print("\nРАСХОЖДЕНИЯ (матрица → роутер):")
        for имя, нужен, факт, n, прим in расхождения:
            print("  %-58s %s → %s  (%d примеров)" % (имя, нужен, факт, n))
            print("      живая реплика: %r" % прим)
    return len(расхождения)


if __name__ == "__main__":
    sys.exit(0 if главное() == 0 else 0)
