def собрать_выборку(сколько):
    """Заморозить выборку один раз: сравнивать можно только одно и то же.

    ⚠ ДВА БАКА, И ВТОРОЙ ВАЖЕН НЕ МЕНЬШЕ. Первая редакция брала диалоги из
    `train_mode.из_корпуса` — там условие «оператор вёл не меньше трёх ходов», а бот по
    правилу первичности на таких ходах МОЛЧИТ. Прогон честно показал 38 молчаний из 39
    и балл, посчитанный по одному ходу: эталон мерил не бота, а собственную выборку.

      «первичка» — клиент открыл разговор, берём его первые два хода. Здесь бот ОБЯЗАН
                   отвечать, и здесь считаются нарушения.
      «молчание»  — ход, на котором оператор уже сделал 3+ хода. Здесь бот ОБЯЗАН
                   молчать, и правильный ответ — пустая строка. Без этого бака любая
                   правка, вернувшая бота во все диалоги подряд, подняла бы балл.
    """
    # ⚠ БЕРЁМ ЖИВОЙ КОРПУС АВИТО, А НЕ АРХИВ JIVO. Бизнес работает на Авито; Jivo —
    # другой канал, другие операторы, другая эпоха. Если файла живого корпуса нет,
    # честно падаем обратно на Jivo и говорим об этом вслух.
    живой = os.path.join(КОРЕНЬ, "analysis", "LEARNING", "avito_corpus.jsonl")
    источник = живой if os.path.exists(живой) else os.path.join(
        КОРЕНЬ, "analysis", "LEARNING", "corpus.jsonl")
    print("источник выборки: %s" % os.path.basename(источник))
    из = []
    for line in io.open(источник, encoding="utf-8"):
        try:
            d = json.loads(line)
        except Exception:
            continue
        msgs = [{"role": ("client" if (m.get("role") or "") == "client" else "operator"),
                 "text": (m.get("text") or "").strip()}
                for m in (d.get("messages") or d.get("реплики") or [])
                if (m.get("text") or "").strip()]
        if len(msgs) < 6 or msgs[0]["role"] != "client":
            continue
        if len(_слова(msgs[0]["text"])) < 3:
            continue                      # «здравствуйте» первичкой не считаем
        if sum(1 for m in msgs if m["role"] == "operator") < 3:
            continue
        город = (d.get("город")
                 or ((d.get("meta") or {}).get("visitor") or {}).get("city")
                 or (d.get("meta") or {}).get("city") or "")
        из.append({"город": город, "тема": d.get("тема") or "", "реплики": msgs[:14]})
        if len(из) >= сколько * 6:
            break
    шаг = max(1, len(из) // (сколько * 2))
    отобранные = из[::шаг][:сколько * 2]
    os.makedirs(ДИР, exist_ok=True)
    # ⚠ УЖЕ ЗАМОРОЖЕННУЮ ОБУЧАЮЩУЮ НЕ ТРОГАЕМ. К ней привязана кассета: ключ записи —
    # переписка, и другой набор диалогов обнулит запись целиком. Поэтому обучающая
    # пишется один раз, а контрольная набирается из ОСТАВШИХСЯ.
    было = set()
    if os.path.exists(ВЫБОРКА):
        было = {json.loads(l)["реплики"][0]["text"]
                for l in io.open(ВЫБОРКА, encoding="utf-8") if l.strip()}
        обучающая = [json.loads(l) for l in io.open(ВЫБОРКА, encoding="utf-8") if l.strip()]
        print("обучающая уже заморожена: %d диалогов (не трогаю — к ней привязана кассета)"
              % len(обучающая))
    else:
        обучающая = отобранные[0::2][:сколько]
        with io.open(ВЫБОРКА, "w", encoding="utf-8") as f:
            for d in обучающая:
                f.write(json.dumps(d, ensure_ascii=False) + "\n")
        было = {d["реплики"][0]["text"] for d in обучающая}
        print("заморожено: %d диалогов → %s" % (len(обучающая), ВЫБОРКА))
    контрольная = [d for d in из if d["реплики"][0]["text"] not in было][:сколько]
    with io.open(КОНТРОЛЬ, "w", encoding="utf-8") as f:
        for d in контрольная:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")
    print("заморожено: %d диалогов → %s" % (len(контрольная), КОНТРОЛЬ))
    return обучающая


def выборка(контроль=False):
    путь = КОНТРОЛЬ if контроль else ВЫБОРКА
    if not os.path.exists(путь):
        собрать_выборку(30)
    return [json.loads(l) for l in io.open(путь, encoding="utf-8") if l.strip()]


def прогнать_диалог(d, кассета=None):
    """Ходы бота по одному диалогу, разложенные по бакам «первичка» и «молчание».

    ⚠ ПРОМАХ КАССЕТЫ НЕ ВЫГЛЯДИТ МОЛЧАНИЕМ. Бот сам ловит отказ шлюза и отдаёт пустой
    ответ с передачей человеку — то есть промах кассеты снаружи неотличим от законного
    «промолчал». Поэтому промахи считаем ДО и ПОСЛЕ хода: вырос счётчик — ход не
    записан, и в балл он не идёт.
    """
    ходы, история, свои = [], [], []
    ходов_оператора = 0
    первичных = 0
    for i, m in enumerate(d["реплики"]):
        история.append(m)
        if m["role"] != "client":
            ходов_оператора += 1
            continue
        if not any(x["role"] == "operator" for x in d["реплики"][i + 1:i + 3]):
            continue
        бак = "первичка" if ходов_оператора <= 1 else "молчание"
        if бак == "первичка":
            первичных += 1
            if первичных > 2:
                continue
        elif ходов_оператора < 3:
            continue                      # серая зона: ни первичка, ни явный чужой диалог
        было_промахов = кассета.промахов if кассета else 0
        try:
            # ⚠ СВОИ ПРОШЛЫЕ РЕПЛИКИ ПЕРЕДАЁМ ОТДЕЛЬНЫМ ПОЛЕМ, КАК ЭТО ДЕЛАЕТ ПАНЕЛЬ.
            # В режиме подсказки ответ бота уходит заметкой и в переписку не
            # возвращается: без `prior_self` все его анти-повторные правила считают по
            # репликам ОПЕРАТОРА, и эталон мерил бы не то, что происходит в бою.
            r = server.run_relay([dict(x) for x in история],
                                 known={"city": d.get("город") or "",
                                        "visitor": "", "title": d.get("тема") or "",
                                        "prior_self": list(свои)})
        except Exception as e:
            ходы.append({"не_записан": True, "почему": str(e)})
            continue
        if кассета and кассета.промахов > было_промахов:
            ходы.append({"не_записан": True, "почему": "нет записи в кассете"})
            continue
        текст = (r.get("reply_text") or r.get("reply") or "").strip()
        живой = ""
        for сл in d["реплики"][i + 1:]:
            if сл["role"] == "operator":
                живой = сл["text"]
                break
            if сл["role"] == "client":
                break
        речь = "\n".join(x["text"] for x in история if x["role"] == "client")
        ходы.append({
            "бак": бак,
            "живой": живой,
            "состояние": move_value.состояние(
                речь, ходов_оператора + 1, bool(server._адрес_в_переписке(история))),
            "клиент": m["text"],
            "клиент_всё": [x["text"] for x in история if x["role"] == "client"],
            "бот": текст,
            "свои_прошлые": list(свои),
            "адрес_известен": bool(server._адрес_в_переписке(история)),
            "передал": bool(r.get("notify_human")),
        })
        if текст:
            свои.append(текст)
    первички = [х for х in ходы if х.get("бак") == "первичка"]
    if первички:
        первички[-1]["последний_первичный"] = True
    return ходы


def главное():
    режим = ("записать" if "--записать" in sys.argv else
             "живой" if "--живой" in sys.argv else "сухой")
    for i, a in enumerate(sys.argv):
        if a == "--выборка" and i + 1 < len(sys.argv):
            собрать_выборку(int(sys.argv[i + 1]))
            return 0

    диалоги = выборка(контроль="--контроль" in sys.argv)
    кассета = Кассета(КАССЕТА, режим)
    настоящая = кассета.обернуть()
    очки, чистые, длины, счёт_нарушений, не_записано = [], [], [], {}, 0
    # ⚠ ЦЕНУ ХОДА БЕРЁМ ПО ЖИВОМУ КОРПУСУ АВИТО: бота меряем тем каналом, в котором
    # он работает. Таблица Jivo осталась рядом — по ней видно, что выводы совпадают
    # на двух независимых корпусах, и это единственная причина её держать.
    цены = move_value.загрузить(авито=True)
    пары, мало_данных = [], 0
    молчание_всего = молчание_верно = 0
    первичка_всего = первичка_молча = 0
    худшие, болтуны = [], []
    try:
        for n, d in enumerate(диалоги, 1):
            for х in прогнать_диалог(d, кассета):
                if х.get("не_записан"):
                    не_записано += 1
                    continue
                if х["бак"] == "молчание":
                    молчание_всего += 1
                    if not х["бот"]:
                        молчание_верно += 1
                    else:
                        болтуны.append({"диалог": n, "клиент": х["клиент"][:100],
                                        "бот": х["бот"][:160]})
                    continue
                первичка_всего += 1
                if not х["бот"]:
                    первичка_молча += 1
                    continue
                из_за = нарушения(х)
                штраф = sum(ШТРАФЫ.get(v, 5) for v in из_за)
                балл = max(0, 100 - штраф)
                очки.append(балл)
                чистые.append(0 if из_за else 1)
                длины.append(len(" ".join(r.split())) if (r := х["бот"]) else 0)
                for v in из_за:
                    счёт_нарушений[v] = счёт_нарушений.get(v, 0) + 1
                if из_за:
                    худшие.append({"диалог": n, "балл": балл, "клиент": х["клиент"][:120],
                                   "бот": х["бот"][:200], "нарушения": из_за})
                # ── СИЛА ХОДА: не «красиво ли», а «к чему такой ход приводил»
                если_бот = move_value.цена(х["состояние"], move_value.ход_класс(х["бот"])[0], цены)
                если_жив = move_value.цена(х["состояние"], move_value.ход_класс(х["живой"])[0], цены)
                if если_бот and если_жив:
                    пары.append((если_бот[0], если_жив[0], х))
                else:
                    мало_данных += 1
            print("диалог %d из %d" % (n, len(диалоги)), flush=True)
    finally:
        claude_api.messages = настоящая
        кассета.сохранить()

    # ⚠ ГЛАВНОЕ ЧИСЛО — ДОЛЯ БЕЗУПРЕЧНЫХ ХОДОВ, А НЕ СРЕДНИЙ БАЛЛ. Первая редакция брала
    # среднее «100 минус штрафы»: 60 % ходов с дефектом дали 96,1 — число, по которому
    # ничего не решишь и которое незаметно ползёт. Доля чистых ходов не прощает: один
    # дефект — ход не чистый. Средний балл остаётся рядом, он показывает ТЯЖЕСТЬ.
    чисто = round(100.0 * sum(чистые) / len(чистые), 1) if чистые else 0.0
    качество = round(sum(очки) / len(очки), 1) if очки else 0.0
    тишина = round(100.0 * молчание_верно / молчание_всего, 1) if молчание_всего else 0.0
    # ⚠ ОБЩИЙ БАЛЛ — СРЕДНЕЕ ДВУХ, А НЕ ОДНО КАЧЕСТВО. Бот, который молчит везде, имеет
    # безупречное качество на нуле ходов; бот, который лезет в каждый диалог, — идеальную
    # первичку и разваленную дисциплину. Идеал требует обоих.
    балл = round((чисто + тишина) / 2, 1)
    худшие.sort(key=lambda x: x["балл"])
    print("\n" + "=" * 68)
    print("РЕЖИМ: %s   диалогов: %d" % (режим, len(диалоги)))
    if не_записано:
        print("НЕ ЗАПИСАНО В КАССЕТЕ: %d ходов — они в балл не вошли. "
              "Обновите кассету: --записать" % не_записано)
    print("ПЕРВИЧКА: %d ходов, ответил %d, промолчал %d"
          % (первичка_всего, len(очки), первичка_молча))
    print("МОЛЧАНИЕ: %d ходов чужих диалогов, смолчал %d" % (молчание_всего, молчание_верно))
    print("-" * 68)
    длинных = sum(1 for L in длины if L > ДЛИННЫЙ_ХОД)
    медиана = sorted(длины)[len(длины) // 2] if длины else 0
    print("ЧИСТЫХ ХОДОВ: %.1f %%   (средний балл хода %.1f)" % (чисто, качество))
    print("ПОХОЖЕСТЬ НА ЖИВОГО: медиана %d знаков (у мастеров 39), длиннее %d — %d ходов (%.0f %%)"
          % (медиана, ДЛИННЫЙ_ХОД, длинных, 100.0 * длинных / max(1, len(длины))))
    print("ДИСЦИПЛИНА МОЛЧАНИЯ: %.1f %%" % тишина)
    print("ОБЩИЙ БАЛЛ: %.1f из 100" % балл)
    print("-" * 68)
    for имя, к in sorted(счёт_нарушений.items(), key=lambda kv: -kv[1] * ШТРАФЫ.get(kv[0], 5)):
        print("  %-32s %4d ход(ов)   цена %2d   вклад -%.1f"
              % (имя, к, ШТРАФЫ.get(имя, 5), к * ШТРАФЫ.get(имя, 5) / max(1, len(очки))))
    if болтуны:
        print("-" * 68)
        print("ВЛЕЗ В ЧУЖОЙ ДИАЛОГ (%d):" % len(болтуны))
        for б in болтуны[:5]:
            print("  диалог %d · клиент: %s" % (б["диалог"], б["клиент"].replace("\n", " ")))
            print("            бот:    %s" % б["бот"].replace("\n", " "))
    if пары:
        лучше = sum(1 for б, ж, _ in пары if б > ж + 0.02)
        хуже = sum(1 for б, ж, _ in пары if ж > б + 0.02)
        ср_б = sum(б for б, _, _ in пары) / len(пары)
        ср_ж = sum(ж for _, ж, _ in пары) / len(пары)
        print("-" * 68)
        print("СИЛА ХОДА (историческая конверсия класса хода в той же обстановке,")
        print("           %d пар «бот против живого», данных не хватило на %d ходов):"
              % (len(пары), мало_данных))
        print("   бот выбрал более ценный ход:  %d" % лучше)
        print("   живой выбрал более ценный:    %d" % хуже)
        print("   поровну:                      %d" % (len(пары) - лучше - хуже))
        print("   средняя цена хода: бот %.1f %%   живой %.1f %%   (%+.1f п.п.)"
              % (100 * ср_б, 100 * ср_ж, 100 * (ср_б - ср_ж)))
        слабее = sorted([p for p in пары if p[1] > p[0] + 0.02], key=lambda p: p[0] - p[1])
        for б, ж, х in слабее[:4]:
            print("   ↓ %.0f%% против %.0f%%  бот: «%s»" % (100 * б, 100 * ж, х["бот"][:70]))
            print("                       живой: «%s»" % х["живой"][:70])
    print("-" * 68)
    print("ХУДШИЕ ХОДЫ ПЕРВИЧКИ:")
    for х in худшие[:8]:
        print("  [%d] диалог %d · %s" % (х["балл"], х["диалог"], ", ".join(х["нарушения"])))
        print("      клиент: %s" % х["клиент"].replace("\n", " "))
        print("      бот:    %s" % х["бот"].replace("\n", " "))

    метка_выборки = "%s:%d:%s" % (
        "контроль" if "--контроль" in sys.argv else "обучающая", len(диалоги),
        hashlib.sha256("|".join(d["реплики"][0]["text"] for d in диалоги)
                       .encode("utf-8")).hexdigest()[:8])
    запись = {"ts": time.strftime("%Y-%m-%dT%H:%M:%S"), "режим": режим, "балл": балл,
              "выборка": метка_выборки,
              "чисто": чисто, "качество": качество, "тишина": тишина,
              "медиана_длины": медиана, "длинных": длинных,
              "первичка": первичка_всего, "с_ответом": len(очки),
              "молчание": молчание_всего, "смолчал": молчание_верно,
              "не_записано": не_записано, "нарушения": счёт_нарушений,
              "пар_силы": len(пары),
              "сила_бот": round(100 * sum(б for б, _, _ in пары) / len(пары), 1) if пары else None,
              "сила_живой": round(100 * sum(ж for _, ж, _ in пары) / len(пары), 1) if пары else None}
    os.makedirs(ДИР, exist_ok=True)
    with io.open(ИСТОРИЯ, "a", encoding="utf-8") as f:
        f.write(json.dumps(запись, ensure_ascii=False) + "\n")
    # ⚠ ПОЛНЫЙ РЕЗУЛЬТАТ — ОТДЕЛЬНЫМ ФАЙЛОМ ПО ЗАПРОСУ. В историю идёт только сводка:
    # она читается глазами и растёт вечно. Худшие ходы нужны следующему шагу цикла
    # (`self_train.py`), и таскать их через историю значило бы её испортить.
    for i, a in enumerate(sys.argv):
        if a == "--json" and i + 1 < len(sys.argv):
            подробно = dict(запись)
            подробно["худшие"] = худшие
            подробно["слабее_живого"] = [
                {"бот": х["бот"], "живой": х["живой"], "клиент": х["клиент"],
                 "состояние": х["состояние"], "цена_бота": round(100 * б, 1),
                 "цена_живого": round(100 * ж, 1)}
                for б, ж, х in пары if ж > б + 0.02]
            подробно["болтуны"] = болтуны
            json.dump(подробно, io.open(sys.argv[i + 1], "w", encoding="utf-8"),
                      ensure_ascii=False, indent=1)
            print("подробный результат: %s" % sys.argv[i + 1])
    # ⚠ СРАВНИВАЕМ ТОЛЬКО ОДНО С ТЕМ ЖЕ. Первый прогон по живому корпусу Авито показал
    # «98,0 → 82,7 (-15,3)» — и это была не регрессия, а другая выборка: 100 боевых
    # диалогов вместо 30 архивных. Число, которое падает при смене материала, обучению
    # не помощник, а помеха: по нему решают «стало хуже» и откатывают верную правку.
    # Метку выборки кладём в историю и сравниваем только внутри неё.
    прошлые = [json.loads(l) for l in io.open(ИСТОРИЯ, encoding="utf-8") if l.strip()]
    прошлые = [p for p in прошлые[:-1]
               if p.get("режим") == режим and p.get("выборка") == запись["выборка"]]
    print("-" * 68)
    print("ВЫБОРКА: %s" % метка_выборки)
    if прошлые:
        было = прошлые[-1]["балл"]
        print("ПРОШЛЫЙ ПРОГОН НА ТОЙ ЖЕ ВЫБОРКЕ (%s): %.1f → сейчас %.1f  (%+.1f)"
              % (прошлые[-1]["ts"], было, балл, балл - было))
    else:
        print("на этой выборке прогонов ещё не было — сравнивать не с чем")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
