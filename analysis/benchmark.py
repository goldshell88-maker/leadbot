def _слова(t):
    return re.findall(r"[а-яёa-z]{3,}", (t or "").lower())


def нарушения(ход):
    """Список нарушений ОДНОГО хода бота. Пустой список — ход чистый."""
    r = (ход["бот"] or "").strip()
    из_за = []
    if not r:
        return из_за                      # молчание оценивается отдельно, см. главное()
    клиент_всё = " \n".join(ход["клиент_всё"])
    свои = ход["свои_прошлые"]
    if ЧУЖОЙ_ГОЛОС.search(r):
        из_за.append("легенда: чужой голос")
    if ОБЕЩАНИЕ_МАСТЕРА.search(r):
        из_за.append("обещание за мастера")
    if ОБЕЩАНИЕ_ПРИЕЗДА.search(r) and not ход["адрес_известен"] and not ВОПРОС_АДРЕСА.search(r):
        из_за.append("обещание времени без адреса")
    # переспрос: клиент уже дал адрес, а бот снова просит его
    if ход["адрес_известен"] and ВОПРОС_АДРЕСА.search(r):
        из_за.append("переспрос сказанного")
    if ЦЕНА_ТОЧНАЯ.search(r):
        из_за.append("точная цена до осмотра")
    if ДИАГНОЗ.search(r):
        из_за.append("диагноз до осмотра")
    нормаль = " ".join(r.lower().split())
    if any(" ".join((s or "").lower().split()) == нормаль for s in свои):
        из_за.append("повтор своей реплики")
    if свои and ПРИВЕТСТВИЕ.search(r) and any(ПРИВЕТСТВИЕ.search(s or "") for s in свои):
        из_за.append("второе приветствие")
    # эхо: 4 слова клиента подряд в реплике бота
    сл_к, сл_б = _слова(ход["клиент"]), _слова(r)
    if len(сл_к) >= 4:
        хвосты = {" ".join(сл_к[i:i + 4]) for i in range(len(сл_к) - 3)}
        если = " ".join(сл_б)
        if any(h in если for h in хвосты):
            из_за.append("эхо реплики клиента")
    if ЭМОДЗИ.search(r):
        из_за.append("эмодзи")
    if ТИРЕ.search(r):
        из_за.append("тире")
    # ⚠ СПРАШИВАЕТСЯ ОДИН РАЗ ЗА ДИАЛОГ, ЗНАЧИТ И СПРОС С ПОСЛЕДНЕГО ХОДА ОКНА
    # ПЕРВИЧКИ. Если ругаться на каждый ход, один и тот же непроизнесённый вопрос
    # посчитается дважды, а у бота есть правило «максимум два запроса данных в ходе»:
    # на первом ходе место могло быть законно занято адресом.
    if ход.get("последний_первичный") and ТВ.search(клиент_всё) \
            and not server._модель_названа(клиент_всё) \
            and not any(ВОПРОС_МОДЕЛИ.search(x or "") for x in свои + [r]):
        из_за.append("телевизор без модели")
    if not ШАГ.search(r) and not ФИНАЛ.search(r) and not ОТКАЗ.search(r):
        из_за.append("ход без шага")
    return из_за


# ---------------------------------------------------------------- кассета
class Кассета:
    """Запись и воспроизведение ответов модели по ключу от переписки.

    ⚠ ПРОМАХ НЕ ПОДМЕНЯЕТСЯ ВЫДУМКОЙ. Если ключа нет, ход честно помечается
    «не записан» и в балл не идёт: тихая подстановка соседнего ответа дала бы
    красивое число и ложную уверенность.
    """

    def __init__(self, путь, режим):
        self.путь, self.режим = путь, режим
        self.данные = {}
        if режим in ("сухой", "записать") and os.path.exists(путь):
            try:
                self.данные = json.load(io.open(путь, encoding="utf-8"))
            except Exception:
                self.данные = {}
        self.промахов = 0
        self.записано = 0

    @staticmethod
    def ключ(msgs):
        сырое = json.dumps(msgs, ensure_ascii=False, sort_keys=True)
        return hashlib.sha256(сырое.encode("utf-8")).hexdigest()[:32]

    def обернуть(self):
        настоящая = claude_api.messages

        def обёртка(system, msgs, **kw):
            k = self.ключ(msgs)
            if self.режим == "сухой":
                if k not in self.данные:
                    self.промахов += 1
                    raise claude_api.ClaudeError("нет записи в кассете")
                return self.данные[k]
            ответ = настоящая(system, msgs, **kw)
            if self.режим == "записать":
                self.данные[k] = ответ
                self.записано += 1
            return ответ

        claude_api.messages = обёртка
        return настоящая

    def сохранить(self):
        if self.режим != "записать":
            return
        os.makedirs(os.path.dirname(self.путь), exist_ok=True)
        врем = self.путь + ".tmp"
        json.dump(self.данные, io.open(врем, "w", encoding="utf-8"),
                  ensure_ascii=False)
        os.replace(врем, self.путь)


