# -*- coding: utf-8 -*-
"""БОТ САМ РЕШАЕТ, КАКАЯ РЕПЛИКА ТРЕБУЕТ ОТВЕТА, А КАКАЯ НЕТ.

ВЛАДЕЛЕЦ 27.08: «при создании заявки бот сам должен понимать, какой ответ требует ответа и
какой нет».

ЧТО БЫЛО. После назначенного визита стоял глухой заслон: «визит уже назначен — дальше ведёт
человек». Он молчал на ВСЁ подряд и вдобавок ПЕРЕДАВАЛ диалог — а после передачи панель бота
в диалог больше не пускает (`bot_entry_block`: handoff_done). То есть на «а во сколько точно?»
клиент получал тишину, и диалог уходил насовсем.

ЗАМЕР, НА КОТОРОМ ПОСТРОЕНО ПРАВИЛО. 2927 реплик клиента ПОСЛЕ назначенного визита в боевом
корпусе; для каждой видно, ответил ли живой мастер следующим ходом:

    группа реплики        шт    живой отвечает
    вопрос («?»)         611        61,5 %
    длинное по делу      944        55,8 %
    короткое, не акк     672        40,3 %
    служебное             53        32,1 %
    ПОДТВЕРЖДЕНИЕ        647        17,8 %   ← единственная группа, где живой молчит
    ────────────────────────────────────────
    всего               2927        44,6 %

Значит молчать надо ровно на подтверждении, а не на всём. Итог правила на тех же 2927:
бот молчит на 645 (22 %), где живой отвечал в 16,1 %; отвечает на 2282 (78 %), где живой
отвечал в 52,7 %.

⚠ ОСТОРОЖНАЯ СТОРОНА — ОТВЕТИТЬ. Промолчать там, где клиент ждал ответа, дороже: он остаётся
с тишиной и уходит. Поэтому вопрос, цифра и любая суть снимают признак, даже рядом со «спасибо».

Запуск: uv run python analysis/test_otvet_nuzhen_2708.py
Офлайн, 0 токенов.
"""
import io
import json
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import leadchat as lc                                  # noqa: E402
import server as s                                     # noqa: E402

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:110]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


print("\n1. ОТВЕТА НЕ ТРЕБУЮТ — подтверждение и прощание")
for т in ("хорошо", "Ок", "окей", "спасибо", "спасибо большое", "благодарю", "До встречи",
          "до свидания", "да", "договорились", "отлично", "супер", "жду", "буду ждать",
          "понял", "принято", "ок, спасибо", "хорошо, спасибо", "👍", "🤝", "✅"):
    проверь("«%s»" % т, s._не_требует_ответа(т))

print("\n2. ОТВЕТА ТРЕБУЮТ — всё, где есть суть")
for т in ("вы приедете?", "а во сколько", "перезвоните мне", "можно перенести на завтра",
          "Ленина 5 кв 12", "хорошо, но давайте в 16:00", "спасибо, а сколько будет стоить?",
          "жду, но домофон не работает", "да, только я до 14 на работе", "89001234567",
          "отменяю", "не смогу сегодня", "а мастер во сколько будет"):
    проверь("«%s»" % т[:38], not s._не_требует_ответа(т))

print("\n3. ПУСТОТА И КРАЯ")
проверь("пустая строка ответа не требует... но и молчать не о чем", not s._не_требует_ответа(""))
проверь("None не роняет", not s._не_требует_ответа(None))
проверь("цифра в подтверждении снимает признак", not s._не_требует_ответа("хорошо, в 15"))
проверь("вопрос в подтверждении снимает признак", not s._не_требует_ответа("хорошо?"))

print("\n4. ГЛУХОГО МОЛЧАНИЯ ПОСЛЕ ВИЗИТА БОЛЬШЕ НЕТ")
_после_визита = [{"role": "client", "text": "телевизор не включается"},
                 {"role": "operator", "text": "Буду у вас завтра к 15:00, до встречи", "свой": True},
                 {"role": "client", "text": "а во сколько точно?"}]
проверь("заслон «не наш диалог» на это больше не срабатывает",
        s._молчать_почему(_после_визита) == "", s._молчать_почему(_после_визита))
_чужой = _после_визита + [{"role": "operator", "text": "здравствуйте, я оператор"},
                          {"role": "operator", "text": "смотрю"},
                          {"role": "operator", "text": "сейчас уточню"}]
проверь("а настоящий чужой диалог заслон по-прежнему видит",
        "не первичный" in s._молчать_почему(_чужой), s._молчать_почему(_чужой))

print("\n5. ПРОВОДКА: ветка молчаливого удержания стоит ДО модели")
исходник = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
проверь("ветка зовёт признак", "and _не_требует_ответа(last_client):" in исходник)
проверь("и требует назначенного визита", "_ВИЗИТ_НАЗНАЧЕН_RX.search(" in исходник)
# ⚠ ПРОВЕРЯЕМ ПОЛЯ ПЕРЕДАЧИ, А НЕ ТЕКСТ ФЛАГА. Диверсия «поставить handoff=True рядом с тем же
# флагом» первую редакцию не роняла — а это ровно возврат к старому поведению, когда молчание
# означало потерю диалога.
_ветка = исходник[исходник.index("and _не_требует_ответа(last_client):"):][:700]
проверь("молчим, но диалог держим: передачи в ветке нет",
        '"to_operator": False, "handoff": False' in _ветка, _ветка[:200])
проверь("и наружу это уходит без «нужен оператор»",
        lc.to_answer({"reply": "", "handoff": False, "to_operator": False,
                      "model": "локальный роутер (молчим, диалог держим)",
                      "flag": {"kind": "silent_hold", "reason": "визит назначен"},
                      "state": {}, "missing": [], "ready": False})["needs_operator"] is False)
проверь("ветка стоит РАНЬШЕ вызова модели",
        исходник.index("and _не_требует_ответа(last_client):")
        < исходник.index("res = suggest_reply(norm, known=known)"))
проверь("глухая строка про «дальше ведёт человек» убрана из кода",
        not [n for n, л in enumerate(исходник.split("\n"), 1)
             if "визит уже назначен — дальше ведёт человек" in л
             and not л.lstrip().startswith("#")])

print("\n6. ПРАВИЛО НА БОЕВОМ КОРПУСЕ (если он рядом)")
_корпус = os.path.join(КОРЕНЬ, "analysis", "LEARNING", "avito_corpus.jsonl")
if os.path.exists(_корпус):
    пары = []
    for стр in io.open(_корпус, encoding="utf-8"):
        d = json.loads(стр)
        реп = [(р.get("role"), (р.get("text") or "").strip()) for р in d["реплики"]]
        реп = [(r, t) for r, t in реп if t]
        назначен = False
        for i, (r, t) in enumerate(реп):
            if r != "client":
                if s._ВИЗИТ_НАЗНАЧЕН_RX.search(t):
                    назначен = True
                continue
            if not назначен:
                continue
            о = next((x for x in реп[i + 1:] if x[0] != "client"), None)
            c = next((x for x in реп[i + 1:] if x[0] == "client"), None)
            пары.append((t, (реп.index(о) if о else 10 ** 9) < (реп.index(c) if c else 10 ** 9)))
    молчим = [(т, о) for т, о in пары if s._не_требует_ответа(т)]
    говорим = [(т, о) for т, о in пары if not s._не_требует_ответа(т)]
    дм = sum(о for _, о in молчим) / max(1, len(молчим))
    дг = sum(о for _, о in говорим) / max(1, len(говорим))
    print("     молчим на %d из %d (%.0f %%), живой отвечал там в %.1f %%"
          % (len(молчим), len(пары), 100 * len(молчим) / max(1, len(пары)), 100 * дм))
    print("     отвечаем на %d, живой отвечал там в %.1f %%" % (len(говорим), 100 * дг))
    проверь("молчим заметно реже, чем говорим", len(молчим) < len(говорим))
    проверь("там, где молчим, живой тоже в основном молчал", дм < 0.25, дм)
    проверь("там, где отвечаем, живой отвечал вдвое чаще", дг > дм * 2, (дг, дм))
    проверь("доля молчания разумна (не всё и не ничего)", 0.10 < len(молчим) / len(пары) < 0.35,
            len(молчим) / len(пары))
else:
    print("     — корпуса нет локально, замер пропущен")

print("\n" + "─" * 60)
print("проверок: %d, провалов: %d" % (всего[0], len(ошибки)))
for о in ошибки:
    print("  ПРОВАЛ:", о)
sys.exit(1 if ошибки else 0)
