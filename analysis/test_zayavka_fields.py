# -*- coding: utf-8 -*-
"""ПОЛЯ АВТОЗАЯВКИ: что уезжает диспетчеру в карточку (разбор жалобы 25.08).

Владелец прислал боевую заявку №1234570 и перечислил, что в ней не так. Каждый
пункт — отдельный дефект, и все они сходятся в одном месте: карточку собирает
`server._maybe_autocreate`, а заполняют её два РАЗНЫХ пути — серверный `crm.py`
и расширение Chrome (`ui/crm-extension/offscreen.js`). Правило, починенное в
одном, во втором оставалось сломанным.

Что было в №1234570 и что здесь закреплено:
 · партнёр 007 уехал как «_197» — поиск номера ПОДСТРОКОЙ;
 · «Вид работ» пустой — темы «добрый, сможете, отремонтировать» вместо «кровать»;
 · «от 1500 рублей услуга» и «от 1500р» — одна цена дважды, дедуп сравнивал ТЕКСТ;
 · комментарий = первая реплика целиком, с приветствием и адресом, и БЕЗ того,
   что клиент дописал следующими сообщениями;
 · «Солнечный проспект 14/2» — дом с косой чертой не разбирался, весь адрес
   падал в «Улицу»;
 · заявка не создавалась, если номер записан как «89001112240» без «+».

Офлайн, сеть не трогается, 0 токенов.
"""
import io
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "brain"))
import crm            # noqa: E402
import prefilter      # noqa: E402
import price_book     # noqa: E402
import server as s    # noqa: E402

ok = bad = 0


def chk(label, cond):
    global ok, bad
    if cond:
        ok += 1
    else:
        bad += 1
        print("✗", label)


# ── ТЕЛЕФОН: последняя цифра не теряется ─────────────────────────────────────
# ⚠ Ошибка была только у слитных одиннадцатизначных БЕЗ «+» и НЕ в начале строки:
# движок вставал на пробел перед номером, съедал его разделителем и брал 10 цифр
# из одиннадцати. С «+7…» и с разделителями всё работало — потому и не замечали.
ЭТАЛОН = "9001112240"
for текст in ("89001112240", "мой номер 89001112240", "звоните 89001112240",
              "+79001112240", "номер +7 900 111-22-40", "тел 8 900 111 22 40",
              "вот 79001112240", "8(900)111-22-40", "мой 8-900-111-22-40"):
    chk("номер целиком: " + текст[:28], prefilter.phones_found(текст) == [ЭТАЛОН])

chk("два номера — оба и по порядку",
    prefilter.phones_found("сначала 89261234567 потом 89031112233")
    == ["9261234567", "9031112233"])
chk("повтор одного номера не удваивается",
    prefilter.phones_found("89261234567 или 8 926 123-45-67") == ["9261234567"])
chk("ключи дедупа — то же самое множеством",
    prefilter.phones_in("мой номер 89001112240") == {ЭТАЛОН})
# ⚠ Не всякое число — телефон: габарит и цена номером быть не должны.
for не_номер in ("ошибка 5 на дисплее", "дом 14/2 квартира 15", "цена 15000 рублей",
                 "шкаф 90/90/208"):
    chk("НЕ телефон: " + не_номер[:26], prefilter.phones_found(не_номер) == [])


# ── ПАРТНЁР: номер сравнивается ЧИСЛОМ, а не подстрокой ──────────────────────
# ⚠ Деньги за лид идут по этому полю. « 7 » не спасало: pick_option делает .strip().
_ПАРТНЁРЫ = [("11", "_197", False), ("22", "007", False),
             ("33", "_723", False), ("44", "Партнёр 7 (розница)", False)]
chk("007 → 007, а не _197", crm.pick_number(_ПАРТНЁРЫ, "7") == "22")
chk("ведущие нули не мешают", crm.pick_number(_ПАРТНЁРЫ, "007") == "22")
chk("197 находит себя", crm.pick_number(_ПАРТНЁРЫ, "197") == "11")
chk("723 находит себя", crm.pick_number(_ПАРТНЁРЫ, "723") == "33")
chk("чужого не подставляем", crm.pick_number(_ПАРТНЁРЫ, "999") == "")
chk("пустой номер — пустой ответ", crm.pick_number(_ПАРТНЁРЫ, "") == "")
chk("мусор на входе не роняет", crm.pick_number([], "7") == "")
# ⚠ Ровно та ошибка, что уехала в карточку владельца: старый способ давал «_197».
chk("старый способ (подстрокой) промахивался — зафиксировано",
    crm.pick_option(_ПАРТНЁРЫ, " 7 ", "№7", "7") == "11")


# ── ТЕМЫ: предмет, а не первые длинные слова ─────────────────────────────────
_РЕПЛИКА = ("Добрый день! Вы сможете отремонтировать кровать, скрипят ламелии "
            "и шатаются. Солнечный проспект")
chk("прайс кровать не знает", price_book.topics_in(_РЕПЛИКА) == [])
chk("предмет найден", price_book.objects_in(_РЕПЛИКА) == ["кроват"])
chk("категория раскрыта для расширения",
    price_book.with_categories(price_book.objects_in(_РЕПЛИКА)) == ["кроват", "мебел"])
chk("примета идёт ПЕРЕД категорией (точная позиция справочника должна выиграть)",
    price_book.with_categories(["стиральн"])[0] == "стиральн")
chk("раскрытие идемпотентно (старые записи очереди)",
    price_book.with_categories(["кроват", "мебел"]) == ["кроват", "мебел"])
for текст, ждём in (("розетку поменять", "розетк"), ("унитаз течёт", "унитаз"),
                    ("телевизор не включается", "телевизор"),
                    ("надо шкаф собрать", "шкаф")):
    chk("предмет в «%s»" % текст, price_book.objects_in(текст)[:1] == [ждём])
# ⚠ Стоп-слова темой быть не должны — именно они и уехали в №1234570.
_плохие = {"добрый", "сможете", "отремонтировать"}
chk("стоп-слова темой не становятся",
    not (_плохие & set(price_book.with_categories(price_book.objects_in(_РЕПЛИКА)))))


# ── СУТЬ ПРОБЛЕМЫ: со всей переписки, без приветствия, адреса и телефона ─────
_ДИАЛОГ = [
    {"role": "client", "text": _РЕПЛИКА},
    {"role": "operator", "text": "Здравствуйте, сделаю. Что именно с ней?"},
    {"role": "client", "text": "да"},
    {"role": "client", "text": "Ещё нужна замена подъёмного механизма"},
    {"role": "operator", "text": "Понял. Адрес подскажете и номер?"},
    {"role": "client", "text": "Солнечный проспект 14/2"},
    {"role": "client", "text": "мой номер 89001112240"},
    {"role": "client", "text": "спасибо"},
]
_суть = s._суть_проблемы(_ДИАЛОГ)
chk("приветствия в сути нет", "добрый день" not in _суть.lower())
# ⚠ ОТДЕЛЬНО — ПРИВЕТСТВИЕ В ОДНОМ ПРЕДЛОЖЕНИИ С ПРОБЛЕМОЙ. Когда оно стоит своим
# предложением («Добрый день! Кровать скрипит»), его выбрасывает фильтр пустых реплик,
# и проверка выше проходит даже со сломанным срезанием. Здесь выбросить нечего —
# работает только _strip_greeting, и поломка сразу видна.
chk("приветствие срезано внутри предложения",
    s._суть_проблемы([{"role": "client", "text": "Здравствуйте, кровать скрипит и шатается"}])
    == "кровать скрипит и шатается")
chk("адреса в сути нет (у него своё поле)", "14/2" not in _суть)
chk("телефона в сути нет (ПДн и своё поле)", "9001112240" not in _суть)
chk("пузырь-согласие выброшен", not _суть.lower().startswith("да"))
chk("«спасибо» не хвост сути", not _суть.lower().rstrip(" .").endswith("спасибо"))
# ⚠ ГЛАВНОЕ: раньше бралась ТОЛЬКО первая реплика, и всё сказанное дальше пропадало.
chk("дописанное следующей репликой попало", "подъёмного механизма" in _суть)
chk("сама поломка на месте", "скрипят" in _суть)
chk("пустая переписка не роняет", s._суть_проблемы([]) == "")
chk("переписка без клиента — пусто",
    s._суть_проблемы([{"role": "operator", "text": "Здравствуйте"}]) == "")
chk("длина ограничена карточкой",
    len(s._суть_проблемы([{"role": "client", "text": "поломка. " * 200}])) <= s._СУТЬ_ПРЕДЕЛ)


# ── АДРЕС: дом с косой чертой и квартира через дефис ─────────────────────────
for строка, улица, дом, кв in (
        ("Солнечный проспект 14/2", "Солнечный проспект", "14/2", ""),
        ("Строителей 37/2", "Строителей", "37/2", ""),
        ("Сиреневая 15/2-118", "Сиреневая", "15/2", "118"),
        ("Лесная, 27-45", "Лесная", "27", "45"),
        ("ул. Пушкина, д. 14к2, кв 15", "Пушкина", "14к2", "15"),
        ("Канонерский остров 6а", "Канонерский остров", "6а", "")):
    _a = s._parse_addr(строка)
    chk("адрес по полям: " + строка[:30],
        (_a["street"], _a["building"], _a["office"]) == (улица, дом, кв))
# ⚠ Явная квартира сильнее угаданной через дефис: угадыванием её не перебиваем.
_a = s._parse_addr("Лесная, 27-45, кв 12")
chk("явная «кв» побеждает дефис", _a["office"] == "12")


# ── ОЗВУЧКА ЦЕНЫ: дедуп по СУММЕ, а не по тексту ────────────────────────────
# Прямая проверка правила: две фразы про одну сумму — одна строка в карточке.
def _озвучки(тексты):
    вышло, суммы = [], set()
    import re as _re
    for t in тексты:
        for hit in s._OFFER_IN_REPLY_RX.findall(t)[:2]:
            h = hit.strip()
            ключ = tuple(_re.findall(r"\d+", h))
            if h and ключ and ключ in суммы:
                continue
            if h and h not in вышло:
                вышло.append(h)
                суммы.add(ключ)
    return вышло


chk("одна сумма двумя фразами — одна строка",
    len(_озвучки(["Услуга от 1500 рублей.", "от 1500р"])) == 1)
chk("две разные суммы обе остаются",
    len(_озвучки(["Услуга от 1500 рублей.", "выезд 500 руб"])) == 2)


# ── ОЧЕРЕДЬ: лид можно снять руками ──────────────────────────────────────────
# ⚠ Очередь — журнал ДОПИСЫВАНИЕМ: строку из неё не удалить, снятие это статус.
chk("«dropped» закрывает ключ так же, как «done»", "dropped" in s._CRM_ЗАКРЫТЫЕ)
# ⚠ ЧИСЛО ЗДЕСЬ НЕ САМОЦЕЛЬ: проверка следит, чтобы список закрытых статусов жил в
# ОДНОМ месте и не размножался по коду. 28.08 к трём добавился «no_filial» — город без
# филиала направления в CRM не отправляем, и запись обязана быть закрытой, иначе
# расширение возьмёт её как pending и получит из CRM ту же ошибку.
chk("закрытые статусы перечислены в одном месте",
    set(s._CRM_ЗАКРЫТЫЕ) == {"done", "failed", "dropped", "no_filial"})

_прежний = s._CRM_QUEUE
try:
    import json
    import tempfile
    _f = tempfile.NamedTemporaryFile("w", suffix=".jsonl", delete=False,
                                     encoding="utf-8")
    _f.write(json.dumps({"key": "k1", "ts": 1, "status": "pending",
                         "lead": {}}, ensure_ascii=False) + "\n")
    _f.write(json.dumps({"key": "k2", "ts": 2, "status": "pending",
                         "lead": {}}, ensure_ascii=False) + "\n")
    _f.write(json.dumps({"key": "k1", "ts": 3, "status": "dropped"},
                        ensure_ascii=False) + "\n")
    # поздний pending после рестарта не должен воскресить снятый лид
    _f.write(json.dumps({"key": "k1", "ts": 4, "status": "pending",
                         "lead": {}}, ensure_ascii=False) + "\n")
    _f.close()
    s._CRM_QUEUE = _f.name
    _pend = [r["key"] for r in s._crm_queue_pending(limit=10)]
    chk("снятый лид из очереди ушёл", "k1" not in _pend)
    chk("соседний лид остался", _pend == ["k2"])
    chk("снятый ключ закрыт навсегда",
        s._crm_queue_all()["k1"]["status"] == "dropped")
    chk("снятый лид повторно не захватывается", s._crm_queue_claim("k1") is False)
finally:
    s._CRM_QUEUE = _прежний
    try:
        os.unlink(_f.name)
    except OSError:
        pass

# ── «ВИД УСЛУГ»: ВТОРАЯ СТУПЕНЬ КАСКАДА (жалоба 25.08 по заявке №1234573) ──────
# В эталоне владельца №1234565 стоит «Сантехника» → «Подключение бытовой техники»,
# у бота оба поля пустые. Заполняет их расширение, а живой CRM отсюда не виден:
# доступ только с офисного ПК. Поэтому проверяем не поведение, а СВОЙСТВА кода —
# те, из-за отсутствия которых правка была бы опасной.
# ⚠ ЧЕСТНО О ГРАНИЦЕ: это проверка исходника, а не прогон. Она доказывает, что
# имя поля не вписано наугад и что неудача становится предупреждением, — но НЕ
# доказывает, что каскад в CRM устроен именно так. Это скажет первый живой запуск.
_EXT = io.open(os.path.join(os.path.dirname(__file__), "..", "ui", "crm-extension",
                            "offscreen.js"), encoding="utf-8").read()
_блок = _EXT[_EXT.find("ВИД УСЛУГ"):]
_блок = _блок[:_блок.find("const comment =")]
chk("вид услуг вообще заполняется", bool(_блок))
chk("имя поля ищется в форме, а не вписано наугад",
    "/subappl/i.test" in _блок and "CustomerRequest[subappl" not in _EXT)
chk("тот же список опций во второе поле не ставится", "тоЖеСамое" in _блок)
# ⚠ Ищем ПРИСВОЕНИЕ, а не слово: слово «innerHTML» есть в самом комментарии,
# который объясняет, почему присвоения тут нет.
chk("опции собираются значением и текстом, без переноса разметки",
    "new Option(o.textContent, o.value)" in _блок and ".innerHTML =" not in _блок)
chk("неудача становится предупреждением, а не тишиной",
    _блок.count("warnings.push") >= 3)
chk("падение подгрузки не роняет создание заявки", "catch (e)" in _блок)

print("=" * 50)
print("Поля заявки: %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
