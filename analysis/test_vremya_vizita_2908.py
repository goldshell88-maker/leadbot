# ⚠ ГЛАВНОЕ ЧИСЛО КЛАССА B: +90 минут, а не +60. Проверяем разницу, а не абсолют,
# чтобы тест не зависел от часа запуска.
def _минут(reply):
    import datetime as _dt
    д, т = s._visit_from_reply(reply, "Москва")
    if not д:
        return None
    цель = _dt.datetime.strptime(д + " " + т, "%d-%m-%Y %H:%M")
    _л = s.territory.city_localtime("Москва")
    сейчас = _dt.datetime(_л.tm_year, _л.tm_mon, _л.tm_mday, _л.tm_hour, _л.tm_min)
    return (цель - сейчас).total_seconds() / 60.0

