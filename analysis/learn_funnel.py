def блок_сверка(итог):
    """Печатает, какие числа отчёта скрипт подтвердил, а какие пересматривает."""
    заголовок("11. СВЕРКА С ЧИСЛАМИ, КОТОРЫЕ УЖЕ ПОПАЛИ В ОТЧЁТ ЭТАПА")
    print("  слева — число из зафиксированного факта, справа — что даёт ЭТОТ скрипт;")
    print("  расхождение — граница определения, а не ошибка счёта. Истина — колонка «скрипт».")
    сошлось, разошлось = [], []
    for имя, в_факте, путь in ФАКТЫ_ЭТАПА:
        значение = итог
        for ключ in путь:
            значение = значение.get(ключ) if isinstance(значение, dict) else None
            if значение is None:
                break
        if значение == в_факте:
            сошлось.append(имя)
        else:
            разошлось.append({
                "имя": имя, "в_факте": в_факте, "скрипт": значение,
                "разница": None if значение is None else значение - в_факте,
                "почему": ПОЧЕМУ_РАСХОДИТСЯ.get(имя, "разные регулярки на одной границе смысла"),
            })
    print("  СОШЛОСЬ ДО ДИАЛОГА: %s проверенных чисел" % проц(len(сошлось), len(ФАКТЫ_ЭТАПА)))
    if разошлось:
        print("  РАСХОДИТСЯ:         %s" % проц(len(разошлось), len(ФАКТЫ_ЭТАПА)))
        for с in разошлось:
            print("      %-44s факт %6s → скрипт %6s (%+d)"
                  % (с["имя"], с["в_факте"], с["скрипт"], с["разница"]))
        напечатано = set()
        for с in разошлось:
            if с["почему"] not in напечатано:
                напечатано.add(с["почему"])
                print("      ── %s" % с["почему"])
    итог["_сверка_с_фактами"] = {
        "проверено": len(ФАКТЫ_ЭТАПА), "сошлось": len(сошлось), "разошлось": len(разошлось),
        "расхождения": разошлось,
    }


