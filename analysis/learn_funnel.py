def проц(a, b):
    if not b:
        return "— (0 из 0)"
    return "%.1f%% (%d из %d)" % (100.0 * a / b, a, b)


def подъём(k1, n1, k0, n0):
    """P(событие|группа) − P(событие|остальные того же сценария) + 95%-интервал.

    Возвращает словарь; печатать без n1/n0 запрещено правилом 4.
    """
    if not n1 or not n0:
        return None
    p1, p0 = k1 / float(n1), k0 / float(n0)
    d = p1 - p0
    se = math.sqrt(p1 * (1 - p1) / n1 + p0 * (1 - p0) / n0)
    return {"p1": round(100 * p1, 1), "k1": k1, "n1": n1,
            "p0": round(100 * p0, 1), "k0": k0, "n0": n0,
            "подъём_пп": round(100 * d, 1),
            "низ": round(100 * (d - 1.96 * se), 1), "верх": round(100 * (d + 1.96 * se), 1),
            "значимо": abs(d) > 1.96 * se}


def строка_подъёма(имя, d, ширина=44):
    if d is None:
        return "  %-*s нет базы" % (ширина, имя)
    return ("  %-*s %s | остальные %s | подъём %+.1f п.п. [%+.1f;%+.1f] %s"
            % (ширина, имя, проц(d["k1"], d["n1"]), проц(d["k0"], d["n0"]),
               d["подъём_пп"], d["низ"], d["верх"], "ЗНАЧИМО" if d["значимо"] else "шум"))


def квантиль(значения, p):
    if not значения:
        return None
    v = sorted(значения)
    i = min(len(v) - 1, int(round((len(v) - 1) * p / 100.0)))
    return v[i]


