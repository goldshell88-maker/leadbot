def тип_последней(t):
    """Род последней реплики оператора. Порядок веток = приоритет смысла.

    Отказ идёт первым: «к сожалению, не смогу помочь» — это конец разговора,
    даже если в той же фразе есть слово «выезд» или «цена». Пустое «хорошо»
    проверяется ПОСЛЕДНИМ: «хорошо, буду к 15» — это окно, а не пустое согласие.
    """
    if Ф_ОТКАЗ.search(t):
        return "отказ «не смогу помочь»"
    if просьба_номера(t):
        return "просьба номера/адреса"
    if окно_названо(t):
        return "названное окно/выезд"
    if Ф_ПИНГ.search(t):
        return "пинг «актуально?»"
    if Ф_ЦЕНА.search(t):
        return "цена / выезд-диагностика"
    if Ф_ПРОЩАНИЕ.search(t):
        return "«до встречи / жду сообщения»"
    if Ф_КВАЛИФИКАЦИЯ.search(t):
        return "квалификация (что/где/фото)"
    if Ф_ПРИВЕТ.search(t) and len(t) < 60:
        return "приветствие"
    if Ф_ПУСТОЕ.match(t.strip()) or (len(t) < 40 and re.match(r"^\s*(хорошо|ок|понял|спасибо|да)\b", t, re.I)):
        return "пустое «хорошо/понял/спасибо»"
    return "прочее (короткая рабочая реплика)"


