# как и умолчание. «Артём»/«Октябрьский» выкинуты — это имя человека и район.
НЕОДНОЗНАЧНЫЕ = {"артем", "октябрьский"}


def _шаблон_города(имя):
    токены = re.split(r"[\s\-]+", имя)
    хвост = territory._declined(токены[-1])
    if len(токены) == 1:
        return хвост
    голова = r"[\s\-]+".join(re.escape(t)[:-1] + r"\w{0,3}" if len(t) > 4 else re.escape(t)
                             for t in токены[:-1])
    return голова + r"[\s\-]+" + хвост


_ИМЕНА_ГОРОДОВ = [c for c, off in territory.TZ_OFFSETS.items()
                  if off != 3 and c not in НЕОДНОЗНАЧНЫЕ]
