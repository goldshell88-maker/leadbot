def окно_точное(t):
    """ЖЁСТКИЙ уровень (б): названы ЧАСЫ или подтверждена запись.

    Это «мясо» прокси: связаться уже не с кем, а время визита названо.
    """
    if not t:
        return False
    if ЗАПИСЬ_RX.search(t) and not re.search(r"не\s+записал", t, re.I):
        return True
    if CLOCK_RX.search(t):
        if VISIT_RX.search(t) or ACCEPT_CLOCK_RX.search(t) or DAYPART_RX.search(t):
            return True
        # голая короткая реплика-время («к 11», «10:00-10:30») — это слот в ходе записи
        if len(t) <= 30 and not ГОЛЫЕ_ЧАСЫ_СТОП.search(t):
            return True
    return False


def окно_названо(t):
    """ШИРОКИЙ уровень (б): окно ИЛИ подтверждённый выезд (в т.ч. на уровне дня)."""
    if not t:
        return False
    if окно_точное(t):
        return True
    if NEG_RX.search(t):          # «сегодня не смогу» — это не окно, а отказ
        return False
    if DAYPART_RX.search(t) and (VISIT_RX.search(t) or ACCEPT_DAY_RX.search(t)):
        return True
    return False


