def блок_обрывы(зрелые, итог):
    N = len(зрелые)
    заголовок("2. ГДЕ ОБРЫВАЕТСЯ  (тишина после реплики оператора — НОРМА корпуса)")
    об = collections.Counter(r["обрыв"] for r in зрелые)
    for k, v in об.most_common():
        print("  %-40s %s" % (k, проц(v, N)))
    норма = об["оператор: реплика без вопроса"] + об["оператор: вопрос"]
    print("  ⇒ последним ходом стоит РЕПЛИКА ОПЕРАТОРА: %s — вот почему «после этой фразы"
          % проц(норма, N))
    print("    обычно тишина» ничего не доказывает и все приёмы сравниваются подъёмом.")

    print("\n  --- РОД ПОСЛЕДНЕЙ РЕПЛИКИ ОПЕРАТОРА БЕЗ ВОПРОСА ---")
    без_вопроса = [r for r in зрелые if r["обрыв"] == "оператор: реплика без вопроса"]
    c = collections.Counter(r["тип_последней"] for r in без_вопроса)
    for k, v in c.most_common():
        print("      %-36s %s" % (k, проц(v, len(без_вопроса))))
    print("\n  --- РОД ПОСЛЕДНЕГО ВОПРОСА ОПЕРАТОРА ---")
    с_вопросом = [r for r in зрелые if r["обрыв"] == "оператор: вопрос"]
    c2 = collections.Counter(r["тип_последней"] for r in с_вопросом)
    for k, v in c2.most_common():
        print("      %-36s %s" % (k, проц(v, len(с_вопросом))))

    print("\n  --- НАСТОЯЩИЙ ОБРЫВ — ТАМ, ГДЕ МОЛЧИТ ОПЕРАТОР ---")
    брошен = об["клиент: реплика без ответа оператора"]
    print("      клиент написал, оператор не ответил: %s (база — все зрелые)" % проц(брошен, N))
    окно_гр = [r for r in зрелые if r["окно"]]
    брошен_окно = sum(1 for r in окно_гр if r["обрыв"] == "клиент: реплика без ответа оператора")
    d = подъём(брошен_окно, len(окно_гр), брошен - брошен_окно, N - len(окно_гр))
    print(строка_подъёма("среди диалогов, где окно названо", d, 40))
    итог["обрывы"] = {"база": N, "распределение": dict(об),
                      "род_последней_без_вопроса": {"база": len(без_вопроса), "тип": dict(c)},
                      "род_последнего_вопроса": {"база": len(с_вопросом), "тип": dict(c2)},
                      "брошенный_клиент_подъём_при_окне": d}


def блок_дыра(зрелые, счёт, итог):
    N = len(зрелые)
    заголовок("3. 🔴 ОКНО НАЗВАНО, ТЕЛЕФОНА НЕТ  (проверка числа владельца ~9% / ~330 в неделю)")
    широкий = [r for r in зрелые if r["окно"] and not r["телефон"]]
    жёсткий = [r for r in зрелые if r["окно_точное"] and not r["телефон"]]
    широчайший = [r for r in зрелые if r["предложение_выезда"] and not r["телефон"]]
    for имя, гр in (("ЖЁСТКИЙ (названы часы или подтверждена запись)", жёсткий),
                    ("ШИРОКИЙ (окно или подтверждённый выезд)", широкий),
                    ("ШИРОЧАЙШИЙ (вообще предложил приехать)", широчайший)):
        print("  %-48s %s = %.0f в неделю" % (имя, проц(len(гр), N), len(гр) / НЕДЕЛЬ))
    print("  ⇒ доля 9% не подтверждается ни на одном уровне; абсолют ~330/нед лежит")
    print("    между широким и широчайшим. Целевым для бота берём ЖЁСТКИЙ уровень.")

    D = len(широкий)
    print("\n  --- ПРОСИЛ ЛИ ОПЕРАТОР НОМЕР В ЭТОЙ ДЫРЕ (база — широкий уровень) ---")
    кат = collections.Counter()
    for r in широкий:
        pi, oi = r["индекс_просьбы"], r["индекс_окна"]
        if pi is None:
            кат["номер не просили ВООБЩЕ"] += 1
        elif pi < oi:
            кат["просили ДО окна"] += 1
        elif pi == oi:
            кат["просили В ТОМ ЖЕ сообщении, что и окно"] += 1
        else:
            кат["просили ПОСЛЕ окна"] += 1
    for k, v in кат.most_common():
        print("      %-44s %s" % (k, проц(v, D)))
    print("      ⇒ лид теряется не на отказе клиента, а на НЕЗАДАННОМ вопросе.")

    просили = [r for r in широкий if r["индекс_просьбы"] is not None]
    молчали = [r for r in просили if not r["ответ_на_просьбу"]]
    ответили = [r for r in просили if r["ответ_на_просьбу"]]
    print("\n  --- КОГДА НОМЕР ВСЁ-ТАКИ ПРОСИЛИ (база %d) ---" % len(просили))
    print("      клиент промолчал: %s" % проц(len(молчали), len(просили)))
    c = collections.Counter()
    for r in ответили:
        t = r["ответ_вместо_номера"] or ""
        for имя, rx in ВМЕСТО_НОМЕРА:
            if rx.search(t):
                c[имя] += 1
                break
        else:
            c["прочее"] += 1
    print("      ЧТО отвечают вместо номера (база %d):" % len(ответили))
    for k, v in c.most_common():
        print("         %-38s %s" % (k, проц(v, len(ответили))))

    print("\n  --- ЧЕМ ОПЕРАТОР КОНЧАЕТ В ДЫРЕ ---")
    хвосты = [r["оп_ходов_после_окна"] for r in широкий if r["оп_ходов_после_окна"] is not None]
    ноль_ходов = sum(1 for x in хвосты if x == 0)
    print("      ходов оператора ПОСЛЕ названного окна: медиана %.0f, среднее %.1f"
          % (statistics.median(хвосты), statistics.mean(хвосты)))
    print("      не сделал НИ ОДНОГО хода после окна:   %s" % проц(ноль_ходов, D))
    позиции = [r["индекс_окна"] + 1 for r in широкий]
    print("      окно называется сообщением №: медиана %.0f, среднее %.1f; длина диалога медиана %.0f"
          % (statistics.median(позиции), statistics.mean(позиции),
             statistics.median([r["n"] for r in широкий])))
    пинг = sum(1 for r in широкий if r["тип_последней"] == "пинг «актуально?»")
    print("      последняя реплика — пинг «актуально?»:  %s" % проц(пинг, D))
    созрел = sum(1 for r in широкий if r["адрес"] or r["согласие"])
    print("      адрес/согласие клиента УЖЕ получены, не хватает только телефона: %s"
          % проц(созрел, D))

    итог["дыра_окно_без_телефона"] = {
        "жёсткий": len(жёсткий), "широкий": D, "широчайший": len(широчайший), "база": N,
        "в_неделю": {"жёсткий": round(len(жёсткий) / НЕДЕЛЬ), "широкий": round(D / НЕДЕЛЬ),
                     "широчайший": round(len(широчайший) / НЕДЕЛЬ)},
        "просьба_номера": dict(кат), "просили": len(просили), "промолчали": len(молчали),
        "вместо_номера": dict(c),
        "ходов_после_окна": {"медиана": statistics.median(хвосты),
                             "среднее": round(statistics.mean(хвосты), 1), "нисколько": ноль_ходов},
        "пинг_финал": пинг, "адрес_или_согласие_есть": созрел,
    }


def блок_просьба(зрелые, счёт, итог):
    заголовок("4. ПРОСЬБА НОМЕРА: ПОДЪЁМ ХОДОВ И ЦЕНА ФОРМУЛИРОВКИ")
    print("  --- ПОДЪЁМ ПО ХОДАМ ОПЕРАТОРА: P(клиент ответил | ход) ---")
    гр = счёт["ходы_оператора"]
    прочие = гр["прочие ходы"]
    итог_ходы = {}
    for имя in ("окно+просьба", "окно без просьбы", "просьба без окна", "прочие ходы"):
        n, o = гр[имя]
        if имя == "прочие ходы":
            print("  %-20s %s  ← БАЗА СРАВНЕНИЯ" % (имя, проц(o, n)))
            итог_ходы[имя] = {"ходов": n, "ответов": o}
            continue
        d = подъём(o, n, прочие[1], прочие[0])
        print("  %-20s %s  подъём к «прочим» %+.1f п.п. [%+.1f;%+.1f] %s"
              % (имя, проц(o, n), d["подъём_пп"], d["низ"], d["верх"],
                 "ЗНАЧИМО" if d["значимо"] else "шум"))
        итог_ходы[имя] = {"ходов": n, "ответов": o, "подъём": d}
    print("  ⇒ окно и просьба номера НЕ отпугивают: они поднимают отвечаемость почти на 20 п.п.")

    print("\n  --- P(клиент дал телефон | оператор просил номер) ---")
    просили = [r for r in зрелые if r["просили_номер"]]
    не_просили = [r for r in зрелые if not r["просили_номер"]]
    d1 = подъём(sum(r["телефон"] for r in просили), len(просили),
                sum(r["телефон"] for r in не_просили), len(не_просили))
    print(строка_подъёма("просили номер (вся зрелая база)", d1))
    окно_гр = [r for r in зрелые if r["окно"]]
    ок_пр = [r for r in окно_гр if r["просили_номер"]]
    ок_неп = [r for r in окно_гр if not r["просили_номер"]]
    d2 = подъём(sum(r["телефон"] for r in ок_пр), len(ок_пр),
                sum(r["телефон"] for r in ок_неп), len(ок_неп))
    print(строка_подъёма("просили номер ВНУТРИ «окно названо»", d2))

    print("\n  --- ФОРМУЛИРОВКА ПРОСЬБЫ: номер СЛЕДУЮЩЕЙ репликой клиента ---")
    print("      сравнение только ВНУТРИ своей стадии (до / после названного окна):")
    print("      иначе сравнивались бы стадии диалога, а не слова оператора.")
    итог_форм = {}
    for стадия in ("после окна", "до окна"):
        строки = [x for x in счёт["просьбы"] if x[0] == стадия]
        общ_n = len(строки)
        общ_k = sum(1 for x in строки if x[2])
        print("\n      ПРОСЬБЫ %s (всего %d, номер сразу дали %s):"
              % (стадия.upper(), общ_n, проц(общ_k, общ_n)))
        по_шаблону = collections.defaultdict(lambda: [0, 0, collections.Counter()])
        for _ст, шаб, дал, агент in строки:
            b = по_шаблону[шаб]
            b[0] += 1
            b[1] += дал
            b[2][str(агент)] += 1
        итог_форм[стадия] = {"всего": общ_n, "дали_номер": общ_k, "шаблоны": {}}
        # база для пометки «один_оператор»: доля агента среди ВСЕХ просьб этой стадии
        всего_по_агентам = collections.Counter(str(x[3]) for x in строки)
        for шаб, (n, k, агенты) in sorted(по_шаблону.items(), key=lambda x: -x[1][0]):
            d = подъём(k, n, общ_k - k, общ_n - n)
            дом, дн = агенты.most_common(1)[0]
            доля_дом = 100.0 * дн / n
            его_база = 100.0 * всего_по_агентам[дом] / общ_n
            один = доля_дом >= 50.0 or (доля_дом - его_база) >= 20.0
            print("        %-42s %s | подъём %+.1f п.п. [%+.1f;%+.1f] (база остальных %d)%s"
                  % (шаб, проц(k, n), d["подъём_пп"], d["низ"], d["верх"], d["n0"],
                     "  ⚠ ОДИН_ОПЕРАТОР: agent %s даёт %.0f%% таких просьб (его доля просьб стадии %.0f%%)"
                     % (дом, доля_дом, его_база) if один else ""))
            итог_форм[стадия]["шаблоны"][шаб] = {"просьб": n, "дали_номер": k, "подъём": d,
                                                 "доминант_agent": дом,
                                                 "доля_доминанта_%": round(доля_дом, 1),
                                                 "его_доля_просьб_стадии_%": round(его_база, 1),
                                                 "один_оператор": один}
    итог["просьба_номера"] = {"ходы_оператора": итог_ходы, "телефон_если_просили": d1,
                              "телефон_если_просили_при_окне": d2, "формулировки": итог_форм}


