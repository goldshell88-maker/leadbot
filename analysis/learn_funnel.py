РАЗМАЗ_RX = re.compile(r"(?:\d[\s*_·•\-–.,/\\]{1,3}){9,}\d")


def телефон(t):
    if not t:
        return False
    ч = URL_RX.sub(" ", t)
    return bool(PHONE_RX.search(ч)) or bool(РАЗМАЗ_RX.search(ч))


