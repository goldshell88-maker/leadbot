    место = bool(Ц_МЕСТО.search(txt))
    if есть_от and место:
        return "от_N_плюс_на_месте"
    if есть_от:
        return "от_N_голое"
    if есть_сумма and место:
        return "цифра_плюс_на_месте"
    if есть_сумма:
        return "точная_цифра"
    if место:
        return "уход_на_место"
    if "?" in txt:
        return "встречный_вопрос"
    return "игнор_вопроса"


