def просьба_номера(t):
    """Оператор просит номер: слово «номер/телефон» + просительный глагол.

    «номер заказа/объявления/дома/квартиры» — не просьба контакта, отсекаем.
    """
    if not t:
        return False
    if re.search(r"номер\s*(?:заказа|объявлен|карт|дом[аеу]|квартир)", t, re.I):
        return False
    return bool(_НОМЕР_СЛОВО.search(t) and _ПРОСИТЬ.search(t))


