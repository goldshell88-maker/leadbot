# -*- coding: utf-8 -*-
"""АУДИТ БОТА 30.08 (баги, деградации, логика, ум, легенда): партия фиксов по 4 осям.

Шесть ревизоров прошли бота (706 боевых ходов прочитаны глазами, роутеры и гарды —
фактическими прогонами). Итоги осей: ум модели — 82 % ходов по делу, 18 % тупостей,
и заметная часть «тупостей» оказалась механикой постобработки; деградаций после ~15
партий правок НЕТ (передачи 16,7 % → 8,5 %, дословные дубли 11,2 % → 0); легенда в
основном цела (после гарда 26.08 — ноль разрывов «мы» в бою).

ЧТО ЧИНИТ ЭТА ПАРТИЯ (все находки воспроизведены прогоном до фикса):

CRITICAL — гард цены диагностики переписывал цену РЕМОНТА: `(\\d{3,5})` откатывался
ВНУТРЬ числа («ремонт от 1500» → «от 500» и «от 5000»), а «ОСМОТРЮ, ремонт…»
матчился темой «осмотр». Плюс белый аккаунт без проброшенного 723 получал «от 500»,
и пустой партнёр получал ставку наугад.

HIGH: «такое не отремонтировать» не считалось отказом (в _РАБОТА_ГЛ были только
личные формы) — и следом шла просьба адреса с телефоном; «Передам вашу заявку» —
боевой разрыв легенды 26.08, не ловился ничем; вариант SOGLAS_POOL «по какому
номеру набрать?» был невидим _PHONE_ASK_RX (грозил двойной просьбой номера);
«разбит экран планшета» получал финальный отказ «матрица» вместо согласования
(В-004); «ремонт стационарного телефона» съедался отказом «телефоны».

MEDIUM: «прошить телефон» уходил в тихий соглас вместо отказа; три свежих
гарда-исключения ловили лишнее (голое «терминал», «а вы поддерживаете 1с?»,
«заПАЯть батарею» внутри глагола); двойное «Здравствуйте» от вклейки увода цены
перед приветствием (2 боевых хода 29.08); белый cancel «снимаю заявку» выдумывал
заявку; «Мастер приедет и посмотрит» чинился наполовину («Приеду и посмотрит»).

Запуск: uv run python analysis/test_audit_3008.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter as p  # noqa: E402
import server as s  # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── CRITICAL: ЦЕНА РЕМОНТА НЕПРИКОСНОВЕННА ──────────────────────")
for r in ("Осмотрю, ремонт от 1500",
          "После проверки скажу, от 1500 ремонт обычно",
          "Осмотр покажет, от 1000 работа выйдет"):
    chk("не тронута: «%s»" % r[:40], s._поправить_цену_диагностики(r, "7") == r,
        s._поправить_цену_диагностики(r, "7"))
chk("настоящая диагностика по-прежнему правится",
    "500" in s._поправить_цену_диагностики("Диагностика от 1000р. Куда подъехать?", "7"))
chk("белый аккаунт получает 1000",
    "1000" in s._поправить_цену_диагностики("Диагностика от 500р", "", white=True))
chk("партнёр неизвестен — цифру не трогаем",
    s._поправить_цену_диагностики("Диагностика от 1000р", None) == "Диагностика от 1000р")

print("── ОТКАЗ: ИНФИНИТИВЫ ────────────────────────────────────────────")
chk("«такое не отремонтировать» — отказ",
    s._отказ_от_работы("такое, к сожалению, не отремонтировать, извините"))
chk("«не берусь» — отказ (личная форма жива)", s._отказ_от_работы("за это не берусь"))
chk("«отремонтирую» — не отказ", not s._отказ_от_работы("завтра отремонтирую вам его"))

print("── ЛЕГЕНДА ──────────────────────────────────────────────────────")
for фр in ("по такому объёму только со специалистами. Передам вашу заявку",
           "Заявка создана, оператор свяжется с вами",
           "Мастер будет у вас к 15:00"):
    chk("ловится: «%s»" % фр[:40], bool(s._ОБЕЩАНИЕ_МАСТЕРА_RX.search(фр)))
chk("честное «наберу вас» не тронуто",
    not s._ОБЕЩАНИЕ_МАСТЕРА_RX.search("Хорошо, наберу вас через час"))
chk("«Мастер приедет и посмотрит» → оба глагола",
    s._в_единственном_числе("Мастер приедет и посмотрит") == "Приеду и посмотрю")
chk("белый cancel без слова «заявка»",
    "заявк" not in s._WHITE_ESC_REPLIES["cancel"].lower())

print("── РОУТЕРЫ ──────────────────────────────────────────────────────")
chk("планшет: соглас, не отказ-матрица",
    (p.check_refuse("разбит экран планшета", "разбит экран планшета") or {}).get("kind") == "soglas")
chk("стационарный телефон: соглас",
    (p.check_refuse("ремонт стационарного телефона", "ремонт стационарного телефона") or {}) == {}
    or (p.check_soglasovanie("ремонт стационарного телефона") or {}).get("sub", "") != "")
chk("«прошить телефон» — отказ телефоны",
    (p.check_refuse("прошить телефон сможете?", "прошить телефон сможете?") or {}).get("sub") == "телефоны")
chk("ТВ-матрица не задета",
    (p.check_refuse("разбит экран телевизора", "разбит экран телевизора") or {}).get("sub") == "матрица")

print("── ГАРДЫ-ИСКЛЮЧЕНИЯ СУЖЕНЫ ──────────────────────────────────────")
chk("«оптика возле терминала» — соглас",
    bool(p.check_soglasovanie("перебили оптику возле терминала в подъезде, почините?")))
chk("«подключить оптический терминал» — приём",
    not p.check_soglasovanie("подключить оптический терминал ростелекома"))
chk("«поддерживаете 1с?» — соглас",
    bool(p.check_soglasovanie("устанавливаете и поддерживаете 1с?")))
chk("«виндовс чтобы поддерживала 1с» — приём",
    not p.check_soglasovanie("обычный виндовс, чтобы поддерживала программу 1с"))
chk("«течёт батарея, запаять» — соглас (отопление)",
    bool(p.check_soglasovanie("течёт батарея, запаять сможете?")))
chk("«батарейка в ноутбуке» — приём",
    not p.check_soglasovanie("поменять батарейку в ноутбуке"))

print("── ДВОЙНОЕ ПРИВЕТСТВИЕ ──────────────────────────────────────────")
_р = s._ответить_про_цену("Здравствуйте. Какой телевизор, марка и модель?", True, 3)
chk("приветствие одно и первое", _р.lower().count("здравствуйте") == 1
    and _р.lower().startswith("здравствуйте"), _р[:70])

print("── PHONE_ASK ВИДИТ ВСЕ ВАРИАНТЫ ПУЛА ────────────────────────────")
for в in p.SOGLAS_POOL:
    if "номер" in в.lower() or "телефон" in в.lower() or "связ" in в.lower():
        chk("виден: «%s»" % в[:44], bool(s._PHONE_ASK_RX.search(в)), в)

print("── ВТОРАЯ ПАРТИЯ АУДИТА (свод) ──────────────────────────────────")
# TypeError на строковом сиде — бой падал молча (critical №1)
_сид = s._соглас_сид({"visitor": "Тест"})
chk("строковый сид не роняет удалёнку",
    "выезд" in s._снять_обещание_удалёнки("Удалённо, да, могу подключиться", _сид).lower())
chk("строковый сид не роняет эхо дня",
    bool(s._снять_эхо_дня("Понял, завтра удобно?", "давайте завтра", True, _сид)))
# цена ремонта при слове работы СЛЕВА от суммы (critical №2, вторая итерация)
chk("«После осмотра скажу, ремонт от 1500р» не тронута",
    s._поправить_цену_диагностики("После осмотра скажу, ремонт от 1500р", "7")
    == "После осмотра скажу, ремонт от 1500р")
# «запишу вас на …» разблокирована (high №4)
_п = "Запишу вас на 15:00-15:30, удобно?"
for _rx, _зам in s._BOOKED_SOFTEN:
    _п = _rx.sub(_зам, _п)
chk("«Запишу вас на …, удобно?» жива", _п == "Запишу вас на 15:00-15:30, удобно?", _п)
chk("«Записал вас» по-прежнему глушится",
    "запис" not in s._soften_booking("Записал вас на завтра к 14:00", "")[:20].lower())
# «сверюсь по графику» вычищена (high №13, запрет владельца 19.08)
_ПРОМПТ = io.open(os.path.join(КОРЕНЬ, "brain", "prompt.py"), encoding="utf-8").read()
_живых = [l for l in _ПРОМПТ.splitlines()
          if "сверюсь" in l.lower() and "ЗАПРЕЩЕНА" not in l and "без «сверюсь»" not in l]
chk("«сверюсь по графику» в промпте не предписывается", len(_живых) == 0,
    _живых[0][:80] if _живых else "")
# …и КОДОМ не подставляется (сверка после аудита: пул замены отказов и четыре
# форс-ответа согласования продолжали слать её в бой при чистом промпте)
_СРВ2 = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
_подстановки = [l for l in _СРВ2.splitlines()
                if "сверюсь по графику" in l.split("#")[0] and '"""' not in l
                and "«…по этому" not in l and "ЗАПРЕЩЕНО" not in l]
chk("«сверюсь по графику» кодом не подставляется", len(_подстановки) == 0,
    _подстановки[0][:80] if _подстановки else "")
# легенда: опустевшее и третьи лица (high №8)
chk("«Оператор свяжется» не уходит клиенту",
    s._снять_обещание_мастера("Оператор свяжется с вами") == "Понял вас.")
chk("пустой вход остаётся пустым (тишина шлюза легитимна)",
    s._снять_обещание_мастера("") == "")
# приветствие — не пожелание вечера (high №9)
chk("«Добрый вечер!» не двигает слот",
    s._пожелание_части_дня("Добрый вечер! Зависает телевизор") == ("", None))
# учреждение-ориентир не глушится (high №6)
chk("«возле школы» — не юрлицо",
    (p.check_soglasovanie("в гайдуке, возле школы!") or {}).get("sub", "") != "бригада/учреждение/юрлицо")
chk("боевой B2B №533 ловится",
    (p.check_soglasovanie("нужна команда сборщиков офисной мебели, д/сад на 230 мест") or {}) != {})
# голое существительное не глушит воронку (high №7)
chk("«В квартире кроме стояка ничего нет» — не тема",
    not p.check_soglasovanie("в квартире кроме стояка ничего нет"))
# цена не стирается гардом КЦ (№15)
chk("цена уцелела рядом с запретным оборотом",
    "500" in s._снять_запрет_кц("Засор прочищу, от 500р, работа мелочная, много денег не возьму. Куда подъехать?"))
# вопрос не убивается минутным гардом (№20)
chk("вопрос жив после замены минут",
    s._снять_минутное_обещание("Буду через 10 минут. Что случилось?").endswith("Что случилось?"))
# «восстановить удалённое» — не удалёнка (№17)
chk("«восстановить удалённое» уцелело",
    s._снять_обещание_удалёнки("Да, могу восстановить удалённое, подъеду посмотрю.", 1)
    == "Да, могу восстановить удалённое, подъеду посмотрю.")
# полосы: отрицание и чужие слова (№18)
chk("«показывает без полос» — не матрица",
    not [и for и, rx, *_ in p._REFUSE if rx.search("телевизор показывает без полос, но зависает")])
chk("«двухполосные колонки» — не матрица",
    not [и for и, rx, *_ in p._REFUSE if rx.search("купил двухполосные колонки к телевизору")])

print("=" * 50)
print("Аудит 30.08, партия фиксов: %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
