"""Демонстрационный прогон бота по показательным кейсам для отчёта руководству."""
import paths  # noqa: E402  — единая точка правды по путям
import sys, io, os, json, re, urllib.request, base64
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "brain"))
import server, claude_api  # noqa

OUT = os.path.dirname(os.path.abspath(__file__))
rows = []


def kn(d, name="Клиент", persona=""):
    k = {"visitor": name, "city": "Сыктывкар", "direction": d}
    if persona:
        k["persona"] = persona
    return k


def run(group, client, d, note="", name="Клиент", persona="", history=None):
    msgs = (history or []) + [{"role": "client", "text": client}]
    r = server.run_relay(msgs, known=kn(d, name, persona))
    rep = r.get("reply") or ("(молча оператору)" if r.get("to_operator") else "")
    router = r.get("model") if "роутер" in (r.get("model") or "") else ""
    rows.append({"group": group, "client": client, "bot": rep, "note": note,
                 "router": router, "handoff": bool(r.get("handoff"))})
    print("• [%s] %s" % (group, client[:48]))
    print("    → %s %s" % (rep, "[" + router + "]" if router else ""))
    return rep


# --- Живой ритм / чёткая заявка ---
run("Живое общение", "нужно собрать шкаф", "mnc", "коротко, как оператор (медиана 4 слова)")
run("Живое общение", "сломалась стиральная машина, не сливает воду", "bt", "принял, одна мысль")

# --- Цена: лестница МНЧ (по шагам) ---
h = []
for step, txt in enumerate(["повесить люстру, сколько будет стоить?", "ну хотя бы примерно?"]):
    rep = run("Цена по лестнице", txt, "mnc", "1-й ход мягко, 2-й — «от N»")
    h += [{"role": "client", "text": txt}, {"role": "bot", "text": rep}]

# --- КП: обязательная диагностика 1000 ---
run("КП диагностика", "ноутбук не включается, почём ремонт?", "kp", "КП: всегда «выезд+диагностика 1000, при работах бесплатно»")
