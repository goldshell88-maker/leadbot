# -*- coding: utf-8 -*-
"""Подрезатель длины режет ТОЛЬКО пояснения — и никогда ответ клиенту.

ЛОГИКА ПЕРЕВЁРНУТА 26.08 ПО ТРЕТЬЕЙ ОДИНАКОВОЙ ОШИБКЕ. Сначала подрезатель спасал
перечисленное и резал всё остальное. Трижды подряд это удалило ответ:
  · цену из прайса («установка Windows от 2000») — клиент спросил и не получил;
  · оговорку про потолок бюджета — ту самую, без которой, по замеру плейбука,
    умерли 4 диалога из 4;
  · а на разборе выброшенного нашлись ещё «Установлю вам свежую Windows»,
    «я выездной мастер, сам подъеду к вам», «Могу сам подъехать и проверить ноутбук»,
    «Фото скиньте, посмотрю».
Каждый раз я дописывал очередное исключение — значит неверна была рамка, а не список.

ТЕПЕРЬ: по умолчанию НЕ режем. Режем только опознанное пояснение, и даже его оставляем,
если в нём есть цифра, вопрос, оговорка, приём работы или предложение приехать.

⚠ ЦЕНА РЕШЕНИЯ НАЗВАНА ВСЛУХ. Прежний подрезатель давал >110 знаков в 6 % ходов (как у
живых), новый — 17 % при 20 % без него вовсе. Разница в одиннадцать пунктов куплена тем,
что бот перестал удалять собственные ответы. Остаток длины — не вода: это приём работы,
окно и адрес в одном ходу, и резать там нечего.

Запуск: uv run python analysis/test_trim_water.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import server as s                                      # noqa: E402

ошибки = []


def проверь(имя, условие, чем=""):
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:90]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


ХВОСТ = " По какому адресу вы находитесь? И номер ваш подскажите, пожалуйста"

print("пояснение режем")
for вода in ("Цену скажу точно после осмотра, по подсветке многое зависит от диодов.",
             "Диоды разные бывают, надо смотреть вживую.",
             "Как посмотрю, назову цену, без сюрпризов.",
             "Объём разный у каждой позиции."):
    исход = "Понял, это чиним. " + вода + ХВОСТ
    вых = s._подрезать_длину(исход)
    проверь("срезано: %s" % вода[:46], вода.rstrip(".") not in вых, вых)

print("ответ клиенту НЕ режем никогда")
for ответ in ("Установлю вам свежую Windows или параллельную ОС, без проблем.",
              "Я выездной мастер, мастерской нет, сам подъеду к вам.",
              "Могу сам к вам подъехать и проверить ноутбук на месте.",
              "Установка Windows от 2000, точнее скажу на месте.",
              "Не обещаю, что выйдет ровно столько, объём на месте виден.",
              "Да, помогу с плинтусом."):
    исход = "Здравствуйте. " + ответ + ХВОСТ
    вых = s._подрезать_длину(исход)
    проверь("сохранено: %s" % ответ[:46], ответ.rstrip(".") in вых, вых)

print("вето сильнее совпадения")
_c = s._подрезать_длину("Понял. По цене на месте сориентируюсь, от 1500 выйдет." + ХВОСТ)
проверь("пояснение с ценой остаётся", "1500" in _c, _c)

print("короткую реплику не трогаем")
for т in ("Да, помогу", "Здравствуйте, что случилось?"):
    проверь("цела: %s" % т, s._подрезать_длину(т) == т)

print("пустоту не отдаём")
проверь("длинная вода без шага не обнуляется",
        s._подрезать_длину("Зависит от объёма. Разные бывают. По-разному. "
                           "Надо смотреть вживую. Всё индивидуально.").strip() != "")

print()
if ошибки:
    print("ПРОВАЛЕНО: %d" % len(ошибки))
    for e in ошибки:
        print("  -", e)
    sys.exit(1)
print("Все проверки пройдены")
