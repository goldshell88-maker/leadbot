# -*- coding: utf-8 -*-
"""«НЕЧЕГО СКАЗАТЬ» ПЕРЕСТАЛО ЗНАЧИТЬ «ОТДАТЬ ДИАЛОГ».

ВЛАДЕЛЕЦ 27.08 по диалогу с Samsung ЖК: «модель правильно отреагировала на "Ок", но не
понимаю, почему он всё-таки решил его передать — можно было подержать у себя, чтобы если
клиент напишет, он бы создал заявку на себя».

    23:42 клиент: Ок как буду дома напишу
    23:43 БОТ   : Хорошо, буду ждать, напишите как будете дома
    23:47 клиент: Ок
    23:48 журнал: claude-sonnet-5, confidence 0.0, reply_len 0
    23:48 ЗАМЕТКА: передал менеджеру, причина model_silent

ЦЕНА БЫЛА НЕ В ОДНОЙ ЗАМЕТКЕ. Панель второй раз бота в диалог не пускает — `bot_entry_block`
возвращает «handoff_done: бот уже отдал диалог человеку». То есть на вежливом «Ок» диалог
терялся для бота НАВСЕГДА, вместе с заявкой, которую он собрал бы, когда клиент напишет
«я дома».

ПОЧЕМУ ПРАВИЛО ВООБЩЕ ТАКОЕ. Оно писалось под ПОЛОМКУ: `claude_api.first_tool_input` отдаёт
None при обрыве по max_tokens, ответ выходит пустым, и тогда человек действительно нужен.
Отличить осознанное молчание от обрыва надёжно нельзя, и притворяться, что умеем, не будем:
молчим и остаёмся только там, где молчание очевидно уместно — последнее слово клиента это
вежливое подтверждение без сути. Во всех прочих случаях пустой ответ по-прежнему зовёт человека.

ЦЕПОЧКА ДЛИННЕЕ, ЧЕМ КАЖЕТСЯ, и рвалась она в трёх местах:
  1. мозг возвращал handoff=True → чинится флагом `silent_hold`;
  2. мост `to_answer` ставил needs_operator по правилу «пустой ответ = нужен человек» —
     оно верное, и снимает его ТОЛЬКО этот флаг;
  3. панель писала в журнал «Ответ ушёл клиенту», хотя не ушло ничего.

Запуск: uv run python analysis/test_molchanie_2708.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import leadchat as lc                                  # noqa: E402
import server as s                                     # noqa: E402

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:110]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


print("\n1. ЧТО СЧИТАЕТСЯ ВЕЖЛИВЫМ ПОДТВЕРЖДЕНИЕМ")
for т in ("Ок", "ок", "хорошо", "спасибо", "понял", "да", "ага"):
    проверь("«%s» — молчим и держим" % т, bool(s._ПУСТАЯ_РЕПЛИКА_RX.match(т)))
for т in ("а сколько будет стоить", "я дома", "приезжайте завтра", "телевизор не включается"):
    проверь("«%s» — это суть, молчать нельзя" % т[:28],
            not s._ПУСТАЯ_РЕПЛИКА_RX.match(т))

print("\n2. МОСТ РАЗЛИЧАЕТ МОЛЧАНИЕ И ПОЛОМКУ")
_тихо = {"reply": "", "handoff": False, "to_operator": False,
         "model": "локальный роутер (молчим, диалог держим)",
         "flag": {"kind": "silent_hold", "reason": "…"},
         "state": {}, "missing": [], "ready": False}
_слом = {"reply": "", "handoff": True, "to_operator": True, "model": "claude-sonnet-5",
         "flag": None, "state": {}, "missing": [], "ready": False}
о_тихо, о_слом = lc.to_answer(_тихо), lc.to_answer(_слом)
проверь("молчание не зовёт человека", о_тихо["needs_operator"] is False, о_тихо)
проверь("и не проваливается по уверенности", о_тихо["confidence"] >= 1.0, о_тихо)
проверь("клиенту при этом не уходит ничего", о_тихо["reply"] == "", о_тихо)
проверь("поломка модели по-прежнему зовёт человека", о_слом["needs_operator"] is True, о_слом)
проверь("и уверенность у неё нулевая", о_слом["confidence"] == 0.0, о_слом)

print("\n3. ПРОВОДКА В МОЗГЕ")
исходник = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
проверь("ветка молчания стоит ПЕРЕД передачей человеку",
        исходник.index('if _ПУСТАЯ_РЕПЛИКА_RX.match((last_client or "").strip()):')
        < исходник.index('"notify_reason": "model_silent"'))
проверь("молчание не ставит handoff",
        '"reply": "", "to_operator": False, "handoff": False,' in исходник)
проверь("флаг называется silent_hold", '"kind": "silent_hold"' in исходник)
мост = io.open(os.path.join(КОРЕНЬ, "brain", "leadchat.py"), encoding="utf-8").read()
проверь("мост снимает «нужен оператор» только по этому флагу",
        'or (not reply and not _тихо))' in мост and '== "silent_hold"' in мост)

print("\n4. ПАНЕЛЬ НЕ ПИШЕТ В ЖУРНАЛ ТОГО, ЧЕГО НЕ БЫЛО")
_панель = os.path.join(os.path.dirname(КОРЕНЬ), "..", "Desktop", "LeadChat", "leadchat",
                       "app", "bots", "engine.py")
_панель = os.path.normpath(_панель)
if os.path.exists(_панель):
    д = io.open(_панель, encoding="utf-8").read()
    # ⚠ ПРОВЕРЯЕМ СМЫСЛ, А НЕ СТРОКУ. Первая редакция искала условие дословно
    # («if отправлено is None and not reply.strip():») и упала 28.08, когда соседняя
    # сессия этот код УЛУЧШИЛА: `None` от `send_bot_message` приходит по двум разным
    # поводам — пустой текст (тихое удержание) и погашенный гардом повтор, — и теперь
    # они разведены на две ветки. Смысл сохранён и даже уточнён, а проверка формы
    # объявила это поломкой. Держим три признака, каждый из которых обязан быть.
    проверь("исход записывается только если что-то ушло",
            "отправлено = await self.send_bot_message(" in д
            and "if отправлено is None:" in д
            and "not reply.strip():" in д
            and "bot.silent_hold" in д)
    проверь("и сценарий идёт дальше, а не встаёт", "self._goto(step.next)\n            return" in д)
else:
    print("  — панель не найдена рядом, проверка пропущена:", _панель)

print("\n" + "─" * 60)
print("проверок: %d, провалов: %d" % (всего[0], len(ошибки)))
for о in ошибки:
    print("  ПРОВАЛ:", о)
sys.exit(1 if ошибки else 0)
