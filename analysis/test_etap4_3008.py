# -*- coding: utf-8 -*-
"""4-Й ЭТАП ВОЗРАЖЕНИЙ: УСТУПКА СОМНЕВАЮЩЕМУСЯ (регламент КП «Отработка возражений», 30.08).

Регламент делит возражения по цене на 4 этапа: увод на осмотр → «от 500» → цена из
прайса → и 4-й, когда клиент после всего этого СОМНЕВАЕТСЯ («дорого», «подумаю»).
На 4-м этапе регламент велит: спросить «что именно смущает?», затем закрыть клиента
БЕСПЛАТНЫМ выездом без оговорки про 1000, а при окончательном отказе — отпустить
(«я на связи, пишите») и не дожимать.

ЧЕМУ ЭТО ПРОТИВОРЕЧИЛО. Гард visit_fee_fix (слово владельца 18.08) дописывает
«при отказе 1000» к ЛЮБОМУ «выезд бесплатный» на КП. Для озвучки УСЛОВИЙ это верно,
но уступку 4-го этапа он убивал: бот обещал бесплатный выезд — гард приклеивал 1000,
и уступка переставала быть уступкой. Разрешение узкое: тег stage4_concession ставится
ТОЛЬКО когда клиент выразил сомнение (детектор) И цена уже звучала в прежних репликах.

ЗАМЕР (боевой корпус, 161 диалог с сомнением после цены): живые операторы дают
«бесплатно» лишь в 1,9 % — они отпускают («хорошо, если что пишите»). Расхождение
регламента с практикой мастеров показано владельцу; работаем по регламенту.

ПОПУТНО ЗАКРЫТА СТАРАЯ ДЫРА: регекс гарда знал только порядок «выезд … бесплатный»,
и «сделаю бесплатный выезд» уходило на КП без условия про 1000 задолго до правки.

Запуск: uv run python analysis/test_etap4_3008.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter as p  # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── ДЕТЕКТОР СОМНЕНИЯ ────────────────────────────────────────────")
for т in ("что-то дорого", "Спасибо, я подумаю", "поищу ещё варианты",
          "сравню с другими мастерами", "дороговато выходит", "вряд ли буду заказывать"):
    chk("ловит: «%s»" % т, p.этап4_сомнение(т, "ремонт от 3000 рублей"))
for т, why in (("когда сможете подъехать?", "не сомнение"),
               ("не уверен во времени, напишу позже", "сомнение во времени, не в цене"),
               ("дорогой мастер, здравствуйте", "«дорогой» — обращение")):
    chk("мимо: «%s» (%s)" % (т, why), not p.этап4_сомнение(т, "ремонт от 3000 рублей"))
chk("без озвученной цены этапа 4 НЕТ (это этапы 1-3)",
    not p.этап4_сомнение("что-то дорого", "подъеду, посмотрю на месте"))

print("── ГАРД: УСТУПКА ПРОТИВ ОЗВУЧКИ ─────────────────────────────────")
_уступка, _т1 = p.enforce_callouts(
    "Давайте я для вас сделаю бесплатный выезд, на месте всё обсудим",
    "что-то дорого, подумаю", prior_bot_text="ремонт от 3000 рублей", direction="kp")
chk("уступка: 1000 НЕ дописан", "1000" not in _уступка, _уступка[:60])
chk("уступка: тег stage4_concession", "stage4_concession" in _т1, str(_т1))

_обычн, _т2 = p.enforce_callouts(
    "Выезд для вас будет бесплатным при выполнении работ",
    "сколько стоит выезд? принтер не печатает", prior_bot_text="", direction="kp")
chk("обычный вопрос: 1000 дописан как раньше", "1000" in _обычн, _обычн[:70])
chk("обычный вопрос: тег visit_fee_fix", "visit_fee_fix" in _т2, str(_т2))

_дыра, _т3 = p.enforce_callouts(
    "Сделаю для вас бесплатный выезд",
    "сколько стоит выезд? не печатает принтер", prior_bot_text="", direction="kp")
chk("СТАРАЯ ДЫРА: «бесплатный выезд» (обратный порядок) теперь тоже с 1000",
    "1000" in _дыра, _дыра[:70])

# сомнение из НАЧАЛА диалога не должно вечно выключать озвучку условий
_поздн, _т4 = p.enforce_callouts(
    "Выезд будет бесплатным при выполнении работ",
    "что-то дорого\nладно, а выезд почём? принтер не печатает",
    prior_bot_text="ремонт от 3000", direction="kp")
chk("сомнение в НАЧАЛЕ речи не даёт уступку на позднем ходе",
    "1000" in _поздн, _поздн[:70])

print("── ПРОМПТ ───────────────────────────────────────────────────────")
_ПР = io.open(os.path.join(КОРЕНЬ, "brain", "prompt.py"), encoding="utf-8").read()
chk("сценарий 4-го этапа записан", "4-Й ЭТАП — КЛИЕНТ СОМНЕВАЕТСЯ ПОСЛЕ ЦЕНЫ" in _ПР)
chk("сначала вопрос «что смущает»", "А что именно вас не устроило?" in _ПР)
chk("финал без дожима", "если\n    что-то поменяется или потребуется помощь, напишите" in _ПР
    or "что-то поменяется или потребуется помощь" in _ПР)

print("=" * 50)
print("4-й этап возражений (30.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
