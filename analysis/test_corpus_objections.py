ПОРЯДОК = ("check_complaint", "check_refuse", "check_existing_client",
           "check_call_request", "troll_exit", "check_soglasovanie", "check_junk")


def маршрут(текст, история_бота="", вся_речь=None, был_контент=False):
    """Куда уйдёт реплика ДО модели: имя роутера или «К МОДЕЛИ»."""
    вся = вся_речь if вся_речь is not None else текст
    if p.check_complaint(текст):
        return "жалоба"
    r = p.check_refuse(текст)
    if r:
        return "отказ:" + str(r.get("sub"))
    if p.check_existing_client(текст, bot_history=история_бота, all_client_text=вся):
        return "уже-наш-клиент"
    if p.check_call_request(текст, all_client_text=вся):
        return "звонок"
    if p.troll_exit([текст]):
        return "троллинг"
    s = p.check_soglasovanie(текст)
    if s:
        return "соглас:" + str(s.get("sub"))
    j = p.check_junk(текст, prior_client_content=был_контент)
    if j:
        return "мусор:" + j["sub"]
    return "К МОДЕЛИ"


def _боевой_порядок():
    исходник = open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
    # ⚠ ЧИТАЕМ ФУНКЦИЮ ЦЕЛИКОМ, А НЕ 12 000 ЗНАКОВ (26.08). Окно в байтах — хрупкая
    # мерка: сегодня в `_run_relay_inner` добавилось объяснений, `check_junk` уехал за
    # границу окна, и тест объявил, что роутера в бою нет. Он был на месте.
    # Границей берём следующее определение верхнего уровня — она не зависит от того,
    # сколько комментариев кто-то написал внутри.
    начало = исходник.index("def _run_relay_inner(")
    хвост = исходник[начало + 1:]
    конец = хвост.find("\ndef ")
    кусок = хвост[:конец] if конец > 0 else хвост
    найдено = []
    for имя in re.findall(r"\b(check_\w+|troll_exit)\s*\(", кусок):
        if имя in ПОРЯДОК and имя not in найдено:
            найдено.append(имя)
    return tuple(найдено)


проверка("порядок роутеров в тесте совпадает с боевым", _боевой_порядок(), ПОРЯДОК)


