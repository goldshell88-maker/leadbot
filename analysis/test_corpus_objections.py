# 3. НОЧЬ ПО ЧАСАМ ГОРОДА КЛИЕНТА (23:00–07:00)
# ──────────────────────────────────────────────────────────────────────────────
_ЖИВЫЕ_ЧАСЫ = territory.city_localtime
_ЖИВОЙ_LOCALTIME = time.localtime

# Города всех поясов сети: от Калининграда (UTC+2) до Камчатки (UTC+12).
# ⚠ Взяты только те, где филиал есть на БТ, — иначе окна нет вовсе (сверка с филиалом),
# и проверять «сегодня/завтра» не на чем. Якутск и Камчатка сюда не годятся именно поэтому.
ГОРОДА = ["Калининград", "Москва", "Самара", "Екатеринбург", "Омск",
          "Красноярск", "Иркутск", "Владивосток", "Южно-Сахалинск"]


def _в_час_города(город, ч, мин=30, дата=(2026, 8, 13)):
    """Момент UTC, в который МЕСТНОЕ время ЭТОГО города равно ч:мин.

    ⚠ Не «час в Москве», как в прежнем тесте: там сдвиг города прибавлялся сверху и
    Владивосток проверялся на 13:30, а не на 03:30. Считаем от пояса самого города.
    """
    сдвиг = territory.city_tz_offset(город)
    return calendar.timegm((дата[0], дата[1], дата[2], ч - сдвиг, мин, 0, 0, 0, -1))


def _окно(город, ч, серверные_часы_врут=False):
    """Окно, которое воронка предложит клиенту этого города в этот его час."""
    метка = _в_час_города(город, ч)
    territory.city_localtime = lambda c="", now=None, _t=метка: _ЖИВЫЕ_ЧАСЫ(c, _t)
    if серверные_часы_врут:
        # серверу «полдень пятницы» — на ответ это влиять не должно
        time.localtime = lambda *a, **k: time.gmtime(calendar.timegm(
            (2026, 8, 14, 12, 0, 0, 0, 0, -1)))
    try:
        return server._slot_offer(город, False, "", "bt", "")
    finally:
        territory.city_localtime = _ЖИВЫЕ_ЧАСЫ
        time.localtime = _ЖИВОЙ_LOCALTIME


def _день_правила(город, ч):
    """Какой день назван в блоке часов, который читает модель."""
    метка = _в_час_города(город, ч)
    territory.city_localtime = lambda c="", now=None, _t=метка: _ЖИВЫЕ_ЧАСЫ(c, _t)
    try:
        нота = server._clock_note(city=город, direction="bt")
    finally:
        territory.city_localtime = _ЖИВЫЕ_ЧАСЫ
    m = re.search(r"окно: «(\w+) к ([\d:\-]+)»", нота)
    return (m.group(1), m.group(2)) if m else ("(окна нет)", "")


def _час_в_шапке(город, ч):
    метка = _в_час_города(город, ч)
    territory.city_localtime = lambda c="", now=None, _t=метка: _ЖИВЫЕ_ЧАСЫ(c, _t)
    try:
        нота = server._clock_note(city=город, direction="bt")
    finally:
        territory.city_localtime = _ЖИВЫЕ_ЧАСЫ
    m = re.search(r"СЕЙЧАС у клиента: \S+, (\d\d):\d\d", нота)
    return m.group(1) if m else "??"


for _г in ГОРОДА:
    # 23:00 — сутки ещё вчерашние, ближайший приём завтра утром.
    проверка("%s 23:30 → завтра" % _г, _окно(_г, 23), "завтра к 10:00-10:30")
    # После полуночи «завтра» промахивается ровно на сутки: мастер выезжает СЕГОДНЯ.
    for _ч in (0, 3, 6):
        проверка("%s %02d:30 → сегодня" % (_г, _ч), _окно(_г, _ч), "сегодня к 10:00-10:30")
    # Граница ночи и утра: 07:00 — уже утро, но до 10:00 окно то же.
    проверка("%s 07:30 → сегодня" % _г, _окно(_г, 7), "сегодня к 10:00-10:30")
    # Днём ночного правила быть не должно вовсе.
    проверка("%s 14:30 → ближайшее" % _г, _окно(_г, 14), "через час-полтора")
    # Тот же счёт в блоке часов для модели — правило и воронка не должны расходиться.
    проверка("%s правило 23:30" % _г, _день_правила(_г, 23), ("завтра", "10:00-10:30"))
    проверка("%s правило 03:30" % _г, _день_правила(_г, 3), ("сегодня", "10:00-10:30"))
    # Час в шапке — местный, а не серверный.
    проверка("%s шапка 03:30" % _г, _час_в_шапке(_г, 3), "03")
    # ⚠ ГЛАВНОЕ: серверные часы на ответ не влияют. Подмени их — ответ обязан не дрогнуть.
    проверка("%s 03:30 не зависит от часов сервера" % _г,
             _окно(_г, 3, серверные_часы_врут=True), "сегодня к 10:00-10:30")
    проверка("%s 23:30 не зависит от часов сервера" % _г,
             _окно(_г, 23, серверные_часы_врут=True), "завтра к 10:00-10:30")

# ⚠ РАЗНЫЕ ПОЯСА В ОДНУ И ТУ ЖЕ СЕКУНДУ. Один момент времени — 18:00 UTC 13 августа:
# в Калининграде 20:00 (поздний вечер), во Владивостоке уже 04:00 следующего дня (ночь).
# Ответ обязан различаться, иначе «часы города» существуют только на бумаге.
_один_момент = calendar.timegm((2026, 8, 13, 18, 0, 0, 0, 0, -1))
territory.city_localtime = lambda c="", now=None, _t=_один_момент: _ЖИВЫЕ_ЧАСЫ(c, _t)
try:
    _клг = territory.city_localtime("Калининград").tm_hour
    _влд = territory.city_localtime("Владивосток").tm_hour
    _окно_клг = server._slot_offer("Калининград", False, "", "bt", "")
    _окно_влд = server._slot_offer("Владивосток", False, "", "bt", "")
finally:
    territory.city_localtime = _ЖИВЫЕ_ЧАСЫ
проверка("в один момент Калининград 20:00", _клг, 20)
проверка("в один момент Владивосток 04:00", _влд, 4)
проверка("Владивосток в этот момент — ночное окно", _окно_влд, "сегодня к 10:00-10:30")
проверка("Калининград в этот момент — не ночное", _окно_влд == _окно_клг, False)


