# -*- coding: utf-8 -*-
"""ПАЧКА 2 «стиль и логика победителей» (Э4, 21.08; банк фраз из 3391 успешного диалога
+ аудит 924 живых подсказок; решения владельца В-024/В-025 и «сделай как лучше»).

  1. Телефон со ВТОРОГО ответа доведён до стадий: порог ранней стадии bot_turns<1
     (рассинхрон: промпт ред.19.08, а стадии держали <2 — просьба уезжала на 3-й ход).
  2. Санитайзер «записал» подставляет ЖИВЫЕ замены («буду у вас», «подъеду») —
     прежние «принял,»/«поставлю»/«могу к вам» имеют 0/0/11 вхождений в корпусе.
  3. Приветствие мусорного фильтра — короткое, один вопрос (было 83 символа, два вопроса,
     59 дословных повторов в бою).
  4. СТАДИЯ ВХОД без диагноза-гипотезы (у победителей 0 из 300) и с зеркалом приветствия.
  5. Открытая форма слота разрешена ВТОРОЙ (В-025): гард не давит «когда удобно?»
     на повторном предложении времени.
Запуск: python3 analysis/test_batch2.py  (0 токенов)
"""
import io
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "brain"))
import server      # noqa: E402
import prefilter   # noqa: E402

ok = bad = 0


def chk(label, cond):
    global ok, bad
    if cond:
        ok += 1
    else:
        bad += 1
        print("✗", label)


SRC = io.open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                           "brain", "server.py"), encoding="utf-8").read()

# 1. порог ранней стадии: bot_turns < 1 (в трёх местах телефонной логики)
chk("порог стадий: не осталось bot_turns < 2 в телефонной логике",
    len(re.findall(r"bot_turns < 2", SRC)) == 0)
chk("порог стадий: bot_turns < 1 появился", "bot_turns < 1" in SRC)

# 2. санитайзер — живые замены
for вход, ждём_куски, нельзя in [
    ("Хорошо, записал вас на завтра к 14:00", ["буду у вас", "завтра к 14:00"], ["принял", "поставлю", "записал"]),
    # ⚠ РЕШЕНИЕ ИЗМЕНЕНО 30.08 (аудит): «запишу вас на …» — легальное БУДУЩЕЕ время,
    # сильнейший приём замера 27.08 (+35,9 п.п.); глушится только СВЕРШИВШЕЕСЯ «записал».
    ("Запишу вас на 10:00-10:30", ["Запишу вас", "10:00-10:30"], ["поставлю", "записал вас"]),
    ("Записал вас, до встречи", ["до встречи"], ["принял", "записал"]),
]:
    out = server._soften_booking(вход)
    chk("софтен: «%s» → живое" % вход[:30],
        all(k.lower() in out.lower() for k in ждём_куски)
        and not any(n.lower() in out.lower() for n in нельзя))

# 3. приветствие мусорного фильтра
привет = prefilter.JUNK_REPLIES.get("greet_only", "") if hasattr(prefilter, "JUNK_REPLIES") else ""
if not привет:  # структура может отличаться — ищем по исходнику
    привет = [l for l in io.open(os.path.join(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))), "brain", "prefilter.py"), encoding="utf-8")
        if "greet_only" in l]
    привет = привет[0] if привет else ""
chk("приветствие: короткое, один вопрос", "что посмотреть или отремонтировать" not in str(привет))

# 4. стадия ВХОД: без диагноза-гипотезы, с зеркалом приветствия
chk("ВХОД: диагноз-гипотеза убран", "похоже насос" not in SRC)
chk("ВХОД: зеркало приветствия", "клиент без приветствия" in SRC or "не поздоровался" in SRC)

# 5. открытая форма второй: гард пропускает не-первое предложение времени
проба = "Вам когда удобно?"
out2 = server._offer_instead_of_open_time(проба, "через час-полтора", has_addr=True,
                                          first=False, offered_before=True)
chk("слот: открытая форма разрешена ВТОРОЙ (окно уже звучало, В-025)", out2 == проба)
out3 = server._offer_instead_of_open_time(проба, "через час-полтора", has_addr=True,
                                          first=False, offered_before=False)
chk("слот: первое предложение времени — только окном", out3 != проба and "час-полтора" in out3)

print("\nИТОГО: %d ок, %d провал" % (ok, bad))
sys.exit(1 if bad else 0)
