# -*- coding: utf-8 -*-
"""ЗАСЛОН «НЕ НАШ ДИАЛОГ» СЧИТАЛ СВОИ СОБСТВЕННЫЕ РЕПЛИКИ ЧУЖИМИ.

ВЛАДЕЛЕЦ 26.08 со снимком диалога (Мария, Чита, партнёр 7): «почему он не создал,
он ведь договорился». В диалоге к этой секунде было ВСЁ:

    22:16 бот    : Здравствуйте / берусь. Какая марка и модель?
    22:22 бот    : Ну что, расскажете, что случилось?
    22:46 клиент : Модель я не знаю, исчезло изображение...
    22:48 бот    : Понял. Звук есть, а картинки нет? Завтра к 10:00-10:30 подъеду,
                   скажите адрес / Скиньте номерок для связи
    22:50 клиент : Хорошо. Садовая 12 кв 45, <телефон> меня зовут Мария.
    22:51 клиент : Хорошо?
    22:53 БОТ ПЕРЕДАЛ ДИАЛОГ МЕНЕДЖЕРУ

Телефон, адрес и согласованное время — заявка на 100 % по правилу владельца. Заявка не
создалась не потому, что её нечем было собрать, а потому, что ХОДА НЕ БЫЛО ВООБЩЕ.

ЧТО ПОКАЗАЛ БОЕВОЙ ЖУРНАЛ (12:53:14 UTC = 22:53 в Чите):
    {"layer": "локальный роутер (не наш диалог)", "confidence": 0.0,
     "flag": {"kind": "not_primary",
              "reason": "не первичный: оператор уже ведёт разговор (3 ходов)"}}

Тех «3 ходов оператора» не было. Это три реплики САМОГО БОТА. Заслон считал
`role == "operator"`, а панель отдаёт свои же ответы той же ролью, что и человека.

МАСШТАБ (боевая база и журнал за 7 дней):
    ходов ушло человеку с причиной not_primary   311 из 1436   (21,7 %)
    диалогов, где бот написал 3+ раза            518
    из них человек не написал НИ РАЗУ            517

Заслон сам по себе правильный (владелец 25.08: «бот должен работать только с первичными
диалогами», 65 % ходов были влезанием в чужой разговор) — считал он не то.

Запуск: uv run python analysis/test_ne_nash_dialog_2608.py
Офлайн, 0 токенов (роутер, модель не зовётся).
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import leadchat as lc                                   # noqa: E402
import server as s                                      # noqa: E402

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:110]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


def норм(пары):
    """Пары («кто», «текст») → то, что видит заслон. «бот» — наш ответ, «оператор» — человек."""
    return s._cap_input([
        {"role": "client" if кто == "клиент" else "operator", "text": т, "свой": кто == "бот"}
        for кто, т in пары
    ])


print("\n1. СНИМОК ВЛАДЕЛЬЦА: три реплики бота — это не «оператор ведёт разговор»")
снимок = [
    ("бот", "Здравствуйте\nберусь. Какая марка и модель?"),
    ("бот", "Ну что, расскажете, что случилось?"),
    ("клиент", "Модель я не знаю, исчезло изображение..."),
    ("бот", "Понял. Звук есть, а картинки нет? Завтра к 10:00-10:30 подъеду, скажите адрес"),
    ("клиент", "Хорошо. Садовая 12 кв 45, 89001112253 меня зовут Мария."),
    ("клиент", "Хорошо?"),
]
проверь("бот не молчит в диалоге, который ведёт сам", s._молчать_почему(норм(снимок)) == "",
        s._молчать_почему(норм(снимок)))

print("\n2. ЗАСЛОН НА МЕСТЕ: где разговор реально ведёт человек — бот молчит")
чужой = [
    ("клиент", "Здравствуйте, телевизор не включается"),
    ("оператор", "Здравствуйте! Сейчас гляну по мастерам"),
    ("клиент", "Хорошо"),
    ("оператор", "Мастер сможет завтра к 12"),
    ("оператор", "Адрес подскажете?"),
    ("клиент", "Ленина 5"),
]
проверь("в чужом разговоре бот по-прежнему не вмешивается",
        "не первичный" in s._молчать_почему(норм(чужой)), s._молчать_почему(норм(чужой)))

print("\n3. СМЕШАННЫЙ ДИАЛОГ: человек подключился к тому, что вёл бот")
смешанный = [
    ("клиент", "телевизор не включается"),
    ("бот", "берусь, какая марка?"),
    ("бот", "Завтра к 10 подъеду, адрес скажите"),
    ("бот", "Скиньте номерок"),
    ("оператор", "Здравствуйте, я подключусь"),
    ("оператор", "Мастер будет завтра"),
    ("оператор", "Ждите звонка"),
    ("клиент", "хорошо"),
]
проверь("трое ходов ЧЕЛОВЕКА заслон видит и уступает",
        "не первичный" in s._молчать_почему(норм(смешанный)), s._молчать_почему(норм(смешанный)))

print("\n4. РАЗБОР ЗАПРОСА ПАНЕЛИ: поле `by` доносит автора")
тело = {"dialog": [
    {"role": "user", "content": "телевизор не включается"},
    {"role": "assistant", "content": "берусь, какая марка?", "by": "bot"},
    {"role": "assistant", "content": "я подключусь, это оператор", "by": "operator"},
]}
разобрано, _ = lc.parse_request(тело)[:2] if isinstance(lc.parse_request(тело), tuple) else (lc.parse_request(тело), None)
свои = [m for m in разобрано if m.get("свой")]
проверь("реплика бота помечена своей", len(свои) == 1 and "какая марка" in свои[0]["text"], свои)
проверь("реплика человека своей НЕ помечена",
        not any(m.get("свой") for m in разобрано if "подключусь" in m["text"]))

print("\n5. СТАРАЯ ПАНЕЛЬ БЕЗ `by` — ведём себя как раньше, а не падаем")
тело_старое = {"dialog": [
    {"role": "user", "content": "телевизор не включается"},
    {"role": "assistant", "content": "берусь, какая марка?"},
]}
старое = lc.parse_request(тело_старое)
старое = старое[0] if isinstance(старое, tuple) else старое
проверь("разбор не падает без поля `by`", len(старое) == 2, старое)
проверь("без `by` реплика считается операторской (осторожная сторона)",
        not any(m.get("свой") for m in старое))

print("\n6. СТАРЫЕ ВЫЗОВЫ (Пульт, автоканал): без пометки заслон работает как раньше")
пульт = [("клиент", "повесить полку"), ("оператор", "здравствуйте"), ("клиент", "да"),
         ("оператор", "куда подъехать?"), ("клиент", "мира 5"), ("оператор", "буду"),
         ("клиент", "хорошо")]
без_пометки = [{"role": м["role"], "text": м["text"]} for м in норм(пульт)]
проверь("без пометки реплика считается операторской, заслон срабатывает",
        "не первичный" in s._молчать_почему(s._cap_input(без_пометки)),
        s._молчать_почему(s._cap_input(без_пометки)))

print("\n7. ПРОВОДКА")
исходник = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
проверь("заслон считает ходы человека, а не все подряд",
        'if m["role"] == "operator" and not m.get("свой")' in исходник)
проверь("`свой` доживает до заслона через обрезку истории",
        '"свой": bool(m.get("свой"))' in исходник)
разбор = io.open(os.path.join(КОРЕНЬ, "brain", "leadchat.py"), encoding="utf-8").read()
проверь("разбор запроса читает поле `by`", 'item.get("by")' in разбор)

print("\n" + "─" * 60)
print("проверок: %d, провалов: %d" % (всего[0], len(ошибки)))
for о in ошибки:
    print("  ПРОВАЛ:", о)
sys.exit(1 if ошибки else 0)
