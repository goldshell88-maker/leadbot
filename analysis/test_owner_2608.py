# -*- coding: utf-8 -*-
"""Три боевых правки со снимков владельца 26.08 (ночь).

1. ПОСЛЕДНИЙ СЛОТ ОБЕЩАЕТСЯ, ТОЛЬКО ЕСЛИ ДО НЕГО МОЖНО ДОЕХАТЬ.
   Снимок: Энгельс, у клиента 21:27, бот пишет «Сегодня к 21:30 подъеду». Приём до
   21:30 формально открыт — и ветка последнего слота спрашивала ровно это. Но дорога
   занимает час, и обещание было невыполнимо в момент произнесения.
   Владелец формулировал правило точнее: «самое позднее время, на которое мы можем
   принять заявку, — 21:30, ТО ЕСТЬ если в городе 20:30, мы можем принять на 21:30».
   Значит условий два: приём открыт И осталась минимальная дорога.

2. НАВЕС ТЕЛЕВИЗОРА — МЕЛКАЯ РАБОТА, БЕЗ СОГЛАСОВАНИЯ.
   Снимок: «повесить телевизор диагональю 49 на стену» → бот ушёл в «сверюсь по
   графику и чуть позже дам ответ», то есть отдал человеку простую работу на первичном
   обращении. Владелец, раздел «Мелкие работы»: «Установка ЛЮБЫХ кронштейнов (для
   телевизора, бойлера и т.д.); установка настенных и потолочных гардин. Можно принять
   без согласования».

⚠ ВЕРХНЯЯ И НИЖНЯЯ ГРАНИЦЫ СРОКА ОТВЕЧАЮТ НА РАЗНЫЕ ВОПРОСЫ. Верхняя — «что я обещаю»
(в худшем случае доеду за полтора часа), нижняя — «успею ли физически вообще». Раньше
была только верхняя, и вопрос «успею ли» никто не задавал.

Запуск: uv run python analysis/test_owner_2608.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter                                        # noqa: E402
import server as s                                      # noqa: E402

ошибки = []


def проверь(имя, условие, чем=""):
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:70]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


class Час:
    def __init__(self, ч, м):
        self.tm_hour, self.tm_min = ч, м


print("1. последний слот — только когда до него можно доехать")
для = [((21, 27), False, "снимок владельца: Энгельс, 21:27"),
       ((20, 45), False, "45 минут до 21:30, дорога час"),
       ((20, 30), True, "ровно пример владельца: в городе 20:30"),
       ((19, 0), True, "два с половиной часа в запасе"),
       ((10, 0), True, "утро")]
for (ч, м), ждём, почему in для:
    got = s._успеем_к(Час(ч, м), "час-полтора", "21:30")
    проверь("%02d:%02d → %s (%s)" % (ч, м, "успеем" if ждём else "не успеем", почему),
            got is ждём, got)
проверь("непонятный срок не решает за нас",
        s._успеем_к(Час(20, 0), "как получится", "21:30") is None)

print("   и то же самое через воронку целиком")
_окно_2127 = s._slot_offer("Энгельс", False, "телевизор не работает", "кп", "")
проверь("в 21:27 бот не зовёт на «сегодня к 21:30»",
        "21:30" not in (_окно_2127 or "") or "завтра" in (_окно_2127 or ""),
        "окно сейчас: %r (проверка идёт по РЕАЛЬНОМУ времени в Энгельсе)" % _окно_2127)

print("2. мелкие работы принимаются без согласования")
МЕЛКИЕ = ["Мне нужно повесить телевизор диагональю 49 на стену",
          "Повесить телевизор на гипсокартон",
          "Установить кронштейн для телевизора",
          "Установить кронштейн для бойлера",
          "Повесить гардину на стену",
          "Установка потолочного карниза",
          "Навесить полку и картину"]
for т in МЕЛКИЕ:
    проверь("без согласования: %s" % т[:44], prefilter.soglas_topic(т) is None,
            prefilter.soglas_topic(т))
    проверь("и шаблон не перехватывает: %s" % т[:36],
            (prefilter.check_soglasovanie(т) or {}).get("kind") is None)

print("   а настоящие согласуемые темы остались согласуемыми")
for т, ждём in (("Разблокировать iCloud, пароль не помню", True),
                ("Прошить ТВ-приставку", True),
                ("Замена стояка отопления", True)):
    есть = prefilter.soglas_topic(т) is not None
    проверь("согласование осталось: %s" % т[:40], есть is ждём, prefilter.soglas_topic(т))

print("3. телевизор с дефектом картинки — сначала анамнез")
KR = {"visitor": "", "city": "Новокуйбышевск", "direction": "кп", "title": "Ремонт телевизоров"}
ТВ = [{"role": "client", "text": "Здравствуйте, можете помочь с ремонтом телевизора LG?"},
      {"role": "operator", "text": "Здравствуйте а что с ним"},
      {"role": "client", "text": "Потемнело половина экрана, не совсем черный, "
                                 "видно картинку, но с затемнением"}]


def ответ(reply, msgs):
    out, *_ = s._postprocess_reply(reply, msgs, dict(KR), {}, False)
    return out or ""


_a = ответ("Похоже на подсветку, гляну на месте.", ТВ)
проверь("спрошен анамнез: не били, не роняли, влага",
        bool(s._ТВ_АНАМНЕЗ_СПРОШЕН_RX.search(_a)), _a)
проверь("и номер в ту же реплику НЕ добирается (не анкета)",
        not s._PHONE_ASK_RX.search(_a), _a)
# ⚠ СЧИТАЕМ ВОПРОСЫ-СТРОКИ, А НЕ ЗНАКИ «?». «Ударов, падений не было? Влага не
# попадала?» — это ОДНО уточнение, сказанное так, как говорит живой мастер: одним
# выдохом, двумя короткими вопросами. Счёт по «?» объявил бы это тремя вопросами и
# заставил бы дробить естественную речь.
_строк_с_вопросом = sum(1 for x in _a.split("\n") if "?" in x)
проверь("вопросов-строк в реплике не больше двух", _строк_с_вопросом <= 2,
        "%d строк: %r" % (_строк_с_вопросом, _a))

_b = ответ("Гляну на месте.", ТВ[:2] + [{"role": "client",
           "text": "Потемнело половина экрана, не роняли, не били"}])
проверь("клиент сам сказал — не переспрашиваем",
        not s._ТВ_АНАМНЕЗ_СПРОШЕН_RX.search(_b), _b)

_c = ответ("Гляну на месте.", ТВ[:2] + [{"role": "client",
           "text": "Телевизор не переключает каналы"}])
проверь("дефекта картинки нет — анамнез не навязываем",
        not s._ТВ_АНАМНЕЗ_СПРОШЕН_RX.search(_c), _c)

_d = ответ("Гляну на месте.", [{"role": "client", "text": "Стиралка не отжимает"},
                               {"role": "operator", "text": "здравствуйте, что случилось?"},
                               {"role": "client", "text": "Не отжимает совсем"}])
проверь("не телевизор — анамнез не спрашиваем",
        not s._ТВ_АНАМНЕЗ_СПРОШЕН_RX.search(_d), _d)

print()
if ошибки:
    print("ПРОВАЛЕНО: %d" % len(ошибки))
    for e in ошибки:
        print("  -", e)
    sys.exit(1)
print("Все проверки пройдены")
