print("── М. «ЗАПИШУ ВАС?» РАЗРЕШЕНО, «ЗАПИСАЛ ВАС» — НЕТ ─────────────")
# Замер 27.08 по 40 660 ходам мастеров, где клиент ещё не дал ни адреса, ни номера:
#   «запишу вас на 15:00-15:30, удобно?» → данные в 76,2 % (+35,9 п.п.)
