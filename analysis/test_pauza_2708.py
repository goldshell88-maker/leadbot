import io as _io
_промпт = _io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "brain", "prompt.py"), encoding="utf-8").read()
# ⚠ ИЩЕМ РАЗРЕШАЮЩУЮ СТРОКУ, А НЕ ЛЮБОЕ УПОМИНАНИЕ. Первая версия искала саму формулу
