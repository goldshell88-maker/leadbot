проверить("промпт разрешает «запишу вас» как предложение",
          "✓ так: «запишу вас на 15:00-15:30, удобно?»" in _промпт)
проверить("промпт по-прежнему запрещает свершившийся факт",
          "«записал», «вы записаны», «заявка оформлена»" in _промпт)
проверить("прежней формулировки «корень запис- из лексикона убран» больше нет",
          "корень «запис-» ИЗ ЛЕКСИКОНА УБРАНЫ" not in _промпт)
# и детерминированный срез квитирования не трогает предложение
# ⚠ ПРОБА ПОДОБРАНА ТАК, ЧТОБЫ РАЗЛИЧАТЬ ФОРМЫ. «Запишу вас на 15:00…» не срезается ничем
# просто потому, что после «Запишу» нет запятой, — такая проба гард не проверяет вовсе.
