#   ход без того и другого               → 40,3 %          база
# Разница больше, чем у любого другого приёма в тексте реплики. Решение владельца
# 12.08 верно по сути («утверждать запись нельзя, предлагать можно и нужно»), но
# формулировка «корень запис- убран из лексикона» была шире смысла и убила предложение:
