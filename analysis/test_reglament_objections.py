out = os.path.join(HERE, "test_reglament_objections.md")
recs = []
f = open(out, "w", encoding="utf-8")
f.write("# Стресс-тест: регламент + возражения\n\n")

def run_case(prefix, title, d, turns, expect, section):
    did = "%s_%s" % (prefix, abs(hash(title)) % 100000)
    last = None
    convo = []
    for t in turns:
        last = server.run_turn(did, t, known=kn(d))
        rep = last.get("reply") or ("(пусто→оператору)" if last.get("to_operator") else "(пусто)")
        fl = []
        if last.get("handoff"): fl.append("handoff")
        if last.get("deflect"): fl.append("локальный отказ")
        convo.append((t, rep, ",".join(fl) or "—"))
    return {"section": section, "title": title, "dir": d, "expect": expect, "convo": convo}

print("=== РЕГЛАМЕНТ ===")
f.write("## Знание регламента\n\n")
for title, d, turns, expect in REGLAMENT:
    r = run_case("R", title, d, turns, expect, "reglament")
    recs.append(r)
    f.write("**%s** (%s) · эталон: _%s_\n\n" % (title, d.upper(), expect))
    for t, rep, fl in r["convo"]:
        f.write("- К: %s\n- Б: %s  [%s]\n" % (t, rep, fl))
    f.write("\n")
    print("• %s → %s [%s]" % (title, r["convo"][-1][1], r["convo"][-1][2]))

print("\n=== ВОЗРАЖЕНИЯ ===")
f.write("## Отработка возражений\n\n")
for title, d, turns, expect in OBJECTIONS:
    r = run_case("O", title, d, turns, expect, "objection")
    recs.append(r)
    f.write("**%s** (%s) · эталон: _%s_\n\n" % (title, d.upper(), expect))
    for t, rep, fl in r["convo"]:
        f.write("- К: %s\n- Б: %s  [%s]\n" % (t, rep, fl))
    f.write("\n")
    print("• %s → %s" % (title, r["convo"][-1][1]))

f.close()
