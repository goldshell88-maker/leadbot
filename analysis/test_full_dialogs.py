def ask(hist, kn):
    for att in range(5):
        try:
            return server.run_relay(hist, known=kn)
        except Exception as ex:
            if any(s in str(ex) for s in ("529", "429")) or "overload" in str(ex).lower():
                time.sleep(15 * (att + 1))
                continue
            raise
    raise RuntimeError("API перегружен")


def whole_dialog(rows):
    """Сквозные правила, общие для ЛЮБОГО диалога. Возвращает список нарушений."""
    bad = []
    greets = sum(1 for r in rows if re.match(r"\s*(здравствуйте|добрый|доброе|привет)",
                                             (r["bot"] or "").lower()))
    if greets > 1:
        bad.append("здоровается %d раз за диалог" % greets)
    seen_client = ""
    for i, r in enumerate(rows):
        seen_client += " " + r["client"]
        bot = r["bot"] or ""
        if not bot.strip():
            continue
        if re.search(LOGIST, bot.lower()) and not prefilter.problem_stated(seen_client):
            bad.append("ход %d: зовёт на выезд до названной поломки" % (i + 1))
        if re.search(CANNED, bot.lower()) and not prefilter.check_soglasovanie(r["client"]) \
                and not prefilter.check_refuse(r["client"]):
            bad.append("ход %d: заготовка сверки не по теме" % (i + 1))
        if re.match(r"^(понял|поняла|понимаю),\s*\w+\s+(не |при )", bot.lower()):
            bad.append("ход %d: эхо проблемы клиента" % (i + 1))
        prev = rows[i - 1]["client"] if i else ""
        charity = re.search(CHARITY, (r["client"] + " " + prev).lower())
        if "?" not in bot and not charity \
                and not re.search(BOOKED + r"|всего доброго|обраща|" + ASKING, bot.lower()):
            bad.append("ход %d: ни вопроса, ни финала — воронка встала" % (i + 1))
    return bad


def main():
    results, checks, passed, dialogs_ok = [], 0, 0, 0
    for sid, kn_extra, turns in SCEN:
        kn = dict({"visitor": "Клиент"}, **kn_extra)
        hist, rows = [], []
        for text, must, must_not, what in turns:
            hist.append({"role": "client", "text": text})
            r = ask(hist, kn)
            reply = (r.get("reply") or "").strip()
            rows.append({"client": text, "bot": reply, "handoff": bool(r.get("handoff")),
                         "what": what, "must": must, "must_not": must_not})
            hist.append({"role": "bot", "text": reply or "(молчание)"})

        print("\n" + "═" * 74)
        print("  %s" % sid)
        print("═" * 74)
        fails = []
        for row in rows:
            low = (row["bot"] or "").lower()
            ok = True
            if row["must"] and not re.search(row["must"], low):
                ok = False
            if row["must_not"] and re.search(row["must_not"], low):
                ok = False
            checks += 1
            passed += int(ok)
            if not ok:
                fails.append(row["what"])
            print("  Клиент: %s" % row["client"])
            print("  Бот:    %s%s" % ((row["bot"] or "(молчит)").replace("\n", "\n          "),
                                      "   ⚑ оператору" if row["handoff"] else ""))
            print("          %s %s" % ("✓" if ok else "✗", row["what"]))
            print()
        cross = whole_dialog(rows)
        checks += 1
        if cross:
            fails.extend(cross)
            print("  ✗ сквозные правила: %s" % "; ".join(cross))
        else:
            passed += 1
            print("  ✓ сквозные правила диалога соблюдены")
        dialogs_ok += int(not fails)
        results.append({"id": sid, "rows": rows, "cross": cross})

    out = os.path.join(HERE, "_full_dialogs_results.jsonl")
    with open(out, "w", encoding="utf-8") as f:
        for row in results:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print("\n" + "═" * 74)
    print("ПОЛНЫЕ ДИАЛОГИ: %d/%d проверок, безупречных диалогов %d из %d"
          % (passed, checks, dialogs_ok, len(SCEN)))


if __name__ == "__main__":
    main()
