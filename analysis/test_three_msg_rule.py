# -*- coding: utf-8 -*-
"""ПРАВИЛО ТРЁХ СООБЩЕНИЙ (регламент Авито, решение заказчика 15.08.2026).

«Сообщение, где вы просите номер или предлагаете созвониться, должно быть 3-4 по
счёту» — за раннюю настырность клиенты жалуются, Авито понижает аккаунт партнёра.

Офлайн, без модели и без шлюза: проверяется постобработка _postprocess_reply —
гард _drop_early_phone_ask, ранняя заглушка slot_offer и их исключения
(клиентская инициатива: сам дал данные, сам зовёт или торопит).
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "brain"))
import server as s  # noqa: E402

KR = {"visitor": "", "city": "Москва", "direction": "бт", "title": "Ремонт стиральных машин"}

# история до 2-го сообщения бота: клиент спокоен, данных не давал
MSGS_2 = [
    {"role": "client", "text": "Стиральная машина не отжимает"},
    {"role": "operator", "text": "Здравствуйте\nда, помогу. После чего началось?"},
    {"role": "client", "text": "После переезда началось"},
]
# история до 3-го сообщения бота: адрес уже дан
MSGS_3 = MSGS_2 + [
    {"role": "operator", "text": "Понял, похоже болты. Куда подъехать?"},
    {"role": "client", "text": "Ленинский проспект 5"},
]

CASES = [
    # (метка, реплика модели, история, first_bot, ожидание: номер в итоге есть/нет)
    # ⚠ ПЕРЕВЁРНУТО 19.08 РЕШЕНИЕМ ВЛАДЕЛЬЦА (вариант B): просьба номера разрешена со
    # ВТОРОГО ответа, если в реплике есть дело. Здесь дело названо («похоже
    # транспортировочные болты»), значит просьба законна. Первое касание по-прежнему
    # без логистики — это проверяется отдельно ниже.
    ("2-е сообщение с делом → просьба номера ЗАКОННА (решение 19.08)",
     "Понял, похоже транспортировочные болты. Напишите ваш номер телефона, запишу вас",
     MSGS_2, False, True),
    ("3-е сообщение → просьба номера законна",
     "Отлично. Могу сегодня к 17:00-17:30, удобно? И номер ваш подскажите",
     MSGS_3, False, True),
    # ⚠ ОЖИДАНИЕ ПЕРЕВЁРНУТО 26.08 ПРАВИЛОМ ВЛАДЕЛЬЦА, А НЕ ПРАВКОЙ ЭТОГО ПРАВИЛА.
    # Правило трёх сообщений про номер здесь ни при чём: реплика обещает ПРИЕЗД, а
    # адрес неизвестен — и «час-полтора» без адреса может оказаться невыполнимым
    # (клиент за чертой города). Поэтому вторым элементом идёт адрес, а номер уступает
    # ему место и добирается следующим ходом. Торопящемуся клиенту это тем более верно:
    # приехать без адреса нельзя вовсе.
    ("2-е сообщение, клиент ТОРОПИТ → адрес важнее номера (правило владельца 26.08)",
     "Могу подъехать сегодня. Напишите ваш номер телефона",
     # «не включается», а не «встала»: problem_stated разговорное «встала» поломкой не
     # считает, и реплику съел бы гард логистики — тест же проверяет правило трёх сообщений
     [{"role": "client", "text": "Машинка не включается, нужно сегодня!"},
      {"role": "operator", "text": "Здравствуйте\nда, помогу. Что за модель?"},
      {"role": "client", "text": "LG, вертикальная"}], False, False),
    # ...а когда адрес уже назван, номер к обещанию приезда добирается как и прежде
    ("2-е сообщение, адрес назван → номер к приезду добирается",
     "Могу подъехать сегодня. Напишите ваш номер телефона",
     [{"role": "client", "text": "Машинка не включается, нужно сегодня!"},
      {"role": "operator", "text": "Здравствуйте\nда, помогу. Что за модель?"},
      {"role": "client", "text": "LG вертикальная, адрес Ленина 12 кв 5"}], False, True),
    ("2-е сообщение, клиент сам просил ПОЗВОНИТЬ → не трогаем",
     "Хорошо, наберу. Номер ваш подскажите",
     [{"role": "client", "text": "Посудомойка течёт"},
      {"role": "operator", "text": "Здравствуйте\nда, помогу. Давно течёт?"},
      {"role": "client", "text": "Позвоните мне, обсудим"}], False, True),
    ("клиент сам дал номер в 1-м сообщении → реплика не трогается",
     "Понял. Могу сегодня к 15:00-15:30, наберу вас по номеру",
     [{"role": "client", "text": "Холодильник не морозит, телефон 89261234567, приезжайте"},
      {"role": "operator", "text": "Здравствуйте\nда, помогу. Давно началось?"},
      {"role": "client", "text": "Вчера"}], False, True),
    ("«номер дома» — не просьба телефона, не вырезается",
     "Понял вас. А номер дома какой у вас?",
     MSGS_2, False, True),
]

ok = bad = 0
for label, reply, msgs, first, want_phone in CASES:
    out, _enf, _hf, _lead = s._postprocess_reply(reply, msgs, dict(KR), {}, first)
    got_phone = "номер" in (out or "").lower()
    if got_phone == want_phone:
        ok += 1
    else:
        bad += 1
        print("✗", label)
        print("   реплика:", repr(reply))
        print("   итог:   ", repr(out))

# ── кейсы адверсариальной проверки 15.08 ──
import re as _re
hurry_yes = [
    "нужно сегодня, срочно!", "приезжайте сейчас", "когда сможете подъехать?",
    "затопило соседей, вода хлещет", "дверь захлопнулась, стою на площадке",
    "позвоните вечером", "как можно скорее, пожалуйста", "прямо сейчас можете?",
]
hurry_no = [
    "стиралка сегодня утром перестала отжимать",   # «сегодня» = анамнез, не спешка
    "скорее всего подшипник полетел",
    "сейчас скину фото шильдика",
    "только не сегодня, я на работе",
    "не срочно, на неделе бы",
    "Когда нужна услуга: Как можно скорее",        # шаблон анкеты Авито
    "во сколько обойдётся ремонт?",                # цена, не время
]
for t in hurry_yes:
    if s._client_hurry(t):
        ok += 1
    else:
        bad += 1
        print("✗ спешка НЕ поймана:", t)
for t in hurry_no:
    if not s._client_hurry(t):
        ok += 1
    else:
        bad += 1
        print("✗ ложная спешка:", t)

# канонная формула «номер и адрес» одним предложением: номер режется, адрес возвращается
out = s._drop_early_phone_ask(
    "Подшипник заменю, дело знакомое. Напишите ваш номер и адрес (улица, дом, квартира, "
    "подъезд), договоримся по времени, запишу вас.", 1, "стиралка гудит при отжиме", False)
if "номер" not in out.lower() and "адрес" in out.lower():
    ok += 1
else:
    bad += 1
    print("✗ канонная связка: ждали адрес без номера, итог:", repr(out))

# вся реплика — одна просьба номера: не возвращается нетронутой
out = s._drop_early_phone_ask(
    "Напишите ваш номер и адрес (улица, дом), договоримся по времени, запишу вас", 0,
    "собрать кухню надо", False)
if "номер" not in out.lower():
    ok += 1
else:
    bad += 1
    print("✗ однопредложенческая просьба уцелела:", repr(out))

# ⚠ ПЕРЕВЁРНУТО 19.08: на 2-м ответе автодобор номера — это и есть решение владельца.
# Клиент уже получил экспертизу первым ходом, реплика несёт шаг вперёд («куда подъехать»),
# значит просьба уместна. Проверяем, что она появляется РОВНО ОДИН раз.
msgs_a = [
    {"role": "client", "text": "Стиральная машина Bosch не отжимает"},
    {"role": "operator", "text": "Здравствуйте, да, помогу. После чего началось?"},
    {"role": "client", "text": "Да, давайте"},
]
out, *_ = s._postprocess_reply("Хорошо, запишемся. Куда подъехать?", msgs_a, dict(KR), {}, False)
_просьб = sum(1 for ч in re.split(r"(?<=[.!?])\s+|\n", out or "") if s.phone_asked(ч))
if _просьб == 1:
    ok += 1
else:
    bad += 1
    print("✗ просьб номера на 2-м ответе: %d (ждали 1): %r" % (_просьб, out))

# повторная просьба на СЛЕДУЮЩЕМ ходе вырезается — настырность запрещена регламентом
msgs_b = msgs_a + [
    {"role": "operator", "text": "Куда подъехать? И номер ваш подскажите"},
    {"role": "client", "text": "Ленина 5"},
]
out2, *_ = s._postprocess_reply("Спасибо, и номер телефона для связи?", msgs_b, dict(KR), {}, False)
if not s.phone_asked(out2 or ""):
    ok += 1
else:
    bad += 1
    print("✗ повторная просьба уцелела:", repr(out2))

# ⚠ ЭТА ПРОВЕРКА ТРЕБОВАЛА «АДРЕС, А НЕ ОКНО» — правило изменено владельцем 25.08
# («сделай так, как делают операторы»). Замер 30 428 живых диалогов: оператор ПРЕДЛОЖИЛ
# конкретное окно первым ходом — 37,0 % до заявки, СПРОСИЛ «когда вам удобно» — 15,8 %,
# не сделал ни того ни другого — 8,1 %. То есть плохо здесь именно ОТКРЫТЫЙ ВОПРОС;
# чем его заменят — адресом или конкретным окном, — данные не различают, и запрещать
# окно оснований нет.
# Настоящее правило, которое тут и охраняется: открытый «когда вам удобно» не уцелевает.
out, *_ = s._postprocess_reply(
    "Понял, посмотрю. Когда вам удобно?", MSGS_2, dict(KR), {}, False)
_открытый = re.search(r"(?i)когда\s+(?:вам\s+)?удобно|во\s+сколько|в\s+какое\s+время", out or "")
if not _открытый and (out or "").strip():
    ok += 1
else:
    bad += 1
    print("✗ открытый вопрос времени уцелел на раннем ходе")
    print("   итог:", repr(out))
# ⚠ ЗДЕСЬ Я СНАЧАЛА ДОБАВИЛ ПРОВЕРКУ «на раннем ходе номер не просим» И БЫЛ НЕПРАВ.
# Сверил с состоянием ДО своих правок: просьба номера на этом ходе стояла и раньше —
# это осознанное решение 19.08 («один элемент добрать номером МОЖНО и НУЖНО: после
# первой просьбы телефон приходит следующей репликой в 25,0 % против 1,2 %»), и оно
# опирается на замер. Правило Авито считает сообщения ДИАЛОГА, а это уже третье-четвёртое.
# Требование было выдумано мной, а не измерено, — и правильный ход тут убрать требование,
# а не гнуть под него код. Проверки просьбы номера остаются такими, какими были.

# ── ПОЛОМКА НАЗВАНА: ГАРД ЛОГИСТИКИ СМОТРИТ ИМЕННО СЮДА (находка 23.08) ──────
# Пока problem_stated говорит «нет», постобработка СРЕЗАЕТ вопросы адреса и времени
# и возвращает разговор к «что у вас случилось?». То есть промах здесь заставляет бота
# переспрашивать ровно то, что клиент уже сказал. Замер: 4 формы из 23 не опознавались.
for _t in ("не морозит", "стиралка течёт", "не включается", "барабан не крутит",
           "экран разбит", "экран треснул", "шумит при отжиме", "перестал холодить",
           "перестала работать", "гудит", "искрит розетка", "не греет воду",
           "духовка не нагревается", "посудомойка не сливает воду",
           "телевизор не показывает", "ноутбук не загружается", "висит на логотипе",
           "полосы на экране", "полосит изображение", "нужно шкаф собрать",
           "повесить телевизор на стену", "установить смеситель", "заменить розетку",
           "надо люстру повесить", "собрать кровать", "подключить стиральную машину"):
    if s.prefilter.problem_stated(_t):
        ok += 1
    else:
        bad += 1
        print("✗ поломка не опознана: %s — бот переспросит «что случилось?»" % _t)

# ⚠ ОБРАТНАЯ СТОРОНА: приветствие и болтовня поломкой не считаются. Иначе бот начнёт
# разговор с анкеты «адрес и телефон» — прямое нарушение нулевого правила плейбука.
for _t in ("здравствуйте", "вы бот?", "добрый день", "как дела", "а вы кто", "привет",
           "спасибо", "ясно", "а вы точно мастер?"):
    if not s.prefilter.problem_stated(_t):
        ok += 1
    else:
        bad += 1
        print("✗ болтовня принята за поломку: %s — бот уйдёт в анкету с первого хода" % _t)

print("=" * 50)
print("Правило трёх сообщений: %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
