"""«ЧЕРЕЗ ЧАС-ПОЛТОРА» — ТОЖЕ ВРЕМЯ ВИЗИТА (29.08, боевая заявка №1234571).

Живая заявка (Калуга, Анна). Бот: «Буду у вас через час-полтора, удобно?» Клиент: «Да».
Заявка ушла в CRM с ПУСТЫМИ полями даты и времени визита:
    "visit_date": "", "visit_time": ""
Диспетчер не знает, когда ехать; мастеру заявку не назначить.

ПРИЧИНА. Разбор `_visit_from_reply` ловил только цифровые часы («к 11:00», «10:00-10:30»),
а «через час-полтора» — это язык РЕГЛАМЕНТА для черты города, и бот говорит так чаще
всего. Самая частая формула не разбиралась вовсе.

⚠ ОКРУГЛЯЕМ ВВЕРХ ДО ПОЛУЧАСА: филиал принимает получасовыми окнами, и «19:19» в
карточке выглядит как ошибка. Считаем от ЧАСОВ ГОРОДА КЛИЕНТА, не сервера.

Запуск: uv run python analysis/test_vremya_2908.py
Офлайн, 0 токенов.
"""
import datetime
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402
import territory                                        # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


def сейчас(город):
    л = territory.city_localtime(город)
    return datetime.datetime(л.tm_year, л.tm_mon, л.tm_mday, л.tm_hour, л.tm_min)


print("── БОЕВОЙ СЛУЧАЙ ────────────────────────────────────────────────")
_д, _в = s._visit_from_reply("Буду у вас через час-полтора, удобно?", "Калуга")
chk("дата визита больше не пустая", bool(_д), (_д, _в))
chk("время визита больше не пустое", bool(_в), (_д, _в))
chk("дата в формате CRM (дд-мм-гггг)", len(_д) == 10 and _д[2] == "-", _д)
chk("время в формате ЧЧ:ММ", len(_в) == 5 and _в[2] == ":", _в)

print("── СЧИТАЕМ ОТ ЧАСОВ КЛИЕНТА ─────────────────────────────────────")
for город in ("Калуга", "Владивосток", "Калининград"):
    _д2, _в2 = s._visit_from_reply("Буду через час-полтора", город)
    _ожид = сейчас(город) + datetime.timedelta(minutes=90)
    _вышло = datetime.datetime.strptime("%s %s" % (_д2, _в2), "%d-%m-%Y %H:%M")
    _разница = (_вышло - _ожид).total_seconds() / 60
    # ⚠ ОКРУГЛЕНИЕ ВВЕРХ ДО ПОЛУЧАСА: разница от 0 до 30 минут — это оно и есть
    chk("%s: окно через 90 минут от местного времени" % город,
        0 <= _разница < 30, "%s (разница %.0f мин)" % (_вышло, _разница))

print("── ВСЕ ФОРМУЛЫ РЕГЛАМЕНТА ───────────────────────────────────────")
for фраза, минут in (("Могу через час, удобно?", 60),
                     ("Буду через час-полтора", 90),
                     ("Могу через полтора часа", 90),
                     ("Через два-два с половиной часа удобно?", 150),
                     ("Могу через два часа", 120),
                     ("Буду через полчаса", 30)):
    _д3, _в3 = s._visit_from_reply(фраза, "Калуга")
    chk("«%s» разбирается" % фраза[:32], bool(_д3 and _в3), (_д3, _в3))

print("── ОКРУГЛЕНИЕ ДО ПОЛУЧАСА ───────────────────────────────────────")
_, _вр = s._visit_from_reply("Буду через час-полтора", "Калуга")
chk("минуты кратны 30", _вр.endswith(":00") or _вр.endswith(":30"), _вр)

print("── ЦИФРОВОЕ ВРЕМЯ РАЗБИРАЕТСЯ КАК И РАНЬШЕ ──────────────────────")
# ⚠ ЯВНЫЙ ЧАС СИЛЬНЕЕ «ЧЕРЕЗ ЧАС-ПОЛТОРА»: если в реплике есть и то и другое,
# выигрывает названное клиенту окно, а не расчёт от «сейчас».
_д4, _в4 = s._visit_from_reply("Могу сегодня к 10:00-10:30, удобно?", "Калуга")
chk("окно цифрами берётся дословно", _в4 == "10:00", (_д4, _в4))
_д5, _в5 = s._visit_from_reply("Записал вас на завтра к 11:00", "Калуга")
chk("завтрашний день не подменяется сегодняшним",
    _в5 == "11:00" and _д5 != _д4, (_д5, _в5))
_д6, _в6 = s._visit_from_reply("Через час-полтора буду, значит к 15:00", "Калуга")
chk("явный час сильнее «через час-полтора»", _в6 == "15:00", (_д6, _в6))

print("── ЧУЖОЕ НЕ ТРОГАЕМ ─────────────────────────────────────────────")
for т in ("Что случилось с техникой?", "Марку подскажете?", ""):
    _д7, _в7 = s._visit_from_reply(т, "Калуга")
    chk("«%s» → времени нет" % (т[:26] or "пусто"), not _д7 and not _в7, (_д7, _в7))

print("=" * 50)
print("Время визита из «час-полтора» (29.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
