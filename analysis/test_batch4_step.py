# -*- coding: utf-8 -*-
"""ПАЧКА 4, часть 3 — СЛЕДУЮЩИЙ ШАГ ПО ПРЕДМЕТУ, А НЕ ВСЛЕПУЮ (Э4, 21.08).

Когда клиент уже назвал задачу, а модель всё равно переспрашивает «что у вас
случилось?», сервер вырезает переспрос и подставляет следующий шаг. Шаг выбирался
по одному признаку — направлению: БТ и КП → «Марку и модель подскажите?», ВСЁ
ОСТАЛЬНОЕ → «Объём подскажите — сколько точек и где?».

ДВЕ ДЫРЫ:
  1. ТЕЛЕВИЗОР НАПРАВЛЕНИЯ НЕ ЗАДАЁТ (правка заказчика 01.08: ТВ принимается во все
     три направления). Значит на чистом ТВ-запросе направление пустое, и клиент,
     написавший «телевизор не включается», получал «сколько точек и где?» — вопрос
     электрика, к телевизору отношения не имеющий.
  2. МНЧ — это не только электрика. «Сколько точек» осмысленно для розеток и
     светильников, но на сборке шкафа или установке смесителя это бессмыслица.

Плюс сам признак направления брался как direction_of(речь) — без метки объявления,
хотя рядом в коде уже живёт lock_direction, который метку учитывает и закрепляет
первое определившееся направление на весь диалог.

Запуск: uv run python analysis/test_batch4_step.py   (0 токенов)
"""
import io
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server  # noqa: E402

ok = bad = 0


def chk(label, cond):
    global ok, bad
    if cond:
        ok += 1
    else:
        bad += 1
        print("✗", label)


ПЕРЕСПРОС = "Да, помогу. Что у вас случилось?"
ТОЧКИ = "сколько точек"


def шаг(речь, направление=""):
    return server._снять_переспрос(ПЕРЕСПРОС, True, направление, речь)


# ── 1. телевизор: марка и модель, а не «точки» ──────────────────────────────
for речь in [
    "телевизор не включается, звук есть а картинки нет",
    "Здравствуйте, ТВ самсунг не ловит каналы",
    "телек перестал включаться, поможете?",
]:
    из = шаг(речь)
    chk("ТВ: не спрашиваем про точки — %s" % речь[:34], ТОЧКИ not in из.lower())
    chk("ТВ: спрашиваем модель — %s" % речь[:34],
        re.search(r"модел|марк", из, re.IGNORECASE) is not None)

# ── 2. МНЧ не только электрика ──────────────────────────────────────────────
for речь in [
    "нужно собрать шкаф из икеи",
    "поменять смеситель на кухне",
    "повесить карниз и зеркало",
]:
    из = шаг(речь, "mnc")
    chk("МНЧ без электрики: не «сколько точек» — %s" % речь[:32], ТОЧКИ not in из.lower())
    chk("МНЧ без электрики: шаг ведёт к встрече — %s" % речь[:32],
        re.search(r"куда|подъех|адрес|когда", из, re.IGNORECASE) is not None)

# ── 3. электрика: прежний вопрос остаётся верным ────────────────────────────
for речь in [
    "нужно установить три розетки на кухне",
    "поменять выключатели и повесить люстру",
]:
    chk("электрика: объём точками — %s" % речь[:34], ТОЧКИ in шаг(речь, "mnc").lower())

# ── 4. техника: прежнее поведение не сломано ────────────────────────────────
for направление, речь in [("bt", "стиральная машина не сливает воду"),
                          ("kp", "ноутбук не включается")]:
    из = шаг(речь, направление)
    chk("%s: марка и модель" % направление, "модел" in из.lower())
    chk("%s: без точек" % направление, ТОЧКИ not in из.lower())

# ── 5. ничего не понятно — не выдумываем электрику ──────────────────────────
chk("направление и предмет неизвестны: без «точек»",
    ТОЧКИ not in шаг("нужен мастер, помогите пожалуйста").lower())

# ── 6. направление берётся с меткой объявления ──────────────────────────────
SRC = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
chk("_dir в постобработке считается через lock_direction (с меткой объявления)",
    not re.search(r"_dir = prefilter\.direction_of\(client_all\)", SRC))
chk("метка объявления действительно передаётся",
    re.search(r"_dir = prefilter\.lock_direction\(\s*\[?client_all.*?kr\.get\(\"direction\"\)",
              SRC, re.S) is not None)

print("\nИТОГО: %d ок, %d провал" % (ok, bad))
sys.exit(1 if bad else 0)
