# -*- coding: utf-8 -*-
"""ТЕРРИТОРИАЛЬНЫЕ ПРАВИЛА ВЛАДЕЛЬЦА ОТ 27.08 (по заявке №1234567, посёлок Дубовое).

Владелец дословно:
  «Дубовое это посёлок, по картам называется "Посёлок Дубовое", и мы договорились с клиентом
   за территорией города Белгород. Телевизоры принимаются строго на территории основного
   города или города-спутника, для них не распространяется правило дальнего выезда и 36 км от
   основного филиала. Для города Белгород на КП направлении работает правило "Заявки за
   территорией Белгорода принимаются по согласованию с филиалом (Согласовано с Руководителем
   КЦ)" — то есть у этого города дальнего выезда нет вовсе и все заявки без согласования
   принимаются только на территории города по Яндекс-картам.»

ЧТО ИЗ ЭТОГО УЖЕ РАБОТАЛО, А ЧТО НЕТ:
· «для ТВ нет дальнего выезда» — было с 01.08, проверяем, что не сломалось;
· «у Белгорода дальнего выезда нет вовсе» — не было нигде, заведено;
· «Дубовое за чертой» — не опознавалось: разбор требует слова-типа («посёлок»), клиент его не
  написал. Теперь недостающее берётся с карты.

⚠ КАРТА СТОИТ ВРЕМЕНИ: 1,85 с на холодную (замер), 0 из памяти. Бюджет хода 9 секунд, поэтому
поход в сеть разрешён только пока времени вдоволь, а на пути ответа читается лишь готовое.

Запуск: uv run python analysis/test_territoriya_2708.py
Офлайн; сеть не нужна — там, где её нет, проверки идут по памяти.
"""
import io
import os
import sys
import time

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import filials as f                                    # noqa: E402
import server as s                                     # noqa: E402
import territory as t                                  # noqa: E402

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:110]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


print("\n1. У БЕЛГОРОДА НА КП ДАЛЬНЕГО ВЫЕЗДА НЕТ ВОВСЕ")
проверь("правило записано для пары «город + направление»", f.no_far_trip("Белгород", "kp"))
проверь("на БТ оно не распространяется", not f.no_far_trip("Белгород", "bt"))
проверь("на МНЧ тоже", not f.no_far_trip("Белгород", "mnc"))
проверь("других городов правило не касается", not f.no_far_trip("Воронеж", "kp"))
проверь("регистр и ё не мешают", f.no_far_trip("белгород", "KP"))
проверь("far_trip для Белгорода молчит",
        t.far_trip("посёлок Дубовое Цветочная 21", "Белгород", "kp", "компьютер") is None)
проверь("а для обычного города 36 км работают",
        t.far_trip("село Ямное Ленина 5", "Воронеж", "kp", "холодильник") is not None)

print("\n2. ТЕЛЕВИЗОР — СТРОГО ГОРОД ИЛИ СПУТНИК (правило было, проверяем что цело)")
проверь("на ТВ дальний выезд не даётся даже в обычном городе",
        t.far_trip("село Ямное Ленина 5", "Воронеж", "kp", "телевизор не включается") is None)
проверь("а без ТВ в том же городе даётся",
        t.far_trip("село Ямное Ленина 5", "Воронеж", "kp", "холодильник не морозит") is not None)

print("\n3. «ДУБОВОЕ» БЕЗ СЛОВА «ПОСЁЛОК» — ЗА ЧЕРТОЙ")
_адрес = "Дубовое, центр.. Ул. Цветочная, 21, ориентир Сбер."
проверь("разбор по словам его не видит (так и было в бою)",
        not t.settlement_outside(_адрес, "Белгород"))
_разбор = s._parse_addr(_адрес, "Белгород")
if _разбор.get("settlement"):
    проверь("карта даёт населённый пункт", _разбор["settlement"] != "", _разбор)
    проверь("и он не равен городу заявки",
            t._norm(_разбор["settlement"]) != t._norm("Белгород"), _разбор)
    проверь("а улица уточнена до полного имени",
            "улица" in _разбор.get("street", "").lower(), _разбор)
    проверь("признак «за чертой» срабатывает",
            s._за_чертой_по_карте([{"role": "client", "text": _адрес}], "Белгород"))
    # ⚠ ПОМЕССАЖНО, А НЕ ПО СКЛЕЙКЕ. Первая редакция брала `_адрес_в_переписке`, а он отдаёт
    # склеенный текст: «Добрый вечер, телевизор замигал… Дубовое, Цветочная 21». Разбор берёт
    # головой первый кусок до запятой — «Добрый вечер», — и в карту уходит запрос, по которому
    # она не находит ничего. Признак молчал ровно на боевом диалоге, ради которого писался.
    проверь("адрес найден среди реплик, а не в склейке",
            s._за_чертой_по_карте(
                [{"role": "client", "text": "Добрый вечер, телевизор Haier замигал и потух"},
                 {"role": "client", "text": _адрес}], "Белгород"))
else:
    print("  — карта недоступна, проверки по ней пропущены (это законно: без сети работаем как раньше)")
проверь("городской адрес за чертой не считается",
        not s._за_чертой_по_карте([{"role": "client", "text": "Ленина 5 кв 12"}], "Белгород"))
проверь("без города признак молчит",
        not s._за_чертой_по_карте([{"role": "client", "text": _адрес}], ""))

print("\n4. БЮДЖЕТ ХОДА: КАРТА НЕ ИМЕЕТ ПРАВА ЕГО СЪЕСТЬ")
_было = getattr(s._ХОД, "начало", None)
try:
    if hasattr(s._ХОД, "начало"):
        del s._ХОД.начало
    проверь("вне хода бюджет не ограничиваем", s._бюджет_остался(2.5))
    s._ХОД.начало = time.time()
    проверь("в начале хода карту спрашивать можно", s._бюджет_остался(2.5))
    s._ХОД.начало = time.time() - 6.0
    проверь("на шестой секунде — уже нельзя", not s._бюджет_остался(2.5))
finally:
    if _было is None:
        if hasattr(s._ХОД, "начало"):
            del s._ХОД.начало
    else:
        s._ХОД.начало = _было

print("\n5. ПРОВОДКА")
исходник = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
проверь("«за чертой» учитывает карту", "_за_чертой_по_карте(norm," in исходник)
# ⚠ ПАМЯТЬ СПРАШИВАЕТСЯ РАНЬШЕ СЕТИ, и порядок тут — часть правила, а не стиль.
проверь("память спрашивается раньше сети",
        исходник.index("готовое = geocode.parts_cached(address, city)")
        < исходник.index("return geocode.parts(address, city, timeout=2)"))
проверь("дверь без сети существует",
        "def parts_cached(" in io.open(os.path.join(КОРЕНЬ, "brain", "geocode.py"),
                                       encoding="utf-8").read())
проверь("перед сетью проверяется бюджет", "if not _бюджет_остался(2.5):" in исходник)
проверь("отметка старта хода ставится", "_ХОД.начало = time.time()" in исходник)
_терр = io.open(os.path.join(КОРЕНЬ, "brain", "territory.py"), encoding="utf-8").read()
проверь("far_trip спрашивает правило города", "filials.no_far_trip(city, direction)" in _терр)

print("\n" + "─" * 60)
print("проверок: %d, провалов: %d" % (всего[0], len(ошибки)))
for о in ошибки:
    print("  ПРОВАЛ:", о)
sys.exit(1 if ошибки else 0)
