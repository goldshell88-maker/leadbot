# -*- coding: utf-8 -*-
"""КАРТЫ ФИЛИАЛОВ: словарь имён, свой слой направления, защита выгрузки.

ВЛАДЕЛЕЦ 27.08: «я не понимаю, как у нас устроены наши рабочие яндекс карты… у нас в картах
размечены города только там, где принимается в особой области… углубись, чтобы было всё
грамотно и качественно».

КАК УСТРОЕНО. Три карты в Конструкторе Яндекса, по одной на направление. `fetch_filial_zones.py`
тянет геометрию из виджета и метки со страницы карт, пишет `brain/filial_zones.json`. Правило
приёма владелец пишет прямо в название объекта («СОЧИ ЗА 1,5 ЧАСА», «Зеленоград (МСК)»).

ЧТО БЫЛО СЛОМАНО — ЧЕТЫРЕ ВЕЩИ, ВСЕ ПРОВЕРЕНЫ ПРОГОНОМ.

1. КАРТА И СПРАВОЧНИК ГОВОРИЛИ РАЗНЫМИ СЛОВАМИ. Контуры Петербурга подписаны «СПБ 1»…«СПБ 4»
   и «СПБ3», город из них выходит «Спб», а справочник знает «Санкт-Петербург». Словаря между
   ними не было ни одного: `city_has_map('Санкт-Петербург','kp')` → False при СЕМИ нарисованных
   контурах на трёх картах. Петербург — самый частый город корпуса, 170 диалогов.

2. КОНТУР ЧУЖОГО НАПРАВЛЕНИЯ РЕШАЛ СУДЬБУ ЗАЯВКИ. `locate` после своего слоя проходил по ВСЕМ
   картам. Точка в Красногорске на БТ попадала в контур карты КП и возвращалась как «черта
   города, час-полтора» — при том, что филиала БТ там нет вовсе.

3. ПРАВИЛО «СТРОГО ПО КОНТУРУ» НЕ ВЫЗЫВАЛОСЬ НИОТКУДА. `filials.strict_by_map` — мёртвый код,
   а правило держалось на случайном совпадении имён. У Сочи на карте БТ контур подписан
   правилом, а не городом, — и точка в 60 км от Сочи считалась чертой города.

4. ВЫГРУЗКА МОГЛА ТИХО СТЕРЕТЬ ТЕРРИТОРИИ. Ни одной проверки: смени Яндекс формат виджета —
   файл перезапишется пустым, `territory.zones()` проглотит и вернёт пустоту, и бот останется
   без территорий, ничего никому не сказав. Плюс запись была неатомарной.

ЧТО ДАЛА СВЕЖАЯ ВЫГРУЗКА (карты правились 20.08, файл был от 15.08):
· новый контур «ЛЮБЕРЦЫ» на МНЧ, которого бот не знал;
· четыре контура получили верное время вместо «час-полтора» — Видное, Одинцово (КП),
  Гатчина, Кронштадт (БТ): бот обещал приезд ВДВОЕ быстрее, чем филиал едет.

Запуск: uv run python analysis/test_karty_2708.py
Офлайн, сеть не нужна: работаем по уже выгруженному файлу.
"""
import io
import json
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import filials as f                                    # noqa: E402
import server as _сервер                               # noqa: E402
import territory as t                                  # noqa: E402

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:110]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


print("\n1. СЛОВАРЬ ИМЁН: карта и справочник понимают друг друга")
проверь("«Спб» с карты раскрывается в Санкт-Петербург",
        "санкт-петербург" in f.имена_города("Спб"))
проверь("и обратно: город справочника знает своё имя на карте",
        "спб" in f.имена_города("Санкт-Петербург"))
проверь("«Спб3» — тоже Петербург", "санкт-петербург" in f.имена_города("Спб3"))
проверь("составной контур раскрывается на оба города",
        {"электросталь", "ногинск"} <= f.имена_города("Электросталь-Ногинск"))
проверь("и каждый город находит свой составной контур",
        "раменское-жуковский" in f.имена_города("Жуковский"))
проверь("обычный город лишнего не приобретает", f.имена_города("Курск") == {"курск"})

print("\n2. ПЕТЕРБУРГ НАШЁЛ СВОИ КОНТУРЫ — на всех трёх направлениях")
# ⚠ ДВА МЕХАНИЗМА ПЕРЕКРЫВАЮТ ДРУГ ДРУГА, И ПРОВЕРЯТЬ ИХ НАДО ПО ОТДЕЛЬНОСТИ. Синонимы
# раскрываются и в `cities_on_map` (набор имён), и в `city_has_map` (запасной ход). Диверсия
# показала: сними любой из них — второй подхватит, и проверка останется зелёной.
проверь("набор городов карты содержит имя справочника",
        "санкт-петербург" in t.cities_on_map("kp"), sorted(t.cities_on_map("kp"))[:6])
_настоящий = t.cities_on_map
t.cities_on_map = lambda направление="": {"спб", "москва"}      # как было бы без раскрытия
try:
    проверь("city_has_map находит город и по «сырому» набору имён карты",
            t.city_has_map("Санкт-Петербург", "kp"))
finally:
    t.cities_on_map = _настоящий
for н in ("kp", "bt", "mnc"):
    проверь("контур СПб на %s виден" % н, t.city_has_map("Санкт-Петербург", н))
проверь("центр Петербурга — черта города",
        t.locate(59.9386, 30.3141, "Санкт-Петербург", "kp")["zone"] == "city")
проверь("точка в 120 км от Петербурга — вне контура (согласование)",
        t.locate(59.5, 29.0, "Санкт-Петербург", "kp")["zone"] == "outside")
проверь("город без разметки по-прежнему «неизвестно», а не «за чертой»",
        t.locate(51.7, 36.2, "Курск", "kp")["zone"] == "unknown")

print("\n3. СВОЙ СЛОЙ НАПРАВЛЕНИЯ: чужая карта чужого не решает")
кр = t.locate(55.8236, 37.3300, "Красногорск", "bt")
проверь("Красногорск на БТ не берёт контур карты КП", кр["zone"] == "unknown", кр)
проверь("а на КП и МНЧ он размечен и виден",
        t.locate(55.8236, 37.3300, "Красногорск", "kp")["zone"] != "unknown"
        and t.locate(55.8236, 37.3300, "Красногорск", "mnc")["zone"] != "unknown")

print("\n4. «СТРОГО ПО КОНТУРУ» РАБОТАЕТ ДАЖЕ ТАМ, ГДЕ КОНТУР ПОДПИСАН ПРАВИЛОМ")
# ⚠ ГОРОД ВНЕ СПИСКА «СТРОГО ПО КОНТУРУ» ПРОВЕРЯЕТ ИМЕННО `covered`, а не strict_by_map.
# Электросталь размечена составным контуром и в STRICT_BY_MAP не входит — значит «вне контура»
# для неё может дать только сравнение по всем именам города. Диверсия «covered по точному
# имени» на Петербурге молчала: там срабатывал strict_by_map.
проверь("Электросталь вне своего контура — вне территории",
        t.locate(55.60, 38.90, "Электросталь", "kp")["zone"] == "outside",
        t.locate(55.60, 38.90, "Электросталь", "kp"))
проверь("и она не в списке «строго по контуру» — значит сработал covered",
        not f.strict_by_map("Электросталь"))
проверь("Сочи на БТ вне контура — согласование",
        t.locate(43.4, 39.3, "Сочи", "bt")["zone"] == "outside")
проверь("Сочи на БТ внутри контура — черта города",
        t.locate(43.5855, 39.7231, "Сочи", "bt")["zone"] == "city")
проверь("правило берётся из справочника, а не выдумано",
        f.strict_by_map("Сочи") and f.strict_by_map("Санкт-Петербург")
        and not f.strict_by_map("Курск"))

print("\n5. ФАЙЛ КАРТ ГОВОРИТ, КОГДА ОН СНЯТ И С ЧЕГО")
z = json.load(io.open(os.path.join(КОРЕНЬ, "brain", "filial_zones.json"), encoding="utf-8"))
проверь("есть отметка выгрузки", bool(z.get("снято")), list(z))
проверь("есть хеши карт", len(z.get("карты") or {}) == 3, z.get("карты"))
проверь("есть время последней правки карт владельцем",
        len(z.get("правлено_на_картах") or {}) == 3, z.get("правлено_на_картах"))
проверь("контуров не меньше порога выгрузки", len(z["areas"]) >= 40, len(z["areas"]))

print("\n6. ВРЕМЯ ПРИЁМА, ИСПРАВЛЕННОЕ СВЕЖЕЙ ВЫГРУЗКОЙ")
def _lead(напр, имя):
    return next((a["lead"] for a in z["areas"]
                 if a["direction"] == напр and a["name"] == имя), "")
for напр, имя in (("kp", "Видное (МСК)"), ("kp", "Одинцово (МСК)"),
                  ("bt", "ГАТЧИНА"), ("bt", "КРОНШТАДТ")):
    проверь("«%s» на %s едет 2-2.5 часа, а не час-полтора" % (имя, напр),
            _lead(напр, имя) == "два, два с половиной часа", _lead(напр, имя))
проверь("контур «ЛЮБЕРЦЫ» на МНЧ приехал в файл",
        any(a["direction"] == "mnc" and a["name"] == "ЛЮБЕРЦЫ" for a in z["areas"]))

print("\n7. «ГДЕ КЛИЕНТ» И «ЧТО КАРТА ГОВОРИТ О ГОРОДЕ» — РАЗНЫЕ ВОПРОСЫ")
# ⚠ ЭТО НАШЛОСЬ РЕГРЕССИЕЙ, А НЕ ЗАМЫСЛОМ. Как только Петербург впервые нашёл свои контуры,
# `_slot_offer('Санкт-Петербург')` перестал давать окно ВООБЩЕ: при пустом адресе код
# геокодировал само название города, получал произвольную точку (59.96, 30.16 — западнее всех
# четырёх контуров СПБ) и читал промах как «клиент за чертой».
проверь("без адреса точку клиента не выдумываем",
        t.locate_by_text("", "Санкт-Петербург", "kp") is None)
проверь("название города адресом не считается",
        t.locate_by_text("Санкт-Петербург", "Санкт-Петербург", "kp") is None)
проверь("а адрес — считается",
        (t.map_profile("Санкт-Петербург", "Невский проспект 20", "kp") or {}).get("zone") == "city")
проверь("окно для Петербурга снова есть", bool(_сервер._slot_offer("Санкт-Петербург")))
проверь("город целиком карта описать может и без адреса: Адлер едет 2-2.5 часа",
        (t.city_profile_from_map("Адлер", "kp") or {}).get("lead") == "два, два с половиной часа",
        t.city_profile_from_map("Адлер", "kp"))
проверь("городской профиль помечен как городской",
        (t.city_profile_from_map("Адлер", "kp") or {}).get("по_городу") is True)
# ⚠ ПРОВОДКА: без этого проверки выше зелены впустую — диверсия «убрать городской профиль из
# map_profile» их не роняла, потому что они звали функцию напрямую.
проверь("map_profile без адреса отдаёт именно городской профиль",
        (t.map_profile("Адлер", "", "kp") or {}).get("по_городу") is True,
        t.map_profile("Адлер", "", "kp"))
# ⚠ ГОРОД СО СПОРЯЩИМИ КОНТУРАМИ ГОРОДСКОГО ОТВЕТА НЕ ИМЕЕТ. У Серпухова на КП три разных
# правила («час-полтора», «два, два с половиной», «три часа») — выдать первое попавшееся значит
# пообещать вдвое быстрее там, где владелец нарисовал самую медленную зону.
проверь("Серпухов: контуры спорят — городского ответа нет",
        t.city_profile_from_map("Серпухов", "kp") is None,
        t.city_profile_from_map("Серпухов", "kp"))
проверь("городской профиль НЕ спорит с клиентом, сказавшим «я за городом»",
        t.slot_profile("Москва", True, t.city_profile_from_map("Москва", "mnc"),
                       {"text": "я в пригороде живу", "direction": "mnc"}).get("needs_approval"))

print("\n8. ЗАЩИТА ВЫГРУЗКИ")
скрипт = io.open(os.path.join(КОРЕНЬ, "analysis", "fetch_filial_zones.py"), encoding="utf-8").read()
проверь("порог минимума контуров не просто объявлен, а проверяется",
        "if len(areas) < _МИНИМУМ_КОНТУРОВ:" in скрипт)
проверь("убыль контуров останавливает запись", "стало_n < было_n * 0.8" in скрипт)
проверь("пустое направление останавливает запись", "направления без единого контура" in скрипт)
проверь("запись атомарная", "os.replace(врем, OUT)" in скрипт)
проверь("временный файл перечитывается перед подменой",
        'json.load(open(врем, encoding="utf-8"))' in скрипт)
проверь("линтер имён есть", "def _линтер(" in скрипт)
проверь("линтер не ругается на контуры-правила", "соглас|принима" in скрипт)
проверь("линтер знает про синонимы", "имена_города(гор)" in скрипт)
проверь("«за 2 часа» ровно читается как 2-2.5", "за\\s*2\\s*час" in скрипт)

print("\n" + "─" * 60)
print("проверок: %d, провалов: %d" % (всего[0], len(ошибки)))
for о in ошибки:
    print("  ПРОВАЛ:", о)
sys.exit(1 if ошибки else 0)
