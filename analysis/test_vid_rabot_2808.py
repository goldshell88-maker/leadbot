    chk("заглушка не увеличивает счёт", рг["заглушка_и_два"] == 2, рг)
    chk("пустой список — ноль", рг["пустой"] == 0, рг)
    chk("селекта нет — ноль, а не падение", рг["без_селекта"] == 0, рг)

