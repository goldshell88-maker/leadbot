    # ⚠ РАДИ ЭТОГО ВВОДИЛАСЬ ГРАНИЦА СЛОВА 26.08: «кран» внутри «эКРАНа»
    chk("«кран» не находится внутри «Замена экрана»", р2["кран"] == "", р2)
