# -*- coding: utf-8 -*-
"""ЗАКРЫТИЕ ДИАЛОГА И КВИТАНЦИЯ ЗА МОДЕЛЬ (29.08, боевые диалоги).

1. ДИАЛОГ НЕ ЗАКРЫВАЛСЯ (Санкт-Петербург). Клиент: «Уже вызвала мастера, спасибо».
   Бот: «Если понадоблюсь, пишите» — и диалог остался в очереди со статусом
   «ждёт 11 минут». Признак `done` считался ТОЛЬКО по телефону, адресу и времени,
   а их тут не будет никогда: клиент ушёл. Слова владельца: «диалог логически
   завершил, но всё равно ведёт его — можно просто закрыть».

   ⚠ ЗАКРЫВАЕМ ПО СЛОВАМ КЛИЕНТА, А НЕ ПО СВОИМ. Тёплое закрытие в нашей реплике
   («если что, пишите») отпускает разговор, но не завершает: клиент может вернуться
   этой же минутой.

2. КВИТАНЦИЯ ЗА МОДЕЛЬ (Калуга). Клиент прислал фото карточки товара, бот ответил
   ровно «модель ясна». Слова владельца: «зачем он пишет "модель ясна", похоже на
   робота». Замер по корпусу: получив модель (181 случай), живые операторы НЕ
   подтверждают её вовсе — сразу к делу («да смогу помочь», «давайте подъеду гляну»,
   «вам когда удобно?»). А на телефон отвечают «хорошо» (81) и «записал» (45) —
   там подтверждение уместно, его не трогаем.

Запуск: uv run python analysis/test_zakrytie_2908.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── КЛИЕНТ ЗАВЕРШИЛ РАЗГОВОР ─────────────────────────────────────")
for т in ("Уже вызвала мастера, спасибо", "всё, спасибо", "я уже нашёл мастера",
          "спасибо, не нужно", "нашли другого", "передумал", "неактуально",
          "сам починил", "вопрос решён"):
    chk("«%s» — завершение" % т[:30], bool(s._КЛИЕНТ_ЗАКРЫЛ_RX.search(т)))

print("── А ЭТО РАЗГОВОР ПРОДОЛЖАЕТ ────────────────────────────────────")
# ⚠ «Спасибо» само по себе завершением не является: клиент благодарит и ждёт дальше.
for т in ("спасибо, а когда приедете?", "да, спасибо, записывайте", "хорошо, спасибо",
          "спасибо большое, жду", "Холодильник не морозит", "жду вас"):
    chk("«%s» — не завершение" % т[:30], not s._КЛИЕНТ_ЗАКРЫЛ_RX.search(т))

print("── ЗАКРЫТИЕ ПРИВЯЗАНО К СЛОВАМ КЛИЕНТА ──────────────────────────")
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
# ⚠ ИЩЕМ В БЛОКЕ done, А НЕ ПО ВСЕМУ ФАЙЛУ. Первая редакция искала строку целиком по
# исходнику — и находила её в СОСЕДНЕМ месте (`_снять_вопрос_после_закрытия`, где тот же
# детектор используется для другого). Диверсия против самого done проходила молча.
_блок_done = _ИСХ.split('"done": bool(')[1][:400] if '"done": bool(' in _ИСХ else ""
chk("done учитывает завершение клиентом",
    "_КЛИЕНТ_ЗАКРЫЛ_RX.search(last_client" in _блок_done, _блок_done[:120])
chk("полный набор данных по-прежнему закрывает",
    'out.get("phone") and out.get("address") and out.get("preferred_time")' in _ИСХ)
# ⚠ НАШЕ ТЁПЛОЕ ЗАКРЫТИЕ ДИАЛОГ НЕ ЗАВЕРШАЕТ: клиент ещё может вернуться
chk("своё «если что, пишите» диалог не закрывает",
    "_ТЁПЛОЕ_ЗАКРЫТИЕ_RX.search" not in _ИСХ.split('"done": bool(')[1][:400])

print("── КВИТАНЦИЯ ЗА МОДЕЛЬ ──────────────────────────────────────────")
for т in ("модель ясна", "Модель ясна.", "понял, модель ясна", "ясно, модель понятна"):
    chk("«%s» снимается" % т[:26], s._снять_квитанцию_модели(т) != т, s._снять_квитанцию_модели(т))
chk("вся реплика — квитанция → пусто, ведём к человеку",
    s._снять_квитанцию_модели("модель ясна") == "")
chk("дело в реплике остаётся",
    s._снять_квитанцию_модели("модель ясна\nКогда вам удобно?") == "Когда вам удобно?")

print("── ПОДТВЕРЖДЕНИЕ НОМЕРА ТРОГАТЬ НЕЛЬЗЯ ──────────────────────────")
# ⚠ ЗАМЕР: на телефон живые отвечают «хорошо» (81 раз) и «записал» (45). Это норма речи,
# а не роботизм — снимать нечего.
for т in ("Номер записал. По деньгам сориентирую на месте", "Хорошо, записал вас",
          "Марку подскажете?", "да, ремонтирую. Что с ним случилось?",
          "Записал вас на завтра к 11:00"):
    chk("«%s» не трогаем" % т[:34], s._снять_квитанцию_модели(т) == т)

print("── ГАРД ЖИВОЙ ──────────────────────────────────────────────────")
chk("квитанция снимается в воронке", "reply = _снять_квитанцию_модели(reply)" in _ИСХ)

print("=" * 50)
print("Закрытие диалога и квитанции (29.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
