# -*- coding: utf-8 -*-
"""ЧАСЫ КЛИЕНТА, А НЕ СЕРВЕРА (решение заказчика 15.08).

Сервер живёт не в поясе клиента: «могу сегодня к 17:00» по серверным часам —
полночь во Владивостоке. Шапка «СЕЙЧАС», воронка слота, ключ кэша и окно
пинга обязаны считаться по городу клиента.
"""
import calendar
import os
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "brain"))
import channel  # noqa: E402
import server as s  # noqa: E402
import territory as t  # noqa: E402

ok = bad = 0


def chk(label, cond):
    global ok, bad
    if cond:
        ok += 1
    else:
        bad += 1
        print("✗", label)


# 1) смещения ключевых городов
for город, off in [("Москва", 3), ("Калининград", 2), ("Самара", 4), ("Екатеринбург", 5),
                   ("Омск", 6), ("Новосибирск", 7), ("Иркутск", 8), ("Чита", 9),
                   ("Владивосток", 10), ("Артём", 10), ("Южно-Сахалинск", 11),
                   ("Петропавловск-Камчатский", 12), ("", 3), ("Неведомск", 3)]:
    chk("%s UTC+%d" % (город or "(пусто)", off), t.city_tz_offset(город) == off)

# 2) полдень Москвы: шапка «СЕЙЧАС» живёт в поясе клиента
noon = calendar.timegm((2026, 8, 17, 9, 0, 0, 0, 0, 0))  # 12:00 МСК
real = time.time
time.time = lambda: noon
try:
    for город, час, часть in [("Москва", "12:00", "день"),
                              ("Владивосток", "19:00", "вечер"),
                              ("Екатеринбург", "14:00", "день")]:
        note = s._clock_note(город, False, "стиралка не сливает", "bt", "")
        chk("СЕЙЧАС %s: %s (%s)" % (город, час, часть),
            час in note and часть in note.split(".")[0])
    # 3) ключ кэша различает время суток по городу
    chk("бакет кэша расходится по поясам",
        s._daypart_key("Москва") != s._daypart_key("Владивосток"))
    # 4) пинг-окно: 12:00 МСК = 22:00 Хабаровска — в Хабаровске пинговать поздно...
    noon2 = calendar.timegm((2026, 8, 17, 19, 0, 0, 0, 0, 0))  # 22:00 МСК = 05:00 Влд
    time.time = lambda: noon2
    SENT = []
    channel.avito_api.send = lambda a, c, txt: SENT.append(txt)
    КЛЮЧ = "c|m1"                      # этот ключ вентиль пропускает
    ТИШИНА = channel.ping_after(КЛЮЧ) + 60
    last = {"role": "bot", "text": "Куда подъехать?", "ts": noon2 - ТИШИНА, "id": "m1"}
    st = {"history": [], "handoff": False, "notify_human": False, "escalation": "",
          "ping_at": 0, "resolved": False, "auto_sent": 0, "city": "Владивосток"}
    channel._silence_watch({"id": "a", "auto_reply": True}, {"id": "c"}, st, last, noon2)
    chk("пинг молчит в 5 утра Владивостока", not SENT)
    st["city"] = "Москва"
    channel._silence_watch({"id": "a", "auto_reply": True}, {"id": "c"}, st, last, noon2)
    chk("пинг работает в 22:00 Москвы... (граница 9-21)", not SENT)  # 22 вне окна — тоже тихо
    noon3 = calendar.timegm((2026, 8, 17, 11, 0, 0, 0, 0, 0))  # 14:00 МСК
    time.time = lambda: noon3
    st = {"history": [], "handoff": False, "notify_human": False, "escalation": "",
          "ping_at": 0, "resolved": False, "auto_sent": 0, "city": "Москва"}
    last3 = {"role": "bot", "text": "Куда подъехать?", "ts": noon3 - ТИШИНА, "id": "m1"}
    channel._silence_watch({"id": "a", "auto_reply": True}, {"id": "c"}, st, last3, noon3)
    chk("пинг идёт днём по Москве", len(SENT) == 1)
finally:
    time.time = real

# ── ВЕЧЕР: АРИФМЕТИКУ СЧИТАЕТ КОД, А НЕ МОДЕЛЬ (снимок владельца 25.08) ───────
# Улан-Удэ, 18:35. Бот в ОДНУ минуту предложил «через час-полтора» и тут же
# «к 20 часам я уже не успею, могу завтра с утра». 20:00 было ровно в сроке.
# Правило в промпте звучало «предлагай, пока успеваешь до 21:30» — то есть просило
# модель сложить текущий час со сроком. Теперь сумма считается здесь.
import unittest.mock as _mock                                        # noqa: E402
import server as _s                                                  # noqa: E402
import territory as _t                                               # noqa: E402


def _в(ч, мин, город="Улан-Удэ"):
    lt = time.struct_time((2026, 8, 25, ч, мин, 0, 1, 237, 0))
    with _mock.patch.object(_t, "city_localtime", return_value=lt):
        return _s._slot_state(город, False, "повесить полку", "mnc")[0]


chk("18:35 — ближайший срок влезает", _в(18, 35) == "через час-полтора")
chk("20:00 — ровно влезает (приезд 21:30)", _в(20, 0) == "через час-полтора")
# ⚠ ЗДЕСЬ ТЕРЯЛИСЬ ЗАЯВКИ: раньше с 20:00 воронка звала на утро, хотя приём до 21:30.
# Слово владельца: «если в городе 20:30, мы можем принять на 21:30».
chk("20:10 — срок не влезает, но приём идёт", _в(20, 10) == "сегодня к 21:30")
# ⚠ ГРАНИЦА УТОЧНЕНА 26.08 ПО ЖИВОМУ ПРОМАХУ. Здесь стояло «20:45 — то же самое», то
# есть последний слот обещался, пока приём формально открыт. На боевом снимке это дало
# край: Энгельс, у клиента 21:27, бот пишет «Сегодня к 21:30 подъеду» — приезд через три
# минуты при дороге в час. Владелец формулировал правило с условием, которое мы теряли:
# «21:30 — самое позднее, ТО ЕСТЬ если в городе 20:30, мы можем принять на 21:30».
# Значит последний слот честен, пока до него осталась МИНИМАЛЬНАЯ дорога (час):
#   20:30 → успеваем ровно (пример владельца)      20:31 и позже → уже нет.
# Вечерние заявки при этом не потеряны: окно 20:00–20:30 как работало, так и работает.
chk("20:30 — ровно граница, пример владельца", _в(20, 30) == "сегодня к 21:30")
chk("20:31 — доехать уже не успеваем, зовём на завтра",
    _в(20, 31).startswith("завтра"))
chk("20:45 — тем более завтра", _в(20, 45).startswith("завтра"))
chk("21:27 — снимок владельца: сегодня не обещаем",
    _в(21, 27).startswith("завтра"))
# ⚠ ПОСЛЕДНИЙ СЛОТ БЕЗ ПОЛУЧАСОВОГО ОКНА: «21:30-22:00» обещало бы приезд ПОЗЖЕ
# самой поздней заявки — ровно та ошибка, ради которой окна и считаются.
chk("последний слот точным часом", "22:00" not in _в(20, 45))
chk("21:40 — приём закрыт, завтра", _в(21, 40).startswith("завтра"))
chk("09:00 — раннее утро не сломано", _в(9, 0).startswith("сегодня к 10:00"))

# Модель получает готовый ответ, а не задачу на сложение.
def _правило(ч, мин):
    lt = time.struct_time((2026, 8, 25, ч, мин, 0, 1, 237, 0))
    with _mock.patch.object(_t, "city_localtime", return_value=lt):
        return _s._clock_note(city="Улан-Удэ", client_text="повесить полку", direction="mnc")


chk("в 18:35 сказано, во сколько выйдет приезд", "20:05" in _правило(18, 35))
chk("в 18:35 сказано «сегодня успеваем»", "значит сегодня УСПЕВАЕМ" in _правило(18, 35))
chk("в 20:10 предложен конкретный последний час", "сегодня к 21:30" in _правило(20, 10))
# ⚠ НИЖНЯЯ ГРАНИЦА ТОЖЕ ГРАНИЦА: без неё счёт в 03:00 бодро сообщал «приезд около 04:30,
# успеваем» — до 21:30 действительно далеко, но раньше 10:00 никто не выезжает.
chk("ночью счёт не обещает выезд", "значит сегодня УСПЕВАЕМ" not in _правило(3, 0))
print("=" * 50)
print("Время городов: %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
