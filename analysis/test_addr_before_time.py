# -*- coding: utf-8 -*-
"""ВРЕМЯ НЕ ОБЕЩАЕМ ВСЛЕПУЮ, А ТЕЛЕВИЗОР СПРАШИВАЕМ ПО МОДЕЛИ (правки владельца 26.08).

ПОВОД — боевой снимок. Клиент: «Тв lg не переключает дальше, просто горит логотип».
Бот вторым ходом: «берусь. Буду у вас через час-полтора, удобно вам будет?». Владелец
дословно: «Чтобы предложить время мы должны знать адрес, вдруг клиент вне территории
или ещё что то, так же бот не уточнил марку телевизора».

ДВА ПРАВИЛА, КОТОРЫЕ ЭТО ЗАКРЫВАЮТ:

  (13) обещание приезда без известного адреса ОБЯЗАНО нести вопрос «куда подъехать»;
  (14) на телевизоре без кода модели бот один раз спрашивает модель.

⚠ ОКНО ИЗ РЕПЛИКИ НЕ УБИРАЕТСЯ, И ЭТО ЗАМЕР, А НЕ КОМПРОМИСС. По 28 240 живым диалогам
(`analysis/measure_addr_before_time.py`, исход считается по телефону КЛИЕНТА, чтобы не
мерить окно окном): окно+адрес одной репликой — 39,5 %, только окно — 25,8 %, только
адрес — 18,6 %, ни того ни другого — 12,1 %. Требование владельца и воронка совпали.

Запуск: uv run python analysis/test_addr_before_time.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

KR = {"visitor": "", "city": "Санкт-Петербург", "direction": "кп",
      "title": "Ремонт ЖК и LED телевизоров"}

ТВ = [{"role": "client", "text": "Здравствуйте"},
      {"role": "operator", "text": "Здравствуйте\nЧто у вас случилось?"},
      {"role": "client", "text": "Тв lg не переключает дальше, просто горит логотип"}]
ТВ_С_МОДЕЛЬЮ = ТВ[:2] + [{"role": "client",
                          "text": "Телевизор LG 43UN73006 горит логотип и всё"}]
ТВ_С_АДРЕСОМ = ТВ + [{"role": "operator", "text": "Модель подскажете?"},
                     {"role": "client", "text": "43UN73006, адрес Ленина 12 кв 5"}]

ошибки = []


def проверь(имя, условие):
    print(("  ✓ " if условие else "  ✗ ") + имя)
    if not условие:
        ошибки.append(имя)


def ответ(reply, msgs=ТВ):
    out, *_ = s._postprocess_reply(reply, msgs, dict(KR), {}, False)
    return out or ""


print("(13) обещание приезда без адреса")
# ⚠ ИНВЕРСИЯ 30.08 (скрины владельца, Севастополь и Кострома): «начал договариваться
# по времени, когда не знает адрес» — ошибка. Правило 30.08 главнее замера 26.08
# («окно+адрес вместе — 39,5 %»): окно без адреса ВЫРЕЗАЕТСЯ финальным рубежом
# (_финальный_слот), остаётся вопрос адреса; время предложим, узнав адрес.
_o = ответ("берусь. Буду у вас через час-полтора, удобно вам будет?")
проверь("к обещанию дописан вопрос об адресе", bool(s._ADDRQ_RX.search(_o)))
проверь("окна без адреса в реплике НЕТ (правило 30.08)",
        not s._ОБЕЩАНИЕ_ПРИЕЗДА_RX.search(_o))

_o2 = ответ("берусь. Могу сегодня к 19:00. Куда подъехать?")
проверь("свой вопрос об адресе вторым не дублируется",
        _o2.lower().count("куда подъехать") + _o2.lower().count("адрес") == 1)

_o3 = ответ("берусь. Буду через час-полтора, удобно?", ТВ_С_АДРЕСОМ)
проверь("адрес уже известен — вопрос не дописывается", not s._ADDRQ_RX.search(_o3))

_o4 = ответ("Да, такое ремонтирую. Что именно происходит?")
проверь("без обещания времени адрес не навязываем", not s._ADDRQ_RX.search(_o4))

_o5 = ответ("Здравствуйте\nЧто у вас случилось? Могу сегодня к 21:30, удобно вам будет? "
            "И номер ваш подскажите, пожалуйста")
проверь("номер уступает место адресу, когда время уже обещано",
        bool(s._ADDRQ_RX.search(_o5)) and not s._PHONE_ASK_RX.search(_o5))
# та же инверсия 30.08: окно при неизвестном адресе не живёт и здесь
проверь("окна без адреса НЕТ (правило 30.08)",
        not s._ОБЕЩАНИЕ_ПРИЕЗДА_RX.search(_o5))
проверь("трёх просьб в одной реплике не бывает", s._просьб_данных(_o5) <= 2)

print("(14) модель телевизора")
проверь("«Тв lg» моделью не считается", not s._модель_названа("Тв lg не переключает"))
проверь("«43UN73006» — модель", s._модель_названа("Телевизор LG 43UN73006"))
проверь("«1500руб» моделью не считается", not s._модель_названа("Работа 1500руб выйдет"))
проверь("«43дюйма» моделью не считается", not s._модель_названа("Телевизор 43дюйма"))

# ⚠ ПЕРЕСМОТР 30.08: сцепка «адрес+номер» (живая норма 38 %, обучение 30.08) занимает
# обе просьбы хода, а «номер важнее модели» — прямое правило блока (14): без телефона
# заявки нет вовсе, без модели — есть. Модель уходит на СЛЕДУЮЩИЙ ход, когда адрес
# и номер уже собраны, — это и проверяем.
_m = ответ("Да, берусь за такое. Логотип горит — плата или подсветка.")
проверь("модель уступает сцепке адрес+номер (в этом ходе её нет)",
        not s._МОДЕЛЬ_СПРОШЕНА_RX.search(_m) and s._просьб_данных(_m) >= 1)
ТВ_СОБРАН = ТВ + [{"role": "operator",
                   "text": "Куда приехать надо? Напишите номер телефона"},
                  {"role": "client", "text": "Ленина 12 кв 5, 89012345678"}]
_mс = ответ("Принял, записал.", ТВ_СОБРАН)
проверь("адрес и номер собраны — модель спрошена следующим ходом",
        bool(s._МОДЕЛЬ_СПРОШЕНА_RX.search(_mс)))

_m2 = ответ("Да, берусь. Логотип горит — плата или подсветка.", ТВ_С_МОДЕЛЬЮ)
проверь("модель названа — второй раз не спрашиваем",
        not s._МОДЕЛЬ_СПРОШЕНА_RX.search(_m2))

_m3 = ответ("Да, берусь. Модель подскажете?")
проверь("свой вопрос о модели не дублируется", _m3.lower().count("модел") == 1)

_m4 = ответ("берусь. Буду у вас через час-полтора, удобно вам будет?")
проверь("за один ход дописывается ОДИН вопрос, а не два",
        not (s._ADDRQ_RX.search(_m4) and s._МОДЕЛЬ_СПРОШЕНА_RX.search(_m4)))

print()
if ошибки:
    print("ПРОВАЛЕНО: %d" % len(ошибки))
    for e in ошибки:
        print("  -", e)
    sys.exit(1)
print("Все проверки пройдены")
