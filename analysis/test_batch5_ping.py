"""ПАЧКА 5 — ДОЖИМ ПО-ЖИВОМУ, А НЕ ЧЕРЕЗ ПЯТЬ МИНУТ (Э4, 21.08).

Правило базы знаний (ЗНАНИЯ-2.0/ДИАЛОГ-И-ПАУЗЫ.md, строка 263) не было внедрено.
Перепроверено на свежем корпусе Jivo (27 786 диалогов, 3202 настоящих дожима —
пауза оператора больше двух минут без ответа клиента):

    p25 = 11.3 мин · медиана = 25.2 мин · p75 = 45.5 мин
    быстрее пяти минут — всего 11% дожимов

Бот пингует РОВНО через пять минут, то есть быстрее 89% живых операторов, и делает
это в каждом молчащем диалоге. Живой пингует 17.3% диалогов. Отсюда две правки:

  1. СРОК: 5 минут → 12–25 минут, детерминированно по хэшу чата. Одинаковая для
     всех пауза сама по себе выдаёт автомат — у людей разброс огромный.
  2. ВЕНТИЛЬ: пинг не в каждом молчании, а примерно в каждом пятом. Без вентиля
     перенос срока снижает охват всего с 90% до 88%, а надо до ~20%.
     Регламент связывает настырность с жалобами на Авито и блокировкой аккаунта —
     это не косметика.

Порядок дожима («один пинг на цикл молчания») не трогаем: у живых 2+ пинга всего
в 11% пингованных диалогов, текущее поведение этому и соответствует.

Запуск: uv run python analysis/test_batch5_ping.py   (0 токенов)
"""
import io
import os
import statistics
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "brain"))
import channel  # noqa: E402

ok = bad = 0


def chk(label, cond):
    global ok, bad
    if cond:
        ok += 1
    else:
        bad += 1
        print("✗", label)


# ── 1. срок дожима ──────────────────────────────────────────────────────────
сроки = [channel.ping_after("чат%d|сообщение%d" % (i, i)) for i in range(2000)]
chk("минимальный срок ≥ 12 минут: %d с" % min(сроки), min(сроки) >= 12 * 60)
chk("максимальный срок ≤ 25 минут: %d с" % max(сроки), max(сроки) <= 25 * 60)
chk("медиана в живом диапазоне (14–24 мин): %.1f мин" % (statistics.median(сроки) / 60),
    14 * 60 <= statistics.median(сроки) <= 24 * 60)
chk("разброс есть (σ ≥ 90 с): %.0f с" % statistics.pstdev(сроки),
    statistics.pstdev(сроки) >= 90)
chk("один и тот же чат — один и тот же срок",
    channel.ping_after("чат7|м3") == channel.ping_after("чат7|м3"))
chk("разные чаты — разные сроки",
    len({channel.ping_after("чат%d|м" % i) for i in range(20)}) > 5)

# ── 2. вентиль вероятности ──────────────────────────────────────────────────
разрешено = [channel.ping_allowed("чат%d|сообщение%d" % (i, i)) for i in range(4000)]
доля = 100.0 * sum(разрешено) / len(разрешено)
chk("пингуется 15–25%% молчаний (у живых 17.3%%): %.1f%%" % доля, 15.0 <= доля <= 25.0)
chk("решение устойчиво для одного чата",
    channel.ping_allowed("чат7|м3") == channel.ping_allowed("чат7|м3"))
chk("вентиль и срок сеются независимо (не одна монетка на двоих)",
    len({(channel.ping_allowed("к%d" % i), channel.ping_after("к%d" % i) // 60)
         for i in range(60)}) > 8)

# ── 3. прежние предохранители на месте ──────────────────────────────────────
chk("потолок «тишина старше двух часов» не тронут", channel.PING_MAX_AGE == 2 * 3600)
chk("пометка «Решён» через 10 минут после пинга", channel.RESOLVE_AFTER_PING == 10 * 60)
chk("окно дневных часов на месте", 9 in channel.PING_HOURS and 3 not in channel.PING_HOURS)

# ── 4. комментарий больше не врёт про часы ──────────────────────────────────
SRC = io.open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                           "brain", "channel.py"), encoding="utf-8").read()
chk("в коде нет утверждения «локальное время сервера» рядом с PING_HOURS",
    "локальное время сервера" not in SRC)

print("\nИТОГО: %d ок, %d провал" % (ok, bad))
sys.exit(1 if bad else 0)
