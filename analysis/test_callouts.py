def run_mixed():
    ok = 0
    for name, client, reply, want in MIXED_CASES:
        got, _tags = prefilter.enforce_callouts(reply, client, "", first_reply=False)
        if got == want:
            ok += 1
        else:
            print("[FAIL] смешанная: %-30s -> %r (ждали %r)" % (name, got, want))
    print("Смешанные заявки: %d OK из %d" % (ok, len(MIXED_CASES)))
    return ok == len(MIXED_CASES)

