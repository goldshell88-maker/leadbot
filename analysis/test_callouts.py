def run_white():
    ok = 0
    for name, reply, want_change in WHITE_CASES:
        got = prefilter.raise_white_floor(reply)
        changed = got != reply
        if changed == want_change:
            ok += 1
        else:
            print("[FAIL] белый акк: %-28s %r -> %r" % (name, reply, got))
        # на обычном аккаунте планка не применяется вовсе
        out, _tags = prefilter.enforce_callouts(reply, "смеситель", "", white=False)
        if out != reply and "от 1000" in out and "от 800" in reply:
            print("[FAIL] обычный акк подняли до 1000: %r" % out)
    print("Белый аккаунт: %d OK из %d" % (ok, len(WHITE_CASES)))
    return ok == len(WHITE_CASES)


def run():
    ok = 0
    fail = 0
    for desc, reply, client, prior, first, expect in CASES:
        out, tags = prefilter.enforce_callouts(reply, client, prior, first_reply=first)
        got = tags[0] if tags else None
        # для позитивных проверяем, что нужный тег есть; для негативных — что тегов нет
        good = (expect in tags) if expect else (not tags)
        status = "OK " if good else "FAIL"
        if good:
            ok += 1
        else:
            fail += 1
        print("[%s] %s" % (status, desc))
        if not good:
            print("      client:  %s" % client)
            print("      ждали:   %s | получили теги: %s" % (expect, tags))
            print("      reply→:  %s" % out)
    print("\nИтого: %d OK, %d FAIL из %d" % (ok, fail, len(CASES)))
    return fail == 0


def run_breakdown():
    """ПРИЗНАКИ ПОЛОМКИ — ОДНО ОПРЕДЕЛЕНИЕ НА ФАЙЛ (находка 24.08).

    _BREAKDOWN_RX был объявлен ДВАЖДЫ под одним именем: бытовой список у монтажных
    правил и компьютерный у формулы выезда. Второй молча затирал первый при импорте,
    и бытовая половина была мертва — «не сливает», «не отжимает», «подтекает», «гудит»
    поломкой не считались.

    Что это стоило: на «подключить стиральную машину, она подтекает» гард
    _drop_diagnostics_on_install считал задачу чистым монтажом и вырезал «диагностику»
    из формулы. Клиент слышал «Выезд бесплатный» вместо «Выезд и диагностика бесплатные»
    — мы сами теряли аргумент на ремонтной заявке. Мёртвый шаблон питал ещё три условия
    в enforce_callouts.
    """
    ok = fail = 0
    # сторож самого затирания: определение обязано быть одно
    _src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                             "brain", "prefilter.py"), encoding="utf-8").read()
    if _src.count("_BREAKDOWN_RX = re.compile") == 1:
        ok += 1
    else:
        fail += 1
        print("  FAIL: _BREAKDOWN_RX объявлен %d раз — второе определение затрёт первое"
              % _src.count("_BREAKDOWN_RX = re.compile"))

    БЫТОВЫЕ = ("не сливает воду", "не отжимает", "не набирает воду", "не запускается",
               "не стирает", "не моет", "не сушит", "подтекает", "гудит при отжиме",
               "не крутит барабан")
    КОМПЬЮТЕРНЫЕ = ("не грузится", "тормозит", "синий экран", "полосы на экране",
                    "артефакты", "барахлит", "перегревается", "померла", "сдохла",
                    "отвалился")
    ЧИСТЫЙ_МОНТАЖ = ("подключить стиральную машину", "установить бойлер",
                     "повесить телевизор", "собрать шкаф", "настроить роутер")
    for группа, ждём in ((БЫТОВЫЕ, True), (КОМПЬЮТЕРНЫЕ, True), (ЧИСТЫЙ_МОНТАЖ, False)):
        for t in группа:
            if bool(prefilter._BREAKDOWN_RX.search(t)) == ждём:
                ok += 1
            else:
                fail += 1
                print("  FAIL: «%s» — поломка=%s, а должно быть %s" % (t, not ждём, ждём))

    # ...и поведение, ради которого всё это: формула выезда
    ФОРМУЛА = "Выезд и диагностика бесплатные, приеду посмотрю"
    for t, ждём_диагностику in (("подключить стиральную машину, она подтекает", True),
                                ("подключить стиралку и она не запускается", True),
                                ("подключить бойлер, он не набирает воду", True),
                                ("подключить стиральную машину", False),
                                ("повесить телевизор на стену", False)):
        out = prefilter._drop_diagnostics_on_install(ФОРМУЛА, t)
        if ("диагностик" in out.lower()) == ждём_диагностику:
            ok += 1
        else:
            fail += 1
            print("  FAIL: «%s» → %s (диагностика ждалась=%s)" % (t, out, ждём_диагностику))

    print("\nПоломка против монтажа: %d OK, %d FAIL" % (ok, fail))
    return fail == 0


if __name__ == "__main__":
    _a = run()
    _b = run_white()
    _c = run_mixed()
    _d = run_breakdown()
    sys.exit(0 if (_a and _b and _c and _d) else 1)
