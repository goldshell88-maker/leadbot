# -*- coding: utf-8 -*-
"""КАЧЕСТВО ПУЛА ЭТАЛОНОВ: бот не должен учиться ошибкам операторов (правка 24.08).

Пул `brain/rag_examples.json` — то, по чему бот равняет тон: живые ответы операторов из
успешных диалогов. Вместе с интонацией он перенимал и ошибки, а отбора по грамотности в
петле обучения нет ни на одном из пяти шагов.

Замер до правки: 74 ответа с «в течении» и НИ ОДНОГО с правильным «в течение», 21 «что бы»
вместо «чтобы», два «здраствуйте». Всего 95 пар из 4140.

⚠ ПРОВЕРЯЕМ ТОЛЬКО ОТВЕТ (`a`), НИКОГДА ВОПРОС (`q`). Вопрос — речь КЛИЕНТА, и она обязана
остаться такой, как люди пишут: по ней ищутся похожие ситуации, и «причёсанный» вопрос
перестанет находить живые обращения с опечатками. Ошибка в вопросе — это НЕ дефект пула.

Офлайн, 0 токенов. Запуск: python3 analysis/test_rag_pool_quality.py
"""
import io
import json
import os
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ЗДЕСЬ)
import fix_rag_orthography as орф                   # noqa: E402

ПУЛ = os.path.join(os.path.dirname(ЗДЕСЬ), "brain", "rag_examples.json")

СЛУЧАИ = []


def chk(имя, получили, ждали):
    СЛУЧАИ.append((имя, получили, ждали))


данные = json.load(io.open(ПУЛ, encoding="utf-8"))
примеры = данные.get("examples") or []
chk("пул на месте", len(примеры) > 3000, True)

# ── 1. В ОТВЕТАХ НЕТ ОШИБОК, КОТОРЫЕ БОТ БУДЕТ ПОВТОРЯТЬ ────────────────────
грязные = [(e.get("a") or "") for e in примеры if орф.выпрямить(e.get("a") or "")[1]]
chk("ответов с ошибками орфографии", len(грязные), 0)
if грязные:
    for _г in грязные[:5]:
        print("   грязный ответ: %s" % _г[:100])

# ── 2. ВЫПРЯМИТЕЛЬ ДЕЛАЕТ ТО, ЧТО ОБЕЩАЕТ, И НЕ ТРОГАЕТ ЛИШНЕГО ─────────────
for исход, ждём in (
    ("Могу в течении часа подъехать", "Могу в течение часа подъехать"),
    ("В течении двух часов буду", "В течение двух часов буду"),
    ("Контакт подскажите что бы я мог связаться", "Контакт подскажите чтобы я мог связаться"),
    ("Здраствуйте, приеду", "Здравствуйте, приеду"),
    ("по этому и говорю", "поэтому и говорю"),
    # ⚠ А ВОТ ЭТО ТРОГАТЬ НЕЛЬЗЯ — законные обороты
    ("Приеду по этому адресу", "Приеду по этому адресу"),
    ("По этому поводу свяжусь", "По этому поводу свяжусь"),
    ("Что бы вы ни выбрали, сделаю", "Что бы вы ни выбрали, сделаю"),
    ("В течение часа буду", "В течение часа буду"),
):
    chk("выпрямитель: %s" % исход[:44], орф.выпрямить(исход)[0], ждём)

# ── 3. ИДЕМПОТЕНТНОСТЬ: второй прогон ничего не меняет ──────────────────────
_раз = орф.выпрямить("Могу в течении часа, что бы я успел")[0]
chk("выпрямитель идемпотентен", орф.выпрямить(_раз)[0], _раз)

# ── 4. СБОРЩИК ПУЛА ВЫПРЯМЛЯЕТ ТОЖЕ ─────────────────────────────────────────
# Иначе первая же пересборка вернёт в пул все 95 ошибок обратно.
_сборщик = io.open(os.path.join(ЗДЕСЬ, "build_rag_pool.py"), encoding="utf-8").read()
chk("сборщик зовёт выпрямитель для ОТВЕТА", "norm_ответ(" in _сборщик, True)
chk("сборщик НЕ выпрямляет вопрос", '"q": norm_ответ(' in _сборщик, False)
chk("правила орфографии живут в одном месте",
    _сборщик.count("fix_rag_orthography") >= 1 and "ПРАВИЛА = (" not in _сборщик, True)

# ⚠ ПОДСЧЁТ — ПОСЛЕ ВСЕХ ПРОВЕРОК, А НЕ ПОСРЕДИ ФАЙЛА. Он стоял здесь, и добавленные
# ниже проверки в него не попадали: они честно ложились в СЛУЧАИ, но `плохо` было уже
# посчитано, и набор оставался зелёным при сломанном правиле. Ровно так три поломки
# сборщика 25.08 не дали ни одного красного.

# ── СБОРКА ПУЛА: ВОСПРОИЗВОДИМАЯ И НЕ УНИЧТОЖАЮЩАЯ (замер 25.08) ─────────────
# Две беды разом, обе меряются исходником сборщика.
#  1. НЕВОСПРОИЗВОДИМОСТЬ. Источники читались `glob.glob` БЕЗ сортировки, то есть в
#     случайном порядке файловой системы. От порядка зависит, кто переживёт дедуп
#     («выживает более ранний»), и пересборка меняла 1237 пар из 4140. Пока это так,
#     петля обучения непроверяема: любой замер «до/после» меряет шум сборки.
#     После сортировки две сборки подряд дают ПОБАЙТНО одинаковый файл.
#  2. УНИЧТОЖЕНИЕ. Пересборка давала 1132 пары против 4140 в бою — стёрла бы 3027.
#     Сборщик не воспроизводит: corpus 2695 (входных диалогов читает меньше),
#     dump 151 (подаётся ключом --dump) и «этап7:*» 160 (таких пар он не умеет вовсе).
#     Поэтому сборка ДОБАВЛЯЮЩАЯ: берёт всё, что есть, и дополняет свежим.
#     Проверено на копии боевого файла: 4140 → 4134, повторный прогон не меняет ничего.
_СБОРЩИК = io.open(os.path.join(os.path.dirname(__file__), "build_rag_pool.py"),
                   encoding="utf-8").read()
chk("источники читаются в устойчивом порядке",
    "sorted(glob.glob(" in _СБОРЩИК and "for fp in glob.glob(" not in _СБОРЩИК, True)
chk("порядок классов тоже зафиксирован", "for cls in sorted(by):" in _СБОРЩИК, True)
chk("сборка добавляющая, а не затирающая",
    "перенесено из прежнего пула" in _СБОРЩИК, True)
chk("что сборщик не воспроизводит — печатается",
    "не воспроизводит" in _СБОРЩИК, True)

плохо = [(n, g, w) for n, g, w in СЛУЧАИ if g != w]
print("=" * 60)
for n, g, w in плохо:
    print("ПРОВАЛ  %-46s получили %r, ждали %r" % (n, g, w))
print("Качество пула эталонов: %d/%d" % (len(СЛУЧАИ) - len(плохо), len(СЛУЧАИ)))
sys.exit(1 if плохо else 0)
