# -*- coding: utf-8 -*-
"""ПРАВКИ ПО РАЗБОРУ СУДЬИ (28.08).

Модель-судья оценила 82 боевых ответа бота с контекстом переписки по трём шкалам.
Слабейшая — «ведёт к заявке»: 1,11 из 2, и 23 претензии из 60 про неназванное окно
приезда, 16 — про переспрос уже сказанного.

Дословно из разбора:
  «четвёртый ход, а адреса и окна приезда так и нет»
  «второй уточняющий вопрос подряд вместо адреса и окна приезда»
  «клиент уже описал поломку, бот третий раз спрашивает, что случилось»

Корень у первой группы один: воронка выходит на первом же «?» в реплике модели, а
модель умеет уточнять бесконечно. Правило трёх сообщений и так велит предложить
время с третьего хода — теперь оно не зависит от того, задала ли модель свой вопрос.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "brain"))
import server as s

ok = fail = 0


def проверить(имя, условие, факт=""):
    global ok, fail
    print(("  OK  " if условие else "  FAIL") + "  " + имя + ("" if условие else "  → " + str(факт)))
    if условие:
        ok += 1
    else:
        fail += 1


def воронка(reply, **kw):
    базовые = dict(has_addr=False, has_time=False, has_phone=False, prior_bot="",
                   problem_known=True, first_reply=False, seed="s",
                   slot_offer="сегодня к 18:00", last_client="", ход=0, речь_бота="")
    базовые.update(kw)
    return s._ensure_question(reply, **базовые)


print("── ПОТОЛОК УТОЧНЕНИЙ: С ТРЕТЬЕГО ХОДА ОКНО ЗВУЧИТ ───────────────")
проверить("ход 2 — ещё рано, уточнение остаётся",
          "18:00" not in воронка("Какая модель телевизора?", ход=2))
проверить("ход 3 — окно дописывается поверх вопроса",
          "18:00" in воронка("Какая модель телевизора?", ход=3))
проверить("ход 4 — то же",
          "18:00" in воронка("А что именно с изображением?", ход=4))
# ⚠ повтор окна — это спам той же воронки
проверить("окно уже звучало — второй раз не предлагаем",
          "18:00" not in воронка("Какая модель?", ход=4, речь_бота="Могу сегодня к 15:00, удобно?"))
# ⚠ пустой slot_offer значит «честного окна нет»: города не знаем, за чертой, приём закрыт
проверить("честного окна нет — час не выдумываем",
          "Могу" not in воронка("Какая модель?", ход=4, slot_offer=""))
проверить("финал не трогаем",
          воронка("Записал вас на завтра к 10:00", ход=4) == "Записал вас на завтра к 10:00")
проверить("после отказа окно не предлагаем",
          "18:00" not in воронка("К сожалению, не занимаемся таким", ход=4))

print("── ПЕРЕСПРОС ПОЛОМКИ, КОТОРУЮ КЛИЕНТ УЖЕ ОПИСАЛ ─────────────────")
проверить("вопрос о поломке срезается, на его место шаг",
          s._снять_переспрос_поломки("Что у вас случилось?", True, "сегодня к 18:00")
          == "Могу сегодня к 18:00, удобно вам будет?")
проверить("из составной реплики срезается только вопрос",
          s._снять_переспрос_поломки("Хорошо. Что случилось? Куда подъехать?", True, "сегодня к 18:00")
          == "Хорошо. Куда подъехать?")
проверить("поломка НЕ названа — вопрос остаётся",
          s._снять_переспрос_поломки("Что у вас случилось?", False, "сегодня к 18:00")
          == "Что у вас случилось?")
проверить("окна нет — реплику не обнуляем",
          s._снять_переспрос_поломки("Что у вас случилось?", True, "") == "Что у вас случилось?")

print("── ВЫДУМАННАЯ МАРКА В ОТВЕТЕ ────────────────────────────────────")
# «Придумал Samsung и кинескоп, клиент марку и тип не называл», «приписал клиенту
# модель смакс». Это не стилистика: выдуманная марка уезжает в карточку CRM и в
# работу мастеру.
проверить("выдуманная марка снимается, предложение живёт",
          s._снять_выдуманную_марку("Понял, Samsung не включается. Подъеду сегодня к 18:00",
                                    "телевизор не включается")
          == "Понял, не включается. Подъеду сегодня к 18:00")
# ⚠ марка последним словом — предложение держалось на ней, и это ещё и заочный диагноз
проверить("предложение, державшееся на марке, уходит целиком",
          s._снять_выдуманную_марку("Это скорее всего LG. Подъеду посмотрю", "экран потемнел")
          == "Подъеду посмотрю")
проверить("регистр восстанавливается, если срезали первое слово",
          s._снять_выдуманную_марку("Haier починю, адрес подскажете?", "не работает телевизор")
          == "Починю, адрес подскажете?")
проверить("клиент назвал марку — не трогаем",
          s._снять_выдуманную_марку("Понял, Samsung не включается. Подъеду сегодня",
                                    "у меня Samsung не включается")
          == "Понял, Samsung не включается. Подъеду сегодня")
# ⚠ заголовок объявления — законный источник марки
проверить("марка из заголовка объявления остаётся",
          "Samsung" in s._снять_выдуманную_марку("Samsung починю, адрес подскажете?", "тв не работает",
                                                 "Ремонт телевизоров Samsung LG на дому"))
проверить("реплику целиком не обнуляем",
          s._снять_выдуманную_марку("Samsung", "тв сломался") == "Samsung")

print("── ПРО ЦЕНУ НЕ МОЛЧИМ, ЕСЛИ СПРОСИЛИ ────────────────────────────")
# 12 претензий из 60: «молча проигнорировал вопрос цены, не увёл через объём работ»,
# «вопрос цены оставлен без единого слова, даже без „точнее на месте“», «клиент прямо
# упрекнул за молчание о цене, бот снова промолчал».
# ⚠ ЦИФРУ НЕ ВЫДУМЫВАЕМ: дописывается ровно увод из банка — то же, что предписывает
# первая ступень лестницы. Ступени с цифрой ставит модель по разметке стадии.
_c = s._ответить_про_цену("Что именно случилось с телевизором?", True, 0)
проверить("на молчание о цене дописывается увод", "по объёму работ" in _c, _c)
# ⚠ порядок: сперва ответ на заданный вопрос, потом свой вопрос
проверить("увод встаёт ПЕРЕД вопросом", _c.startswith("Беру по объёму"), _c)
проверить("реплика с ценой не трогается",
          s._ответить_про_цену("Ремонт от 1500 рублей", True, 0) == "Ремонт от 1500 рублей")
проверить("реплика с уводом не трогается",
          s._ответить_про_цену("Расценю на месте под вашу задачу", True, 0)
          == "Расценю на месте под вашу задачу")
проверить("бесплатный выезд считается ответом про деньги",
          s._ответить_про_цену("Выезд бесплатный при ремонте", True, 0)
          == "Выезд бесплатный при ремонте")
проверить("цену не спрашивали — не трогаем",
          s._ответить_про_цену("Что случилось?", False, 0) == "Что случилось?")
проверить("отказ деньгами не дополняем",
          s._ответить_про_цену("К сожалению, таким не занимаемся", True, 0)
          == "К сожалению, таким не занимаемся")
# ⚠ банк оболочек: одна и та же формулировка у всех подряд — «заезженная пластинка»
проверить("оболочка увода меняется по зерну",
          len({s._ответить_про_цену("Что случилось?", True, з) for з in range(5)}) >= 3)

print("── ПРОВОДКА ─────────────────────────────────────────────────────")
import ast, io
_д = ast.parse(io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                                    "brain", "server.py"), encoding="utf-8").read())
_вызовы = [n for n in ast.walk(_д)
           if isinstance(n, ast.Call) and getattr(n.func, "id", "") == "_ensure_question"]
проверить("в вызове воронки есть ход и речь бота",
          bool(_вызовы) and all(
              {"ход", "речь_бота"} <= {k.arg for k in в.keywords} for в in _вызовы),
          [sorted(k.arg or "" for k in в.keywords) for в in _вызовы])
_срез = [n for n in ast.walk(_д)
         if isinstance(n, ast.Call) and getattr(n.func, "id", "") == "_снять_переспрос_поломки"]
проверить("гард переспроса зовётся из боевого пути", len(_срез) >= 1, len(_срез))
_марка = [n for n in ast.walk(_д)
          if isinstance(n, ast.Call) and getattr(n.func, "id", "") == "_снять_выдуманную_марку"]
проверить("гард выдуманной марки зовётся из боевого пути", len(_марка) >= 1, len(_марка))
_цена = [n for n in ast.walk(_д)
         if isinstance(n, ast.Call) and getattr(n.func, "id", "") == "_ответить_про_цену"]
проверить("страховка по цене зовётся из боевого пути", len(_цена) >= 1, len(_цена))

print()
print("итог: ok=%d fail=%d" % (ok, fail))
sys.exit(1 if fail else 0)
