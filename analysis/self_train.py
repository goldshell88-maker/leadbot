# -*- coding: utf-8 -*-
"""ЦИКЛ САМООБУЧЕНИЯ: прогон → худшие ходы → правила → работа → снова прогон.

ЧТО ЭТО НЕ ДЕЛАЕТ. Бот не правит сам себя. Правило, выведенное моделью из разбора,
может быть верным, вредным или уже реализованным — отличить их может только замер и
человек. Автоматическая правка промпта по мнению модели о самой себе — самый короткий
путь к боту, который нравится модели и не нравится клиентам.

ЧТО ЭТО ДЕЛАЕТ. Замыкает цикл и не даёт ему разъехаться:

  1. ПРОГОН ЭТАЛОНА (сухой, 0 токенов). Даёт три числа: доля чистых ходов, дисциплина
     молчания, сила хода против живого оператора.
  2. ОТБОР РАБОТЫ. Берутся не «все ходы подряд», а два списка: ходы с нарушениями и
     ходы, где живой выбрал исторически более ценный ход. Это и есть повестка.
  3. РАЗБОР (по ключу --разбор, платно). Только отобранные ходы уходят модели по
     промпту `PROMPT-РАЗБОР.md`, и из ответа вынимаются строки «Правило: …».
  4. РЕЕСТР. Новые правила дописываются в `analysis/ПРАВИЛА.md` со статусом «новое».
     Дальше их судьбу решает человек: принять, отклонить, «уже есть».
  5. ДОКАЗАТЕЛЬСТВО. Принятое правило обязано получить тест и быть перемеренным на
     КОНТРОЛЬНОЙ выборке (`--контроль`), которой не было видно при выводе правила.

⚠ ПОЧЕМУ КОНТРОЛЬНАЯ ВЫБОРКА ОБЯЗАТЕЛЬНА. Без неё через десяток итераций бот будет
подогнан под тридцать диалогов, а число будет расти. Это не обучение, это заучивание.

Запуск:
    uv run python analysis/self_train.py                 # шаг цикла, 0 токенов
    uv run python analysis/self_train.py --разбор        # + разбор моделью, платно
    uv run python analysis/self_train.py --контроль      # прогон на контрольной выборке
"""
import io
import json
import os
import re
import subprocess
import sys
import time

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПОДРОБНО = os.path.join(КОРЕНЬ, "analysis", "BENCHMARK", "последний.json")
РЕЕСТР = os.path.join(КОРЕНЬ, "analysis", "ПРАВИЛА.md")
ПРОМПТ = os.path.join(КОРЕНЬ, "analysis", "PROMPT-РАЗБОР.md")

ШАПКА = """# Реестр правил бота

Каждая строка — правило, которое цикл самообучения вывел из живых диалогов.
Реестр ведётся руками: статус ставит человек, а не машина.

| Статус | Что значит |
|---|---|
| `новое` | предложено разбором, не рассмотрено |
| `принято` | реализовано в коде или промпте, закрыто тестом |
| `отклонено` | рассмотрено и отвергнуто, причина в колонке «замер» |
| `уже есть` | правило уже действует, разбор его не увидел |

⚠ Правило без теста считается непринятым: сегодня утром выяснилось, что правка
сценария в репозитории год не доезжала до боя именно потому, что её ничто не держало.

| # | Правило | Откуда | Статус | Тест | Замер |
|---|---|---|---|---|---|
"""


def прогон(контроль=False):
    ключи = [sys.executable, os.path.join(КОРЕНЬ, "analysis", "benchmark.py"),
             "--json", ПОДРОБНО]
    if контроль:
        ключи.append("--контроль")
    окружение = dict(os.environ)
    окружение.setdefault("LEADBOT_ANSWER_CACHE",
                         os.path.join(КОРЕНЬ, "data", "self_train_cache.jsonl"))
    p = subprocess.run(ключи, cwd=КОРЕНЬ, env=окружение,
                       capture_output=True, text=True)
    хвост = [s for s in p.stdout.splitlines() if not s.startswith("диалог ")
             and '"event"' not in s]
    print("\n".join(хвост[-30:]))
    if p.returncode:
        print(p.stderr[-1500:])
        return None
    return json.load(io.open(ПОДРОБНО, encoding="utf-8"))


def повестка(res):
    """Что чинить, в порядке вреда. Отдельно — форма, отдельно — сила хода."""
    работы = []
    for имя, к in sorted((res.get("нарушения") or {}).items(), key=lambda kv: -kv[1]):
        работы.append(("форма", "%s — %d ходов" % (имя, к), к))
    for х in res.get("слабее_живого") or []:
        работы.append(("сила", "живой сильнее на %.0f п.п.: «%s» против «%s»"
                       % (х["цена_живого"] - х["цена_бота"], х["бот"][:60], х["живой"][:60]), 1))
    for б in res.get("болтуны") or []:
        работы.append(("дисциплина", "влез в чужой диалог: «%s»" % б["бот"][:70], 5))
    return работы


def разобрать(res):
    """Отобранные ходы — модели, из ответа берём строки «Правило: …»."""
    sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
    import claude_api                                    # noqa: E402
    куски = []
    for х in (res.get("худшие") or [])[:6]:
        куски.append("КЛИЕНТ: %s\nБОТ: %s\nНАРУШЕНИЯ: %s"
                     % (х["клиент"], х["бот"], ", ".join(х["нарушения"])))
    for х in (res.get("слабее_живого") or [])[:6]:
        куски.append("КЛИЕНТ: %s\nБОТ: %s\nЖИВОЙ ОПЕРАТОР: %s\n"
                     "ИСТОРИЧЕСКАЯ ЦЕНА: ход бота %.0f %%, ход живого %.0f %%"
                     % (х["клиент"], х["бот"], х["живой"], х["цена_бота"], х["цена_живого"]))
    if not куски:
        print("разбирать нечего: нарушений и слабых ходов не нашлось")
        return []
    задание = (io.open(ПРОМПТ, encoding="utf-8").read()
               + "\n\n---\n\nНиже — ХУДШИЕ ходы бота с прогона эталона. По каждому дай "
                 "только раздел «Чему учить бота»: одну строку вида «Правило: …», "
                 "проверяемую, такую, чтобы по ней можно было написать код или тест.\n\n"
               + "\n\n---\n\n".join(куски))
    ответ = claude_api.messages(
        system="Отвечай по-русски. Только строки «Правило: …», без вступлений.",
        msgs=[{"role": "user", "content": задание}],
        model="claude-sonnet-5", max_tokens=2000)
    текст = "".join(b.get("text", "") for b in (ответ.get("content") or []))
    правила = [re.sub(r"^\W*Правило:\s*", "", s).strip()
               for s in текст.splitlines() if re.match(r"^\W*Правило:", s)]
    return [p for p in правила if len(p) > 20]


def в_реестр(правила, откуда):
    if not os.path.exists(РЕЕСТР):
        io.open(РЕЕСТР, "w", encoding="utf-8").write(ШАПКА)
    было = io.open(РЕЕСТР, encoding="utf-8").read()
    номер = было.count("\n| ") - 4
    новые = []
    for п in правила:
        if п[:60] in было:                     # то же правило уже предлагали
            continue
        номер += 1
        новые.append("| %d | %s | %s | новое |  |  |" % (номер, п.replace("|", "/"), откуда))
    if новые:
        io.open(РЕЕСТР, "a", encoding="utf-8").write("\n".join(новые) + "\n")
    return новые


def главное():
    контроль = "--контроль" in sys.argv
    print("=" * 68)
    print("ШАГ ЦИКЛА · выборка: %s" % ("КОНТРОЛЬНАЯ" if контроль else "обучающая"))
    print("=" * 68)
    res = прогон(контроль)
    if not res:
        return 1
    работы = повестка(res)
    print("\n" + "=" * 68)
    print("ПОВЕСТКА (%d пунктов, сверху то, что бьёт чаще):" % len(работы))
    for вид, текст, _ in работы[:12]:
        print("  [%-10s] %s" % (вид, текст))
    if контроль:
        print("\n⚠ Это КОНТРОЛЬНАЯ выборка. Правила по ней не выводят — она только "
              "доказывает, что правка работает не только на обучающей.")
        return 0
    if "--разбор" in sys.argv:
        print("\nразбор худших ходов моделью…")
        правила = разобрать(res)
        новые = в_реестр(правила, "эталон %s" % time.strftime("%d.%m"))
        print("правил предложено: %d, новых в реестре: %d" % (len(правила), len(новые)))
        for s in новые:
            print("  " + s)
        print("\nреестр: %s" % РЕЕСТР)
    else:
        print("\n(разбор моделью не запускался — добавьте --разбор, это платно)")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
