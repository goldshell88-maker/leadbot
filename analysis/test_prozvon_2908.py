# -*- coding: utf-8 -*-
"""«ПРОЗВОН ПЕРЕД ВЫЕЗДОМ» ПРИ ЗАЯВКЕ НА ДВА И БОЛЕЕ ДНЯ ВПЕРЁД (29.08).

Правило регламента, которого у бота не было. Дословно: «когда заявка создается на два
и более дня вперед, Прозвон перед выездом нужно ставить ОБЯЗАТЕЛЬНО, вне зависимости,
просил клиент об этом или нет» (пример регламента: обращение 01.10, визит 03.10).
Причина простая: за двое суток человек успевает забыть о записи или уехать, и мастер
приезжает в пустую квартиру.

Как было: флаг ставился только партнёру 619 и когда клиент попросил сам.

⚠ СЧИТАЕМ ПО ЧАСАМ КЛИЕНТА, А НЕ СЕРВЕРА. Сервер живёт по UTC; при написании этого
теста машина разработчика показывала 29.08, UTC — 28.08, Москва — 28.08. Тест,
написанный от даты машины, ошибся на сутки и обвинил верный код. Дату отсчёта берём
из territory.city_localtime, как это делает сам бот.

Запуск: uv run python analysis/test_prozvon_2908.py
Офлайн, 0 токенов.
"""
import datetime
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402
import territory                                        # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


def дата_города(город, сдвиг):
    л = territory.city_localtime(город)
    д = datetime.date(л.tm_year, л.tm_mon, л.tm_mday) + datetime.timedelta(days=сдвиг)
    return д.strftime("%d-%m-%Y")


print("── СКОЛЬКО ДНЕЙ ДО ВИЗИТА ───────────────────────────────────────")
for город in ("Москва", "Санкт-Петербург", "Владивосток", "Калининград"):
    ошибок = [с for с in range(0, 5)
              if s._dney_do_vizita(дата_города(город, с), город) != с]
    chk("%s: счёт дней верен на 0–4 дня" % город, not ошибок, ошибок)

print("── КОГДА СТАВИМ ГАЛОЧКУ ─────────────────────────────────────────")
for сдвиг, ждём in ((0, False), (1, False), (2, True), (3, True), (10, True)):
    д = дата_города("Москва", сдвиг)
    вышло = s._callbefore_flag("", "нужен ремонт холодильника", д, "Москва")
    chk("визит через %d дн. → прозвон %s" % (сдвиг, "ДА" if ждём else "нет"),
        вышло is ждём, вышло)

print("── ПРЕЖНИЕ ОСНОВАНИЯ НЕ ПОТЕРЯНЫ ────────────────────────────────")
chk("клиент попросил сам — ставим",
    s._callbefore_flag("", "позвоните перед выездом пожалуйста", "", "Москва"))
chk("партнёр 619 — ставим всегда", s._callbefore_flag("619", "ремонт", "", "Москва"))
chk("партнёр 0619 — тот же партнёр", s._callbefore_flag("0619", "ремонт", "", "Москва"))
chk("обычная заявка на сегодня — не ставим",
    s._callbefore_flag("", "ремонт холодильника", дата_города("Москва", 0), "Москва") is False)

print("── МУСОР НЕ ЛОМАЕТ И НЕ ВРЁТ ────────────────────────────────────")
# ⚠ НЕРАЗОБРАННАЯ ДАТА — НЕ ПОВОД СТАВИТЬ ГАЛОЧКУ. Иначе любая заявка без даты
# получала бы прозвон, и правило превратилось бы в «всегда».
for мусор in ("", "завтра", "31-02-2026", "не знаю", "2026-08-31", "0-0-0"):
    chk("дата %r → не разобрана, галочки нет" % мусор,
        s._dney_do_vizita(мусор, "Москва") == -1
        and s._callbefore_flag("", "ремонт", мусор, "Москва") is False)
# ⚠ ПРОШЛОЕ — ТОЖЕ НЕ ПОВОД: визит «вчера» это ошибка разбора, а не два дня вперёд
chk("дата в прошлом галочки не даёт",
    s._callbefore_flag("", "ремонт", дата_города("Москва", -3), "Москва") is False)

print("── СЧЁТ ИДЁТ ПО ЧАСАМ КЛИЕНТА ───────────────────────────────────")
# Владивосток +10, Калининград +2: у них «сегодня» может отличаться от UTC-даты,
# и правило обязано это учитывать — иначе ошибка ровно в сутки.
chk("у Владивостока и Калининграда «сегодня» своё",
    s._dney_do_vizita(дата_города("Владивосток", 2), "Владивосток") == 2
    and s._dney_do_vizita(дата_города("Калининград", 2), "Калининград") == 2)
_иcx = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
_бл = _иcx[_иcx.find("def _dney_do_vizita"):][:900]
chk("отсчёт берётся из часов города, а не сервера",
    "territory.city_localtime(city)" in _бл, _бл[:120])

print("── ФЛАГ ПЕРЕСЧИТАН ПОСЛЕ РАЗБОРА ДАТЫ ───────────────────────────")
# ⚠ ПОРЯДОК ЗДЕСЬ РЕШАЕТ ВСЁ. Флаг ставится в словаре lead ДО того, как разобрана дата
# визита, — там правило «два дня вперёд» видеть её не может физически. Пересчёт обязан
# стоять ПОСЛЕ блока, который заполняет visit_date, иначе правило мёртвое.
_поз_флаг = _иcx.find('"call_before_visit": _callbefore_flag(')
_поз_дата = _иcx.find('lead["visit_date"], lead["visit_time"] = _visit_from_reply(')
_поз_пересчёт = _иcx.find('lead["call_before_visit"] = _callbefore_flag(')
chk("пересчёт вообще есть", _поз_пересчёт > 0)
chk("пересчёт стоит ПОСЛЕ разбора даты",
    0 < _поз_дата < _поз_пересчёт, (_поз_дата, _поз_пересчёт))
chk("первичная установка флага осталась раньше", 0 < _поз_флаг < _поз_пересчёт)
_бл2 = _иcx[_поз_пересчёт:][:400]
chk("в пересчёт передаются дата и город",
    'lead.get("visit_date")' in _бл2 and 'lead.get("city")' in _бл2, _бл2[:120])

print("=" * 50)
print("Прозвон перед выездом (29.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
