# -*- coding: utf-8 -*-
"""АДРЕС ПЕРЕД ВРЕМЕНЕМ: сколько стоит правило владельца от 26.08.

ПОВОД. Владелец увидел боевую подсказку «берусь. Буду у вас через час-полтора, удобно
вам будет?» на втором ходу и сказал дословно: «Чтобы предложить время мы должны знать
адрес, вдруг клиент вне территории или ещё что-то». Правило деловое и понятное:
«час-полтора» — обещание черты города, а адреса мы в этот момент не знаем.

ПОЧЕМУ ЭТО НАДО ЗАМЕРИТЬ, А НЕ ПРОСТО СДЕЛАТЬ. Ровно этот ход вчера был поставлен по
замеру: предложить окно первым ходом — 37,0 % до заявки против 15,8 % у «когда вам
удобно». Убрать окно из ранних ходов = отменить самое сильное измеренное движение
воронки. Значит вопрос не «кто прав», а «что теряем и есть ли ход, который держит оба
условия»: адрес узнаём раньше обещания, но темп воронки не роняем.

ЧТО СЧИТАЕМ. По первому ходу оператора (все его сообщения подряд до ответа клиента)
раскладываем диалоги на четыре взаимоисключающие клетки и меряем долю дошедших до
заявки:

    окно        — назвал конкретное время приезда, адрес не спросил
    адрес       — спросил куда ехать, времени не назвал
    оба         — и то и другое в одном ходу        ← ход, который ищем
    ни того     — ни окна, ни адреса

⚠ КОНТРОЛЬ НА ОБРАТНУЮ ПРИЧИННОСТЬ. Окно легче назвать там, где клиент уже сам всё
рассказал. Поэтому вторая таблица — только ГОЛЫЕ старты: клиент в первом сообщении не
дал ни адреса, ни телефона, ни времени. Если преимущество держится и там, это рычаг.

Запуск: uv run python analysis/measure_addr_before_time.py
Офлайн, 0 токенов.
"""
import io
import json
import os
import re
import sys

# ⚠ stdout не перенастраиваем: это делает audit_dialogs при импорте, а две обёртки
# над одним буфером закрывают его, когда первую собирает сборщик мусора.
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter                                        # noqa: E402
import server as s                                      # noqa: E402
from audit_dialogs import КОРПУС, ПРЕДЛОЖИЛ_RX          # noqa: E402

АДРЕС_ВОПРОС_RX = re.compile(
    r"(?i)куда\s+(?:\w+\s+){0,3}(?:ехать|подъехать|приехать|подъезжать)|"
    r"адрес\w*\s*(?:подскажете|подскажите|скажите|напишите|какой|ваш)|"
    r"(?:подскажете|подскажите|скажите|напишите)\s+(?:ваш\s+|полный\s+)?адрес|"
    r"по\s+какому\s+адресу|где\s+вы\s+наход|территориальн\w*\s+(?:вы\s+)?где")
ВРЕМЯ_КЛИЕНТА_RX = re.compile(r"(?i)\bсегодня\b|\bзавтра\b|\bсейчас\b|\bк\s*\d{1,2}\b|\d{1,2}[:.]\d{2}")


def ходы(d, роль):
    """Сообщения одной роли, слитые в ходы: подряд идущие — один ход."""
    out, буфер = [], []
    for m in (d.get("messages") or []):
        т = (m.get("text") or "").strip()
        if not т:
            continue
        if (m.get("role") or "") == роль:
            буфер.append(т)
        elif буфер:
            out.append("\n".join(буфер))
            буфер = []
    if буфер:
        out.append("\n".join(буфер))
    return out


def заявка(d, кл_ходы):
    """Успех = КЛИЕНТ оставил телефон ПОСЛЕ первого хода оператора.

    ⚠ ПОЧЕМУ НЕ ПОЛНОЕ ОПРЕДЕЛЕНИЕ ПРОЕКТА («телефон И названное окно»). Первая
    редакция этого файла считала именно так — и цифры врали в свою пользу. Клетки
    «окно» и «оба» задаются наличием окна в ПЕРВОМ ходу оператора, а окно входит и в
    определение успеха: половина условия выполнялась самим фактом попадания в клетку.
    Замкнутый круг, и он раздувал ровно те две клетки, ради которых всё считается.

    Здесь исход даёт ДРУГАЯ сторона: клиент прислал номер. Это то, чего оператор не
    может поставить себе сам, и то, без чего заявки не бывает.
    """
    return bool(prefilter.phones_in(" \n".join(кл_ходы[1:])))


def клетка(ход):
    окно = bool(ПРЕДЛОЖИЛ_RX.search(ход))
    адрес = bool(АДРЕС_ВОПРОС_RX.search(ход))
    return ("оба" if окно and адрес else
            "окно" if окно else
            "адрес" if адрес else "ни того")


def голый_старт(первое_клиента):
    return not (s._ADDR_RX.search(первое_клиента)
                or prefilter.phones_in(первое_клиента)
                or ВРЕМЯ_КЛИЕНТА_RX.search(первое_клиента))


def таблица(заголовок, счёт):
    print("\n" + заголовок)
    база_у = sum(у for у, в in счёт.values())
    база_в = sum(в for у, в in счёт.values()) or 1
    print("  %-9s %8s %8s %8s" % ("первый ход", "диалогов", "телефон", "доля"))
    for имя in ("оба", "окно", "адрес", "ни того"):
        у, в = счёт.get(имя, (0, 0))
        if not в:
            continue
        print("  %-9s %8d %8d %7.1f%%" % (имя, в, у, 100.0 * у / в))
    print("  %-9s %8d %8d %7.1f%%" % ("ВСЕГО", база_в, база_у, 100.0 * база_у / база_в))


def главное():
    все, голые = {}, {}
    пропущено = 0
    for line in io.open(КОРПУС, encoding="utf-8"):
        try:
            d = json.loads(line)
        except Exception:
            continue
        оп = ходы(d, "operator")
        кл = ходы(d, "client")
        if not оп or not кл:
            пропущено += 1
            continue
        k = клетка(оп[0])
        ок = 1 if заявка(d, кл) else 0
        у, в = все.get(k, (0, 0))
        все[k] = (у + ок, в + 1)
        if голый_старт(кл[0]):
            у, в = голые.get(k, (0, 0))
            голые[k] = (у + ок, в + 1)
    таблица("ВЕСЬ КОРПУС (диалогов без первого хода оператора пропущено: %d)" % пропущено, все)
    таблица("ТОЛЬКО ГОЛЫЕ СТАРТЫ (клиент не дал ни адреса, ни телефона, ни времени)", голые)


if __name__ == "__main__":
    главное()
