# -*- coding: utf-8 -*-
"""СЕМЬ БОЕВЫХ ДИАЛОГОВ 29-30.08 — СЕМЬ ДЕФЕКТОВ РАЗНЫХ КЛАССОВ.

1. ХИМКИ (AUX залит): бот дважды сказал «только на выезд» разными словами.
   `_снять_самоповтор` сличает дословные четвёрки — смысловой повтор не видел.
2. МОСКВА (оптика): «Как я понял это оптика» → бот: «подъеду посмотрю». Регламент:
   оптоволокно — ПО СОГЛАСОВАНИЮ. Роутер знал «оптоволокно», но не «оптику»,
   а модель приняла напрямую — правило в плейбуке без гарда.
3. ВОЛГОДОНСК (экран ТВ): «поменять экран на телевизоре» — бот начал принимать.
   Слова владельца: «замена экрана это то же самое, что замена матрицы».
4. КУДРОВО (принтер): бот сам поставил диагноз («обычно с роликами связано») и
   после нечитаемого видео спросил «Что именно не работает?».
5. ПЯТИГОРСК (сборка ПК): «мне выезд не подходит» → бот попрощался, а диалог
   в панели остался живым. Теперь `client_closed` едет в LeadChat.
6. НОВОСИБИРСК (микрофон): «починить микрофон сколько стоит?» — бот начал
   принимать. Микрофон в регламенте не прописан → «Прочая» → согласование.
7. РЫБИНСК (ТВ): клиент «Завтра можем?» → бот «понял, завтра подойдёт?» — эхо.
   Порядок владельца: сначала адрес, потом время.

ЧЕМ ПРОВЕРЕНО: все гарды прогнаны по боевому корпусу (реплики операторов и пары
клиент→оператор). После сужений: эхо дня — 0 ложных, вопрос поломки — 0 ложных
(широкая версия портила 221 живую реплику — «нужно понять, в чём дело» это
обоснование выезда, а не вопрос), повтор выезда — 0, оптика — 2 ложных сняты
гардом (отрицание «врятли оптика», «оптический терминал» = настройка роутера).

Запуск: uv run python analysis/test_uroki_3008.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter  # noqa: E402
import server as s  # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── 1. ПОВТОР «ТОЛЬКО ВЫЕЗД» ─────────────────────────────────────")
_прош = "я только на выезд работаю, мастерской нет, сам подъеду к вам"
_нов = "у себя не принимаю, только на дом выезжаю. Гнездо гляну и почищу. Могу через час-полтора, удобно?"
_после = s._снять_повтор_выезда(_нов, _прош)
chk("повтор мысли вырезан", "не принимаю" not in _после and "на дом выезжаю" not in _после,
    _после[:60])
chk("дело осталось", "Гнездо гляну" in _после)
chk("первый раз мысль не трогается", s._снять_повтор_выезда(_нов, "Здравствуйте!") == _нов)

print("── 2. ОПТИКА — СОГЛАСОВАНИЕ ─────────────────────────────────────")
chk("«как я понял это оптика» ловится",
    (prefilter.check_soglasovanie("как я понял это оптика") or {}).get("sub") == "оптоволокно")
chk("«оптику варите?» ловится",
    (prefilter.check_soglasovanie("добрый день, оптику варите ?") or {}).get("sub") == "оптоволокно")
chk("«врятли оптика» — отрицание, не ловится",
    prefilter.check_soglasovanie("хз, кабель от роутера на комп, врятли оптика") is None)
chk("оптический терминал = настройка роутера, не ловится",
    prefilter.check_soglasovanie("купил оптический терминал, можно подключить?") is None)
chk("оптический привод — работа ПК, не ловится",
    prefilter.check_soglasovanie("оптический привод не читает диски") is None)

print("── 3. ЗАМЕНА ЭКРАНА ТВ = МАТРИЦА ────────────────────────────────")
def _отказ(т):
    return [и for и, rx, *_ in prefilter._REFUSE if rx.search(т.lower())]
chk("«поменять экран на телевизоре»", "матрица" in _отказ("сколько стоит поменять экран на телевизоре"))
chk("«замена экрана телевизора»", "матрица" in _отказ("замена экрана телевизора сколько"))
chk("«экран поменять на тв»", "матрица" in _отказ("экран поменять на тв надо"))
chk("замена экрана НОУТБУКА не отказ", "матрица" not in _отказ("заменить экран на ноутбуке"))
chk("замена экрана без ТВ рядом не отказ", "матрица" not in _отказ("нужно поменять экран"))

print("── 4. ВОПРОС ПОСЛЕ СОБСТВЕННОГО ДИАГНОЗА ────────────────────────")
chk("после диагноза вопрос о поломке вырезан",
    s._снять_лишний_вопрос_поломки(
        "Что именно не работает?", "зажевывает бумагу",
        "Обычно с роликами или направляющими связано, но надо смотреть") == "")
chk("без диагноза вопрос уместен и остаётся",
    s._снять_лишний_вопрос_поломки("Что случилось?", "принтер", "Здравствуйте!")
    == "Что случилось?")
chk("«нужно понять, в чём дело» — обоснование, не трогается",
    s._снять_лишний_вопрос_поломки(
        "для начала нужно понять в чем дело", "не печатает", "Обычно с роликами связано")
    == "для начала нужно понять в чем дело")

print("── 5. «ВЫЕЗД НЕ ПОДХОДИТ» = КЛИЕНТ ЗАКРЫЛ ───────────────────────")
chk("«мне выезд не подходит» ловится", bool(s._КЛИЕНТ_ЗАКРЫЛ_RX.search("мне выезд не подходит")))
chk("«завтра не подходит» — про время, НЕ ловится",
    not s._КЛИЕНТ_ЗАКРЫЛ_RX.search("завтра не подходит"))
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
chk("client_closed отдаётся отдельным полем", '"client_closed": bool(_КЛИЕНТ_ЗАКРЫЛ_RX' in _ИСХ)
_ЛЧ = io.open(os.path.join(КОРЕНЬ, "brain", "leadchat.py"), encoding="utf-8").read()
chk("client_closed уезжает в meta для LeadChat", '"client_closed": bool(result.get("client_closed"))' in _ЛЧ)

print("── 6. МИКРОФОН — СОГЛАСОВАНИЕ ───────────────────────────────────")
chk("«починить микрофон» ловится",
    (prefilter.check_soglasovanie("починить микрофон сколько стоит?") or {}).get("sub")
    == "микрофон (ремонт)")
chk("«микрофон не работает» ловится",
    (prefilter.check_soglasovanie("микрофон перестал работать") or {}).get("sub")
    == "микрофон (ремонт)")
chk("ПОДКЛЮЧИТЬ микрофон — периферия, берём",
    prefilter.check_soglasovanie("подключить микрофон к компьютеру") is None)

print("── БЭКСТОП: ТЕМА В РЕЧИ + БОТ ПРИНИМАЕТ → СВЕРКА ────────────────")
chk("бэкстоп стоит в воронке",
    "prefilter.soglas_topic(client_all or \"\")" in _ИСХ
    and _ИСХ.index('elif reply and prefilter.soglas_topic') > 0)

print("── 7. ЭХО ДНЯ КЛИЕНТА ───────────────────────────────────────────")
_э = s._снять_эхо_дня("понял, завтра подойдёт?", "Завтра можем?", False)
chk("эхо заменено", "подойдёт?" not in _э, _э)
chk("без адреса — сперва адрес (порядок владельца)", "адрес" in _э.lower() or "куда" in _э.lower(), _э)
_э2 = s._снять_эхо_дня("завтра удобно?", "давайте завтра", True)
chk("с адресом — вопрос часа", "время" in _э2.lower() or "час" in _э2.lower() or "сколько" in _э2.lower(), _э2)
chk("предложение окна — не эхо",
    s._снять_эхо_дня("завтра в 10-10:30 удобно?", "Завтра можем?", False)
    == "завтра в 10-10:30 удобно?")
chk("вопрос часа — не эхо",
    s._снять_эхо_дня("Завтра во сколько удобно?", "Возможно завтра", False)
    == "Завтра во сколько удобно?")
chk("пулы держат по 6 вариантов",
    len(s._ЭХО_ДНЯ_ПУЛ_АДРЕС) >= 6 and len(s._ЭХО_ДНЯ_ПУЛ_ВРЕМЯ) >= 6)

print("── ГАРДЫ ЖИВЫЕ ──────────────────────────────────────────────────")
chk("повтор выезда вызывается", "reply = _снять_повтор_выезда(reply, bot_prior)" in _ИСХ)
chk("вопрос поломки вызывается", "reply = _снять_лишний_вопрос_поломки(reply," in _ИСХ)
chk("эхо дня вызывается", "reply = _снять_эхо_дня(reply," in _ИСХ)

print("=" * 50)
print("Уроки 30.08 (семь диалогов): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
