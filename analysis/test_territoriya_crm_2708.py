# -*- coding: utf-8 -*-
"""ЗАЯВКА СОБИРАЛАСЬ, ВСТАВАЛА В ОЧЕРЕДЬ И ПАДАЛА У РАСШИРЕНИЯ: «город не найден».

ВЛАДЕЛЕЦ 27.08 по диалогу с Иваном (СПб, партнёр 723): «бот сам договорился и договорился
достаточно хорошо, мне пришло уведомление, что можно создать заявку, но почему-то она снова
не создалась».

ЧТО ПОКАЗАЛ БОЕВОЙ ЖУРНАЛ. Заявка создалась и встала в очередь — упало РАСШИРЕНИЕ:

    15:38:03 [ЗАЯВКА] в очереди расширения: kp (тел. …2243)
    15:39:58 [ЗАЯВКА] расширение не смогло (9001112243:2026-08-26):
             город «Санкт-Петербург» не найден в kp

ПРИЧИНА. В списке городов CRM на направлении КП нет строки «Санкт-Петербург»: там «СПБ 1»,
«СПБ 2», «СПБ 3», «СПБ 4» — четыре ТЕРРИТОРИИ филиала. Бот присылал название города,
`pickOption` не находил ничего, и полностью собранная заявка падала на последнем шаге.

За 30 дней журнал насчитал шесть таких потерь: Петербург на КП — четыре раза (23.08 ×3,
26.08 ×1), Рыбинск и Кисловодск на БТ — по разу.

ЧТО ОКАЗАЛОСЬ ПОД РУКОЙ. Справочник `filials.CITY_TERRITORIES` знает это соответствие с самого
начала — и не читал его НИКТО: grep по проекту давал одно объявление и ноль вызовов. А какая
именно из четырёх территорий нужна, знает КАРТА: контур, в который попал адрес клиента,
называется ровно «СПБ 4».

⚠ ГАДАТЬ МЕЖДУ ЧЕТЫРЬМЯ «СПБ» НЕЛЬЗЯ. Не тот филиал хуже, чем ручной разбор: заявка уедет в
чужую смену, и мастер не приедет. Нет адреса или карта не ответила — territory не ставим, и
расширение honestly скажет «не найден», приложив список того, что оно видело.

Запуск: uv run python analysis/test_territoriya_crm_2708.py
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import filials as f                                    # noqa: E402
import server as s                                     # noqa: E402

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:110]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


print("\n1. СПРАВОЧНИК ТЕРРИТОРИЙ ОТКРЫТ И ЧИТАЕТСЯ")
проверь("СПб на КП — четыре территории",
        f.territories("Санкт-Петербург", "kp") == ["СПБ 1", "СПБ 2", "СПБ 3", "СПБ 4"])
проверь("на БТ — одна", f.territories("Санкт-Петербург", "bt") == ["СПБ"])
проверь("Москва на КП — две", len(f.territories("Москва", "kp")) == 2)
проверь("у обычного города территорий нет", f.territories("Курск", "kp") == [])
проверь("направление обязательно", f.territories("Санкт-Петербург", "") == [])

print("\n2. ТЕРРИТОРИЯ ВЫБИРАЕТСЯ ПО КАРТЕ, А НЕ УГАДЫВАЕТСЯ")
def _т(адрес, город="Санкт-Петербург", напр="kp"):
    return s._территория_crm(напр, {"city": город}, {}, [{"role": "client", "text": адрес}])
_невский = _т("Невский проспект 24, кв 9")
проверь("адрес в центре → СПБ 4", _невский == "СПБ 4", _невский)
_восток = _т("Дальневосточный проспект 19")
проверь("адрес на востоке → другая территория", _восток and _восток != _невский, _восток)
проверь("номер квартиры карте не мешает (её геокодер не находит с «кв»)",
        _т("Невский проспект 24, кв 9") == _т("Невский проспект 24"))

print("\n3. ГДЕ ГАДАТЬ НЕЛЬЗЯ — НЕ ГАДАЕМ")
проверь("нет адреса и территорий несколько — territory пустой",
        s._территория_crm("kp", {"city": "Санкт-Петербург"}, {}, []) == "")
проверь("а если территория одна — ставим её без адреса",
        s._территория_crm("bt", {"city": "Санкт-Петербург"}, {}, []) == "СПБ")
проверь("обычный город territory не получает", _т("Ленина 5", "Курск") == "")
проверь("нет города — нет территории", s._территория_crm("kp", {}, {}, []) == "")

print("\n4. ПРОВОДКА: territory доезжает до заявки и до расширения")
сервер = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
проверь("lead несёт territory", '"territory": _территория_crm(d, kr, state, messages),' in сервер)
проверь("в карту уходит разобранный адрес, а не сырая строка",
        "_р = _parse_addr(адрес, город)" in сервер)
ext = io.open(os.path.join(КОРЕНЬ, "ui", "crm-extension", "offscreen.js"), encoding="utf-8").read()
проверь("расширение пробует территорию первой",
        "let cityId = lead.territory ? pickOption(citySel, lead.territory) : '';" in ext)
проверь("и город — вторым", "if (!cityId) cityId = pickOption(citySel, lead.city);" in ext)
проверь("ошибка называет список, который расширение видело",
        "В списке CRM: " in ext)
проверь("и называет территорию, если она была", "(территория «" in ext)

print("\n" + "─" * 60)
print("проверок: %d, провалов: %d" % (всего[0], len(ошибки)))
for о in ошибки:
    print("  ПРОВАЛ:", о)
sys.exit(1 if ошибки else 0)
