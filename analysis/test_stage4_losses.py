# -*- coding: utf-8 -*-
"""Проигрыши бота живому диспетчеру — слепая сверка этапа 4 (analysis/LEARNING/04-СВЕРКА.md).

Из 238 отсуженных вслепую пар бот проиграл в 35. Разбор дал четыре повторяющихся
дефекта — F-008…F-011. Здесь каждый закреплён проверкой на РОУТЕРАХ и ГАРДАХ, то
есть без обращения к модели: набор офлайновый и входит в analysis/_run_offline.sh.

⚠ Эти проверки писались ДО починки и обязаны были падать. Если набор зелёный на
коде, где дефект не исправлен, — значит проверка написана слабо, а не дефекта нет.

Запуск: python3 analysis/test_stage4_losses.py
"""
import io
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "brain"))

import prefilter                                                     # noqa: E402

ok = bad = 0


def chk(имя, условие, подсказка=""):
    global ok, bad
    if условие:
        ok += 1
        print("[OK ] %s" % имя)
    else:
        bad += 1
        print("ПРОВАЛ: %s%s" % (имя, (" — " + подсказка) if подсказка else ""))


# ── F-008: прямой вопрос о выезде обязан получить формулу, а не встречный вопрос ──
# Живой диспетчер: «выезд и диагностика 1000р в случае работ»; бот: «Зависит от
# техники, что за прибор у вас?». Клиент спросил про деньги и ответа не получил.
def озвучка(реплика, речь, направление, prior=""):
    r, tags = prefilter.enforce_callouts(реплика, речь, prior, direction=направление)
    return r, tags


_ФОРМУЛА_RX = re.compile(r"бесплатн|1000", re.IGNORECASE)

for напр, случай in (("kp", "ноутбук не включается, сколько стоит ваш выезд?"),
                     ("bt", "стиралка не отжимает, сколько стоит выезд?"),
                     ("mnc", "розетку поменять, выезд платный?")):
    r, tags = озвучка("Что у вас случилось?", случай, напр, prior="Здравствуйте")
    chk("F-008 [%s] прямой вопрос о выезде получает формулу" % напр,
        bool(_ФОРМУЛА_RX.search(r)) or bool(tags),
        "ответ «%s» без озвучки выезда" % r[:50])

# Частный случай из сверки: клиент ставит УСЛОВИЕ, а не спрашивает цену.
# ⚠ Речь клиента здесь — вся, а не последняя реплика: пока техника не названа,
# регламент запрещает обещать бесплатность вслепую, и гард обязан молчать.
r, tags = озвучка("Что у вас случилось?",
                  "стиралка не отжимает. ну вы можете приехать если выезд бесплатный к 18 ч",
                  "bt", prior="Здравствуйте, что случилось?")
# в пуле три формулировки, «бесплатно» — только одна из них
_БЕСПЛАТНО_RX = re.compile(r"бесплатн|ничего\s+не\s+бер[её]м|только\s+за\s+работу", re.IGNORECASE)
chk("F-008 «приеду, если выезд бесплатный» — подтверждаем бесплатность",
    bool(_БЕСПЛАТНО_RX.search(r)), "ответ «%s»" % r[:50])
r2, _ = озвучка("Что у вас случилось?", "можете приехать если выезд бесплатный", "bt",
                prior="Здравствуйте")
chk("F-008 техника НЕ названа — бесплатность вслепую не обещаем (регламент)",
    not _БЕСПЛАТНО_RX.search(r2), "пообещали, не зная техники: %s" % r2[:50])

# ── F-009: скупка и продажа — прямой отказ, а не «сверюсь по графику» ──
# Живой: «Продажами не занимаюсь»; бот: «По графику сверюсь и чуть позже дам ответ».
# Этап 3: конверсия скупки 5.7% против базы 11.5% — ветку закрывают быстро.
for текст in ("вы занимаетесь продажей б/у машин? нам нужна кофемашина",
              "скупаете технику? хочу продать холодильник",
              "продаёте бу стиральные машины?"):
    отказ = prefilter.check_refuse(текст)
    соглас = prefilter.check_soglasovanie(текст)
    chk("F-009 скупка → отказ, не согласование: %s" % текст[:38],
        bool(отказ) and not соглас,
        "отказ=%s, согласование=%s" % (bool(отказ), bool(соглас)))

# ── F-010: статусный вопрос после записи — человеку, а не отписка ──
# Живой: «да скоро вам наберу»; бот: «Уточню по времени и вернусь к вам».
import escalation                                                    # noqa: E402

СТАТУС = [
    ("Ну что вас ждать или нет", True),
    ("мастер будет сегодня или нет?", True),
    ("во сколько мастер приедет, я жду", True),
    ("вы вообще приедете?", True),
]
ЗАПИСЬ = "Записал вас на сегодня, мастер подъедет к 15:00"
for текст, ждём in СТАТУС:
    r = escalation.detect(текст, all_client_text=текст, bot_history=ЗАПИСЬ, booked=True)
    chk("F-010 статус после записи → человеку: %s" % текст[:38],
        bool(r) == ждём, "detect вернул %s" % (r or "None"))

# ── F-011: цена в первом ходе — антипаттерн (этап 3: −2.4 п.п.) ──
# Живой: «давайте заеду посмотрим»; бот: «Ремонт видеокарты от 5000».
# Проверяем гард первого хода: цену в первом ответе дописывать нельзя.
import server                                                        # noqa: E402

_ЦИФРА_RX = re.compile(r"\bот\s*\d{3,}|\d{3,}\s*(?:руб|₽)", re.IGNORECASE)
chk("F-011 в первом ходе бота гард цену не дописывает",
    not _ЦИФРА_RX.search(server._добрать_номер("да, сделаю. Какая модель ноутбука?")),
    "гард добавил цифру")
r, tags = озвучка("да, сделаю. Какая модель?", "можно приехать посмотреть ноутбук", "kp",
                  prior="")
chk("F-011 на первом ходе озвучка цены не навязывается",
    not _ЦИФРА_RX.search(r), "первый ход получил цену: %s" % r[:60])

# ── F-012: клиент ОТЛОЖИЛ визит — не дожимать его окном и номером ────────────
# Пересверка после починок (19.08): из 35 проигрышей осталось 10, и худший — этот.
# Клиент: «Завтра не сможем приехать, я вам напишу когда сможем». Бот: «хорошо, жду
# от вас. По какому адресу? / Могу сегодня к 10:00-10:30, удобно? / И номер ваш
# подскажите» — три требования подряд человеку, который явно попросил паузу.
# Живой диспетчер отвечает одной строкой: «хорошо, буду ждать сообщения».
# Сценарий «отложил» — 1425 ходов корпуса, конверсия 14.4% против базы 11.5%: эти
# клиенты возвращаются, если их не давить.
ОТСРОЧКИ = [
    "Завтра не сможем приехать, я вам напишу когда сможем, чтоб посмотрели",
    "я подумаю и напишу вам",
    "давайте позже, сейчас некогда",
    "пока не готовы, сообщу как определимся",
    "нужно посоветоваться с женой, потом напишу",
]
for текст in ОТСРОЧКИ:
    chk("F-012 отсрочка распознана: %s" % текст[:40], prefilter.postponed(текст),
        "postponed вернул False")
chk("F-012 «когда приедете» отсрочкой НЕ считается",
    not prefilter.postponed("когда приедете?"))
chk("F-012 «давайте сегодня» отсрочкой НЕ считается",
    not prefilter.postponed("давайте сегодня после 18"))
chk("F-012 при отсрочке номер не добираем",
    "номер" not in server._добрать_номер("Могу сегодня к 10:00, удобно?",
                                         отложил=True).lower())
chk("F-012 без отсрочки добираем как раньше",
    "номер" in server._добрать_номер("Могу сегодня к 10:00, удобно?").lower())
chk("F-012 предложение времени при отсрочке снимается",
    "10:00" not in server._снять_дожим(
        "хорошо, жду от вас\nМогу сегодня к 10:00-10:30, удобно вам будет?", отложил=True))
chk("F-012 без отсрочки предложение времени остаётся",
    "10:00" in server._снять_дожим(
        "хорошо\nМогу сегодня к 10:00-10:30, удобно вам будет?", отложил=False))

print("=" * 62)
print("Проигрыши сверки (этап 4): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
