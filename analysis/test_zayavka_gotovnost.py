def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:90]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


def часы(ч, м=0, день=26):
    """struct_time «сейчас в городе клиента» — подменяем, чтобы прогон не зависел от суток."""
    return time.localtime(time.mktime((2026, 8, день, ч, м, 0, 0, 0, -1)))


class ЧасыГорода:
    """Подмена territory.city_localtime на фиксированный момент."""

    def __init__(self, ч, м=0, день=26):
        self.момент = часы(ч, м, день)
        self.прежние = None

    def __enter__(self):
        self.прежние = s.territory.city_localtime
        s.territory.city_localtime = lambda город, now=None: self.момент
        return self

    def __exit__(self, *_):
        s.territory.city_localtime = self.прежние


