# -*- coding: utf-8 -*-
"""ОРИЕНТИР РЯДОМ С ДОМОМ — приём на лояльность из регламента КЦ (29.08).

Регламент, раздел про адрес: «Для получения большей лояльности клиента используйте
ориентиры, уточняйте что именно находится с его домом или в нем», с примерами:
    «У вас рядом с домом еще магазин "Магнит" находится, верно?»
    «У вас в доме аптека еще есть, да?»
    «У вас дом напротив школы, верно же?»

⚠ ЭТО НЕ ВОПРОС ОБ АДРЕСЕ. Адрес уже известен; объект бот НАЗЫВАЕТ сам, посмотрев
карту, и просит подтвердить. Спрашивать «что у вас рядом?» нельзя: за 45 516 реплик
живых операторов такой вопрос встретился трижды, и все три раза про район, а не про
соседний магазин.

ОТКУДА ДАННЫЕ БЕЗ КЛЮЧЕЙ. Overpass, два зеркала. Замер 29.08: overpass.osm.ch отвечал
3 раза из 3 и все три раза ПУСТОТОЙ — у него только швейцарская база. Считать такой
ответ успехом значит повторить ошибку с заглушкой «Выбрать ...» в справочнике CRM:
проверять доступность вместо пригодности. Годных зеркала два, каждое 2/3, перебор ≈89 %.
Качество на живых адресах: Пятёрочка (Москва), Вкустер (СПб), аптека Столички (СПб),
в Саранске не нашлось ничего — молчим.

Запуск: uv run python analysis/test_orientir_2908.py
Офлайн, 0 токенов, БЕЗ обращений к карте.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import geocode                                          # noqa: E402
import server as s                                      # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


def узел(**теги):
    return {"tags": теги}


print("── КОГО БЕРЁМ В ОРИЕНТИРЫ ───────────────────────────────────────")
chk("сетевой магазин важнее аптеки",
    s and geocode._лучший_ориентир([узел(amenity="pharmacy"),
                                    узел(shop="supermarket", brand="Пятёрочка")])
    == {"имя": "Пятёрочка", "вид": "магазин"})
chk("аптека важнее школы",
    geocode._лучший_ориентир([узел(amenity="school", name="Школа 5"),
                              узел(amenity="pharmacy", name="Столички")])["вид"] == "аптека")
# ⚠ БЕЗ ИМЕНИ МАГАЗИН НЕ ОРИЕНТИР: «у вас рядом магазин, верно?» звучит как угадывание.
# Аптеке и школе имя не нужно — их узнают и без вывески.
chk("магазин без имени не берём",
    geocode._лучший_ориентир([узел(shop="supermarket")]) == {})
chk("аптека без имени берётся",
    geocode._лучший_ориентир([узел(amenity="pharmacy")])["вид"] == "аптека")
chk("чужие виды объектов игнорируем",
    geocode._лучший_ориентир([узел(amenity="restaurant", name="Кафе"),
                              узел(shop="clothes", name="Одежда")]) == {})
chk("пусто на входе — пусто на выходе",
    geocode._лучший_ориентир([]) == {} and geocode._лучший_ориентир(None) == {})
chk("бренд предпочитается имени",
    geocode._лучший_ориентир([узел(shop="supermarket", name="Продукты"),
                              узел(shop="supermarket", brand="Магнит")])["имя"] == "Магнит")

print("── ФРАЗЫ ДОСЛОВНО ИЗ РЕГЛАМЕНТА ─────────────────────────────────")
chk("магазин: называем по имени",
    s._фраза_ориентир({"имя": "Магнит", "вид": "магазин"})
    == "у вас рядом с домом ещё «Магнит», верно?")
chk("аптека: «в доме аптека ещё есть, да?»",
    s._фраза_ориентир({"вид": "аптека"}) == "у вас в доме аптека ещё есть, да?")
chk("школа: «дом напротив школы, верно же?»",
    s._фраза_ориентир({"вид": "школа"}) == "у вас дом напротив школы, верно же?")
chk("нет объекта — нет фразы", s._фраза_ориентир({}) == "")
chk("длинное имя обрезается", len(s._фраза_ориентир({"имя": "Я" * 90, "вид": "магазин"})) < 70)

print("── КОГДА ПРОИЗНОСИМ ─────────────────────────────────────────────")
_О = "Записать вас на завтра к 11:00?"
_ор = {"имя": "Пятёрочка", "вид": "магазин"}
chk("адрес известен, ещё не говорили — произносим",
    s._сказать_ориентир(_О, _ор, False, True) != _О)
chk("второй раз не повторяем", s._сказать_ориентир(_О, _ор, True, True) == _О)
chk("без адреса молчим", s._сказать_ориентир(_О, _ор, False, False) == _О)
chk("объекта нет — молчим, а не выдумываем", s._сказать_ориентир(_О, {}, False, True) == _О)
chk("вопрос хода не затирается", _О in s._сказать_ориентир(_О, _ор, False, True))
chk("ориентир идёт отдельной строкой",
    s._сказать_ориентир(_О, _ор, False, True).count("\n") == 1)

print("── СЕТИ НА ПУТИ ОТВЕТА НЕТ ──────────────────────────────────────")
chk("незнакомый адрес — пусто", geocode.ориентир("Небывалая 7", "Москва") == {})
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
_бл = _ИСХ[_ИСХ.find("УТОЧНЕНИЕ СТРОЕНИЯ — БЕЗ ЕДИНОГО ПОХОДА В СЕТЬ"):][:1800]
chk("ориентир греется в фоне", "geocode.прогреть_ориентир(" in _бл, _бл[:80])
chk("произносится по памяти, а не по запросу", "geocode.ориентир(" in _бл, _бл[:80])
# ⚠ ДВА ВОПРОСА ПРО АДРЕС В ОДНОЙ РЕПЛИКЕ — ЭТО ДОПРОС. Сомнение про строение важнее
# лояльности: если спрашиваем про корпус, ориентир молчит.
chk("ориентир не звучит вместе с вопросом про строение",
    'if _вид not in ("строение", "стройка"):' in _бл, _бл[:120])

print("── ЗЕРКАЛА КАРТЫ ────────────────────────────────────────────────")
chk("зеркал ровно два и оба с данными по России", len(geocode.OVERPASS) == 2)
chk("швейцарское зеркало не используется",
    not any("osm.ch" in u for u in geocode.OVERPASS), geocode.OVERPASS)
_ГЕО = io.open(os.path.join(КОРЕНЬ, "brain", "geocode.py"), encoding="utf-8").read()
_бг = _ГЕО[_ГЕО.find("def _overpass"):][:900]
chk("пустой ответ зеркала не считается успехом", "if эл:" in _бг, _бг[:120])
chk("при сбое зеркала идём к следующему", "continue" in _бг, _бг[:120])
chk("пустой результат тоже запоминается — второй раз не ходим",
    "_ОРИЕНТИРЫ[q] = найдено" in _ГЕО)

print("=" * 50)
print("Ориентир рядом с домом (29.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
