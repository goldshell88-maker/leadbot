import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "brain"))
import prefilter  # noqa: E402

ok = bad = 0


def chk(label, cond):
    global ok, bad
    if cond:
        ok += 1
    else:
        bad += 1
        print("✗", label)


# ── ЛИДЫ: молчать нельзя ────────────────────────────────────────────────────
ЛИДЫ = [
    "Здравствуйте, нужен демонтаж шкафов, ремонт некоторый в них и монтаж обратно. "
    "как можно обсчитать, шкафов несколько?",
    "Можете обсчитать сколько выйдет по деньгам?",
    "Здравствуйте. Можете сориентировать по стоимости ремонта, ПММ midea. Ошибка е4. "
    "Некачественная соль (в гранулах), забила всё внутри",
    "Некачественный кабель застройщик положил, поменяете?",
    "Сможете спрятать это безобразие?",
    "Можете убрать это безобразие с проводами?",
    "В общежитие, в комнату проведена вода, но видимо некачественно было сделано "
    "или трубы забиты, вода плохо уходит",
]
for т in ЛИДЫ:
    chk("лид не считается претензией: %s" % т[:46], prefilter.check_complaint(т) is None)

# ── ПРЕТЕНЗИИ: ловим по-прежнему ────────────────────────────────────────────
ПРЕТЕНЗИИ = [
    "Ваш сотрудник делал ремонт холодильника за немаленькую сумму, сделал некачественно",
    "Попрошу информацию о человеке, который делал мне некачественную услугу 04.08.2026",
    "Работа выполнена некачественно, переделывайте",
    "Безобразие.",
    "Что за безобразие вы устроили в квартире",
    "Верните мне деньги",
    "Мастер взял 3500 и уехал, ничего не сделал",
    "Я недоволен вашими услугами",
    "Напишу плохой отзыв про вас",
    "Буду жаловаться, обращусь в прокуратуру",
    "Меня обсчитали на 2000",
    "Вы меня обсчитали",
    "Ваш мастер разбил стекло",
    "мастер так и не приехал, как договаривались",
]
for т in ПРЕТЕНЗИИ:
    r = prefilter.check_complaint(т)
    chk("претензия ловится: %s" % т[:46], r is not None and r.get("kind") == "complaint")

# ── прежние гарды не тронуты ────────────────────────────────────────────────
chk("чужой мастер — не претензия к нам (лид)",
    prefilter.check_complaint("предыдущий мастер плохо сделал, переделать сможете?") is None)
chk("страх обмана — не претензия (молчать нельзя)",
    prefilter.check_complaint("а вы не мошенники? деньги вперёд не дам") is None)
chk("хороший отзыв за скидку — торг, не претензия",
    prefilter.check_complaint("скиньте немного, я вам хороший отзыв напишу") is None)

print("\nИТОГО: %d ок, %d провал" % (ok, bad))
sys.exit(1 if bad else 0)
