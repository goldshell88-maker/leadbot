  if [ $CODE -ne 0 ] && echo "$OUT" | grep -q "No such file or directory.*dialogs.jsonl"; then
    printf "SKIP %-22s корпуса нет локально (этап 1 программы обучения)\n" "$t"
    continue
  fi
