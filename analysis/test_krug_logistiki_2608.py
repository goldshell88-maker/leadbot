import prefilter as pf                                  # noqa: E402
import server as s                                      # noqa: E402
s_mod = s

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:110]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


СНИМОК = [
    {"role": "client", "text": "здравствуйте"},
    {"role": "operator", "text": "Здравствуйте\nРассказывайте, что у вас произошло?"},
    {"role": "client", "text": "🖼 https://example/photo.jpg"},
    {"role": "operator", "text": "почистить компьютер от пыли надо. Расскажите, что случилось?"},
    {"role": "client", "text": "кулер отпал"},
    {"role": "client", "text": "по всей видимости"},
    {"role": "client", "text": "он вот на этой штуке которая за кулером держался"},
]
ВОПРОС = "Давайте подъеду посмотрю. Куда подъехать?"


def режем(до, first_bot=False, **поля):
    м = СНИМОК[:до]
    serious = " ".join(x["text"] for x in м if x["role"] == "client")
    поля.setdefault("has_addr", False)
    поля.setdefault("has_phone", False)
    поля.setdefault("has_time", False)
    return s._резать_логистику(ВОПРОС, м, serious, first_bot, **поля)[0]


print("\n1. СЛОВАРЬ: отсоединившийся узел — это названная поломка")
for т in ("кулер отпал", "шлейф отошёл", "петля оторвалась", "вентилятор выпал",
          "ручка отвалилась", "кулер отпал по всей видимости он вот на этой штуке"):
    проверь("«%s» — поломка названа" % т[:40], pf.problem_stated(т), pf.problem_stated(т))
print("   и обратная сторона — болтовнёй поломка не становится:")
for т in ("здравствуйте", "вы бот?", "а вы кто", "спасибо"):
    проверь("«%s» — поломки нет" % т, not pf.problem_stated(т))

print("\n2. САМ СНИМОК: круг разорван на втором и третьем ходу")
# ⚠ ПРОВЕРЯЕМ ПРИЧИНУ, А НЕ ТОЛЬКО ФАКТ. Диверсия показала: сними ветку плейбука — и
# первый ответ всё равно режется, просто уже как «поломка не названа». Факт совпадает,
# правило исчезло. Ветка плейбука тем и отличается, что режет ДАЖЕ когда всё сказано.
_первый = s._резать_логистику(ВОПРОС, СНИМОК[:2], "здравствуйте", True,
                              has_addr=False, has_phone=False, has_time=False)
проверь("1-й ответ: логистику режем именно по плейбуку", _первый == (True, "первый ответ"), _первый)
_первый_полный = s._резать_логистику(
    ВОПРОС,
    [{"role": "client", "text": "телевизор не включается, ленина 5, 89001234567, завтра с утра"}],
    "телевизор не включается, ленина 5, 89001234567, завтра с утра", True,
    has_addr=True, has_phone=True, has_time=True)
проверь("в 1-м ответе режем, даже когда клиент сказал ВСЁ сразу (в этом и смысл плейбука)",
        _первый_полный == (True, "первый ответ"), _первый_полный)
проверь("2-й ответ (после фото): не режем", not режем(4))
проверь("3-й ответ (после «кулер отпал»): не режем", not режем(7))

print("\n3. ГЛАВНОЕ: круг рвётся ДАЖЕ ЕСЛИ СЛОВАРЬ СЛЕП")
# ⚠ КАЖДЫЙ ВЫХОД ПРОВЕРЯЕТСЯ В ОДИНОЧКУ, И ЭТО НЕ ПЕДАНТИЗМ. Первая редакция гоняла все
# три по одному и тому же снимку — а там есть и фото, и ответ клиента сразу. Диверсия
# показала: убери любой выход, и его подхватывает соседний, тест остаётся зелёным. Ниже
# у каждого случая ровно один сработавший выход, поэтому пропажа выхода видна.
_ОТВЕТИЛ = [{"role": "client", "text": "здравствуйте"},
            {"role": "operator", "text": "Здравствуйте, расскажите, что случилось?"},
            {"role": "client", "text": "кулер отпал"}]
_СНИМОК_БЕЗ_ВОПРОСА = [{"role": "client", "text": "здравствуйте"},
                       {"role": "operator", "text": "Здравствуйте, слушаю вас"},
                       {"role": "client", "text": "🖼 https://example/photo.jpg"}]
_АДРЕС_БЕЗ_ВОПРОСА = [{"role": "client", "text": "здравствуйте"},
                      {"role": "operator", "text": "Здравствуйте, слушаю вас"},
                      {"role": "client", "text": "ленина 5 квартира 12"}]


def режем_в(диалог, **поля):
    поля.setdefault("has_addr", False)
    поля.setdefault("has_phone", False)
    поля.setdefault("has_time", False)
    serious = " ".join(x["text"] for x in диалог if x["role"] == "client")
    return s._резать_логистику(ВОПРОС, диалог, serious, False, **поля)[0]


настоящий = pf.problem_stated
pf.problem_stated = lambda t: False
try:
    проверь("бот спросил про поломку, клиент ответил — второй раз не спрашиваем "
            "(ни фото, ни адреса в диалоге нет)", not режем_в(_ОТВЕТИЛ))
    проверь("клиент прислал снимок — не требуем вдобавок словесного описания "
            "(бот про поломку не спрашивал)", not режем_в(_СНИМОК_БЕЗ_ВОПРОСА))
    проверь("клиент назвал адрес — «ехать некуда» уже неправда "
            "(ни фото, ни вопроса про поломку)", not режем_в(_АДРЕС_БЕЗ_ВОПРОСА, has_addr=True))
    проверь("клиент дал номер — то же самое", not режем_в(_АДРЕС_БЕЗ_ВОПРОСА, has_phone=True))
    проверь("клиент назвал время — то же самое", not режем_в(_АДРЕС_БЕЗ_ВОПРОСА, has_time=True))
    # и контроль: без единого выхода тот же диалог режется — значит выходы и правда решают
    проверь("без всякого повода режем (контроль: выходы не «всегда не режем»)",
            режем_в([{"role": "client", "text": "здравствуйте"},
                     {"role": "operator", "text": "Здравствуйте, слушаю вас"},
                     {"role": "client", "text": "ага"}]))
finally:
    pf.problem_stated = настоящий

print("\n4. ЗАПРЕТ ОСТАЛСЯ ТАМ, РАДИ ЧЕГО ЗАВОДИЛСЯ")
