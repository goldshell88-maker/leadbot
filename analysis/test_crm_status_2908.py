# -*- coding: utf-8 -*-
"""ИСХОД ЗАЯВКИ ИЗ CRM: статус рядом с заявкой, деньги вместо переписки (29.08).

ЗАЧЕМ. Слова владельца: заявка, закрытая в «Готов», «Отказ» или «Отмена Филиала»,
приносит 60 ₽; пока она «Ожидает» — тоже. А «Отмена КЦ» СПИСЫВАЕТ 60 ₽ обратно, то
есть такая заявка стоит вдвое дороже несозданной. До сих пор бот мерил ПЕРЕПИСКУ
(«дожал до адреса», «клиент дал номер»), а не исход, и отличить выгодную заявку от
убыточной было нечем — это был самый большой пробел в измерениях.

КАК УСТРОЕНО. Сервер отдаёт расширению список созданных заявок без известного исхода,
расширение раз в полчаса читает их карточки в CRM (чужой сессией владельца, поэтому
редко и помалу) и возвращает статусы. Имя поля в карточке неизвестно — живой CRM виден
только с офисного ПК, — поэтому статус ищется тремя способами и расширение докладывает,
какой сработал: тот же приём, что вытащил пустой «Вид работ».

⚠ ЗДЕСЬ ТОЛЬКО ЗАПИСЬ, БЕЗ ВЫВОДОВ. Что делать с «Отменой КЦ» — вопрос разбора, когда
статусов наберётся достаточно. На трёх заявках выводов не делают.

Запуск: uv run python analysis/test_crm_status_2908.py
Офлайн, 0 токенов.
"""
import io
import json
import os
import sys
import tempfile

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


def очередь(записи):
    """Подставная очередь: пишем во временный файл и переключаем на него сервер."""
    ф = tempfile.NamedTemporaryFile("w", suffix=".jsonl", delete=False, encoding="utf-8")
    for r in записи:
        ф.write(json.dumps(r, ensure_ascii=False) + "\n")
    ф.close()
    s._CRM_QUEUE = ф.name
    return ф.name


print("── ЭКОНОМИКА СТАТУСОВ ───────────────────────────────────────────")
chk("«Готов» приносит 60", s.CRM_ДЕНЬГИ["Готов"] == 60)
chk("«Отказ» тоже приносит 60", s.CRM_ДЕНЬГИ["Отказ"] == 60)
chk("«Отмена Филиала» приносит 60", s.CRM_ДЕНЬГИ["Отмена Филиала"] == 60)
chk("«Ожидает» приносит 60", s.CRM_ДЕНЬГИ["Ожидает"] == 60)
# ⚠ ЕДИНСТВЕННЫЙ ОТРИЦАТЕЛЬНЫЙ: заявка не просто не оплачена — деньги списывают обратно
chk("«Отмена КЦ» СПИСЫВАЕТ 60", s.CRM_ДЕНЬГИ["Отмена КЦ"] == -60)
chk("«Не оформлена» не приносит и не списывает", s.CRM_ДЕНЬГИ["Не оформлена"] == 0)
chk("отрицательный статус ровно один",
    [к for к, в in s.CRM_ДЕНЬГИ.items() if в < 0] == ["Отмена КЦ"])

print("── КОГО ОПРАШИВАЕМ ──────────────────────────────────────────────")
очередь([
    {"key": "a", "ts": 1, "t": "", "dir": "kp", "status": "pending", "lead": {}},
    {"key": "a", "ts": 2, "t": "", "status": "done", "id": 111},
    {"key": "b", "ts": 3, "t": "", "dir": "bt", "status": "pending", "lead": {}},
    {"key": "b", "ts": 4, "t": "", "status": "done", "id": 222, "crm_статус": "Готов"},
    {"key": "c", "ts": 5, "t": "", "dir": "mnc", "status": "pending", "lead": {}},
    {"key": "c", "ts": 6, "t": "", "status": "failed", "id": None},
    {"key": "d", "ts": 7, "t": "", "dir": "kp", "status": "pending", "lead": {}},
    {"key": "d", "ts": 8, "t": "", "status": "done", "id": 444, "crm_статус": "Ожидает"},
])
_т = s._crm_tracked()
_ключи = {з["key"] for з in _т}
chk("созданную без исхода опрашиваем", "a" in _ключи, _т)
# ⚠ ФИНАЛЬНЫЙ СТАТУС ПЕРЕСПРАШИВАТЬ НЕЗАЧЕМ: карточки читаются рабочей сессией владельца
chk("заявку с финальным исходом больше не трогаем", "b" not in _ключи, _т)
chk("несозданную не опрашиваем", "c" not in _ключи, _т)
# «Ожидает» не финал: заявка ещё может уйти в «Отмену КЦ», а это минус деньги
chk("«Ожидает» продолжаем отслеживать", "d" in _ключи, _т)
chk("направление берётся из записи создания",
    all(з.get("dir") for з in _т), _т)
chk("id есть у каждой отслеживаемой", all(з.get("id") for з in _т), _т)

print("── ЗАПИСЬ ИСХОДА ────────────────────────────────────────────────")
n = s._crm_status_save([{"id": 111, "статус": "Готов", "как": "поле status"}])
chk("статус записан", n == 1, n)
_после = s._crm_queue_all()
chk("статус лёг рядом с заявкой", _после["a"].get("crm_статус") == "Готов", _после.get("a"))
chk("способ находки сохранён — видно, чему верить",
    _после["a"].get("crm_как") == "поле status", _после.get("a"))
chk("заявка перестала опрашиваться", "a" not in {з["key"] for з in s._crm_tracked()})
chk("чужой id молча игнорируется",
    s._crm_status_save([{"id": 999999, "статус": "Готов"}]) == 0)
chk("мусор вместо записи не роняет",
    s._crm_status_save(["строка", None, 42, {}]) == 0)
chk("пустой вход не роняет", s._crm_status_save(None) == 0)
chk("длинный статус обрезается",
    s._crm_status_save([{"id": 444, "статус": "Я" * 200}]) == 1
    and len(s._crm_queue_all()["d"].get("crm_статус")) <= 32)

print("── СВОДКА ПО ДЕНЬГАМ ────────────────────────────────────────────")
# ⚠ ЭКЗАМЕН ПО КОДУ 29.08 НАШЁЛ CRM_ДЕНЬГИ ОБЪЯВЛЕННЫМ И НИКЕМ НЕ ВЫЗВАННЫМ — тот же
# класс, что мёртвые гарды кронштейна и geocode, невидимый воронке. Таблица, которая
# лежит без дела, не ошибается, но создаёт видимость учёта. Теперь она считает.
