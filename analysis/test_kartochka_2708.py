import io
import json
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prompt as pr                                    # noqa: E402
import server as s                                     # noqa: E402

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:110]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


ТВ = [{"role": "client", "text": "телевизор Haier не показывает, запах гари, красная лампочка мигает"}]

print("\n1. НАПРАВЛЕНИЕ: телевизор уходит на КП")
проверь("направления нет — ставим КП", s._направление_тв(None, {"city": "Белгород"}, ТВ) == "kp")
проверь("ошибочный МНЧ («лампочка») исправляется на КП",
        s._направление_тв("mnc", {"city": "Белгород"}, ТВ) == "kp")
проверь("БТ у белого партнёра — тупик, переводим на КП",
        s._направление_тв("bt", {"city": "Белгород"}, ТВ, white=True) == "kp")
проверь("честный БТ у обычного партнёра не трогаем",
        s._направление_тв("bt", {"city": "Белгород"}, ТВ, white=False) == "")
проверь("КП не переписываем", s._направление_тв("kp", {"city": "Белгород"}, ТВ) == "")
проверь("не ТВ — правило молчит",
        s._направление_тв(None, {"city": "Белгород"},
                          [{"role": "client", "text": "холодильник не морозит"}]) == "")
# ⚠ ПРОВОДКА: без вызова в `_maybe_autocreate` всё выше зелено впустую — диверсия это показала.
_сервер = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
проверь("правило зовётся из создания заявки",
        "d = _направление_тв(d, kr, messages, white=white) or d" in _сервер)
проверь("зовётся ПОСЛЕ вычисления «белый», иначе флаг не тот",
        _сервер.index("white = _is_white(known)")
        < _сервер.index("d = _направление_тв(d, kr, messages, white=white)"))

print("\n2. АДРЕС: улица и дом по отдельности, сырая строка в карточку не уезжает")
разбор = s._parse_addr("Дубовое, центр.. Ул. Полевая, 12, ориентир Сбер.")
проверь("улица без мусора", разбор["street"] == "Полевая", разбор)
проверь("дом отдельно", разбор["building"] == "12", разбор)
проверь("«ориентир Сбер» в улицу не попал", "Сбер" not in разбор["street"])
проверь("«центр..» в улицу не попало", "центр" not in разбор["street"].lower())

print("\n3. КАРТОЧКА: улица берётся из разбора, а не сырой строкой")
крм = io.open(os.path.join(КОРЕНЬ, "brain", "crm.py"), encoding="utf-8").read()
проверь("улица в патч идёт из разбора", 'patch["Customer[address_street]"] = адр["street"]' in крм)
проверь("источник канала кладётся в «Комментарий Партнёра»",
        'CustomerRequest[partner_comment]' in крм and 'lead["partner_note"]' in крм)
проверь("имя поля населённого пункта по-прежнему ищется в форме, а не вписано наугад",
        "CustomerRequest[settlement]" not in крм)

print("\n4. ИСТОЧНИК ДОХОДИТ ДО ЗАЯВКИ")
сервер = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
проверь("lead несёт источник канала", '"partner_note": (kr.get("origin") or "").strip(),' in сервер)

print("\n5. КОММЕНТАРИЙ: формулировка модели вместо пересказа слов клиента")
# ⚠ ПРОВЕРЯЕМ КЛЮЧ СХЕМЫ, А НЕ ПОДСТРОКУ. Диверсия «переименовать в problem_line_off»
