# -*- coding: utf-8 -*-
"""ОБУЧЕНИЕ ПО ЖИВЫМ ЧАТАМ (30.08): семь агентов разобрали 30 351 первичный диалог.

Задача владельца: «понять, как и почему мы что-то спросили, ответили и приняли,
чтобы бот покрывал все первичные диалоги и отвечал как живой человек».

ГЛАВНЫЕ ЧИСЛА КОРПУСА, на которых стоят правки:
  • 36,5 % первых сообщений — НЕ открывашки, а обрывки порванных Авито-чатов;
    живые здороваются на обрывках лишь в 26 %, на фото-входе — в 9 %;
  • первый ход живого: медиана 6 слов, 1,5 пузыря, телефон в первом ходе — 0,4 %;
  • имя живые спрашивают 18 раз на 89 730 реплик (0,02 %) — вопрос имени у бота УБРАН,
    имя берётся из профиля Авито, а из чата — только если клиент назвался сам;
  • «а вы точно почините?» — 3-е по частоте возражение (484), промптом не покрывалось;
  • ответ ценой на просьбу адреса (1 018 диалогов): связка «закрыл цену + вернул
    просьбу адреса» даёт 66,7 % против 31,2 % у голого увода;
  • p95 живой реплики — 14 слов; SOGLAS_POOL держал 18-27 — укорочен.

ЧТО ОТКЛОНЕНО ИЗ ПЛАНА АГЕНТОВ И ПОЧЕМУ (важно не потерять):
  • пинг «актуально?» (1 798 живых употреблений) — ЗАПРЕЩЁН словом владельца по замеру:
    58 заглушенных диалогов, 0 телефонов. Массовость — не эффективность;
  • «выезд по городу бесплатный» одной строкой — на КП выезд 1000 при отказе,
    формула уже разрулена гардом по направлениям;
  • сцепка «адрес+телефон одной репликой» и мостик на претензии — вопросы владельцу.

Запуск: uv run python analysis/test_uroki_zhivyh_3008.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter as p  # noqa: E402
import server as s  # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


_ПР = io.open(os.path.join(КОРЕНЬ, "brain", "prompt.py"), encoding="utf-8").read()
_СРВ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()

print("── ПРОМПТ: СЕМЬ УРОКОВ КОРПУСА ──────────────────────────────────")
chk("блок уроков на месте", "УРОКИ ЖИВОГО КОРПУСА" in _ПР)
chk("«а вы точно почините?» покрыт", "А ВЫ ТОЧНО ПОЧИНИТЕ" in _ПР)
chk("«сколько времени займёт» покрыт", "СКОЛЬКО ВРЕМЕНИ ЗАЙМЁТ РЕМОНТ" in _ПР)
chk("гарантия после работ — условная формула", "если случай\n  гарантийный — гляну бесплатно" in _ПР
    or "гарантийный — гляну бесплатно" in _ПР)
chk("цена в ответ на адрес: закрыть и вернуть просьбу",
    "КЛИЕНТ ОТВЕЧАЕТ ЦЕНОЙ НА ПРОСЬБУ АДРЕСА" in _ПР)
chk("обрывки: не начинать анкету заново", "ОБРЫВОК, А НЕ НАЧАЛО" in _ПР)
chk("перенос до заявки — шаг воронки", "КЛИЕНТ ПРОСИТ ДРУГОЕ ВРЕМЯ ДО ЗАЯВКИ" in _ПР)
chk("первый ход: зеркальное приветствие, два пузыря", "ПЕРВЫЙ ХОД — КАК У ЖИВОГО" in _ПР)
chk("без гарантий исхода", "точно починю" in _ПР)  # как запрет в ⛔

print("── ИМЯ: ВОПРОС УБРАН, FALLBACK ЖИВ ──────────────────────────────")
chk("пул вопросов имени удалён", "_ВОПРОС_ИМЯ" not in _СРВ)
chk("дописывание вопроса имени удалено", "_ИМЯ_СПРОШЕНО_RX" not in _СРВ)
chk("имя из чата — запасной источник карточки", "or _имя_из_чата(messages)" in _СРВ)
chk("fallback работает: «Меня зовут Ирина»",
    s._имя_из_чата([{"role": "client", "text": "Меня зовут Ирина"}]) == "Ирина")
chk("склонённое имя не берём",
    s._имя_из_чата([{"role": "client", "text": "Меня зовут Петром"}]) == "")

print("── ПУЛЫ: ЖИВАЯ ДЛИНА И ЖИВЫЕ СЛОВА ──────────────────────────────")
chk("SOGLAS_POOL укорочен: максимум ≤ 14 слов",
    max(len(т.split()) for т in p.SOGLAS_POOL) <= 14,
    str(max(len(т.split()) for т in p.SOGLAS_POOL)))
chk("SOGLAS_POOL держит минимум 6 вариантов", len(p.SOGLAS_POOL) >= 6)
chk("голосовое укорочено ≤ 11 слов", len(p.ГОЛОСОВОЕ_ОТВЕТ.split()) <= 11,
    str(len(p.ГОЛОСОВОЕ_ОТВЕТ.split())))
chk("статус-пул пополнен живым «наберу»",
    any("наберу" in т for т in p.STATUS_BRIDGE_VARIANTS))
chk("«черкните» вычищено (0 употреблений в корпусе)", "черкните" not in _СРВ)
chk("«шильдик» заменён наклейкой", "шильдик" not in _СРВ.lower() or
    _СРВ.lower().count("шильдик") <= _СРВ.lower().count("наклейк"))

print("── ОТКЛОНЁННОЕ НЕ ПРОСОЧИЛОСЬ ───────────────────────────────────")
chk("пинг «актуально?» по-прежнему под запретом владельца",
    "ЗАПРЕЩЕНЫ" in _ПР and "актуальна?»" in _ПР)
# фраза в промпте ЕСТЬ — но в правиле для БТ/ТВ (слово владельца 18.08), а для КП
# рядом стоит двухчастная формула. Проверяем, что направленческая оговорка на месте.
_い = _ПР.lower().find("выезд по городу бесплатный")
chk("«выезд по городу бесплатный» остался только в правиле БТ/ТВ",
    _い > 0 and "только для кп" in _ПР.lower()[max(0, _い - 200):_い])

print("=" * 50)
print("Уроки живых чатов (30.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
