# -*- coding: utf-8 -*-
"""БОЕВЫЕ ДИАЛОГИ 29.08, ВТОРАЯ ТРОЙКА: планка озвучки, номер перед выездом, отказ.

Все три — один класс: ГАРД ЕСТЬ, НО ПРИВЯЗАН К ХРУПКОМУ ПРИЗНАКУ. Это опаснее, чем
отсутствие защиты: она создаёт ложное чувство, что случай закрыт.

1. ПЛАНКА ОЗВУЧКИ (Курск, партнёр 723). Бот: «Переустановка Windows с Office и чистка
   от пыли, вместе от 1500». В `_планка_озвучки` стояло «тема прайса опознана → сумма
   законна какой угодно». Клиент сказал «windows» — тема опознана, и 1500 прошло
   насквозь. А 1500 к windows отношения не имеет: прайс КП 2000, планка белого 1000,
   1500 — это floor МНЧ. Слова владельца: «для 723 партнёра сначала озвучка от 1000,
   потом, если есть фиксированные, фиксированный — но по правилам отработки возражений».

2. НОМЕР ПЕРЕД ВЫЕЗДОМ (Оренбург). Бот: «отлично, выезжаю сейчас, буду до 12» — и
   поехал без телефона, номер дописал администратор руками. Блок добора номера живёт
   внутри `if _was_booked or _BOOKED_REPLY_RX.search(reply)`, где regex — слово «запис».
   Обещание приехать записью не считалось. Слова владельца: «мы без номера телефона
   не выезжаем».

3. ОТКАЗ И ПРОСЬБА АДРЕСА (Березники). Клиент прислал фото разбитого экрана; модель
   отказала — и в той же реплике попросила адрес с квартирой и телефон. Слова владельца:
   «зачем-то снова начал просить адрес на матрицу».

Запуск: uv run python analysis/test_boy2_2908.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402
import price_book as pb                                 # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


_ЖИВАЯ_ЦЕНА = "Переустановка Windows с Office и чистка от пыли, вместе от 1500. Точнее скажу на месте."
_РЕЧЬ = "А сколько будет стоить? переустановка windows и чистка от пыли"

print("── ЛЕСТНИЦА ЦЕНЫ ПАРТНЁРА 723 ───────────────────────────────────")
_белый = s._планка_озвучки(_ЖИВАЯ_ЦЕНА, _РЕЧЬ, True, "kp")
chk("«от 1500» на белом больше не звучит", "1500" not in _белый, _белый)
chk("первая ступень — «от 1000»", "1000" in _белый, _белый)
chk("обоснование сохранено", "Точнее скажу на месте" in _белый, _белый)
# ⚠ ФИКС — ЭТО ТРЕТЬЯ СТУПЕНЬ, ПО ПРАВИЛАМ ОТРАБОТКИ ВОЗРАЖЕНИЙ, А НЕ ПЕРВЫЙ ОТВЕТ
chk("прайсовая цена проходит как есть",
    s._планка_озвучки("Windows от 2000", _РЕЧЬ, True, "kp") == "Windows от 2000")
chk("прайс КП по Windows действительно 2000", pb.price_for("windows") == 2000)
chk("на обычном аккаунте своя планка",
    "500" in s._планка_озвучки(_ЖИВАЯ_ЦЕНА, _РЕЧЬ, False, "kp"))
# ⚠ 1500 ЗАКОНЕН НА МНЧ: это floor его собственной лестницы
chk("на МНЧ «от 1500» остаётся",
    s._планка_озвучки("Сборка мебели от 1500", "соберите шкаф", True, "mnc")
    == "Сборка мебели от 1500")
chk("суммы тем берутся из прайса, а не выдуманы",
    s._суммы_тем("переустановка windows") == {2000}, s._суммы_тем("переустановка windows"))
chk("прайс молчит — суммы пусты", s._суммы_тем("здравствуйте") == set())

print("── БЕЗ НОМЕРА НЕ ВЫЕЗЖАЕМ ───────────────────────────────────────")
_живой_выезд = "отлично, выезжаю сейчас, буду до 12"
_добрано = s._не_выезжать_без_номера(_живой_выезд, False, 1, "сид")
chk("к обещанию выезда дописан номер", _добрано != _живой_выезд, _добрано)
chk("само обещание не снято", "выезжаю сейчас" in _добрано, _добрано)
chk("номер спрошен", s._PHONE_ASK_RX.search(_добрано) is not None, _добрано)
for т in ("подъеду к 14:00", "буду у вас через час", "еду к вам", "приеду сегодня"):
    chk("«%s» — тоже обещание выезда" % т,
        s._не_выезжать_без_номера(т, False, 0, "с") != т)

print("── КОГДА НЕ ДАВИМ ───────────────────────────────────────────────")
chk("номер уже есть — молчим", s._не_выезжать_без_номера(_живой_выезд, True, 1) == _живой_выезд)
# ⚠ ТРЁХ ПРОСЬБ ДОСТАТОЧНО: дальше это уже не настойчивость, а давление
chk("просили трижды — больше не просим",
    s._не_выезжать_без_номера(_живой_выезд, False, 3) == _живой_выезд)
chk("нет обещания выезда — не трогаем",
    s._не_выезжать_без_номера("Что случилось с техникой?", False, 0)
    == "Что случилось с техникой?")
chk("номер уже просим в этой реплике — не дублируем",
    s._не_выезжать_без_номера("выезжаю, номер ваш подскажите", False, 0)
    == "выезжаю, номер ваш подскажите")

print("── ПРИЗНАК ЗАПИСИ — ПО СМЫСЛУ, А НЕ ПО СЛОВУ ────────────────────")
# ⚠ ИМЕННО ЭТО И СЛОМАЛОСЬ: «выезжаю» записью не считалось, и весь блок добора
# номера не выполнялся вовсе.
for т in ("записал вас на завтра", "выезжаю сейчас", "буду до 12",
          "подъеду к 15:00", "еду к вам"):
    chk("«%s» считается фиксацией" % т, bool(s._BOOKED_REPLY_RX.search(т)))
chk("обычный вопрос фиксацией не считается",
    not s._BOOKED_REPLY_RX.search("что у вас случилось?"))

print("── ПОСЛЕ ОТКАЗА ДАННЫХ НЕ ПРОСИМ ────────────────────────────────")
_живой_отказ = ("такое, к сожалению, не отремонтировать, извините. "
                "Напишете адрес с квартирой и подъездом?\nНапишите номер телефона, спишемся по времени")
_после = s._снять_просьбы_после_отказа(_живой_отказ)
chk("адрес больше не просим", "адрес" not in _после.lower(), _после)
chk("телефон больше не просим", "телефон" not in _после.lower(), _после)
chk("сам отказ остался", "не отремонтировать" in _после, _после)
chk("извинение осталось", "извините" in _после, _после)
chk("без отказа реплику не трогаем",
    s._снять_просьбы_после_отказа("Записать вас? Напишите адрес с квартирой")
    == "Записать вас? Напишите адрес с квартирой")
chk("пустая реплика не роняет", s._снять_просьбы_после_отказа("") == "")

print("── ВСЕ ТРИ ГАРДА ЖИВЫЕ ──────────────────────────────────────────")
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
chk("планка зовётся из воронки", "_планка_озвучки(reply, client_all" in _ИСХ)
chk("номер перед выездом зовётся", "reply = _не_выезжать_без_номера(reply" in _ИСХ)
chk("снятие просьб после отказа зовётся", "reply = _снять_просьбы_после_отказа(reply)" in _ИСХ)
# ⚠ ВЧЕРАШНЯЯ ПРАВКА СНЯТА: она ставила прайс в обход ступени «от 1000»
chk("правка, прыгавшая через ступень, убрана",
    "reply = _floor_своего_направления(reply" not in _ИСХ)

print("=" * 50)
print("Боевые диалоги, вторая тройка: %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
