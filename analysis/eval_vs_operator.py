# -*- coding: utf-8 -*-
"""БОТ ПРОТИВ ОПЕРАТОРА: чем ответы отличаются и чей лучше.

ЗАЧЕМ. «Бот отвечает хуже» — ощущение, пока не сказано, ЧЕМ хуже и по какой мерке.
Здесь две разные проверки, и путать их нельзя:

  1. ЧЕМ ОТЛИЧАЮТСЯ — считается офлайн, 0 токенов: длина, вопросы, приветствие,
     предложенное окно, названная цена. Это описание, а не оценка.
  2. ЧЕЙ ЛУЧШЕ — по мерке, ВЫВЕДЕННОЙ ИЗ ДАННЫХ, а не из моего вкуса. Сегодняшний
     замер 30 428 живых диалогов (analysis/audit_dialogs.py) показал, что до заявки
     доходят 8,0 %, и сильнее всего это меняет ПЕРВЫЙ ход: предложил конкретное окно —
     37,0 %, спросил «когда удобно» — 15,8 %, ничего — 8,1 %. По этой шкале и считаем.

⚠ СРАВНИВАЕМ ТОЛЬКО ТАМ, ГДЕ БОТ ДОЛЖЕН ГОВОРИТЬ. С 25.08 он молчит в чужом диалоге
(оператор уже ведёт разговор) и после назначенного визита. Гнать его туда ради красивой
таблицы — мерить то, чего в бою не будет.

⚠ ЧЕГО ЭТА ПРОВЕРКА НЕ ЗНАЕТ. Приехал ли мастер и заплатил ли клиент — в переписке
этого нет. «Лучше» здесь = «ход, который по замеру чаще доводит до заявки».

Запуск:  uv run python analysis/eval_vs_operator.py [сколько=40]
⚠ ПЛАТНО: один вызов модели на диалог. 40 диалогов ≈ 30 ₽.
Кэш ответов уводится в отдельный файл, боевой не растёт.
"""
import collections
import io
import json
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.environ.setdefault("LEADBOT_ANSWER_CACHE",
                      os.path.join(КОРЕНЬ, "analysis", "_eval_cache.jsonl"))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server                                            # noqa: E402

КОРПУС = os.path.join(КОРЕНЬ, "analysis", "LEARNING", "corpus.jsonl")

ОКНО_RX = re.compile(r"(?i)(?:могу|подъеду|буду|приеду)[^.!?\n]{0,30}"
                     r"(?:через\s+час|час[- ]полтора|сегодня|завтра|к\s*\d{1,2})"
                     r"|через\s+час[- ]полтора[^.!?\n]{0,20}удобно")
СПРОСИЛ_RX = re.compile(r"(?i)когда\s+(?:вам\s+)?удобно|во\s+сколько|в\s+какое\s+время")
ЦЕНА_RX = re.compile(r"(?i)\bот\s*\d{3,}|\d{3,}\s*(?:р\b|руб)")
ПРИВЕТ_RX = re.compile(r"(?i)^\s*(здравствуйте|добрый|доброе|приветствую)")
#: признаки НАСТОЯЩЕГО первого обращения
ТЕХНИКА_ИЛИ_РАБОТА_RX = re.compile(
    r"(?i)стиральн|стиралк|холодильник|телевизор|\bтв\b|посудомо|плит[аыу]|духов|ноутбук|"
    r"компьютер|принтер|роутер|микроволн|пылесос|бойлер|мебел|шкаф|кухн|кроват|"
    r"повесить|собрать|установ|подключ|заменить|починить|отремонт|навес|прикрут|сверл")
ЦЕНА_ВОПРОС_RX = re.compile(r"(?i)скольк|\bцена\b|стоимост|почём|почем\b|по\s+деньгам")
#: зачин, каким начинают ПРОДОЛЖЕНИЕ, а не обращение
ПРОДОЛЖЕНИЕ_RX = re.compile(
    r"(?i)^\s*(?:да|нет|ага|угу|хорошо|ок|окей|понятно|спасибо|а\b|и\b|ну\b|это\b|"
    r"тогда|давайте|конечно|верно|именно)\b")


def отбор(сколько):
    """Первичные диалоги: клиент написал, оператор ответил ПЕРВЫМ ходом."""
    из = []
    for line in io.open(КОРПУС, encoding="utf-8"):
        try:
            d = json.loads(line)
        except Exception:
            continue
        msgs = [(m.get("role"), (m.get("text") or "").strip())
                for m in (d.get("messages") or []) if (m.get("text") or "").strip()]
        if len(msgs) < 2 or msgs[0][0] != "client" or msgs[1][0] != "operator":
            continue
        клиент, оператор = msgs[0][1], msgs[1][1]
        if len(клиент) < 15 or len(оператор) < 5:
            continue
        # ⚠ ПЕРВОЕ СООБЩЕНИЕ В ЗАПИСИ ≠ ПЕРВОЕ ОБРАЩЕНИЕ. Корпус склеен из кусков, и
        # у части диалогов «первая» реплика — это середина разговора: «Новое девяткино»,
        # «Нет, только один дощатый пол». Бот на такое честно отвечает «что случилось?»,
        # и сравнение меряет не качество, а негодную выборку — я на этом уже попался.
        # Берём только те, где клиент ОТКРЫВАЕТ разговор: здоровается, называет технику
        # или работу, либо спрашивает цену.
        if not (ПРИВЕТ_RX.search(клиент)
                or ТЕХНИКА_ИЛИ_РАБОТА_RX.search(клиент)
                or ЦЕНА_ВОПРОС_RX.search(клиент)):
            continue
        # продолжение разговора выдаёт себя зачином-ответом
        if ПРОДОЛЖЕНИЕ_RX.search(клиент):
            continue
        город = (((d.get("meta") or {}).get("visitor") or {}).get("city")
                 or (d.get("meta") or {}).get("city") or "Москва")
        из.append({"клиент": клиент, "оператор": оператор, "город": город})
        if len(из) >= сколько * 4:
            break
    # берём вразброс, а не первые подряд: начало корпуса — это один период
    шаг = max(1, len(из) // сколько)
    return из[::шаг][:сколько]


def признаки(текст):
    т = текст or ""
    return {
        "знаков": len(т),
        "вопрос": "?" in т,
        "приветствие": bool(ПРИВЕТ_RX.search(т)),
        "предложил окно": bool(ОКНО_RX.search(т)),
        "спросил время": bool(СПРОСИЛ_RX.search(т)),
        "назвал цену": bool(ЦЕНА_RX.search(т)),
    }


#: ⚠ ШКАЛА ВЫВЕДЕНА ИЗ ДАННЫХ, А НЕ ИЗ ВКУСА. Числа — доля диалогов, дошедших до
#: заявки, при таком первом ходе (замер 30 428 живых диалогов, база 8,0 %).
ШКАЛА = [("предложил окно", 37.0), ("спросил время", 15.8)]
БАЗА = 8.1


def оценка(п):
    for имя, доля in ШКАЛА:
        if п[имя]:
            return доля
    return БАЗА


def главное():
    сколько = int(sys.argv[1]) if len(sys.argv) > 1 else 40
    пары = отбор(сколько)
    print("диалогов взято: %d (первичные: клиент → ответ оператора)\n" % len(пары))
    св = {"бот": collections.Counter(), "оператор": collections.Counter()}
    длины = {"бот": [], "оператор": []}
    очки = {"бот": 0.0, "оператор": 0.0}
    молчал = 0
    примеры = []

    for i, п in enumerate(пары, 1):
        r = server.run_relay([{"role": "client", "text": п["клиент"]}],
                             known={"city": п["город"], "visitor": "", "title": ""})
        бот = (r.get("reply_text") or r.get("reply") or "").strip()
        if not бот:
            молчал += 1
            continue
        for кто, текст in (("бот", бот), ("оператор", п["оператор"])):
            пр = признаки(текст)
            длины[кто].append(пр["знаков"])
            for k, v in пр.items():
                if v is True:
                    св[кто][k] += 1
            очки[кто] += оценка(пр)
        if len(примеры) < 5:
            примеры.append((п["клиент"], бот, п["оператор"]))
        if i % 10 == 0:
            print("  …%d из %d" % (i, len(пары)), flush=True)

    n = len(длины["бот"])
    if not n:
        print("сравнивать нечего")
        return 1

    def мед(xs):
        xs = sorted(xs)
        return xs[len(xs) // 2]

    print("\n" + "═" * 74)
    print("ЧЕМ ОТЛИЧАЮТСЯ (на %d парах, бот промолчал в %d)" % (n, молчал))
    print("═" * 74)
    print("%-24s %10s %12s" % ("признак", "бот", "оператор"))
    print("%-24s %9d %11d" % ("медиана знаков", мед(длины["бот"]), мед(длины["оператор"])))
    for k in ("вопрос", "приветствие", "предложил окно", "спросил время", "назвал цену"):
        print("%-24s %8.0f%% %10.0f%%"
              % (k, 100.0 * св["бот"][k] / n, 100.0 * св["оператор"][k] / n))

    print("\n" + "═" * 74)
    print("ЧЕЙ ХОД ЧАЩЕ ДОВОДИТ ДО ЗАЯВКИ (шкала из замера, база %.1f%%)" % БАЗА)
    print("═" * 74)
    for кто in ("бот", "оператор"):
        print("  %-9s ожидаемая доля заявок %.1f%%" % (кто, очки[кто] / n))
    _б, _о = очки["бот"] / n, очки["оператор"] / n
    print("  разница: %+.1f п.п. в пользу %s" % (abs(_б - _о), "бота" if _б > _о else "оператора"))

    print("\n── ПРИМЕРЫ (клиент → бот → оператор)")
    for кл, б, о in примеры:
        print("\n  клиент  : %s" % кл[:96].replace("\n", " "))
        print("  бот     : %s" % б[:96].replace("\n", " "))
        print("  оператор: %s" % о[:96].replace("\n", " "))
    return 0


if __name__ == "__main__":
    sys.exit(главное())
