# -*- coding: utf-8 -*-
"""Теневой журнал и смотрелка: наблюдение не мешает работе и не врёт.

ТРИ СВОЙСТВА, РАДИ КОТОРЫХ ЭТОТ ФАЙЛ.

1. ЖУРНАЛ НЕ РОНЯЕТ ХОД. Наблюдение не стоит ни одного потерянного ответа клиенту,
   поэтому любая ошибка записи гасится — и это проверяется подсунутым нечитаемым путём.
2. ТЕЛЕФОН В ФАЙЛ НЕ ПОПАДАЕТ ЦЕЛИКОМ. Журнал смотрят с ноутбука, и живёт он дольше
   диалога. Последние четыре цифры оставляем — по ним ход узнаётся.
3. СМОТРЕЛКА РИСУЕТ ТОЛЬКО СВОИ ЗАПИСИ. В ту же трубу течёт служебный журнал бота
   (стоимость модели, эскалации) — он тоже JSON. Первый прогон честно показал: без
   проверки вида смотрелка рисовала из этих строк пустые карточки.

Запуск: uv run python analysis/test_shadow.py
Офлайн, 0 токенов.
"""
import io
import json
import os
import sys
import tempfile

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
sys.path.insert(0, os.path.join(КОРЕНЬ, "analysis"))

ВРЕМЕННЫЙ = os.path.join(tempfile.mkdtemp(), "shadow.jsonl")
os.environ["LEADBOT_SHADOW_FILE"] = ВРЕМЕННЫЙ
os.environ["LEADBOT_SHADOW"] = "1"
import shadow                                           # noqa: E402
import watch                                            # noqa: E402

ошибки = []


def проверь(имя, условие):
    print(("  ✓ " if условие else "  ✗ ") + имя)
    if not условие:
        ошибки.append(имя)


def строки():
    if not os.path.exists(shadow.ФАЙЛ):
        return []
    return [json.loads(x) for x in io.open(shadow.ФАЙЛ, encoding="utf-8") if x.strip()]


print("маска телефона")
проверь("номер в тексте маскируется",
        shadow.маска("мой номер 89001112240, звоните") == "мой номер тел…2240, звоните")
проверь("формат +7 тоже", "тел…2240" in shadow.маска("+7 900 111-22-40"))
проверь("номер дома не трогаем", shadow.маска("Ленина 12 кв 5") == "Ленина 12 кв 5")

print("запись хода")
shadow.ход(
    [{"role": "client", "text": "Тв lg горит логотип, мой 89001112240"},
     {"role": "operator", "text": "берусь, куда подъехать?"}],
    {"city": "Санкт-Петербург", "direction": "кп", "key": "chat-1",
     "prior_self": ["здравствуйте, что случилось?"]},
    {"reply_text": "берусь. Могу сегодня к 19:00. Куда подъехать?",
     "model": "claude-sonnet-5", "missing": ["phone"], "note": "🎓 разметка"},
    ms=1200, стадия="СТАДИЯ ВХОД")
з = строки()
проверь("строка записана", len(з) == 1)
if з:
    r = з[0]
    проверь("вид проставлен", r.get("вид") == "ход")
    проверь("телефона клиента в журнале нет", "89001112240" not in json.dumps(r, ensure_ascii=False))
    проверь("реплика оператора попала", "куда подъехать" in r["оператор"])
    проверь("прошлая подсказка попала", "что случилось" in r["подсказка_до"])
    проверь("стадия попала", r["стадия"] == "СТАДИЯ ВХОД")
    проверь("слой попал", r["слой"] == "claude-sonnet-5")

print("пробелы входа названы вслух")
shadow.ход([{"role": "client", "text": "подключить стиральную машину"}],
           {"city": "", "title": "", "prior_self": []},
           {"reply_text": "здравствуйте, да, сделаю. Машинку уже купили?"})
п = строки()[-1].get("пробелы") or []
проверь("нет города — сказано", any("город" in x for x in п))
проверь("нет объявления — сказано", any("объявлени" in x for x in п))
shadow.ход([{"role": "client", "text": "подключить стиральную машину"}],
           {"city": "Москва", "title": "Ремонт стиральных машин"},
           {"reply_text": "да, сделаю"})
проверь("вход полный — пробелов нет", not (строки()[-1].get("пробелы") or []))

print("стадия доезжает из рабочей нити (боевой промах 26.08)")
import threading                                        # noqa: E402
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server                                           # noqa: E402
метка = {"брошен": False}


def _нить():
    server._ХОД.метка = метка
    server._fields_note([{"role": "client", "text": "стиралка не отжимает"}], окно="через час-полтора")


t = threading.Thread(target=_нить)
t.start()
t.join()
проверь("главная нить видит стадию через общий словарь",
        (метка.get("стадия") or "").startswith("СТАДИЯ"))

print("журнал не роняет ход")
было = shadow.ФАЙЛ
shadow.ФАЙЛ = "/несуществующий/каталог/шпион.jsonl"
try:
    shadow.пиши(вид="ход", клиент="а")
    shadow.ход([{"role": "client", "text": "а"}], {}, {"reply": "б"})
    упал = False
except Exception:
    упал = True
shadow.ФАЙЛ = было
проверь("ошибка записи проглочена, исключения нет", not упал)

print("выключатель")
shadow.ВКЛЮЧЁН = False
до = len(строки())
shadow.пиши(вид="ход", клиент="не должно записаться")
проверь("LEADBOT_SHADOW=0 — в файл ничего не идёт", len(строки()) == до)
shadow.ВКЛЮЧЁН = True

print("смотрелка")
нарисовано = []
watch.нарисовать.__globals__["print"] = lambda *a, **k: нарисовано.append(" ".join(str(x) for x in a))
watch.нарисовать({"вид": "ход", "ts": "2026-08-26T02:00:00", "клиент": "привет", "бот": "да"})
проверь("свою запись рисует", bool(нарисовано))
нарисовано.clear()
# ровно та строка, что течёт из журнала бота в общую трубу
watch.нарисовать({"ts": "2026-08-26T02:00:00+1000", "event": "leadbot.model_cost",
                  "model": "claude-sonnet-5", "input_tokens": 2178})
проверь("служебную строку бота НЕ рисует", not нарисовано)
del watch.нарисовать.__globals__["print"]

print("сверка с живым")
с = " ".join(watch.сверка("Могу сегодня к 19:00. Куда подъехать?", "Здравствуйте, когда удобно?"))
проверь("видит, что время назвал только бот", "только бот" in с)
проверь("видит, что адрес спросил только бот", "адрес" in с)
проверь("считает длину обоих", "длина" in с)
проверь("сравнивать нечего — пусто", watch.сверка("что-то", "") == [])

print()
if ошибки:
    print("ПРОВАЛЕНО: %d" % len(ошибки))
    for e in ошибки:
        print("  -", e)
    sys.exit(1)
print("Все проверки пройдены")
