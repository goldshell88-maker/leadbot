ok = bad = 0


def chk(имя, условие):
    global ok, bad
    if условие:
        ok += 1
    else:
        bad += 1
        print("ПРОВАЛ: %s" % имя)


def напр(тексты, метка=""):
    return prefilter.lock_direction(тексты if isinstance(тексты, list) else [тексты], метка)


