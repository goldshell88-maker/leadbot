# -*- coding: utf-8 -*-
"""Этап 9: метрики живого потока — те же, что в точке отсчёта (этап 0б).

ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ. Корпус — это прошлое и это ЛЮДИ. Как только бот заговорит
с клиентами, мерить надо его, теми же линейками, иначе сравнивать будет не с чем.

⚠ СРАВНИВАТЬ ЧЕСТНО. Бот включается в одном окне и на одном аккаунте, поэтому
сравнение «до и после» по всему каналу соврёт: разница окажется разницей между
ночью и днём, а не между ботом и человеком. Скрипт считает метрики С РАЗБИВКОЙ по
часам московского времени (в них живёт расписание диспетчеров) и отдельно по
аккаунту, чтобы сравнивать бота с людьми В ТЕ ЖЕ ЧАСЫ.

ИСТОЧНИК — журнал бота на боевом сервере, ТОЛЬКО ЧТЕНИЕ:
    ssh leadchat-watch "journalctl -u leadbot --since '3 days ago' --no-pager" > поток.log
    python3 analysis/LEARNING/поток.py поток.log

Никаких обращений к боевой CRM и никакой записи на сервер.
"""
import collections
import io
import json
import os
import re
import sys
from datetime import datetime

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
LEARNING = os.path.dirname(os.path.abspath(__file__))

#: Строки журнала, из которых собираются метрики. Формат задан logbook.py.
СОБЫТИЕ_RX = re.compile(r'\{"ts":\s*"([^"]+)".*?"event":\s*"([^"]+)"(.*)$')
ЧАТ_RX = re.compile(r'"chat"[:=]\s*"?([\w-]+)')
МС_RX = re.compile(r'"ms":\s*(\d+)')
ПРИЧИНА_RX = re.compile(r'причина=(\S+)')

#: База из точки отсчёта (этап 0б, замер 18.08 на корпусе живых диспетчеров).
БАЗА = {
    "телефон_%": 18.0,
    "заявка_прокси_%": 11.2,
    "первый_ответ_медиана_с": 1071,
    "цена_хода_$": 0.01362,
    "без_ответа_%": 7.4,
}

#: Стоп-правило (назначено ДО включения, см. живой-поток.md).
ПОРОГИ = {
    "телефон_%": 14.0,          # ниже — откат
    "эскалаций_%": 20.0,        # выше — откат
}


def разобрать(путь):
    события = []
    for line in open(путь, encoding="utf-8", errors="replace"):
        m = СОБЫТИЕ_RX.search(line)
        if m:
            события.append({"ts": m.group(1), "event": m.group(2), "raw": line})
            continue
        if "[ЭСКАЛАЦИЯ" in line or "[ПИНГ]" in line or "[ЗАЯВКА]" in line:
            события.append({"ts": "", "event": line.split("]")[0].strip("[ "), "raw": line})
    return события


def час_мск(ts):
    try:
        d = datetime.fromisoformat(ts.replace("Z", "+00:00"))
        return d.hour
    except Exception:
        return None


def главное():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    события = разобрать(sys.argv[1])
    if not события:
        print("в журнале нет событий бота — проверь, тот ли файл и включён ли бот")
        return 1

    по_событиям = collections.Counter(с["event"] for с in события)
    # имена событий сверены с боевым журналом 19.08: leadbot.answered (ответ клиенту),
    # leadbot.model_cost (цена хода), leadbot.refused (отказ хода), leadbot.repeat
    ответов = (по_событиям.get("leadbot.answered", 0) + по_событиям.get("leadbot.relayed", 0))
    отказов = по_событиям.get("leadbot.refused", 0)
    эскалаций = sum(v for k, v in по_событиям.items() if "ЭСКАЛАЦИЯ" in k)
    заявок = sum(v for k, v in по_событиям.items() if "ЗАЯВКА" in k)

    # скорость: ms из событий ответа
    задержки = [int(m.group(1)) for с in события for m in [МС_RX.search(с["raw"])] if m]
    задержки.sort()
    медиана = задержки[len(задержки) // 2] if задержки else None

    # телефоны и прокси-заявки: из событий лида
    лидов = sum(1 for с in события if '"lead": true' in с["raw"].lower() or "[ЛИД]" in с["raw"])
    # цена: суммируем стоимость ходов, как в базе этапа 0б
    ЦЕНЫ = {"claude-haiku-4-5-20251001": (1.0, 5.0, 0.10, 1.25),
            "claude-sonnet-5": (3.0, 15.0, 0.30, 3.75)}
    доллары, ходов = 0.0, 0
    for с in события:
        if с["event"] != "leadbot.model_cost":
            continue
        try:
            r = json.loads(с["raw"][с["raw"].index("{"):])
        except Exception:
            continue
        ц = ЦЕНЫ.get(r.get("model"))
        if not ц:
            continue
        ч = lambda k: r.get(k) or 0
        доллары += (ч("input_tokens") * ц[0] + ч("output_tokens") * ц[1]
                    + ч("cache_read") * ц[2] + ч("cache_write") * ц[3]) / 1e6
        ходов += 1

    часы = collections.Counter(час_мск(с["ts"]) for с in события if с["ts"])
    причины = collections.Counter(m.group(1) for с in события
                                  for m in [ПРИЧИНА_RX.search(с["raw"])] if m)

    итог = {
        "событий_в_журнале": len(события),
        "ответов_бота": ответов,
        "отказов_хода": отказов,
        "ходов_модели": ходов,
        "цена_хода_$": round(доллары / ходов, 5) if ходов else None,
        "эскалаций": эскалаций,
        "эскалаций_%": round(100.0 * эскалаций / ответов, 1) if ответов else None,
        "заявок_событий": заявок,
        "лид-событий": лидов,
        "медиана_ответа_мс": медиана,
        "по_часам_мск": dict(sorted((k, v) for k, v in часы.items() if k is not None)),
        "причины_эскалаций": dict(причины.most_common(8)),
        "база_этапа_0б": БАЗА,
        "пороги_отката": ПОРОГИ,
    }
    with open(os.path.join(LEARNING, "поток.json"), "w", encoding="utf-8") as f:
        json.dump(итог, f, ensure_ascii=False, indent=1)

    print("СОБЫТИЙ: %d | ОТВЕТОВ БОТА: %d | ОТКАЗОВ ХОДА: %d | ЛИД-СОБЫТИЙ: %d"
          % (len(события), ответов, отказов, лидов))
    if ходов:
        знак = "дороже" if доллары / ходов > БАЗА["цена_хода_$"] else "дешевле"
        print("ЦЕНА ХОДА: $%.5f по %d ходам (база $%.5f, то есть %s)"
              % (доллары / ходов, ходов, БАЗА["цена_хода_$"], знак))
    if медиана is not None:
        print("МЕДИАНА ОТВЕТА: %d мс (у живых было %d с = %d мс)"
              % (медиана, БАЗА["первый_ответ_медиана_с"], БАЗА["первый_ответ_медиана_с"] * 1000))
    if итог["эскалаций_%"] is not None:
        плохо = итог["эскалаций_%"] > ПОРОГИ["эскалаций_%"]
        print("ЭСКАЛАЦИЙ: %.1f%% (порог отката %.1f%%) %s"
              % (итог["эскалаций_%"], ПОРОГИ["эскалаций_%"], "🔴 ОТКАТ" if плохо else "ок"))
    if причины:
        print("причины эскалаций:", dict(причины.most_common(5)))
    print("\n⚠ Доля с телефоном и заявки считаются по выгрузке диалогов, а не по журналу:")
    print("   когда наберётся 3 дня, снять свежие диалоги и прогнать learn_funnel.py —")
    print("   он даст те же метрики, что и точка отсчёта, и сравнение будет честным.")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
