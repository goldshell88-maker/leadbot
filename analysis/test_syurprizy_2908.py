# -*- coding: utf-8 -*-
"""«БЕЗ СЮРПРИЗОВ» — ОПРАВДАНИЕ БЕЗ ОБВИНЕНИЯ (29.08, боевой диалог, Астрахань).

Клиент спросил цену ремонта джойстика. Бот: «Как посмотрю, назову цену, без сюрпризов».
Слова владельца: «нельзя озвучивать "без сюрпризов" — это обесценивает работу мастера».

ПОЧЕМУ ОБОРОТ ВРЕДЕН. Клиент ни в чём не упрекал и о сюрпризах не спрашивал. Фраза сама
подсказывает ему мысль, что сюрпризы у мастеров бывают, — и мастер заранее оправдывается
за то, чего не делал. Смысл «цифру назову после осмотра» держится и без неё.

ЧТО СДЕЛАНО. Оборот убран из банка оболочек увода цены и из плейбука; на случай, если
модель напишет его сама, стоит гард — он снимает оборот, оставляя саму фразу про цену.

Запуск: uv run python analysis/test_syurprizy_2908.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── БОЕВОЙ СЛУЧАЙ ────────────────────────────────────────────────")
_живой = "Как посмотрю, назову цену, без сюрпризов. Оба стика барахлят или только эти кнопки?"
_вышло = s._снять_оправдание(_живой)
chk("оборот убран", "сюрприз" not in _вышло.lower(), _вышло)
chk("фраза про цену осталась", "назову цену" in _вышло, _вышло)
chk("вопрос клиенту не пострадал", "барахлят" in _вышло, _вышло)
chk("запятая не повисла", ", ." not in _вышло and ",." not in _вышло, _вышло)

print("── РОДСТВЕННЫЕ ОБОРОТЫ ──────────────────────────────────────────")
for т in ("Назову цену без подвоха", "Цена без неожиданностей",
          "Скажу сумму, без сюрпризов", "работаю без сюрпризов"):
    chk("«%s» → оборот снят" % т[:30],
        "сюрприз" not in s._снять_оправдание(т).lower()
        and "подвох" not in s._снять_оправдание(т).lower()
        and "неожиданн" not in s._снять_оправдание(т).lower(), s._снять_оправдание(т))

print("── ЧУЖОЕ НЕ ТРОГАЕМ ─────────────────────────────────────────────")
for т in ("Как посмотрю — сразу назову цену", "Что случилось с приставкой?",
          "Точную сумму назову после осмотра", "Выезд и диагностика бесплатны при выполнении работ"):
    chk("«%s» не тронуто" % т[:34], s._снять_оправдание(т) == т)
chk("пустая реплика не роняет", s._снять_оправдание("") == "")

print("── ОБОРОТА НЕТ В ИСТОЧНИКАХ ─────────────────────────────────────")
# ⚠ ГАРД — ПОСЛЕДНИЙ РУБЕЖ, А НЕ ЕДИНСТВЕННЫЙ. Пока фраза лежит в банке оболочек,
# сервер сам подаёт её модели: гард будет снимать то, что сам же и предложил.
chk("нет в банке оболочек увода цены",
    not any("сюрприз" in x.lower() for x in s._LEAD_BANK), s._LEAD_BANK)
chk("банк не обеднел — вариантов хватает", len(s._LEAD_BANK) >= 6, len(s._LEAD_BANK))
_ПР = io.open(os.path.join(КОРЕНЬ, "brain", "prompt.py"), encoding="utf-8").read()
chk("в плейбуке оборот запрещён явно",
    "НЕ добавляй «без сюрпризов»" in _ПР)
chk("в плейбуке он больше не пример для подражания",
    "«Как посмотрю — назову цену,\n  без сюрпризов»" not in _ПР)

print("── ГАРД ЖИВОЙ ──────────────────────────────────────────────────")
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
chk("вызывается из воронки", "reply = _снять_оправдание(reply)" in _ИСХ)

print("=" * 50)
print("«Без сюрпризов» (29.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
