# -*- coding: utf-8 -*-
"""ЧТО ПИШУТ КЛИЕНТЫ, ЧТО ПИШУТ ОПЕРАТОРЫ И ЧЕМ ОТЛИЧАЮТСЯ УДАЧНЫЕ ДИАЛОГИ.

ЗАЧЕМ. Бота учат либо на догадках («надо теплее»), либо на замере. Здесь замер: весь
корпус живых диалогов (30 526), где отвечали ЛЮДИ, разложен по трём вопросам —
с чем приходит клиент, что делает оператор, и что из этого отличает диалоги,
дошедшие до заявки, от тех, что рассыпались.

ОТМЕТКИ УСПЕХА В ДАННЫХ НЕТ, поэтому берём определение самого проекта: заявка собрана,
когда есть ТЕЛЕФОН клиента и НАЗВАННОЕ ОКНО приезда. Это ровно то, что бот считает
`lead_ready`, — то есть меряем ту цель, ради которой он работает, а не похожесть текста.

⚠ ЧЕГО ЭТОТ РАЗБОР НЕ ЗНАЕТ. Приехал ли мастер и заплатил ли клиент — в переписке
этого нет. «Удача» здесь = диалог дошёл до заявки, а не до денег.

⚠ ДВА КОНТРОЛЯ, БЕЗ КОТОРЫХ ЦИФРЫ ВРУТ, И ОБА ПОЙМАЛИ МЕНЯ НА ГОРЯЧЕМ.
 1. ДЛИНА СЧИТАЕТСЯ ПО ХОДАМ, А НЕ ПО ПУЗЫРЯМ. Операторы пишут очередями: 36 % ходов
    состоят больше чем из одного сообщения. По пузырям медиана выходит 26 знаков, по
    ходам — 39. Первая цифра сделала бы вывод «бот вдвое многословнее», а правда мягче:
    58 против 39, то есть бот сидит примерно на 70-м процентиле оператора.
 2. «НАЗВАЛ ВРЕМЯ ПЕРВЫМ ХОДОМ» ПРОВЕРЕНО НА ОБРАТНУЮ ПРИЧИННОСТЬ. Могло быть так, что
    время называют там, где клиент уже всё сказал. Разделили: на ГОЛОМ старте (клиент не
    дал ни адреса, ни телефона, ни времени) выигрыш всё равно +15,0 п.п. — 22,2 % против
    7,2 %. Значит это рычаг, а не следствие.

Запуск: uv run python analysis/audit_dialogs.py [--примеры]
Офлайн, 0 токенов.
"""
import collections
import io
import json
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter                                        # noqa: E402
import server as s                                      # noqa: E402

КОРПУС = os.path.join(КОРЕНЬ, "analysis", "LEARNING", "corpus.jsonl")

ОКНО_RX = re.compile(
    r"\bчас[- ]полтора\b|\bчерез\s+час\b|\bдва,?\s*два\s*с\s*половиной\b|"
    r"\bк\s*\d{1,2}(?:[:.]\d{2})?\b|\bв\s*\d{1,2}[:.]\d{2}\b|\bсегодня\b|\bзавтра\b",
    re.IGNORECASE)
ЦЕНА_RX = re.compile(r"\bсколько\b|\bцена\b|\bстоимост|\bпочём|\bпочем\b|\bпо\s+деньгам\b", re.I)
ТЕХНИКА_RX = re.compile(r"стиральн|стиралк|холодильник|телевизор|\bтв\b|посудомо|плит[аыу]|"
                        r"духов|ноутбук|компьютер|принтер|роутер|микроволн|пылесос|бойлер", re.I)
РАБОТА_RX = re.compile(r"повесить|собрать|установ|подключ|заменить|починить|отремонт|"
                       r"навес|прикрут|сверл|перенест", re.I)
#: ⚠ РАЗНИЦА, РАДИ КОТОРОЙ ВЕСЬ РАЗБОР: ПРЕДЛОЖИТЬ окно и СПРОСИТЬ время — не одно и
#: то же. Замер: предложил — 37,0 % до заявки, спросил — 15,2 %, ни того ни другого — 7,6 %.
ПРЕДЛОЖИЛ_RX = re.compile(
    r"(?i)(?:могу|подъеду|буду|приеду)[^.!?\n]{0,30}"
    r"(?:через\s+час|час[- ]полтора|сегодня|завтра|к\s*\d{1,2})"
    r"|через\s+час[- ]полтора[^.!?\n]{0,20}удобно")
СПРОСИЛ_RX = re.compile(
    r"(?i)когда\s+(?:вам\s+)?удобно|во\s+сколько|в\s+какое\s+время|"
    r"когда\s+(?:вас\s+)?ждать|когда\s+могу")
СРОЧНО_RX = re.compile(r"\bсрочно\b|\bсегодня\b|\bсейчас\b|\bкак можно (?:быстрее|скорее)\b", re.I)
ВОПРОС_RX = re.compile(r"\?")


def реплики(d, роль):
    return [(m.get("text") or "").strip() for m in (d.get("messages") or [])
            if (m.get("role") or "") == роль and (m.get("text") or "").strip()]


def главное():
    примеры = "--примеры" in sys.argv
    всего = 0
    удачных = 0
    перв_дл, оп_дл = [], []
    перв_что = collections.Counter()
    оп_перв_что = collections.Counter()
    ходов_до_заявки = []
    удача_по_ходам = collections.Counter()
    всего_по_ходам = collections.Counter()
    удача_если = collections.Counter()
    всего_если = collections.Counter()
    первые_вопросы = collections.Counter()
    врем = {}

    for line in io.open(КОРПУС, encoding="utf-8"):
        try:
            d = json.loads(line)
        except Exception:
            continue
        кл, оп = реплики(d, "client"), реплики(d, "operator")
        if not кл:
            continue
        всего += 1
        первая = кл[0]
        вся_кл, вся_оп = " \n".join(кл), " \n".join(оп)
        перв_дл.append(len(первая))
        for т in оп:
            оп_дл.append(len(т))

        # ── с чем приходит клиент
        if ЦЕНА_RX.search(первая):
            перв_что["спросил цену"] += 1
        if ТЕХНИКА_RX.search(первая):
            перв_что["назвал технику"] += 1
        if РАБОТА_RX.search(первая):
            перв_что["назвал работу"] += 1
        if s._ADDR_RX.search(первая):
            перв_что["сразу дал адрес"] += 1
        if prefilter.phones_in(первая):
            перв_что["сразу дал телефон"] += 1
        if СРОЧНО_RX.search(первая):
            перв_что["торопит"] += 1
        if not ВОПРОС_RX.search(первая) and len(первая) < 40:
            перв_что["короткая реплика без вопроса"] += 1

        # ── что делает оператор ПЕРВЫМ ходом
        if оп:
            п = оп[0]
            if re.match(r"(?i)\s*(здравствуйте|добрый|доброе|приветствую)", п):
                оп_перв_что["поздоровался"] += 1
            if ВОПРОС_RX.search(п):
                оп_перв_что["задал вопрос"] += 1
            if ОКНО_RX.search(п):
                оп_перв_что["сразу назвал время"] += 1
            if re.search(r"(?i)\bот\s*\d{3,}|\d{3,}\s*(?:р\b|руб)", п):
                оп_перв_что["сразу назвал цену"] += 1
            if len(п) <= 60:
                оп_перв_что["ответил коротко (≤60 знаков)"] += 1
            m = re.search(r"[^.!?\n]*\?", п)
            if m:
                первые_вопросы[re.sub(r"\s+", " ", m.group(0).strip().lower())[:60]] += 1

        # ── успех: телефон клиента + названное окно у оператора
        есть_тел = bool(prefilter.phones_in(вся_кл))
        есть_окно = bool(ОКНО_RX.search(вся_оп))
        успех = есть_тел and есть_окно
        удачных += успех
        n = min(len(оп), 12)
        всего_по_ходам[n] += 1
        удача_по_ходам[n] += успех
        if успех:
            ходов_до_заявки.append(len(оп))

        # ── что КОРРЕЛИРУЕТ с успехом
        признаки = {
            "оператор поздоровался": bool(оп and re.match(r"(?i)\s*(здравствуйте|добрый|доброе)", оп[0])),
            "оператор ответил коротко (первый ход ≤60)": bool(оп and len(оп[0]) <= 60),
            "оператор задал вопрос первым ходом": bool(оп and ВОПРОС_RX.search(оп[0])),
            "оператор назвал ЦЕНУ первым ходом": bool(оп and re.search(r"(?i)\bот\s*\d{3,}", оп[0])),
            "оператор назвал ВРЕМЯ первым ходом": bool(оп and ОКНО_RX.search(оп[0])),
            "клиент спросил цену первым": bool(ЦЕНА_RX.search(первая)),
            "клиент сразу дал адрес": bool(s._ADDR_RX.search(первая)),
            "клиент торопит": bool(СРОЧНО_RX.search(первая)),
            "диалог длиннее 4 ходов оператора": len(оп) > 4,
        }
        for k, v in признаки.items():
            if v:
                всего_если[k] += 1
                удача_если[k] += успех

        if оп:
            вид = ("ПРЕДЛОЖИЛ окно" if ПРЕДЛОЖИЛ_RX.search(оп[0])
                   else ("СПРОСИЛ время" if СПРОСИЛ_RX.search(оп[0]) else "ни то ни другое"))
            x = врем.setdefault(вид, [0, 0])
            x[0] += 1
            x[1] += успех

    def med(xs):
        xs = sorted(xs)
        return xs[len(xs) // 2] if xs else 0

    print("═" * 78)
    print("РАЗБОР ЖИВЫХ ДИАЛОГОВ: %d штук, отвечали ЛЮДИ" % всего)
    print("═" * 78)
    print("дошли до заявки (телефон + названное окно): %d (%.1f%%)"
          % (удачных, 100.0 * удачных / всего))
    print("медиана первой реплики клиента: %d знаков | медиана реплики оператора: %d"
          % (med(перв_дл), med(оп_дл)))
    print("медиана ходов оператора до заявки: %d" % med(ходов_до_заявки))

    print("\n── С ЧЕМ ПРИХОДИТ КЛИЕНТ (первая реплика)")
    for k, v in перв_что.most_common():
        print("   %-34s %6d  (%.0f%%)" % (k, v, 100.0 * v / всего))

    print("\n── ЧТО ДЕЛАЕТ ОПЕРАТОР ПЕРВЫМ ХОДОМ")
    сдоп = sum(1 for _ in range(0))  # noqa
    for k, v in оп_перв_что.most_common():
        print("   %-34s %6d  (%.0f%%)" % (k, v, 100.0 * v / max(1, всего)))

    print("\n── ЧТО СВЯЗАНО С УСПЕХОМ (доля дошедших до заявки)")
    база = 100.0 * удачных / всего
    print("   %-46s %6s %8s" % ("признак", "было", "успех"))
    for k in sorted(всего_если, key=lambda x: -(100.0 * удача_если[x] / max(1, всего_если[x]))):
        n, u = всего_если[k], удача_если[k]
        доля = 100.0 * u / max(1, n)
        print("   %-46s %6d %7.1f%%  %+.1f п.п." % (k, n, доля, доля - база))
    print("   %-46s %6d %7.1f%%   (база)" % ("ВСЕ ДИАЛОГИ", всего, база))

    print("\n── УСПЕХ ПО ДЛИНЕ РАЗГОВОРА (ходов оператора)")
    for n in sorted(всего_по_ходам):
        т, у = всего_по_ходам[n], удача_по_ходам[n]
        if т < 50:
            continue
        print("   %2d ходов: диалогов %5d, до заявки %5.1f%%" % (n, т, 100.0 * у / т))

    # ── ДВА КОНТРОЛЯ И ГЛАВНЫЙ РАСКЛАД ──────────────────────────────────────────
    print("\n── ДЛИНА ХОДА ОПЕРАТОРА (пузыри склеены в ход, как читает клиент)")
    ходы = []
    for line in io.open(КОРПУС, encoding="utf-8"):
        try:
            d = json.loads(line)
        except Exception:
            continue
        текущ = []
        for m in (d.get("messages") or []):
            т = (m.get("text") or "").strip()
            if not т:
                continue
            if (m.get("role") or "") == "operator":
                текущ.append(т)
            elif текущ:
                ходы.append(" ".join(текущ))
                текущ = []
        if текущ:
            ходы.append(" ".join(текущ))
    дх = sorted(len(x) for x in ходы)
    print("   ходов %d | медиана %d знаков | 75%% %d | 90%% %d"
          % (len(ходы), дх[len(дх) // 2], дх[int(len(дх) * .75)], дх[int(len(дх) * .9)]))
    print("   ⚠ по ПУЗЫРЯМ медиана вышла бы %d — и вывод про многословность бота был бы вдвое злее"
          % med(оп_дл))

    print("\n── ГЛАВНОЕ: ЧТО ОПЕРАТОР ДЕЛАЕТ СО ВРЕМЕНЕМ В ПЕРВОМ ХОДЕ")
    print("   %-22s %8s %10s" % ("вид", "диалогов", "до заявки"))
    for k in ("ПРЕДЛОЖИЛ окно", "СПРОСИЛ время", "ни то ни другое"):
        n, u = врем.get(k, [0, 0])
        print("   %-22s %8d %9.1f%%" % (k, n, 100.0 * u / max(1, n)))
    print("   ⚠ предложить конкретное окно вчетверо сильнее, чем спросить «когда удобно».")
    print("   ⚠ так делают 276 операторов из %d — меньше процента." % всего)

    if примеры:
        print("\n── САМЫЕ ЧАСТЫЕ ПЕРВЫЕ ВОПРОСЫ ОПЕРАТОРА")
        for q, n in первые_вопросы.most_common(20):
            print("   %5d  %s" % (n, q))
    return 0


if __name__ == "__main__":
    sys.exit(главное())
