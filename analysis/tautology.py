# -*- coding: utf-8 -*-
"""ТАВТОЛОГИЯ В РЕПЛИКАХ БОТА: замер и разбор по видам.

ЗАЧЕМ. Повтор — самый заметный признак автомата. Человек, сказав «цену назову на
месте», второй раз это в том же сообщении не говорит; бот говорит. Здесь тавтология
разложена на четыре ПРОВЕРЯЕМЫХ вида, а не на ощущение «звучит криво»:

  внутренний повтор  одна и та же мысль дважды в ОДНОЙ реплике («расценю на месте…
                     точнее скажу на месте»). Ловится повтором содержательной
                     тройки слов.
  эхо клиента        четыре слова клиента подряд, вернувшиеся в ответе. Клиент читает
                     это как «бот повторил за мной».
  повтор себя        та же фраза, что бот уже говорил в ЭТОМ диалоге раньше.
  дубль-предложения  два предложения одной реплики про одно и то же (сходство ≥ 0,5).

⚠ СЛУЖЕБНЫЕ СЛОВА НЕ СЧИТАЮТСЯ. «на», «по», «вам» повторяются в любой живой речи;
тавтология — это повтор ЗНАЧАЩИХ слов. Берём слова от четырёх букв и режем стоп-лист.

⚠ ЦИТАТА КЛИЕНТА НЕ ВСЕГДА ЭХО. Названия («Хендай Солярис», «43UN73006») повторить
приходится, иначе непонятно, о чём речь. Цифро-буквенные коды и слова с заглавной
буквы внутри фразы из эха исключены.

Запуск:
    uv run python analysis/tautology.py            # по живым подсказкам из боя
    uv run python analysis/tautology.py --эталон   # по эталонной выборке (кассета)
Офлайн, 0 токенов.
"""
import io
import json
import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
sys.path.insert(0, os.path.join(КОРЕНЬ, "analysis"))

ЖИВЫЕ = os.path.join(КОРЕНЬ, "analysis", "LEARNING", "avito_corpus.jsonl")

#: Слова, повтор которых ничего не значит: предлоги, союзы, вежливость, местоимения.
СТОП = frozenset("""
это что как для или если когда чтобы тогда потом ещё уже там тут вот так этот эта
вас вам ваш ваша ваше ваши мне меня мной себе себя его её их них ним нему
буду будет быть было есть был была были
пожалуйста спасибо здравствуйте добрый доброе доброго день вечер утро
можно нужно надо очень просто только даже тоже также всего всё все
""".split())

_СЛОВО = re.compile(r"[а-яёa-z]{4,}", re.IGNORECASE)
_КОД = re.compile(r"[a-zа-я]*\d+[a-zа-я0-9-]*", re.IGNORECASE)


def значащие(текст):
    return [w for w in (x.lower() for x in _СЛОВО.findall(текст or "")) if w not in СТОП]


def предложения(текст):
    куски = re.split(r"[.!?\n]+", текст or "")
    return [к.strip() for к in куски if len(значащие(к)) >= 3]


def _тройки(слова):
    return [tuple(слова[i:i + 3]) for i in range(len(слова) - 2)]


def внутренний_повтор(реплика):
    """Одна и та же содержательная тройка слов дважды в одной реплике."""
    сл = значащие(реплика)
    видел, повторы = set(), []
    for т in _тройки(сл):
        if т in видел:
            повторы.append(" ".join(т))
        видел.add(т)
    return повторы


def эхо_клиента(реплика, речь_клиента):
    """Четыре слова клиента подряд в ответе. Названия и коды не в счёт."""
    сл_к = значащие(речь_клиента)
    сл_б = " ".join(значащие(реплика))
    из_за = []
    for i in range(len(сл_к) - 3):
        кусок = сл_к[i:i + 4]
        if any(_КОД.fullmatch(w) for w in кусок):
            continue
        фраза = " ".join(кусок)
        if фраза in сл_б:
            из_за.append(фраза)
    return из_за


def повтор_себя(реплика, прошлые):
    """Та же четвёрка слов, что бот уже говорил в этом диалоге."""
    сл_б = значащие(реплика)
    было = set()
    for п in прошлые:
        сл = значащие(п)
        было |= {tuple(сл[i:i + 4]) for i in range(len(сл) - 3)}
    return [" ".join(т) for т in
            {tuple(сл_б[i:i + 4]) for i in range(len(сл_б) - 3)} & было]


def дубль_предложений(реплика, порог=0.5):
    """Два предложения одной реплики про одно и то же."""
    пр = предложения(реплика)
    из_за = []
    for i in range(len(пр)):
        A = set(значащие(пр[i]))
        for j in range(i + 1, len(пр)):
            B = set(значащие(пр[j]))
            if A and B and len(A & B) / len(A | B) >= порог:
                из_за.append((пр[i][:50], пр[j][:50]))
    return из_за


ВИДЫ = ("внутренний повтор", "эхо клиента", "повтор себя", "дубль-предложения")


def разбор(реплика, речь_клиента="", прошлые=()):
    return {
        "внутренний повтор": внутренний_повтор(реплика),
        "эхо клиента": эхо_клиента(реплика, речь_клиента),
        "повтор себя": повтор_себя(реплика, прошлые),
        "дубль-предложения": дубль_предложений(реплика),
    }


#: ⚠ ТЕКСТЫ СЦЕНАРИЯ — НЕ РЕПЛИКИ БОТА, И СЧИТАТЬ ИХ ЗДЕСЬ НЕЛЬЗЯ. В ленте они лежат под
#: тем же префиксом «Подсказка бота», потому что проходят через ту же точку исходящих, но
#: пишет их не мозг, а шаг сценария фиксированной строкой. Их и чинят иначе: дожим в
#: режиме подсказки выключен 26.08, а сам текст исправлен миграцией 0052 в базе панели.
#: Мерить ими работу бота — всё равно что записывать ему в ошибки чужую заготовку.
СЦЕНАРНЫЕ = (
    "ну что, подскажете",
    "подскажете номер? перезвоним",
    "мастер ответит утром",
    "отвечу утром. оставьте телефон",
    "это сервис lead partner",
    "кажется, это не номер",
)


def _сценарный(текст):
    н = " ".join((текст or "").split()).lower()
    return any(н.startswith(x) for x in СЦЕНАРНЫЕ)


def из_боя():
    """Живые подсказки бота вместе с речью клиента до них."""
    for line in io.open(ЖИВЫЕ, encoding="utf-8"):
        try:
            d = json.loads(line)
        except Exception:
            continue
        п = d.get("подсказки_бота") or []
        if not п:
            continue
        речь = " ".join(m["text"] for m in (d.get("реплики") or [])
                        if m.get("role") == "client")
        for i, р in enumerate(п):
            if _сценарный(р):
                continue
            yield р, речь, п[:i]


def главное():
    if "--эталон" in sys.argv:
        import benchmark as B
        кассета = B.Кассета(B.КАССЕТА, "сухой")
        настоящая = кассета.обернуть()
        случаи = []
        try:
            for d in B.выборка():
                for х in B.прогнать_диалог(d, кассета):
                    if х.get("не_записан") or not х.get("бот"):
                        continue
                    случаи.append((х["бот"], " ".join(х["клиент_всё"]), х["свои_прошлые"]))
        finally:
            import claude_api
            claude_api.messages = настоящая
        источник = "эталонная выборка"
    else:
        случаи = list(из_боя())
        источник = "живые подсказки из боя"
    # ⚠ РЕЖИМ «ПОСЛЕ ГАРДА»: те же живые реплики, пропущенные через `_снять_самоповтор`.
    # Это честная проверка починки на боевом материале: переписку заново прогонять через
    # модель незачем, чинится ровно текст, и чинится он детерминированно.
    if "--после" in sys.argv:
        import server as _s
        случаи = [(_s._снять_самоповтор(р, " \n".join(прошлые), 7,
                                        вопрос_клиента=реч.rstrip().endswith("?")),
                   реч, прошлые)
                  for р, реч, прошлые in случаи]
        источник += " ПОСЛЕ гарда самоповтора"

    счёт = {в: 0 for в in ВИДЫ}
    грязных = 0
    примеры = {в: [] for в in ВИДЫ}
    for реплика, речь, прошлые in случаи:
        r = разбор(реплика, речь, прошлые)
        плохо = False
        for в in ВИДЫ:
            if r[в]:
                счёт[в] += 1
                плохо = True
                if len(примеры[в]) < 3:
                    примеры[в].append((r[в][0], реплика))
        грязных += 1 if плохо else 0

    n = len(случаи) or 1
    print("=" * 70)
    print("ТАВТОЛОГИЯ · источник: %s · реплик: %d" % (источник, len(случаи)))
    print("=" * 70)
    print("С ТАВТОЛОГИЕЙ: %d из %d — %.1f %%" % (грязных, len(случаи), 100.0 * грязных / n))
    print("-" * 70)
    for в in ВИДЫ:
        print("  %-20s %4d реплик (%.1f %%)" % (в, счёт[в], 100.0 * счёт[в] / n))
    for в in ВИДЫ:
        if not примеры[в]:
            continue
        print("-" * 70)
        print("%s:" % в.upper())
        for что, реплика in примеры[в]:
            print("   повтор: %s" % (что if isinstance(что, str) else " // ".join(что)))
            print("   в реплике: %s" % " ".join(реплика.split())[:110])
    return 0


if __name__ == "__main__":
    sys.exit(главное())
