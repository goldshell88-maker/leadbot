"""ПАЧКА 5, часть 2 — БУФЕР ТИШИНЫ ПЕРЕД ОТВЕТОМ (Э4, 21.08).

Правила базы знаний (ДИАЛОГ-И-ПАУЗЫ.md, №59 и №67) не были внедрены:

    «Буфер тишины 20–25 с всегда, 35–45 с если реплика незакончена;
     исключение для «?» снять»
    «Реплика с «?» получает то же окно тишины (можно сократить до 15–20 с,
     но не до нуля)»

Было: 12 секунд на обычную реплику, 35 на незаконченную и РОВНО НОЛЬ на любую
реплику с вопросительным знаком. Ноль — это мгновенный ответ, а мгновенный ответ
на вопрос выдаёт автомат надёжнее любой формулировки: живой мастер физически не
успевает прочитать и ответить за секунду.

Вторая причина ждать — деньги и смысл: замер корпуса показал 34.1% лишних вызовов
модели, потому что клиент дописывает мысль частями, а бот отвечает на каждый кусок.
Вопросы тут не исключение — «сколько стоит?» сплошь и рядом продолжается адресом
и моделью техники следующим сообщением.

Пауза не одинаковая, а вразброс по содержанию реплики: ровное число секунд у всех
ответов — тоже примета автомата.

Запуск: uv run python analysis/test_batch5_silence.py   (0 токенов)
"""
import io
import os
import statistics
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "brain"))
import server  # noqa: E402

ok = bad = 0


def chk(label, cond):
    global ok, bad
    if cond:
        ok += 1
    else:
        bad += 1
        print("✗", label)


# ── 1. обычная законченная реплика: 20–25 с ─────────────────────────────────
ОБЫЧНЫЕ = [
    "Не работает стиральная машина Bosch, не отжимает бельё.",
    "Нужно собрать шкаф и повесить полку в спальне.",
    "Холодильник течёт снизу, вода на полу.",
]
for т in ОБЫЧНЫЕ:
    w = server.debounce_wait(т, 0)
    chk("законченная реплика ждёт 20–25 с: %.0f с — %s" % (w, т[:32]), 20 <= w <= 25)

# ── 2. незаконченная: 35–45 с ───────────────────────────────────────────────
НЕЗАКОНЧЕННЫЕ = ["здравствуйте", "Bosch", "стиралка не отжимает, и ещё", "а"]
for т in НЕЗАКОНЧЕННЫЕ:
    w = server.debounce_wait(т, 0)
    chk("незаконченная ждёт 35–45 с: %.0f с — %s" % (w, т[:32]), 35 <= w <= 45)

# ── 3. вопрос: короче, но НЕ ноль ───────────────────────────────────────────
ВОПРОСЫ = ["сколько будет стоить?", "Когда сможете подъехать?", "а вы матрицу меняете?"]
for т in ВОПРОСЫ:
    w = server.debounce_wait(т, 0)
    chk("вопрос ждёт 15–20 с, а не ноль: %.0f с — %s" % (w, т[:32]), 15 <= w <= 20)

# ── 4. разброс есть, ровного числа у всех нет ───────────────────────────────
разброс = [server.debounce_wait("Сломался холодильник номер %d." % i, 0) for i in range(60)]
chk("пауза не одинаковая у всех (σ ≥ 1 с): %.1f" % statistics.pstdev(разброс),
    statistics.pstdev(разброс) >= 1.0)
chk("одна и та же реплика — одна и та же пауза",
    server.debounce_wait("Холодильник течёт.", 0) == server.debounce_wait("Холодильник течёт.", 0))

# ── 5. прежние предохранители ───────────────────────────────────────────────
chk("пусто — ждать нечего", server.debounce_wait("", 0) == 0.0)
chk("уже подождали — не ждём снова", server.debounce_wait("здравствуйте", 60) == 0.0)
chk("остаток считается от прошедшего",
    0 < server.debounce_wait("здравствуйте", 30) < server.debounce_wait("здравствуйте", 0))

print("\nИТОГО: %d ок, %d провал" % (ok, bad))
sys.exit(1 if bad else 0)
