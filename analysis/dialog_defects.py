# -*- coding: utf-8 -*-
"""Детерминированные дефекты диалога — БЕЗ вызовов модели и без сети.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Живость мерил `test_context_liveness.py`, но его проверок
было ровно две — повторное приветствие и роботизмы. По ним прогон 12 августа дал
чистые 0/10, а в самих сохранённых диалогах лежало вот это:

    К: а во сколько сегодня могли бы?
    Б: куда подъехать? По адресу сориентирую по времени
    К: хм, а пораньше никак?
    Б: по возможности постараюсь раньше. подскажите адрес (улица, дом, квартира)?
    К: ну ладно, надо подумать          ← клиент ушёл

Клиент дважды спросил про время, дважды получил вопрос про адрес и ушёл. Прогон
при этом отчитался «✓ чисто». Проверка, которая не видит потерянный лид, хуже
отсутствующей: она даёт ложное спокойствие.

ПОЧЕМУ ПРОВЕРКИ ЗДЕСЬ, А НЕ В ПРОГОНЕ. Эти функции работают над УЖЕ СОХРАНЁННЫМИ
диалогами (`test_context_liveness.jsonl`), поэтому счёт можно пересчитать сколько
угодно раз и ни разу не заплатить за токены. Живой прогон нужен только чтобы
получить новые диалоги; оценка их качества — бесплатна и повторяема.

ЧТО ЗДЕСЬ НАМЕРЕННО НЕ ПРОВЕРЯЕТСЯ: вежливость, «живость», тон. Это вкусовщина, и
меряется она судьёй, а не регуляркой. Здесь только то, что можно предъявить как
факт: клиент спросил — бот не ответил; бот назвал вторник, потом сегодня; один и
тот же вопрос дважды в одном сообщении.

Запуск:  python3 analysis/dialog_defects.py [файл.jsonl]
"""
import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# --------------------------------------------------------------- словари

#: Клиент спрашивает ПРО ВРЕМЯ. Только прямые вопросы: «когда», «во сколько»,
#: «пораньше». Слово «время» само по себе не берём — «времени нет» это не вопрос.
_КЛИЕНТ_ПРО_ВРЕМЯ = re.compile(
    r"(когда\s+(?:смож\w+|може\w+|приед\w+|буде\w+|подъед\w+)"
    r"|во\s?сколько"
    r"|в\s+какое\s+время"
    r"|пораньше"
    r"|пораньше\s+никак"
    r"|как\s+скоро"
    r"|сегодня\s+(?:смож\w+|може\w+|получится|реально)"
    r"|успе\w+\s+сегодня)",
    re.IGNORECASE,
)

#: Ответ, в котором ВРЕМЯ НАЗВАНО. Достаточно любого из: часы, «к 17», день,
#: длительность. Это и есть «бот ответил на вопрос про время».
#:
#: ⚠ «сориентирую по времени» сюда НЕ попадает, и это главное. Слово «время» в
#: ответе — не ответ; ответ — это час, день или длительность.
_ВРЕМЯ_НАЗВАНО = re.compile(
    r"(\d{1,2}[:.]\d{2}"
    r"|\bк\s+\d{1,2}\b"
    r"|\bпосле\s+\d{1,2}\b"
    r"|час[аоу]?[-\s]*полтора"
    r"|полтора\s+час"
    r"|\bсегодня\b|\bзавтра\b|\bпослезавтра\b"
    r"|понедельник|вторник|сред[уы]|четверг|пятниц[уы]|суббот[уы]|воскресень)",
    re.IGNORECASE,
)

#: Открытый вопрос о времени — прямо запрещён разбором заказчика 02.08:
#: «когда удобно?» без предложенного окна — потеря инициативы.
_ОТКРЫТЫЙ_ВОПРОС = re.compile(
    r"(когда\s+вам\s+удобно"
    r"|во\s?сколько\s+вам\s+удобно"
    r"|когда\s+(?:смож\w+|може\w+)\s+принять"
    r"|когда\s+вам\s+(?:помощь\s+)?нужн\w*"
    r"|когда\s+вас\s+ждать"
    r"|в\s+какое\s+время\s+вам\s+удобно"
    r"|когда\s+удобно)",
    re.IGNORECASE,
)

#: Конкретное ОКНО — то, наличие чего делает открытый вопрос допустимым.
#: Именно окно, а не просто упоминание дня: «сегодня вечером» окном не является,
#: потому что клиенту всё ещё нечего подтвердить.
_ОКНО_НАЗВАНО = re.compile(
    r"(\d{1,2}[:.]\d{2}"
    r"|\bк\s+\d{1,2}\b"
    r"|час[аоу]?[-\s]*полтора"
    r"|\bчерез\s+\d"
    r"|\bдва[-\s]*два\s+с\s+половиной)",
    re.IGNORECASE,
)

#: ПРОСЬБА назвать адрес. Только повелительное наклонение и прямой вопрос.
#:
#: ⚠ ГЛАГОЛ РАЗЛИЧАЕМ ПО ЛИЦУ, И ЭТО НЕ ПРИДИРКА. «сориентируйте по адресу» —
#: просьба; «по адресу сориентирую по времени» — обещание. Возьми обе формы одной
#: маской `сориентир\w*` — и объяснение «скажу время, когда узнаю адрес» посчитается
#: вторым вопросом. На живых диалогах именно это давало три ложных срабатывания из
#: четырёх, то есть проверка шумела громче, чем находила.
_ПРОСЬБА_АДРЕС = re.compile(
    r"(куда\s+(?:подъех|приех|ех)\w*"
    r"|по\s+какому\s+адресу"
    r"|какой\s+(?:у\s+вас\s+)?адрес"
    r"|где\s+вы\s+находитесь"
    r"|(?:подскажите|подскажете|скажите|назовите|напишите|сориентируйте|дайте|киньте|уточните)"
    r"\s+(?:мне\s+)?(?:по\s+)?(?:\w+\s+){0,2}адрес"
    r"|адрес\w*\s+(?:подскажите|подскажете|скажите|назовите|напишите|сориентируйте))",
    re.IGNORECASE,
)

#: Границы предложений: повтор считаем ПО ПРЕДЛОЖЕНИЯМ, а не по совпадениям.
#: «По адресу подскажите куда подъехать» — это один вопрос, сформулированный
#: двумя оборотами, а не два вопроса.
_ГРАНИЦА = re.compile(r"[.!?\n]+")

#: ВОПРОС О ГОРОДЕ — прямой запрет промпта (prompt.py: «⛔ ГОРОД НЕ СПРАШИВАЙ НИКОГДА — он
#: известен из объявления»). Тот же запрет отдельно продублирован в анти-маркерах сборщика
#: RAG-пула, потому что пара «Когда подъедете?» → «В каком городе проживаете?» однажды вышла
#: в пуле в top-1. Спросив город, бот сообщает клиенту, что не видит объявления, — а живой
#: мастер его видит всегда.
#:
#: ⚠ «Адрес: город, улица, дом» — это ТОЖЕ вопрос о городе, и ловится он только так: по
#: слову «город» внутри просьбы об адресе. Отдельная строка «в каком городе» этого не видит.
_СПРАШИВАЕТ_ГОРОД = re.compile(
    r"(в\s+каком\s+городе"
    r"|из\s+какого\s+город\w*"
    r"|с\s+какого\s+город\w*"
    r"|какой\s+(?:у\s+вас\s+)?город"
    r"|город\w*\s+(?:подскаж|назов|напиш|уточн)\w*"
    r"|адрес[^.!?]{0,20}\(\s*город"
    r"|адрес[^.!?]{0,20}город\w*\s*,)",
    re.IGNORECASE,
)

#: Маркеры КАЛЕНДАРНОГО ДНЯ — по ним ловится флип-флоп «вторник → сегодня».
_ДЕНЬ = re.compile(
    r"(сегодня|завтра|послезавтра"
    r"|понедельник\w*|вторник\w*|сред[ауые]\w*|четверг\w*"
    r"|пятниц\w*|суббот\w*|воскресень\w*)",
    re.IGNORECASE,
)


def _дни(текст):
    """Множество названных дней, приведённых к общей основе."""
    вышло = set()
    for m in _ДЕНЬ.finditer(текст or ""):
        сл = m.group(0).lower()
        # «среду»/«среда»/«среды» — один день; обрезаем окончание грубо, но одинаково
        вышло.add(сл[:6])
    return вышло


# --------------------------------------------------------------- проверки


def ignored_time_question(rows):
    """Клиент спросил ПРО ВРЕМЯ, а в ответе времени нет.

    САМЫЙ ДОРОГОЙ ДЕФЕКТ ИЗ ЗДЕШНИХ. По отчёту операторов окно времени — точка,
    где лид теряется чаще всего (17–21% доходят). Диалог `time_no_flipflop` это
    показывает дословно: два вопроса про время, два ответа про адрес, уход
    клиента. Клиент не обязан спрашивать трижды.
    """
    беда = []
    for r in rows:
        вопрос, ответ = r.get("client") or "", r.get("bot") or ""
        if not _КЛИЕНТ_ПРО_ВРЕМЯ.search(вопрос):
            continue
        if _ВРЕМЯ_НАЗВАНО.search(ответ):
            continue
        беда.append((вопрос, ответ))
    return беда


def open_time_question(rows):
    """Открытый «когда вам удобно?» без предложенного окна.

    Запрещено прямым разбором заказчика 02.08: вопрос без окна отдаёт инициативу
    клиенту, а клиент отвечает «я подумаю». Предлагать должен бот.
    """
    беда = []
    for r in rows:
        ответ = r.get("bot") or ""
        if _ОТКРЫТЫЙ_ВОПРОС.search(ответ) and not _ОКНО_НАЗВАНО.search(ответ):
            беда.append(ответ)
    return беда


def repeated_question(rows):
    """Один и тот же вопрос дважды в ОДНОМ сообщении.

    «сориентируйте точный адрес и номер телефона / По какому адресу вы
    находитесь?» — так человек не пишет. Клиент видит, что его не читают.

    Считаем по ПРЕДЛОЖЕНИЯМ: два разных предложения, и каждое просит адрес.
    Внутри одного предложения обороты складываются («По адресу подскажите куда
    подъехать») — это одна просьба, а не две.
    """
    беда = []
    for r in rows:
        ответ = r.get("bot") or ""
        просящих = sum(1 for кусок in _ГРАНИЦА.split(ответ)
                       if кусок.strip() and _ПРОСЬБА_АДРЕС.search(кусок))
        if просящих >= 2:
            беда.append(ответ)
    return беда


def time_flipflop(rows):
    """Бот назвал один день, потом другой — и клиент об этом не просил.

    «Во вторник к 17:00-17:30 удобно?» → клиент «?» → «могу сегодня к 17
    подъехать». После такого клиент не знает, когда приедет мастер, и переспросит
    в лучшем случае — а в худшем уйдёт.

    ⚠ Смена дня ПО ПРОСЬБЕ КЛИЕНТА дефектом не является: если клиент сам написал
    «сегодня вечером можно?», перейти на сегодня — это и есть работа. Поэтому
    новый день ищется в реплике клиента, и найденный там — не в счёт.
    """
    беда = []
    прежние = set()
    for r in rows:
        свои = _дни(r.get("bot") or "")
        клиентские = _дни(r.get("client") or "")
        новые = свои - прежние - клиентские
        if прежние and новые:
            беда.append((sorted(прежние), sorted(новые), r.get("bot") or ""))
        прежние |= свои
    return беда


# ⚠ ЗДЕСЬ БЫЛА ШЕСТАЯ ПРОВЕРКА — «Здравствуйте» отдельной строкой, — И ОНА БЫЛА НЕВЕРНА.
# Она нашла 6 «дефектов» из 10 диалогов, а поведение оказалось намеренным:
# `server._split_greeting_bubble` в 55% случаев ставит перенос, потому что живые операторы
# ровно так и пишут — приветствие отдельным сообщением, остальное вторым. Доля замерена, выбор
# стабилен по хэшу.
#
# Оставляю запись вместо молчаливого удаления: ложная тревога стоит столько же, сколько
# пропуск. Проверка, помечающая правильное красным, заставляет чинить исправное — и в
# следующий раз её захотят написать снова.


def asks_for_city(rows):
    """Бот спрашивает город — прямой запрет («он известен из объявления»).

    Живой мастер видит объявление, на которое ему написали. Спросив город, бот
    сообщает клиенту обратное — и это одна из самых заметных выдач машины.
    Прячется она чаще всего не в отдельной фразе, а внутри просьбы об адресе:
    «Адрес подскажите (город, улица, дом, квартира, подъезд)?».
    """
    беда = []
    for r in rows:
        ответ = r.get("bot") or ""
        if _СПРАШИВАЕТ_ГОРОД.search(ответ):
            беда.append(ответ)
    return беда


ПРОВЕРКИ = [
    ("клиент спросил время — ответа нет", ignored_time_question),
    ("открытый вопрос без окна", open_time_question),
    ("один вопрос дважды в сообщении", repeated_question),
    ("флип-флоп дня", time_flipflop),
    ("спрашивает город", asks_for_city),
]


# ------------------------------------------------------------------ счёт


def score(dialogs):
    """{имя проверки: [(id сценария, находка), ...]} по всем диалогам."""
    итог = {имя: [] for имя, _ in ПРОВЕРКИ}
    for d in dialogs:
        for имя, чек in ПРОВЕРКИ:
            for находка in чек(d.get("rows") or []):
                итог[имя].append((d.get("id") or "?", находка))
    return итог


def main(path=None):
    # ⚠ stdout перехватываем ЗДЕСЬ, а не при импорте. Модуль импортируется из
    # `test_dialog_quality.py`, и перехват на уровне модуля закрывал чужую обёртку:
    # тест падал на первой же строке вывода с «I/O operation on closed file».
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    path = path or os.path.join(HERE, "test_context_liveness.jsonl")
    if not os.path.exists(path):
        print("Нет файла с диалогами: %s" % path)
        print("Сначала прогон: python3 analysis/test_context_liveness.py")
        return 2
    dialogs = [json.loads(s) for s in open(path, encoding="utf-8") if s.strip()]
    итог = score(dialogs)
    print("=== ДЕФЕКТЫ ДИАЛОГА: %d сценариев, %s ===\n" % (len(dialogs), os.path.basename(path)))
    всего = 0
    for имя, _ in ПРОВЕРКИ:
        находки = итог[имя]
        всего += len(находки)
        задето = len({s for s, _ in находки})
        отметка = "✓" if not находки else "⚠"
        print("%s %-34s %d шт. в %d/%d сценариях" % (отметка, имя, len(находки), задето, len(dialogs)))
        for sc, что in находки:
            текст = что if isinstance(что, str) else " → ".join(str(x) for x in что)
            print("      [%s] %s" % (sc, текст.replace("\n", " ⏎ ")[:120]))
    print("\n" + "=" * 55)
    print("ИТОГО дефектов: %d" % всего)
    return 0 if всего == 0 else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else None))
