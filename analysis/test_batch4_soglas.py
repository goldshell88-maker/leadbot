# -*- coding: utf-8 -*-
"""ПАЧКА 4, часть 2 — СОГЛАСОВАНИЕ БЕЗ СЛЕПЫХ ОБЕЩАНИЙ (Э4, 21.08).

ДВА ДЕФЕКТА в SOGLAS_POOL, найденные разбором слепых зон и подтверждённые
регламентом (prompt.py ━━━ 6. ЦЕНА, стр. 460-462):

  1. ДЕНЬГИ ВСЛЕПУЮ. Реплики пула обещали «Выезд по городу бесплатный» и
     «не возьмусь — с вас ничего». Регламент запрещает это прямым текстом:
     «НЕ говори "выезд бесплатный" вслепую — для КП выезд+диагностика 1000,
     для БТ/МНЧ бесплатный, а направление ещё неизвестно». Согласуемая тема —
     ровно тот случай, где направление НЕ определено (планшет и картридж это КП,
     сварка и москитка — МНЧ), и пул раздавал бесплатный выезд всем подряд.

  2. СВЯЗЫВАЕМОСТЬ АККАУНТОВ. Вариантов было три на восемь боевых каналов:
     один и тот же текст на разных аккаунтах связывает их между собой
     (требование несвязываемости от 17.08). Три варианта — это гарантированный
     дословный повтор.

Тексты собраны из живого корпуса (успешные-300 + свежий Jivo): «давайте заеду
гляну фронт работ», «надо по месту смотреть», «по фотографии не определю, только
по месту», «полный адрес пропишите и оставьте номер». Ничего не выдумано.

Запуск: uv run python analysis/test_batch4_soglas.py   (0 токенов)
"""
import io
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "brain"))
import prefilter  # noqa: E402

ok = bad = 0


def chk(label, cond):
    global ok, bad
    if cond:
        ok += 1
    else:
        bad += 1
        print("✗", label)


ПУЛ = prefilter.SOGLAS_POOL

# ── 1. никаких денег вслепую ────────────────────────────────────────────────
ДЕНЬГИ = re.compile(r"бесплатн|с вас ничего|не возьму денег|\d{3,}\s*(?:руб|₽|р\b)|"
                    r"выезд\w*\s+(?:по городу|платн)", re.IGNORECASE)
for i, т in enumerate(ПУЛ):
    chk("пул[%d]: без обещаний по деньгам вслепую" % i, not ДЕНЬГИ.search(т))

# ── 2. хватает вариантов на восемь боевых каналов ───────────────────────────
chk("вариантов ≥ 6 (несвязываемость 8 аккаунтов): %d" % len(ПУЛ), len(ПУЛ) >= 6)
chk("все варианты различны", len(set(ПУЛ)) == len(ПУЛ))

# ── 3. каждая реплика работает как реплика ──────────────────────────────────
ШАГ = ("подъед", "подъеду", "заеду", "приеду", "гляну", "посмотрю", "подъехать")
КОНТАКТ = ("номер", "телефон", "адрес", "куда")
for i, т in enumerate(ПУЛ):
    chk("пул[%d]: одна строка (приветствие добавляет сервер)" % i, "\n" not in т)
    chk("пул[%d]: без приветствия внутри" % i, "здравствуйте" not in т.lower())
    chk("пул[%d]: есть шаг вперёд (приезд/осмотр)" % i,
        any(w in т.lower() for w in ШАГ))
    chk("пул[%d]: просит контакт — это главный множитель заявки" % i,
        any(w in т.lower() for w in КОНТАКТ))
    chk("пул[%d]: держит честность согласования (не обещает взяться)" % i,
        any(w in т.lower() for w in ("не обещаю", "не скажу", "не определю",
                                     "не смогу сказать", "смотреть надо",
                                     "по месту", "на месте", "фронт работ")))
    chk("пул[%d]: живая длина (≤ 210 символов)" % i, len(т) <= 210)
    chk("пул[%d]: без канцелярита" % i,
        not re.search(r"кратчайш|оставьте заявку|наш специалист|уточните информацию|"
                      r"в ближайшее время с вами свяж", т, re.IGNORECASE))

# ── 4. раздача по чатам действительно разная ────────────────────────────────
розданные = {prefilter.soglas_reply("чат-%d" % i) for i in range(200)}
chk("на 200 чатов раздаются все варианты: %d из %d" % (len(розданные), len(ПУЛ)),
    len(розданные) == len(ПУЛ))
chk("один чат — один и тот же текст (стабильность)",
    prefilter.soglas_reply("чат-7") == prefilter.soglas_reply("чат-7"))

print("\nИТОГО: %d ок, %d провал" % (ok, bad))
sys.exit(1 if bad else 0)
