# -*- coding: utf-8 -*-
"""ТОЧНЫЕ МИНУТЫ ПРИЕЗДА — ОБЕЩАНИЕ, КОТОРОЕ ДЕРЖИТ НЕ БОТ (29.08, боевой диалог).

Первый же живой диалог после включения бота. Клиент (Оренбург, принтер) спросил
«А пораньше можно?», и бот ответил:

    «сегодня подъеду раньше, минут через 40-50, только адрес дайте»

Слова владельца: «Отвечать 40-50 минут нельзя. Условно в течение часа постараюсь быть
максимум». Разница не в вежливости: за 40 минут мастер не доедет через город, а клиент
запомнит именно названную цифру — и встретит опоздание как обман.

Регламент это и предписывает: в черте города «Буду у вас в течение часа, постараюсь
как можно раньше», у спутника — «в течение двух часов». Правило было записано в
промпте, но держалось на памяти модели, и она от него отступила. Тот же случай, что с
маркой техники: без гарда правило не работает.

⚠ ЧАСЫ ОСТАВЛЯЕМ. «Час-полтора» и «два-два с половиной» — это язык самого регламента,
и трогать их нельзя: без срока вообще ответ на «а пораньше можно?» превращается в уход
от вопроса.

Запуск: uv run python analysis/test_minuty_2908.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── БОЕВОЙ СЛУЧАЙ ────────────────────────────────────────────────")
_живой = "сегодня подъеду раньше, минут через 40-50, только адрес дайте"
_вышло = s._снять_минутное_обещание(_живой)
chk("«минут через 40-50» больше не звучит", "40-50" not in _вышло, _вышло)
chk("на его месте срок регламента", "в течение часа" in _вышло, _вышло)
chk("остальная реплика цела", "адрес дайте" in _вышло, _вышло)
# ⚠ «раньше» уже есть в реплике — второй раз не добавляем: «раньше… как можно раньше»
chk("«раньше» не удваивается", _вышло.lower().count("раньше") == 1, _вышло)

print("── ЛЮБЫЕ МИНУТЫ, НЕ ТОЛЬКО 40-50 ───────────────────────────────")
for т in ("подъеду через 30 минут", "буду за 20 минут", "через 40-50 минут буду",
          "минут через 15 подъеду", "буду через 90 мин"):
    r = s._снять_минутное_обещание(т)
    chk("«%s» → срок регламента" % т[:26],
        "мин" not in r.lower() and "в течение часа" in r, r)

print("── СРОК БЕЗ ПРЕДЛОГА ───────────────────────────────────────────")
# ⚠ ДЫРУ НАШЛА ДИВЕРСИЯ, А НЕ РАССУЖДЕНИЕ. Я убрал из шаблона ветку «голые N минут» —
# и тест остался зелёным: все его случаи ловились соседними ветками («через N», «за N»).
# А эта ветка одна держит формы без предлога, где срок звучит не менее твёрдо.
for т in ("подъеду, 20 минут и я у вас", "ехать 25 минут", "приеду 45 мин",
          "дорога 30 минут займёт"):
    r = s._снять_минутное_обещание(т)
    chk("«%s» → срок регламента" % т[:28], "мин" not in r.lower(), r)

print("── ЧАСЫ РЕГЛАМЕНТА НЕ ТРОГАЕМ ──────────────────────────────────")
for т in ("Через час-полтора подойдёт?", "Могу через два-два с половиной часа",
          "Буду у вас в течение часа, постараюсь как можно раньше",
          "Записать вас на завтра к 11:00?", "Завтра в 10:00-10:30 удобно?"):
    chk("«%s» не тронуто" % т[:34], s._снять_минутное_обещание(т) == т,
        s._снять_минутное_обещание(т))

print("── СПУТНИК: СРОК ВДВОЕ БОЛЬШЕ ──────────────────────────────────")
_сп = s._снять_минутное_обещание("подъеду минут через 40", спутник=True)
chk("у спутника «в течение двух часов»", "двух часов" in _сп, _сп)
chk("в черте города — часа", "в течение часа" in s._снять_минутное_обещание("подъеду минут через 40"))

print("── ХВОСТ СТАВИТСЯ В КОНЕЦ, А НЕ В СЕРЕДИНУ ─────────────────────")
# Первая редакция подставляла хвост внутрь: «в течение часа, постараюсь как можно
# раньше буду» — слова верные, порядок сломан.
_х = s._снять_минутное_обещание("через 40-50 минут буду")
chk("порядок слов не сломан", _х.rstrip(".").endswith("раньше"), _х)
chk("пустая реплика не роняет", s._снять_минутное_обещание("") == "")
chk("реплика без сроков не меняется",
    s._снять_минутное_обещание("Что случилось с принтером?") == "Что случилось с принтером?")

print("── ГАРД ЖИВОЙ, А НЕ ОБЪЯВЛЕННЫЙ ────────────────────────────────")
# ⚠ ГЛАВНЫЙ УРОК ЭТОЙ СЕССИИ: правило, которое никто не зовёт, не работает.
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
chk("вызывается из воронки ответа", "reply = _снять_минутное_обещание(reply" in _ИСХ)
chk("стоит после воронки, а не до неё",
    _ИСХ.find("_снять_минутное_обещание(reply") > _ИСХ.find("_ensure_question(_split_greeting_bubble"))
chk("спутник определяется, а не захардкожен", "_спутник" in _ИСХ)

print("=" * 50)
print("Минутные обещания (29.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
