# -*- coding: utf-8 -*-
"""ЦЕНА ХОДА: сколько стоит КАЖДЫЙ тип хода оператора, по 30 428 живым диалогам.

ЗАЧЕМ. Всё, что мы до сих пор умели, отвечало на вопрос «соблюдено ли правило».
Правила можно соблюсти все до одного и не получить ни одной заявки. Здесь считается
другое: какой ход к чему приводит. Ход раскладывается на признаки (назвал время,
спросил адрес, попросил номер, назвал цену, принял работу, задал уточнение), и по
корпусу смотрится, чем такие ходы кончались.

ИСХОД ДАЁТ КЛИЕНТ, А НЕ ОПЕРАТОР. Успех = клиент прислал телефон ПОСЛЕ этого хода.
Это единственное, чего оператор не может поставить себе сам. Ровно на этом я уже
обжёгся один раз: первая редакция `measure_addr_before_time.py` считала успехом
«телефон И названное окно», а окно входило и в определение хода — половина условия
выполнялась самим фактом попадания в клетку, и цифры врали в свою пользу.

⚠ ГЛАВНЫЙ КОНТРОЛЬ — СОСТОЯНИЕ ДО ХОДА. Ход «попросил номер» конвертирует прекрасно,
но не потому, что он сильный: его делают тогда, когда клиент уже согласился. Поэтому
считаем не «ход → исход», а «(состояние, ход) → исход»: сравниваются только ходы,
сделанные в ОДИНАКОВОЙ обстановке. Без этого таблица меряет не ход, а везение.

⚠ ДОВЕРИТЕЛЬНЫЙ ИНТЕРВАЛ ОБЯЗАТЕЛЕН. Клетка из шести диалогов с конверсией 50 %
выглядит как открытие и не значит ничего. Считаем интервал Вилсона и при сравнении
двух ходов требуем, чтобы интервалы не пересекались.

Запуск:
    uv run python analysis/move_value.py                 # таблица
    uv run python analysis/move_value.py --строить       # пересобрать analysis/BENCHMARK/цена_хода.json
Офлайн, 0 токенов.
"""
import io
import json
import math
import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter                                        # noqa: E402

КОРПУС = os.path.join(КОРЕНЬ, "analysis", "LEARNING", "corpus.jsonl")
АВИТО = os.path.join(КОРЕНЬ, "analysis", "LEARNING", "avito_corpus.jsonl")
ТАБЛИЦА = os.path.join(КОРЕНЬ, "analysis", "BENCHMARK", "цена_хода.json")
ТАБЛИЦА_АВИТО = os.path.join(КОРЕНЬ, "analysis", "BENCHMARK", "цена_хода_авито.json")

# ── признаки хода. Свои и простые: их считает и этот файл, и эталон, и смотрелка ──
ОКНО = re.compile(r"(?:могу|подъеду|приеду|буду|заеду|подъехать|выеду)[^.!?\n]{0,40}"
                  r"(?:через\s+час|час[аоу]?[-\s]*полтора|сегодня|завтра|"
                  r"\bк\s*\d{1,2}\b|\d{1,2}[:.]\d{2})", re.IGNORECASE)
СПРОС_ВРЕМЕНИ = re.compile(r"когда\s+(?:вам\s+|вас\s+)?(?:удобно|ждать|подъехать|можно)|"
                           r"во\s+сколько|в\s+какое\s+время", re.IGNORECASE)
АДРЕС = re.compile(r"куда\s+(?:\w+\s+){0,3}(?:ехать|подъехать|приехать)|"
                   r"адрес\w*\s*(?:подскаж|напиш|скаж|какой|ваш|нужен)|"
                   r"по\s+какому\s+адресу|где\s+вы\s+наход|территориальн", re.IGNORECASE)
НОМЕР = re.compile(r"номер\s+(?:телефона|ваш|оставь|подскаж|напиш)|телефон\s*(?:ваш|оставь|подскаж)|"
                   r"оставьте\s+номер|скиньте\s+номер|напишите\s+номер", re.IGNORECASE)
ЦЕНА = re.compile(r"\bот\s*\d{3,}|\d{3,}\s*(?:руб|р\b|₽)|бесплатн", re.IGNORECASE)
ПРИЁМ = re.compile(r"\b(?:да|конечно|сделаю|соберу|помогу|берусь|возьмусь|отремонтир|"
                   r"починю|подключ|повешу|установлю|справлюсь)\b", re.IGNORECASE)
ОТКАЗ = re.compile(r"не\s*(?:занимаюсь|беру|возьмусь|работаю|смогу|помогу|делаю)", re.IGNORECASE)
УТОЧНЕНИЕ = re.compile(r"\?")

ПРИЗНАКИ = ("окно", "спрос_времени", "адрес", "номер", "цена", "приём", "отказ", "уточнение")


def ход_класс(текст):
    t = текст or ""
    d = {"окно": bool(ОКНО.search(t)),
         "спрос_времени": bool(СПРОС_ВРЕМЕНИ.search(t)),
         "адрес": bool(АДРЕС.search(t)),
         "номер": bool(НОМЕР.search(t)),
         "цена": bool(ЦЕНА.search(t)),
         "приём": bool(ПРИЁМ.search(t)),
         "отказ": bool(ОТКАЗ.search(t)),
         "уточнение": bool(УТОЧНЕНИЕ.search(t))}
    # ⚠ ИМЯ КЛАССА — ТОЛЬКО ИЗ ЦЕЛЕВЫХ ДЕЙСТВИЙ. «Приём» и «уточнение» есть почти
    # везде; если их включить в имя, классов станет вчетверо больше, а в каждом —
    # горстка диалогов, и таблица развалится на шум.
    имя = "+".join(k for k in ("окно", "спрос_времени", "адрес", "номер", "цена", "отказ")
                   if d[k]) or "без шага"
    return имя, d


ВРЕМЯ_КЛИЕНТА = re.compile(r"\bсегодня\b|\bзавтра\b|\bсейчас\b|\bк\s*\d{1,2}\b|\d{1,2}[:.]\d{2}",
                           re.IGNORECASE)
ГОТОВ = re.compile(r"когда\s+(?:вы\s+)?(?:сможете|можете|подъедете|приедете)|записывайте|"
                   r"приезжайте|подъезжайте|жду\s+вас|давайте\s+приезжайте", re.IGNORECASE)
#: ⚠ «КЛИЕНТ СПРОСИЛ ЦЕНУ» — ОБЯЗАТЕЛЬНАЯ ЧАСТЬ ОБСТАНОВКИ, И ЭТО НЕ ПРИДИРКА.
#: Без неё класс «ответил ценой» выглядел хуже базы на обоих корпусах (8,4 % против
#: 11,7 % у Jivo, 19,8 % против 25,5 % у Авито) — и вывод «цену называть вредно» был
#: бы ложным: цену называют тем, кто про неё спросил, а такой клиент холоднее. Сравнивать
#: надо внутри одной обстановки: спросил про цену — ответили цифрой или ушли от неё.
#: ⚠ МЕЖДУ «СКОЛЬКО» И ГЛАГОЛОМ БЫВАЮТ СЛОВА. Живое «сколько ПРИМЕРНО будет стоить»
#: мимо прежнего шаблона проходило, и разбор объявлял ответ ценой «незваной цифрой» —
#: при том что клиент про цену и спросил. Допускаем до трёх слов между.
СПРОСИЛ_ЦЕНУ = re.compile(r"скольк\w*(?:\s+\w+){0,3}\s+(?:сто|будет|выйдет|возьм|обойд)|"
                          r"\bцен[аыуе]\b|стоимост|почём|почем\b|\bпрайс\b|по\s+деньгам|"
                          r"скольк\w*\s+(?:это\s+)?(?:стоит|сто[ий]т)",
                          re.IGNORECASE)


def состояние(речь_клиента, номер_хода, адрес_есть):
    """Обстановка ДО хода. Сравниваем только ходы, сделанные в одинаковых условиях."""
    горячий = bool(ГОТОВ.search(речь_клиента))
    время = bool(ВРЕМЯ_КЛИЕНТА.search(речь_клиента))
    цена = bool(СПРОСИЛ_ЦЕНУ.search(речь_клиента))
    ход = "1" if номер_хода == 1 else ("2" if номер_хода == 2 else "3+")
    return "ход%s/%s%s%s%s" % (ход,
                               "адрес" if адрес_есть else "-",
                               "/время" if время else "",
                               "/горячий" if горячий else "",
                               "/спросил_цену" if цена else "")


def вилсон(k, n, z=1.96):
    """Интервал Вилсона: на маленьких n он честнее нормального приближения."""
    if not n:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    ц = (p + z * z / (2 * n)) / d
    р = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, ц - р), min(1.0, ц + р))


def ходы_по_ролям(d):
    """Слитые ходы: подряд идущие реплики одной стороны — один ход.

    ⚠ ДВА ФОРМАТА НАРОЧНО. Корпус Jivo хранит реплики в `messages`, живой корпус
    Авито — в `реплики` (там же лежат подсказки бота отдельным полем, и в ходы
    оператора они не идут: иначе бот мерил бы сам себя своими же репликами).
    """
    out, буфер, роль = [], [], None
    for m in (d.get("messages") or d.get("реплики") or []):
        т = (m.get("text") or "").strip()
        if not т:
            continue
        р = "client" if (m.get("role") or "") == "client" else "operator"
        if роль is None or р == роль:
            буфер.append(т)
            роль = р
        else:
            out.append((роль, "\n".join(буфер)))
            буфер, роль = [т], р
    if буфер:
        out.append((роль, "\n".join(буфер)))
    return out


АДРЕС_В_РЕЧИ = re.compile(r"\b(?:ул|улиц|просп|проспект|пер|переул|шоссе|бульвар|мкр|"
                          r"микрорайон|д\.|дом)\b|[А-ЯЁ][а-яё]{3,}\s+\d{1,3}[а-я]?\b")


def построить(источник=None, куда=None):
    таблица = {}
    for line in io.open(источник or КОРПУС, encoding="utf-8"):
        try:
            d = json.loads(line)
        except Exception:
            continue
        ходы = ходы_по_ролям(d)
        речь, номер = "", 0
        for i, (роль, текст) in enumerate(ходы):
            if роль == "client":
                речь += "\n" + текст
                continue
            номер += 1
            # исход: телефон от КЛИЕНТА после этого хода
            дальше = " \n".join(t for r, t in ходы[i + 1:] if r == "client")
            успех = 1 if prefilter.phones_in(дальше) else 0
            имя, _ = ход_класс(текст)
            ключ = состояние(речь, номер, bool(АДРЕС_В_РЕЧИ.search(речь))) + " | " + имя
            k, n = таблица.get(ключ, (0, 0))
            таблица[ключ] = (k + успех, n + 1)
    путь = куда or ТАБЛИЦА
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    json.dump({k: list(v) for k, v in таблица.items()},
              io.open(путь, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    print("таблица собрана: %d клеток → %s" % (len(таблица), путь))
    return таблица


def загрузить(авито=False):
    путь = ТАБЛИЦА_АВИТО if авито else ТАБЛИЦА
    if not os.path.exists(путь):
        return построить(АВИТО if авито else КОРПУС, путь)
    return {k: tuple(v) for k, v in json.load(io.open(путь, encoding="utf-8")).items()}


def цена(состояние_ключ, имя_класса, таблица=None, минимум=25):
    """Историческая конверсия этого хода в этой обстановке. None — данных мало."""
    т = таблица if таблица is not None else загрузить()
    k, n = т.get(состояние_ключ + " | " + имя_класса, (0, 0))
    if n < минимум:
        return None
    return k / n, n, вилсон(k, n)


def главное():
    авито = "--авито" in sys.argv
    if "--строить" in sys.argv:
        таблица = построить(АВИТО if авито else КОРПУС,
                            ТАБЛИЦА_АВИТО if авито else ТАБЛИЦА)
    else:
        таблица = загрузить(авито)
    print("ИСТОЧНИК: %s" % ("живой корпус Авито" if авито else "корпус Jivo"))
    # печатаем по обстановкам: внутри одной обстановки ходы сравнимы между собой
    по_состоянию = {}
    for ключ, (k, n) in таблица.items():
        с, х = ключ.split(" | ", 1)
        по_состоянию.setdefault(с, []).append((х, k, n))
    порядок = sorted(по_состоянию.items(), key=lambda kv: -sum(n for _, _, n in kv[1]))
    for с, клетки in порядок[:8]:
        всего = sum(n for _, _, n in клетки)
        база_k = sum(k for _, k, _ in клетки)
        print("\n%s   (ходов %d, база %.1f %%)" % (с, всего, 100.0 * база_k / всего))
        клетки = [x for x in клетки if x[2] >= 25]
        for х, k, n in sorted(клетки, key=lambda x: -x[1] / x[2])[:9]:
            низ, верх = вилсон(k, n)
            print("   %-34s %5d ходов   %5.1f %%   [%.1f–%.1f]"
                  % (х, n, 100.0 * k / n, 100 * низ, 100 * верх))
    return 0


if __name__ == "__main__":
    sys.exit(главное())
