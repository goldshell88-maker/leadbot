# -*- coding: utf-8 -*-
"""МАРКА И МОДЕЛЬ — ВОПРОС ОБЯЗАН ПРОЗВУЧАТЬ ПО ВСЕЙ ТЕХНИКЕ ИЗ РЕГЛАМЕНТА (29.08).

Регламент КЦ дословно: «При приеме заявок на ремонт и обслуживание холодильников,
морозилок, стиральных машин, сушильных машин, посудомоечных машин, кондиционеров,
сплит-систем, духовок, духовых шкафов, электроплит и телевизоров необходимо ОБЯЗАТЕЛЬНО
уточнять модель и производителя данной техники… главное, чтобы этот вопрос ЗВУЧАЛ
в диалоге с клиентом».

ЧТО БЫЛО. Гард, дописывающий вопрос, стоял только на телевизоре: из одиннадцати видов
техники покрывался один. Остальные держались на том, что модель вспомнит правило сама.

⚠ ЧЕСТНО О ГРАНИЦЕ ЗАМЕРА. Проверить это по боевому журналу не вышло: в `shadow.jsonl`
1460 ходов, но РАЗНЫХ реплик клиента там четыре — это тестовый прогон, а не живой
трафик. Вывод «в бою бот марку не спрашивает» по таким данным делать нельзя, и я его
не делаю. Здесь проверяется код: что предмет распознан и вопрос дописан.

Запуск: uv run python analysis/test_marka_2908.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── ВСЕ ОДИННАДЦАТЬ ВИДОВ ИЗ РЕГЛАМЕНТА ──────────────────────────")
for т in ("холодильник не морозит", "морозильная камера потекла",
          "стиральная машина не сливает", "стиралка прыгает при отжиме",
          "сушильная машина шумит", "посудомойка не включается",
          "кондиционер не холодит", "сплит система течёт",
          "духовка не греет", "духовой шкаф сломался",
          "электроплита не работает", "телевизор не включается"):
    chk("«%s» → марку спрашиваем" % т[:34], bool(s._МОДЕЛЬ_НУЖНА_RX.search(т)))

print("── ЧУЖОЕ НЕ ЗАДЕВАЕМ ────────────────────────────────────────────")
# ⚠ У этой техники и работ регламент марку не требует — лишний вопрос удлиняет приём
for т in ("розетку поменять", "кран течёт", "собрать шкаф", "повесить полку",
          "прочистить засор", "поклеить обои", "вскрыть замок"):
    chk("«%s» → не спрашиваем" % т[:30], not s._МОДЕЛЬ_НУЖНА_RX.search(т))
# ТВ-приставка это не телевизор: у неё свой раздел регламента
chk("тв-приставка не считается телевизором",
    not s._МОДЕЛЬ_НУЖНА_RX.search("тв приставка не показывает"))

print("── ВОПРОС ЗВУЧИТ ПО ПРЕДМЕТУ ────────────────────────────────────")
chk("для телевизора свой пул", any("телевизор" in ф.lower() for ф in s._ВОПРОС_МОДЕЛЬ_ТВ))
# ⚠ «Модель телевизора подскажете?» у холодильника выдаёт шаблон с головой
chk("для остальной техники предмет не называем",
    not any("телевизор" in ф.lower() for ф in s._ВОПРОС_МОДЕЛЬ_ТЕХНИКИ),
    s._ВОПРОС_МОДЕЛЬ_ТЕХНИКИ)
chk("пул не из одной фразы", len(s._ВОПРОС_МОДЕЛЬ_ТЕХНИКИ) >= 3)
chk("во всех фразах спрашивается именно модель или марка",
    all(("модел" in ф.lower() or "марк" in ф.lower()) for ф in s._ВОПРОС_МОДЕЛЬ_ТЕХНИКИ))

print("── КОГДА НЕ СПРАШИВАЕМ ──────────────────────────────────────────")
# модель уже названа — второй раз не спрашиваем
chk("код модели в речи закрывает вопрос", s._модель_названа("холодильник Atlant XM-4021"))
chk("одна марка вопрос НЕ закрывает", not s._модель_названа("холодильник атлант"))
chk("цена и диагональ за модель не сходят",
    not s._модель_названа("стиралка за 1500руб") and not s._модель_названа("телевизор 43дюйма"))

print("── ГАРД ПРИВЯЗАН К РЕГЛАМЕНТУ, А НЕ К ОДНОМУ ТЕЛЕВИЗОРУ ─────────")
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
chk("в гарде стоит расширенный предмет",
    "_МОДЕЛЬ_НУЖНА_RX.search(client_all)" in _ИСХ)
chk("узкий тв-предмет в гарде больше не решает",
    "_ТВ_ПРЕДМЕТ_RX.search(client_all)\n            and not _модель_названа" not in _ИСХ)
chk("пул выбирается по предмету", "_ВОПРОС_МОДЕЛЬ_ТЕХНИКИ)" in _ИСХ)

print("── НОМЕР ВАЖНЕЕ МОДЕЛИ ──────────────────────────────────────────")
# ⚠ ДОПИСАННЫЙ ВОПРОС ЗАНИМАЕТ ЕДИНСТВЕННОЕ МЕСТО ЗА ХОД. На первом ходу без телефона
# вопрос про модель отбирал место у просьбы номера — без номера заявки нет вовсе,
# а без модели она есть: регламент сам пишет «если клиент не смог дать ответ, ничего
# страшного нет». Поймал тест правила трёх сообщений, а не рассуждение.
chk("на первом ходу без номера модель не спрашиваем",
    "and (hp or _bot_cnt != 1)" in _ИСХ)
chk("условие стоит В ГАРДЕ модели, а не где-то рядом",
    "_МОДЕЛЬ_НУЖНА_RX.search(client_all)\n            and (hp or _bot_cnt != 1)" in _ИСХ)

print("── КАРТА ДОСТУПНА ИЗ ВОРОНКИ ────────────────────────────────────")
# ⚠ ЭТО НЕ ПРИДИРКА К СТИЛЮ. geocode импортировался ЛОКАЛЬНО внутри одной функции,
# и обращения к нему из воронки падали с «name 'geocode' is not defined» — молча,
# в лог: уточнение строения и ориентир не работали ни разу. Проверки звали функции
# напрямую и этого не видели.
chk("geocode импортирован на уровне модуля",
    "\nimport geocode" in _ИСХ, "")
import server as _s2                                    # noqa: E402
chk("и реально доступен как s.geocode",
    hasattr(_s2, "geocode") and hasattr(_s2.geocode, "ориентир"))

print("── ЭТАЖ В ФОРМУЛЕ АДРЕСА ────────────────────────────────────────")
# Регламент: «полный адрес — улица, дом, квартира, подъезд, ЭТАЖ, наличие домофона»
_ПР = io.open(os.path.join(КОРЕНЬ, "brain", "prompt.py"), encoding="utf-8").read()
_формулы = [л for л in _ПР.split("\n") if "подъезд," in л and "домофон" in л and "«" in л]
chk("формулы адреса найдены", len(_формулы) >= 2, _формулы)
chk("этаж есть в КАЖДОЙ формуле адреса",
    all("этаж" in ф for ф in _формулы), [ф[:70] for ф in _формулы if "этаж" not in ф])

print("=" * 50)
print("Марка и модель (29.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
