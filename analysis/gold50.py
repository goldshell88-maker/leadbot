def cross_check(rows):
    """Сквозные правила, обязательные для ЛЮБОГО диалога."""
    bad = []
    greets = sum(1 for r in rows if re.match(r"\s*(здравствуйте|добрый|доброе|привет)",
                                             (r["bot"] or "").lower()))
    if greets > 1:
        bad.append("здоровается %d раз" % greets)
    seen = ""
    for i, r in enumerate(rows, 1):
        seen += " " + r["client"]
        bot = (r["bot"] or "")
        if not bot.strip():
            continue
        low = bot.lower()
        if re.search(LOGIST, low) and not prefilter.problem_stated(seen):
            bad.append("ход %d: зовёт на выезд до названной поломки" % i)
        held = held_topic(r["client"], seen)
        if re.search(CANNED, low) and not held:
            bad.append("ход %d: заготовка сверки не по теме" % i)
        if re.match(r"^(понял|поняла|понимаю),\s*\w+\s+(не |при )", low):
            bad.append("ход %d: эхо проблемы клиента" % i)
        # ⚠ противоречие — это когда время названо в ОДНОМ предложении, а спрошено в ДРУГОМ.
        # «Когда вам удобно, завтра к 10:00-10:30?» — одна фраза с конкретным слотом, это норма.
        _sents = [x for x in re.split(r"(?<=[.!?…])\s+|\n+", low) if x.strip()]
        if any(_TIME_SAID.search(a) for a in _sents) and \
                any(_TIME_ASK.search(b) and not _TIME_SAID.search(b) for b in _sents):
            bad.append("ход %d: назвал время и тут же спрашивает время" % i)
        if len(_ADVICE.findall(low)) > 1 and low.count("можно сделать хуже") > 1:
            bad.append("ход %d: совет «не трогайте» продублирован" % i)
        if i == 1 and re.search(LOGIST, low):
            bad.append("ход 1: адрес/время в первом же ответе (плейбук запрещает)")
        charity = re.search(CHARITY, (r["client"] + " " +
                                      (rows[i - 2]["client"] if i > 1 else "")).lower())
        # обещание выезда словами («приеду прямо сейчас», «буду в течение часа») закрывает ход
        _committed = re.search(r"в течение (?:часа|получас)|через час|час-полтора|"
                               r"(?:приеду|буду|выеду) (?:прямо )?сейчас", low)
        if "?" not in bot and not charity and not held and not _committed \
                and not re.search(BOOKED + r"|" + BYE + r"|" + ASKING, low):
            bad.append("ход %d: ни вопроса, ни финала" % i)
    return bad


def outcome_ok(kind, rows):
    """Дошёл ли диалог туда, куда должен был по регламенту."""
    last = (rows[-1]["bot"] or "").lower()
    handoff = any(r["handoff"] for r in rows)
    if kind == "запись":
        return bool(re.search(CLOSING, last))
    if kind == "сверка":
        return bool(re.search(HOLD, last)) and handoff
    if kind == "закрытие":
        return bool(re.search(BYE + r"|" + HOLD, last))
    if kind == "оператор":
        return handoff
    if kind == "продолжение":
        # ступень 1 лестницы: откликнулся и спросил про поломку, человека не звал
        return bool(re.search(r"случил|сломал|техник|помочь|ремонт|посмотрет", last)) \
            and not re.search(CANNED, last)
    return False


def main():
    limit = int(sys.argv[1]) if len(sys.argv) > 1 else len(SCEN)
    results, ok_out, ok_cross = [], 0, 0
    t0 = time.time()
    for n, (sid, group, city, direction, turns, kind) in enumerate(SCEN[:limit], 1):
        kn = {"visitor": "Клиент", "city": city, "direction": direction}
        hist, rows = [], []
        for text in turns:
            hist.append({"role": "client", "text": text})
            r = ask(hist, kn)
            reply = (r.get("reply") or "").strip()
            rows.append({"client": text, "bot": reply, "handoff": bool(r.get("handoff"))})
            hist.append({"role": "bot", "text": reply or "(молчание)"})
        cross = cross_check(rows)
        good = outcome_ok(kind, rows)
        ok_out += int(good)
        ok_cross += int(not cross)
        results.append({"id": sid, "group": group, "city": city, "direction": direction,
                        "kind": kind, "rows": rows, "cross": cross, "outcome_ok": good})
        print("%s %2d/%d [%s] %s — исход «%s»%s"
              % ("✓" if (good and not cross) else "✗", n, min(limit, len(SCEN)), group, sid,
                 kind, "" if not cross else "  ⚠ " + "; ".join(cross)))
        sys.stdout.flush()

    out = os.path.join(HERE, "_gold50.jsonl")
    with open(out, "w", encoding="utf-8") as f:
        for row in results:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    turns = sum(len(r["rows"]) for r in results)
    print("\n" + "=" * 62)
    print("ЭТАЛОН-50: диалогов %d, ходов %d, за %.0f мин" % (len(results), turns,
                                                            (time.time() - t0) / 60))
    print("  исход по регламенту: %d/%d" % (ok_out, len(results)))
    print("  сквозные правила:    %d/%d" % (ok_cross, len(results)))
    print("  безупречных:         %d/%d"
          % (sum(1 for r in results if r["outcome_ok"] and not r["cross"]), len(results)))


if __name__ == "__main__":
    main()
