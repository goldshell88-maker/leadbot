def ask(hist, kn):
    for att in range(6):
        try:
            return server.run_relay(hist, known=kn)
        except Exception as ex:
            if any(s in str(ex) for s in ("529", "429")) or "overload" in str(ex).lower():
                time.sleep(12 * (att + 1))
                continue
            raise
    raise RuntimeError("API перегружен")


def held_topic(text, seen=""):
    """Тема, которую регламент УДЕРЖИВАЕТ и передаёт человеку: согласование, отказные
    позиции («не отказываем никому» → та же отписка), мусор, адрес за чертой города.
    Для них ответ без вопроса и с формулой сверки — штатное поведение, а не брак."""
    try:
        if prefilter.check_soglasovanie(text) or prefilter.check_refuse(text) \
                or prefilter.check_junk(text, prior_client_content=False) \
                or prefilter.soglas_topic(seen or text):
            return True
        import territory
        return bool(territory.settlement_outside(text, ""))
    except Exception:
        return False


