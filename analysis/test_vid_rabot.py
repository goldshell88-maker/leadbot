"""«ВИД РАБОТ» И «ВИД УСЛУГ» В КАРТОЧКЕ ЗАЯВКИ: подбор по границе слова, а не подстрокой.

Задача владельца 26.08: «доведи автозаявки до идеала, чтобы исходя из заявки ставился
правильно вид услуг, вид работ и т.д.».

ЧТО БЫЛО НЕ ТАК. Вся цепочка подбора работала ПОДСТРОКОЙ, на четырёх участках подряд:
    бот  → objects_in()   ищет примету в речи клиента
    бот  → topics_in()    ищет позицию прайса в речи клиента
    CRM  → pick_option()  ищет тему в подписи опции справочника (сервер)
    CRM  → pickOption()   то же самое в расширении Chrome

Замер на 9742 живых первых сообщениях: 7027 попаданий приметы ВНУТРЬ чужого слова.
Два массовых и оба портили карточку:
    «тв»   — 6369 раз, из них 5548 внутри слова «здравствуйте» (здравс-ТВ-уйте);
    «кран» — 608 раз внутри «экран»: телевизор с битым экраном уезжал в САНТЕХНИКУ.
После правки тема «тв» встречается в 225 сообщениях вместо 5076.

Деньги это тоже задевало: «посудомойку почините» ловилось позицией прайса «раковина»
(в ней альтернатива «мойк», а «посудо-МОЙК-у» её содержит) — посудомоечная машина
ценилась как раковина, 3000 ₽.

Запуск: uv run python analysis/test_vid_rabot.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import crm                                              # noqa: E402
import price_book as pb                                 # noqa: E402
import server as s                                      # noqa: E402

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:90]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


def тема(текст):
    """То, что уезжает в lead['topics'] — ровно как в server._maybe_autocreate."""
    return pb.with_categories(pb.topics_in(текст) or pb.objects_in(текст))


print("1. примета ищется с начала слова, а не где попало")
для = [("Здравствуйте, подскажите пожалуйста", "тв", False, "здравс-ТВ-уйте"),
       ("Здравствуйте, разбит экран телевизора", "кран", False, "э-КРАН"),
       ("посудомойку почините?", "мойк", False, "посудо-МОЙК-у"),
       ("нужно положить плитку", "плит", False, "ПЛИТк-а это отделка"),
       ("столько стоит?", "стол", False, "СТОЛь-ко"),
       ("прикроватную тумбу собрать", "кроват", False, "при-КРОВАТ-ную"),
       ("течёт кран на кухне", "кран", True, "настоящий кран"),
       ("телевизор не показывает", "телевизор", True, "настоящий телевизор"),
       ("стиральная машина не отжимает", "стиральн", True, "склонение — норма")]
for текст, примета, ждём, почему in для:
    есть = примета in pb.objects_in(текст)
    проверь("«%s» → примета «%s» %s (%s)"
            % (текст[:34], примета, "есть" if ждём else "НЕ ловится", почему),
            есть is ждём, pb.objects_in(текст))

print("2. позиция прайса — тоже с начала слова (это про деньги)")
проверь("«посудомойку почините» больше не «раковина»",
        "раковина" not in pb.topics_in("посудомойку почините"), pb.topics_in("посудомойку почините"))
проверь("а настоящая мойка — по-прежнему «раковина»",
        "раковина" in pb.topics_in("мойку установить"), pb.topics_in("мойку установить"))
проверь("«смесителя» (склонение) ловится",
        "смеситель" in pb.topics_in("поменять смесителя"))

print("3. сбор за выезд — не вид работ")
проверь("«выезд и диагностика» в темы для CRM не уходит",
        "выезд и диагностика" not in тема("сколько стоит выезд и диагностика? ванна течёт"),
        тема("сколько стоит выезд и диагностика? ванна течёт"))
проверь("а предмет при этом остался",
        "ванна" in тема("сколько стоит выезд и диагностика? ванна течёт"))
проверь("в прайсе позиция осталась (цену считать надо)",
        "выезд и диагностика" in pb.topics_in("сколько стоит выезд и диагностика"))

print("4. роутер — самый частый предмет, которого не было в словаре")
# Замер: в 3220 диалогах без единой темы «роутер» встретился 701 раз.
for текст in ("настроить роутер", "не ловит вай-фай", "подключить wifi", "модем не работает"):
    проверь("«%s» → тема есть" % текст, bool(тема(текст)), тема(текст))
проверь("«в интернете нашла вас» темой не становится", not тема("в интернете нашла вас"))

print("5. подбор опции справочника — по границе слова (сервер)")
ОПЦИИ = [("1", "Замена экрана", False), ("2", "Сантехника", False),
         ("3", "Стиральные машины", False), ("4", "Прочая", False)]
проверь("тема «кран» не выбирает «Замена экрана»", crm.pick_option(ОПЦИИ, "кран") == "")
проверь("тема «стиральн» выбирает «Стиральные машины»",
        crm.pick_option(ОПЦИИ, "стиральн") == "3")
проверь("тема «сантехник» выбирает «Сантехника»", crm.pick_option(ОПЦИИ, "сантехник") == "2")
проверь("порядок тем уважается: первая подходящая и выигрывает",
        crm.pick_option(ОПЦИИ, "стиральн", "сантехник") == "3")

