# -*- coding: utf-8 -*-
"""ПЕРВАЯ ПОЛНОСТЬЮ АВТОМАТИЧЕСКАЯ ЗАЯВКА — ЧЕТЫРЕ ДЕФЕКТА (29.08, №1234567, Казань).

Заявку бот собрал и отправил сам, без человека. В карточке нашлись четыре разных изъяна,
и каждый — свой класс ошибки, а не одна причина в четырёх видах:

1. БОТ ПЕРЕСПРОСИЛ НОМЕР, который клиент уже дал. В теневом журнале `не_хватает: ['phone']`
   при заполненном телефоне в самой заявке. Оказалось, состояние на МОДЕЛЬНОМ пути
   собиралось целиком из JSON модели, а на кэш-ветке — регексом. Модель поле забыла,
   гарды не было. Теперь пустое поле добирается `_добрать_поля`.

2. ЭТАЖ И ДОМОФОН ПОТЕРЯНЫ. Клиент назвал адрес двумя ходами: «Садовая 9.кв.124.2 подъезд»,
   потом «11 этаж.домофон 124». `_адрес_в_переписке` возвращала ПОСЛЕДНИЙ адресный ход —
   вместе с этажом уезжала и улица. Теперь хвост приклеивается к ходу с улицей.

3. КОММЕНТАРИЙ БЫЛ СВАЛКОЙ РЕПЛИК. Поле `problem_line` описано в схеме и модель его
   возвращала, но в `state` не переносилось — и запасная выжимка работала не «на роутерных
   путях», как обещал комментарий кода, а ВСЕГДА. В карточку уезжало «Да, хочу. Подходит.
   Сколько будет стоить услуга?».

4. ПОРЯДОК СТРОК И ЦЕНА. Владелец дал эталон: маркер заявки первой строкой, ссылка
   последней, цена без разговорной оговорки «точнее скажу, когда посмотрю».

Запуск: uv run python analysis/test_zayavka2_2908.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── 1. ТЕЛЕФОН, КОТОРЫЙ МОДЕЛЬ ЗАБЫЛА ───────────────────────────")
_реплики = [{"role": "client", "text": "Здравствуйте, телевизор не включается"},
            {"role": "bot", "text": "Подскажите номер для связи?"},
            {"role": "client", "text": "+7 900 111-22-41"}]
_ст = s._добрать_поля({"city": "", "phone": "", "address": "", "service": "",
                       "preferred_time": "", "problem_line": ""}, _реплики)
chk("телефон добран из переписки", "9001112241" in (_ст.get("phone") or ""),
    repr(_ст.get("phone")))
chk("«не хватает» больше не просит телефон", "phone" not in s._missing(_ст),
    str(s._missing(_ст)))

_свой = s._добрать_поля({"phone": "9990001122"}, _реплики)
chk("непустое поле модели не перетирается", _свой.get("phone") == "9990001122",
    repr(_свой.get("phone")))

print("── 2. АДРЕС ДВУМЯ ХОДАМИ ────────────────────────────────────────")
_адр = [{"role": "client", "text": "Садовая 9.кв.124.2 подъезд"},
        {"role": "bot", "text": "договорились. Этаж и домофон подскажите?"},
        {"role": "client", "text": "11 этаж.домофон 124"}]
_строка = s._адрес_в_переписке(_адр)
_р = s._parse_addr(_строка, "Казань")
chk("улица уцелела", (_р.get("street") or "").endswith("Садовая"), repr(_р.get("street")))
chk("дом уцелел", _р.get("building") == "9", repr(_р.get("building")))
chk("квартира уцелела", _р.get("office") == "124", repr(_р.get("office")))
chk("подъезд уцелел", _р.get("entrance") == "2", repr(_р.get("entrance")))
chk("этаж собран", _р.get("floor") == "11", repr(_р.get("floor")))
chk("домофон собран", _р.get("intercom") == "124", repr(_р.get("intercom")))

# один ход с полным адресом не должен обрастать ничем лишним
_один = s._адрес_в_переписке([{"role": "client", "text": "Ленина 12 кв 5"}])
chk("полный адрес одним ходом не склеивается", _один == "Ленина 12 кв 5", repr(_один))

print("── 3. problem_line ДОЕЗЖАЕТ ДО КАРТОЧКИ ─────────────────────────")
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
chk("поле в списке переносимых из ответа модели",
    '"preferred_time", "problem_line"' in _ИСХ)
chk("карточка по-прежнему предпочитает формулировку модели",
    'state.get("problem_line") or "").strip() or _суть_проблемы' in _ИСХ)

print("── 4. ЦЕНА И ПОРЯДОК СТРОК ──────────────────────────────────────")
chk("оговорка отрезана",
    s._цена_в_карточку("услуга от 1000 рублей, точнее скажу, когда посмотрю")
    == "от 1000 рублей",
    repr(s._цена_в_карточку("услуга от 1000 рублей, точнее скажу, когда посмотрю")))
chk("две части цены не режутся",
    s._цена_в_карточку("выезд и диагностика бесплатно, ремонт от 1500 рублей")
    == "выезд и диагностика бесплатно, ремонт от 1500 рублей")
chk("чистая цена не портится", s._цена_в_карточку("от 2000 рублей") == "от 2000 рублей")
chk("пустое остаётся пустым", s._цена_в_карточку("") == "")

_шапка, _ссылка = (s._white_lines("https://clck.ru/3Ustqt") + ["", ""])[:2]
chk("маркер белой заявки — первой строкой", _шапка == "🔴БЕЛАЯ ЗАЯВКА🔴", repr(_шапка))
chk("ссылка — отдельной строкой", _ссылка.startswith("Ссылка: "), repr(_ссылка))
chk("сборка ставит шапку перед проблемой",
    "[_шапка] + ([первая] if первая else [])" in _ИСХ)
chk("ссылка идёт последней", "+ [_ссылка]) if x])" in _ИСХ)

print("── УРОК: ДВА ПУТИ СЧИТАЮТ ОДИНАКОВО ────────────────────────────")
# Класс ошибки, вскрытый разбором заявки 1234567: одно и то же поле на кэш-ветке и на
# модельном пути считалось по-разному, и расхождение жило до первой боевой жалобы.
_врем = s._добрать_поля({}, [{"role": "client", "text": "давайте завтра в 14:00"}])
chk("окно добирается из речи клиента", bool((_врем.get("preferred_time") or "").strip()),
    repr(_врем.get("preferred_time")))
chk("«не хватает» больше не просит время",
    "preferred_time" not in s._missing(dict(_врем, category="БТ", address="Ленина 1",
                                            phone="9990001122", service="ремонт")),
    str(s._missing(dict(_врем, category="БТ", address="Ленина 1",
                        phone="9990001122", service="ремонт"))))
_свое = s._добрать_поля({"preferred_time": "завтра к 11:00"},
                        [{"role": "client", "text": "давайте завтра в 14:00"}])
chk("окно от модели не перетирается", _свое.get("preferred_time") == "завтра к 11:00",
    repr(_свое.get("preferred_time")))
chk("кэш-ветка идёт тем же добором", "_st = _добрать_поля({" in
    io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read())

print("── ГАРДЫ ЖИВЫЕ ──────────────────────────────────────────────────")
chk("добор полей вызывается из воронки", "\"state\": _добрать_поля(" in _ИСХ)
chk("склейка адреса вызывается", "return _дособрать_адрес(ходы) or найдено" in _ИСХ)
chk("обрезка цены вызывается", "t = _цена_в_карточку(t)" in _ИСХ)

print("=" * 50)
print("Первая автозаявка (29.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
