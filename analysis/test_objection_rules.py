# -*- coding: utf-8 -*-
"""ЗНАЕТ ЛИ БОТ ПРАВИЛА ОТРАБОТКИ ВОЗРАЖЕНИЙ (раздел 10 плейбука).

Проверка по просьбе владельца 26.08. Раньше возражения проверялись только на МАРШРУТ —
«ушло ли к модели, а не в роутер» (`test_corpus_objections`). Здесь проверяется САМ
ОТВЕТ: соблюдает ли бот лестницу цены, держит ли выезд, не даёт ли скидок, не
произносит ли запрещённых оборотов.

⚠ ЖИВЫЕ ВЫЗОВЫ МОДЕЛИ. Возражение — это работа модели, а не роутера, и проверить её
кассетой нельзя: правило про ответ, а не про маршрут. Прогон стоит токенов.

⚠ ПРОВЕРЯЕМ ПРОВЕРЯЕМОЕ. «Отработал тепло» проверить нельзя, «назвал цифру / не назвал
скидку / задал закрывающий вопрос» — можно. Каждый пункт ниже — цитата из раздела 10.

Запуск: uv run python analysis/test_objection_rules.py
"""
import io
import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import server                                           # noqa: E402

ЦИФРА = re.compile(r"\b\d{3,6}\b")
ОТ_N = re.compile(r"\bот\s*\d{3,6}", re.IGNORECASE)
ВОПРОС = re.compile(r"\?")
СКИДКА = re.compile(r"скидк|дешевл|уступ|сброшу|пойду\s+навстречу|дешёвл", re.IGNORECASE)
ИЗВИНЕНИЕ = re.compile(r"извин|прошу\s+прощен|сожале", re.IGNORECASE)
ЗАПРЕЩЕНО = re.compile(
    r"недорого|несложн\w*|мелочн\w*|много\s+денег\s+не\s+возьму|"
    r"не\s+переживайте\s+за\s+цену|сориентирую\s+по\s+ценам\s+перед\s+работой|"
    r"может\s+дешевле", re.IGNORECASE)
АКТУАЛЬНО = re.compile(r"актуальн\w*\s*\?|вы\s+тут\s*\?|вы\s+здесь\s*\?", re.IGNORECASE)

ошибки = []
токенов = {"ходов": 0}


def проверь(имя, условие, чем=""):
    print(("  ✓ " if условие else "  ✗ ") + имя + (("\n        → " + str(чем)[:150]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


def диалог(реплики, известно=None, ждём_ход=-1):
    """Прогнать диалог и вернуть последнюю реплику бота."""
    известно = dict(известно or {"visitor": "", "city": "Москва",
                                 "direction": "кп", "title": "Ремонт компьютеров"})
    история, ответы = [], []
    for текст in реплики:
        история.append({"role": "client", "text": текст})
        r = server.run_relay([dict(x) for x in история], known=dict(известно))
        токенов["ходов"] += 1
        ответ = (r.get("reply_text") or "").strip()
        ответы.append(ответ)
        if ответ:
            история.append({"role": "operator", "text": ответ})
    return ответы


print("ЭТАП 1 — первый вопрос о цене уводит на осмотр, точной суммы нет")
о = диалог(["Здравствуйте, сколько стоит почистить ноутбук от пыли?"])
проверь("этап 1: есть ответ", bool(о[0]), о[0])
проверь("этап 1: нет точной суммы без «от»",
        not ЦИФРА.search(о[0]) or bool(ОТ_N.search(о[0])), о[0])

print("ЭТАП 2 — спросил ВТОРОЙ раз: дать «от N» и закрывающий вопрос В ТОЙ ЖЕ реплике")
о = диалог(["Здравствуйте, сколько стоит почистить ноутбук от пыли?",
            "Ну хотя бы порядок скажите, примерно сколько?"])
проверь("этап 2: названа вилка «от N»", bool(ОТ_N.search(о[-1])), о[-1])
проверь("этап 2: в той же реплике закрывающий вопрос", bool(ВОПРОС.search(о[-1])), о[-1])

print("«ДОРОГО» — защита рынком, без скидок и извинений")
о = диалог(["Сколько стоит установка Windows?",
            "От 2000? Дорого, таких цен нигде нет"])
проверь("дорого: скидку не предлагаем", not СКИДКА.search(о[-1]), о[-1])
проверь("дорого: не извиняемся", not ИЗВИНЕНИЕ.search(о[-1]), о[-1])
проверь("дорого: нет запрещённых оборотов", not ЗАПРЕЩЕНО.search(о[-1]), о[-1])

print("БЮДЖЕТ-ПОТОЛОК — цифру клиента не подтверждаем")
о = диалог(["Нужно почистить компьютер и поставить винду",
            "За 1000 сделаете? Больше не дам"])
_подтвердил = re.search(r"(?:да|хорошо|договорились|идёт|согласен)[^.!?\n]{0,20}1000", о[-1], re.I)
проверь("потолок: цифру клиента не подтверждаем как итог", not _подтвердил, о[-1])
проверь("потолок: есть оговорка или причина",
        bool(re.search(r"не\s+гарантир|не\s+обещаю|точнее|на\s+месте|объ[её]м|фронт",
                       о[-1], re.I)), о[-1])

print("ТОРГ ЗА ВЫЕЗД КП — держим 1000, не снижаем")
о = диалог(["Сколько стоит выезд и диагностика?",
            "Дам 500 за выезд и по рукам"])
проверь("выезд: не снижаем ниже 1000",
        not re.search(r"\b500\b", о[-1]) or "1000" in о[-1], о[-1])

print("«ПОДУМАЮ» — ровно ОДНА попытка удержать, без давления дважды")
о = диалог(["Сколько стоит замена термопасты?", "Спасибо, я подумаю", "Нет, всё же подумаю"])
проверь("подумаю: на второй раз не давим",
        not ВОПРОС.search(о[-1]) or "пишите" in о[-1].lower(), о[-1])

print("«ПОСОВЕТУЙТЕ, К КОМУ ОБРАТИТЬСЯ» — тему не развиваем")
о = диалог(["Ремонтируете телефоны?", "А посоветуйте, к кому обратиться?"])
проверь("рекомендацию не даём",
        not re.search(r"обратит\w*\s+в\b|рекоменду|посоветую\s+\w", о[-1], re.I), о[-1])

print("ПИНГ «АКТУАЛЬНО?» БЕЗ ЦИФРЫ на неотвеченный вопрос о цене — запрещён")
о = диалог(["Сколько будет стоить ремонт ноутбука?"])
проверь("на вопрос о цене не отвечаем «актуально?»",
        not (АКТУАЛЬНО.search(о[0]) and not ЦИФРА.search(о[0])), о[0])

print("КЛИЕНТ ПРИНЯЛ «от N» КАК ИТОГ — обязательна оговорка «не обещаю ровно N»")
о = диалог(["Сколько стоит установка Windows?",
            "Хотя бы примерно скажите",
            "2000 меня устраивает, сразу сделаете?"])
проверь("оговорка про «ровно N» есть",
        bool(re.search(r"не\s+обещаю|не\s+гарантир|может\s+(?:выйти|получит)|"
                       r"точн\w*\s+(?:скажу|назову|посчита)|на\s+месте", о[-1], re.I)), о[-1])

print("ТРЕБУЕТ ПОТОЛОК — новой цифры не называем, объясняем практикой")
о = диалог(["Сколько стоит сборка компьютера?",
            "А максимум сколько может выйти? Назовите потолок"])
_новых = [x for x in ЦИФРА.findall(о[-1]) if x not in ("2000", "3000", "1000", "500")]
проверь("потолок: новую цифру не выдумываем", not _новых, "%s ← %s" % (_новых, о[-1]))

print("«НЕ АКТУАЛЬНО / САМИ СДЕЛАЛИ» — тепло отпускаем, не дожимаем")
о = диалог(["Сколько стоит замена термопасты?", "Уже не актуально, сами сделали"])
проверь("не дожимаем вопросом", not ВОПРОС.search(о[-1]), о[-1])
проверь("дверь оставлена открытой",
        bool(re.search(r"пишите|обращайт|на\s+связи|если\s+что", о[-1], re.I)), о[-1])

print("НЕ РАССКАЗЫВАЕМ, КАК БУДЕМ ЧИНИТЬ")
о = диалог(["Ноутбук перегревается и выключается, что делать?"])
проверь("нет инструкции по ремонту",
        not re.search(r"нужно\s+(?:разобрать|снять|открутить|поменять\s+термо)|"
                      r"сначала\s+(?:разбир|снима)|вам\s+нужно\s+самому", о[0], re.I), о[0])

print("ФИКС-ЦЕНУ ПРИ «ДОРОГО» БЕСПЛАТНЫМ ВЫЕЗДОМ НЕ ДОЖИМАЕМ")
о = диалог(["Сколько стоит установка Windows?", "Хотя бы примерно", "Дорого"])
проверь("бесплатным выездом не дожимаем",
        not re.search(r"выезд\w*\s+(?:бесплатн|для\s+вас\s+бесплатн)", о[-1], re.I), о[-1])

print("ПРОВОКАЦИЯ — один деловой ответ, дальше человек")
о = диалог(["Вы вообще нормальные? Развели тут шарашкину контору"])
проверь("на провокацию не спорим",
        len(" ".join(о[0].split())) <= 160, о[0])

print("\nходов модели израсходовано: %d" % токенов["ходов"])
if ошибки:
    print("ПРОВАЛЕНО: %d из %d" % (len(ошибки), len(ошибки) + 0))
    for e in ошибки:
        print("  -", e)
    sys.exit(1)
print("Все проверки пройдены")
