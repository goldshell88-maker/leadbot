# -*- coding: utf-8 -*-
"""Границы слова: шаблон не должен совпадать ВНУТРИ более длинного слова.

За один день этот класс ошибок выстрелил четыре раза:
  «скол» внутри «СКОЛько»       — любой ценовой вопрос про подсветку уходил в отказ (23 диалога);
  «вы где» внутри «отЗЫВЫ ГДЕ»  — вопрос про отзывы получал мостик «гляну по графику»;
  «час» внутри «сейЧАС»         — «сейчас» считалось указанием времени в переносе;
  «кран» внутри «эКРАН»         — экран телевизора тянуло в направление МНЧ.
Плюс «утер» внутри «роУТЕР» и «сколько» внутри «неСКОЛЬКО».

Проверка общая, а не про эти шесть случаев: берём частотные слова живого корпуса и требуем,
чтобы ни один тематический шаблон не начинал совпадение в середине слова. Любой новый
шаблон с той же болезнью упадёт здесь, а не в бою.

Запуск: python3 analysis/test_boundaries.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "brain"))
import escalation as e                              # noqa: E402
import prefilter as p                               # noqa: E402

# Частотные слова живого корпуса Jivo (13 852 диалога). В списке намеренно нет тематических
# слов вроде «холодильник» — только те, внутри которых шаблон совпасть НЕ ДОЛЖЕН.
TRAPS = [
    "сколько", "несколько", "сколько-то", "поскольку", "сейчас", "экран", "экраном", "экране",
    "роутер", "роутера", "роутером", "отзывы", "отзыв", "соответственно", "другом", "другому",
    "здравствуйте", "пожалуйста", "спасибо", "подскажите", "получится", "работает", "стоимость",
    "квартира", "квартире", "телевизора", "стиральная", "посудомоечная", "микроволновка",
    "приставка", "картридж", "программа", "проверить", "договорились", "документы", "доставка",
    "материал", "аккуратно", "актуально", "перезвоните", "переустановить", "прокладка",
    "накладка", "закладная", "выключатель", "включается", "выключается", "покрасить",
    "украшение", "заказать", "показать", "сказать", "оказалось", "красиво", "интернет",
    "интересно", "стоять", "настроение", "принтер", "принтера", "напечатать", "температура",
    "теплый", "утеплить", "потерялся", "утюг", "мастера", "мастерская", "гарантия", "гараж",
]

# Совпадения внутри слова, которые ПРАВИЛЬНЫ по смыслу: приставка меняет форму, но не тему.
ALLOWED_INSIDE = {
    "отремонтировать", "переустановить", "почистить", "демонтаж", "перепаять", "перенастроить",
    "подключить", "переподключить", "перекрасить", "заменить", "поменять", "починить",
}

PATTERNS = []
for mod, mname in ((p, "prefilter"), (e, "escalation")):
    for name in dir(mod):
        v = getattr(mod, name)
        if isinstance(v, re.Pattern) and name.startswith("_"):
            PATTERNS.append(("%s.%s" % (mname, name), v))
for kind, rx, _reason in p._REFUSE:
    PATTERNS.append(("REFUSE:" + kind, rx))
for sub, rx in p._SOGLAS:
    PATTERNS.append(("SOGLAS:" + sub, rx))
for sub, rx, _pol in p._JUNK_RULES:
    PATTERNS.append(("JUNK:" + sub, rx))

# Односимвольные и служебные шаблоны проверять бессмысленно — они и должны ловить буквы
SKIP = {"prefilter._CYR_RX", "escalation._CYR_RX", "escalation._LAT_RX",
        "prefilter._WORD_RX", "prefilter._DIGIT_RX", "escalation._W"}

fails = []
checked = 0
for name, rx in PATTERNS:
    if name in SKIP:
        continue
    for w in TRAPS:
        if w in ALLOWED_INSIDE:
            continue
        checked += 1
        m = rx.search(w)
        if m and m.start() > 0:
            fails.append((name, w, m.group(0)))

# точечные проверки на четыре уже случившихся случая — читаются как история болезни
HISTORY = [
    ("подсветка при вопросе о цене",
     lambda: bool(p.check_refuse("Замена подсветки матрицы, сколько будет стоить?")), False),
    ("вопрос про отзывы — не статус",
     lambda: bool(p.check_existing_client("Отзывы где посмотреть можно?")), False),
    ("«сейчас» не считается временем переноса",
     lambda: bool(e._TIME_WORD_RX.search("сейчас")), False),
    ("«экран» не тянет в МНЧ",
     lambda: p.direction_of("Разбит экран телевизора") == "mnc", False),
    ("«роутер» не считается утерянными данными",
     lambda: bool(p._NO_CREDS_RX.search("настроить роутер")), False),
    ("«несколько» не денежный контекст",
     lambda: bool(p._MONEY_CTX_RX.search("приеду через несколько дней")), False),
    # и обратная сторона: настоящие смыслы ловиться обязаны
    ("«сколько стоит» — денежный контекст",
     lambda: bool(p._MONEY_CTX_RX.search("сколько стоит ремонт")), True),
    ("«течёт кран» — направление МНЧ",
     lambda: p.direction_of("Течёт кран на кухне") == "mnc", True),
    ("«через час» — указание времени",
     lambda: bool(e._TIME_WORD_RX.search("через час")), True),
    ("«пароль утерян» — данных нет",
     lambda: bool(p._NO_CREDS_RX.search("пароль утерян")), True),
]

hist_fails = []
for label, fn, want in HISTORY:
    got = fn()
    checked += 1
    if got != want:
        hist_fails.append((label, want, got))

# ── ПРОВЕРКА «ПОХОЖ ЛИ НА БОТА» (12.08) ─────────────────────────────────────
# Замер на живом мозге: пять «разных клиентов» с одинаковой репликой получали 2.6 разных
# ответа из пяти, худший повтор — 4 из 5. Человек, написавший на несколько наших объявлений,
# видит это первым. Здесь закреплено то, что чинилось детерминированно.
import server as srv                                   # noqa: E402

BOTNESS = [
    # предлог: «с шкафом» так по-русски не пишут
    ("предлог со шкафом", srv._humanize("да помогу с шкафом"), "да помогу со шкафом"),
    ("предлог со стиральной", srv._humanize("разберусь с стиральной"), "разберусь со стиральной"),
    ("предлог не трогаем", srv._humanize("приеду с инструментом"), "приеду с инструментом"),
]
for label, got, want in BOTNESS:
    checked += 1
    if got != want:
        hist_fails.append((label, want, got))

# зачин разводится ПО КЛИЕНТУ и не рвёт фразу с дополнением
_opens = {srv._vary_help_opening("Здравствуйте, да, помогу. Какая модель?", n)
          for n in ("Анна", "Сергей", "Ольга", "Дмитрий", "Марина")}
checked += 1
if len(_opens) < 3:
    hist_fails.append(("зачин разводится по клиенту", ">=3 варианта", len(_opens)))
checked += 1
if srv._vary_help_opening("Здравствуйте, да помогу со сборкой. Схема есть?", "Анна") != \
        "Здравствуйте, да помогу со сборкой. Схема есть?":
    hist_fails.append(("глагол с дополнением не рвём", "без изменений", "порвано"))
# легенда одиночки: во вариантах зачина нет «мы»
checked += 1
if any(v.endswith(("ем", "им")) for v in srv._HELP_OPEN_VARIANTS):
    hist_fails.append(("нет «мы» в зачинах", "только единственное число",
                       [v for v in srv._HELP_OPEN_VARIANTS if v.endswith(("ем", "им"))]))
# хвост воронки тоже разный у разных клиентов
_tails = {srv._ensure_question("да помогу", False, False, False,
                               problem_known=False, first_reply=True, seed=n)
          for n in ("Анна", "Сергей", "Ольга", "Дмитрий", "Марина")}
checked += 1
if len(_tails) < 3:
    hist_fails.append(("хвост воронки разводится по клиенту", ">=3 варианта", len(_tails)))

for name, w, span in fails:
    print("  ПРОВАЛ границы: %-42s совпал внутри «%s» куском %r" % (name[:42], w, span))
for label, want, got in hist_fails:
    print("  ПРОВАЛ истории: %-46s ждали=%s получили=%s" % (label, want, got))
print("=" * 62)
print("Границы слова: %d проверок, %d шаблонов, провалов %d"
      % (checked, len(PATTERNS) - len(SKIP), len(fails) + len(hist_fails)))
sys.exit(0 if not fails and not hist_fails else 1)
