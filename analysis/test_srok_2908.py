# -*- coding: utf-8 -*-
"""СРОК ПРИЕЗДА НАЗЫВАЕМ, ТОЛЬКО ЗНАЯ АДРЕС (29.08, боевой диалог, Воронеж).

Бот: «Здравствуйте, да, это ко мне. Подъеду через час-полтора, удобно вам будет? …
По какому адресу вы находитесь?» — то есть назвал срок и тут же спросил адрес.
Слова владельца: «Ориентирует по времени не зная адрес».

Он прав по сути: «час-полтора» — срок ЧЕРТЫ ГОРОДА. За чертой это два-два с половиной
часа или вовсе согласование с филиалом, а где клиент — бот в этот момент не знает.

⚠ НО ВРЕМЯ УБИРАТЬ НЕЛЬЗЯ. Замер 26.08 показал, что связка «время + адрес» одной
репликой сильнее обеих половин по отдельности. Поэтому меняем не наличие времени,
а его ФОРМУ.

ЗАМЕР ПО ЖИВОМУ КОРПУСУ (8426 диалогов, исход — телефон КЛИЕНТА, чтобы не мерить
наши же слова нашими словами):
    без срока, адрес не известен   1274 диалога, телефон дали 36,1 %   ← лучший исход
    со сроком, адрес не известен    217 диалогов,             30,9 %
    без срока, адрес известен       503 диалога,              27,0 %
    со сроком, адрес известен       311 диалогов,             27,0 %
Живые операторы называют время без срока в ШЕСТЬ раз чаще (1777 против 528) и доводят
до телефона на 5 п.п. лучше. Их формула — не назначить, а спросить: «вам когда удобно?»
(201 раз в корпусе), «когда удобно будет?» (40), «могу сегодня, во сколько удобно?».

Запуск: uv run python analysis/test_srok_2908.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── БОЕВОЙ СЛУЧАЙ ────────────────────────────────────────────────")
_живой = "Здравствуйте, да, это ко мне. Подъеду через час-полтора, удобно вам будет?"
_вышло = s._срок_только_с_адресом(_живой, False, 2)
chk("«час-полтора» без адреса не звучит", "полтора" not in _вышло, _вышло)
chk("разговор о времени остался", "удобно" in _вышло.lower(), _вышло)
chk("начало реплики цело", "это ко мне" in _вышло, _вышло)
# ⚠ ПРОВЕРКА НА ДУБЛЬ ГЛАГОЛА УБРАНА КАК ПУСТАЯ (29.08). Она гласила «слово "подъед"
# встречается не больше раза» и не могла провалиться: даже сняв отбор форм без глагола,
# я не получил ни одного дубля на шести сидах — до формул «сегодня могу подъехать»
# очередь не доходит. Проверка, которую нельзя уронить диверсией, ничего не стережёт;
# держим вместо неё ту, что ловит: в пуле обязаны БЫТЬ формы без глагола (ниже).

print("── ЛЮБОЙ КОНКРЕТНЫЙ СРОК ────────────────────────────────────────")
for т in ("Могу к 15:00-15:30, удобно?", "Подъеду через два часа",
          "Буду через 40 минут", "Приеду в течение часа", "Могу через полчаса"):
    r = s._срок_только_с_адресом(т, False, 1)
    chk("«%s» → без срока" % т[:30],
        not s._СРОК_ПРИЕЗДА_RX.search(r), r)
# ⚠ ЕДИНИЦА ВРЕМЕНИ УХОДИТ ВМЕСТЕ С ЧИСЛОМ: «через два часа» нельзя резать по «два»,
# иначе остаётся висеть «часа» — «Подъеду часа, вам когда удобно?».
chk("хвостов единиц не остаётся",
    "часа," not in s._срок_только_с_адресом("Подъеду через два часа", False, 1),
    s._срок_только_с_адресом("Подъеду через два часа", False, 1))

print("── КОГДА СРОК ЗАКОНЕН ───────────────────────────────────────────")
# адрес известен — конкретное окно и есть цель разговора
chk("с адресом окно остаётся",
    s._срок_только_с_адресом("Могу к 15:00-15:30, удобно?", True)
    == "Могу к 15:00-15:30, удобно?")
chk("реплика без времени не трогается",
    s._срок_только_с_адресом("Что случилось с техникой?", False)
    == "Что случилось с техникой?")
chk("пустая реплика не роняет", s._срок_только_с_адресом("", False) == "")

print("── ФОРМУЛЫ ИЗ ЖИВОГО КОРПУСА ────────────────────────────────────")
chk("самая частая формула в пуле",
    any("вам когда удобно" in ф.lower() for ф in s._ВРЕМЯ_БЕЗ_СРОКА), s._ВРЕМЯ_БЕЗ_СРОКА)
chk("пул из шести — правило проекта", len(s._ВРЕМЯ_БЕЗ_СРОКА) >= 6)
chk("во всех формулах спрашиваем, а не назначаем",
    all("?" in ф for ф in s._ВРЕМЯ_БЕЗ_СРОКА), s._ВРЕМЯ_БЕЗ_СРОКА)
# ⚠ ЕСТЬ ФОРМЫ БЕЗ ГЛАГОЛА ВЫЕЗДА — на случай, когда он уже сказан в реплике
chk("есть формы без «подъеду»",
    any("подъед" not in ф.lower() and "могу" not in ф.lower() for ф in s._ВРЕМЯ_БЕЗ_СРОКА))

print("── ГАРД ЖИВОЙ ──────────────────────────────────────────────────")
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
chk("вызывается из воронки", "reply = _срок_только_с_адресом(reply" in _ИСХ)
chk("знание адреса передаётся, а не выдумывается",
    "_срок_только_с_адресом(reply, ha," in _ИСХ, "")
chk("стоит после воронки", _ИСХ.find("_срок_только_с_адресом(reply") >
    _ИСХ.find("_ensure_question(_split_greeting_bubble"))

print("=" * 50)
print("Срок приезда без адреса (29.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
