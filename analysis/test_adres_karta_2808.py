# -*- coding: utf-8 -*-
"""АДРЕС СВЕРЯЕТСЯ С КАРТОЙ: есть ли такой ДОМ (28.08).

ЗАМЕЧАНИЕ ВЛАДЕЛЬЦА по тестовой заявке №1234567: «Тверская 10 по факту нет в Москве,
есть Тверская 10с1». Мастер поехал бы по несуществующему номеру и потерял час, а бот
об этом даже не спрашивал: номер дома из ответа карты ВЫБРАСЫВАЛСЯ.

ЧТО КАРТА ОТВЕЧАЕТ НА САМОМ ДЕЛЕ (живая проба 28.08, Nominatim):
    Москва, Тверская 10          → house='10'      дом карте известен
    Москва, Тверская улица 10с1  → house=None      привязка только к улице
    Москва, Тверская улица 27    → house='27 с1'   карта сама уточняет строение
    Москва, Тверская 999         → ни дома, ни улицы

Отсюда правило: карта знает улицу, но не знает дома — предупреждаем. Это ПОДСКАЗКА,
а не запрет: OSM неполна, новостройки и частный сектор появляются в ней с опозданием,
и отказывать клиенту из-за молчания карты нельзя.

⚠ ТРИ СОСТОЯНИЯ, А НЕ ДВА. «Карта не ответила» — это НЕ «дома нет». Кэш состава собран
до этой правки (5879 записей), и если считать отсутствие ключа за «дома нет», то каждый
старый адрес молча объявлялся бы несуществующим.

Запуск: uv run python analysis/test_adres_karta_2808.py
Офлайн, 0 токенов, БЕЗ обращений к карте (состав подставляется в память).
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import geocode                                          # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


# сеть в тесте запрещена: любой поход к карте должен быть виден как отказ
_походы = []


def _без_сети(address, city="", timeout=6):
    _походы.append((address, city))
    return {}


geocode.parts = _без_сети


def подставить(город, адрес, состав):
    geocode._СОСТАВ[geocode._norm_query(город, адрес)] = состав


print("── ЧТО ЗНАЧИТ ОТВЕТ КАРТЫ ───────────────────────────────────────")
подставить("Москва", "Тверская 27", {"street": "Тверская улица", "house": "27 с1"})
р = geocode.дом_подтверждён("Тверская 27", "Москва")
chk("дом известен карте → подтверждён", р["есть_дом"] and р["карта"], р)
chk("уточнение строения от карты сохраняется", р["дом"] == "27 с1", р)

подставить("Москва", "Тверская 10", {"street": "Тверская улица", "house": ""})
р = geocode.дом_подтверждён("Тверская 10", "Москва")
chk("улица есть, дома нет → НЕ подтверждён", not р["есть_дом"] and р["карта"], р)
chk("улица из карты возвращается для текста", р["улица"] == "Тверская улица", р)

# ⚠ СТАРАЯ ЗАПИСЬ КЭША: ключа house нет вовсе — про дом карту не спрашивали
подставить("Москва", "Ленина 5", {"street": "улица Ленина"})
_походы.clear()
р = geocode.дом_подтверждён("Ленина 5", "Москва")
chk("старая запись кэша не выдаётся за ответ карты", not р["карта"], р)
chk("за старой записью идём к карте", len(_походы) == 1, _походы)
chk("молчание карты не значит «дома нет»", р["есть_дом"] is False and not р["карта"], р)

print("── КАРТА МОГЛА НАЙТИ ДРУГУЮ УЛИЦУ ───────────────────────────────")
# ⚠ ЖИВАЯ ПРОБА 28.08: на запрос «Тверская 27» карта вернула дом 27 на «4-й
# Тверской-Ямской улице». Подтвердить адрес по такому ответу значит отправить
# мастера в другой конец города. Сравниваем РАВЕНСТВО значимых слов: вложенность
# сначала казалась добрее, но склеила «Садовую» с «Большой Садовой».
for своя, карты, ждём in (
        ("Тверская", "4-я Тверская-Ямская улица", False),
        ("Тверская", "Тверская улица", True),
        ("Ленина", "улица Ленина", True),                 # тип улицы не различает
        ("Невский проспект", "Невский проспект", True),
        ("Малый проспект В.О.", "Малый проспект", True),  # пометка берега — не имя
        ("Садовая", "Большая Садовая улица", False),      # «Большая» различает
        ("Садовая-Кудринская", "Садовая", False),
        ("Мира", "улица Гагарина", False),
        ("", "Тверская улица", False)):
    chk("улицы «%s» и «%s»" % (своя or "—", карты),
        geocode.улицы_совпали(своя, карты) is ждём)

подставить("Москва", "Тверская 27", {"street": "4-я Тверская-Ямская улица", "house": "27"})
р = geocode.дом_подтверждён("Тверская 27", "Москва")
chk("чужая улица не подтверждает дом", not р["есть_дом"], р)
chk("и прямо сообщает, что улица чужая", р["улица_чужая"] is True, р)

print("── РАЗБОР ОТВЕТА КАРТЫ ──────────────────────────────────────────")
# ⚠ ЭТО ПРОВЕРЯЕТСЯ ОТДЕЛЬНО. Выше состав подставлялся руками, и диверсия «снова
# выбрасывать номер дома» проходила МОЛЧА: тест до разбора не доставал. Функция
# чистая — сеть не нужна, подаём такой же объект, какой отдаёт Nominatim.
def разобрать(объект, запрос="проба"):
    geocode._СОСТАВ.pop(запрос, None)
    geocode._запомнить_состав_osm(запрос, объект)
    return dict(geocode._СОСТАВ.get(запрос) or {})

_д = разобрать({"address": {"city": "Москва", "road": "Тверская улица",
                            "house_number": "27 с1"}})
chk("номер дома из ответа сохраняется", _д.get("house") == "27 с1", _д)
chk("улица сохраняется рядом", _д.get("street") == "Тверская улица", _д)
_у = разобрать({"address": {"city": "Москва", "road": "Тверская улица"}})
chk("дома в ответе нет → ключ есть, значение пустое",
    "house" in _у and _у["house"] == "", _у)
_п = разобрать({"address": {}})
chk("пустой ответ состава не создаёт", _п == {}, _п)

print("── БОТ ПЕРЕСПРАШИВАЕТ ПРО СТРОЕНИЕ ──────────────────────────────")
# ⚠ ПОЧЕМУ ТОЛЬКО ПО ДВУМ ПРИЗНАКАМ ИЗ ЧЕТЫРЁХ. Замер на 48 живых адресах корпуса:
# «карта не знает дома» срабатывает на 16 % (OSM неполна в малых городах), «нашла
# другую улицу» — на 3 %. А в 45 516 репликах живых операторов переспрос про корпус
# адреса встретился ДВАЖДЫ. Спрашивать по слабым признакам значит дёргать каждого
# пятого там, где человек не спрашивает почти никогда. Клиента тревожим, только когда
# карта прямо называет уточнение («20 с1») или говорит, что дома ещё нет.
import server as _srv                                    # noqa: E402
_ОТВЕТ = "Записать вас на завтра к 11:00?"
for вид, ном, ждём in (("строение", "20 с1", "дом 20 — строение 1?"),
                       ("строение", "18 к1", "дом 18 — корпус 1?"),
                       ("стройка", "10", "у вас там корпус или строение?"),
                       ("нет_дома", "", None),
                       ("чужая_улица", "улица Мира", None)):
    вышло = _srv._уточнить_строение(_ОТВЕТ, вид, ном, False)
    if ждём is None:
        chk("«%s» клиента НЕ тревожит" % вид, вышло == _ОТВЕТ, вышло)
    else:
        chk("«%s» → «%s»" % (вид, ждём), вышло.endswith(ждём), вышло)

chk("второй раз про то же не спрашиваем",
    _srv._уточнить_строение(_ОТВЕТ, "строение", "20 с1", True) == _ОТВЕТ)
chk("бот уже спросил сам — не дублируем",
    _srv._уточнить_строение("а корпус какой?", "строение", "20 с1", False) == "а корпус какой?")
chk("непонятный номер карты — молчим",
    _srv._уточнить_строение(_ОТВЕТ, "строение", "20", False) == _ОТВЕТ)
# ⚠ ТОН ИЗ КОРПУСА, А НЕ ИЗ ГОЛОВЫ: живые операторы пишут строчными и коротко
_х = _srv._уточнить_строение(_ОТВЕТ, "строение", "20 с1", False).split("\n")[-1]
chk("вопрос короткий (как у операторов)", len(_х) <= 40, _х)
chk("без объяснений про карты", "карт" not in _х.lower(), _х)
chk("основной вопрос хода не потерян", _ОТВЕТ in
    _srv._уточнить_строение(_ОТВЕТ, "строение", "20 с1", False))
# ⚠ ЭТИ ДВЕ ПРОВЕРКИ ДОБАВЛЕНЫ ПОСЛЕ МОЛЧАЛИВОЙ ДИВЕРСИИ. Слабые признаки не проходили
# не потому, что их отсекает белый список видов, а потому что у них не тот формат
# номера, — то есть защита держалась СЛУЧАЙНО. Проверяем сам список.
_ИСХ0 = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
_гард = _ИСХ0[_ИСХ0.find("def _уточнить_строение"):][:900]
chk("виды перечислены белым списком, а не «любой непустой»",
    'вид not in ("строение", "стройка")' in _гард, _гард[:160])
chk("слабый признак с номером строения всё равно отсечён",
    _srv._уточнить_строение(_ОТВЕТ, "нет_дома", "20 с1", False) == _ОТВЕТ)

# ⚠ И ВТОРАЯ МОЛЧАЛИВАЯ: непрогретый кэш обязан давать пустое сомнение БЕЗ похода в сеть
_походы.clear()
_вид0, _ном0 = geocode.сомнение("Небывалая 7", "Москва")
chk("незнакомый адрес — сомнения нет", (_вид0, _ном0) == ("", ""), (_вид0, _ном0))
chk("и в сеть за ним не ходим", not _походы, _походы)

print("── СЕТЬ НА ПУТИ ОТВЕТА ЗАПРЕЩЕНА ────────────────────────────────")
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
# ⚠ ГРАНИЦУ БЕРЁМ ПО СМЫСЛУ, А НЕ ПО ЧИСЛУ СИМВОЛОВ. Срез в 1200 знаков покраснел,
# как только в тот же блок добавился ориентир: проверка «сбой не роняет ответ» просто
# вышла за край окна. Режем до конца блока — до строки, что идёт следом.
_нач = _ИСХ.find("УТОЧНЕНИЕ СТРОЕНИЯ — БЕЗ ЕДИНОГО ПОХОДА В СЕТЬ")
_кон = _ИСХ.find("_neutralize_tech_wording", _нач)
_бл2 = _ИСХ[_нач:_кон if _кон > _нач else _нач + 2500]
chk("сомнение берётся функцией без сети", "geocode.сомнение(" in _бл2, _бл2[:100])
chk("карта греется в фоне, а не ждётся", "geocode.прогреть(" in _бл2, _бл2[:100])
chk("сбой карты не роняет ответ", "except Exception" in _бл2 and "logbook.event" in _бл2)
chk("повтор ловится по прошлой речи бота", "анти_повтор" in _бл2, _бл2[:100])

print("── ПРЕДУПРЕЖДЕНИЕ СОБИРАЕТСЯ ТОЛЬКО ПО ДЕЛУ ─────────────────────")
_SRV = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
_бл = _SRV[_SRV.find("КАРТА ЗНАЕТ УЛИЦУ, НО НЕ ДОМ"):]
_бл = _бл[:_бл.find("addr_check_failed") + 40]
# ⚠ ЗАМЕР РЕШИЛ, ЧТО ПИСАТЬ В КАРТОЧКУ. «Дома нет» срабатывало на 16 % живых адресов
# и почти всегда означало неполноту бесплатной карты в малых городах, а не кривой адрес.
# Предупреждение на каждой шестой заявке диспетчер перестаёт читать — и оно не срабатывает
# тогда, когда действительно нужно. Осталось то, что почти всегда по делу.
подставить("Коломна", "Гоголя 12", {"street": "улица Гоголя", "house": "",
                                    "kind": "residential"})
_к = geocode.дом_подтверждён("Гоголя 12", "Коломна")
chk("«дома нет» в карточку НЕ идёт",
    not (_к["карта"] and (_к["улица_чужая"] or _к["стройка"])), _к)
подставить("Москва", "Тверская 10", {"street": "Тверская улица", "house": "10",
                                     "kind": "construction"})
_с = geocode.дом_подтверждён("Тверская 10", "Москва")
chk("стройка в карточку идёт", _с["карта"] and _с["стройка"], _с)
chk("«дома нет» и «стройка» — разные признаки",
    _к["стройка"] is False and _с["стройка"] is True)

chk("предупреждение только когда карта ОТВЕТИЛА",
    '_чек.get("карта") and (_чек.get("улица_чужая") or _чек.get("стройка"))' in _бл,
    _бл[:160])
chk("в карту идёт разобранный адрес, а не сырая строка",
    "_parse_addr(lead.get(\"address\")" in _бл, _бл[:120])
chk("без улицы или дома карту не тревожим", "if _ул and _дом:" in _бл, _бл[:120])
chk("сбой карты не роняет сбор заявки", "except Exception" in _бл and "logbook.event" in _бл)
chk("у чужой улицы свой текст, не про дом",
    '_чек.get("улица_чужая")' in _бл and "не нашла улицу" in _бл, _бл[:120])
chk("поле всегда есть, даже пустое", 'lead["addr_warn"] = ""' in _бл)

print("── ДИСПЕТЧЕР ВИДИТ ЭТО В КАРТОЧКЕ ───────────────────────────────")
_JS = io.open(os.path.join(КОРЕНЬ, "ui", "crm-extension", "offscreen.js"),
              encoding="utf-8").read()
_к = _JS[_JS.find("СОМНЕНИЕ В АДРЕСЕ"):][:700]
chk("предупреждение попадает в комментарий заявки", "lead.addr_warn ?" in _к, _к[:100])
chk("оно стоит ПЕРЕД текстом бота, а не в хвосте",
    _к.find("addr_warn") < _к.find("lead.comment ||"), _к[:100])
chk("пустое предупреждение не оставляет пустой строки", "filter(Boolean)" in _к, _к[:100])
chk("оно же уходит в журнал бота", "warnings.push('адрес: '" in _к, _к[:100])

print("=" * 50)
print("Адрес по карте (28.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
