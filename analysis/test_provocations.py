def ask(hist, kn):
    for att in range(5):
        try:
            return server.run_relay(hist, known=kn)
        except Exception as e:
            if "529" in str(e) or "overload" in str(e).lower() or "429" in str(e):
                time.sleep(15 * (att + 1))
                continue
            raise
    raise RuntimeError("API перегружен")


def main():
    results, total, passed = [], 0, 0
    for sid, direction, turns, checks in SCEN:
        kn = dict(KN, direction=direction)
        hist, rows = [], []
        for t in turns:
            hist.append({"role": "client", "text": t})
            r = ask(hist, kn)
            reply = (r.get("reply") or "").strip()
            rows.append({"client": t, "bot": reply, "handoff": bool(r.get("handoff"))})
            hist.append({"role": "bot", "text": reply or "(молчание)"})
        verdicts = []
        for turn_i, must, must_not, what in checks:
            low = (rows[turn_i]["bot"] or "").lower()
            ok = True
            if must and not re.search(must, low):
                ok = False
            if must_not and re.search(must_not, low):
                ok = False
            total += 1
            passed += int(ok)
            verdicts.append({"turn": turn_i, "what": what, "ok": ok})
            print("%s [%s] %s" % ("✓" if ok else "✗", sid, what))
        for row in rows:
            print("   К: %s" % row["client"][:88])
            print("   Б: %s%s" % (row["bot"][:150] or "(МОЛЧИТ)",
                                  "  ⚑оператору" if row["handoff"] else ""))
        print()
        results.append({"id": sid, "rows": rows, "verdicts": verdicts})

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_provocations_results.jsonl")
    with open(out, "w", encoding="utf-8") as f:
        for row in results:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print("=" * 55)
    print("РАСКАЧКА: %d/%d прошло" % (passed, total))


if __name__ == "__main__":
    main()
