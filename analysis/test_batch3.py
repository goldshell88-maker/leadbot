# -*- coding: utf-8 -*-
"""ПАЧКА 3 «границы приёма» (Э4, 21.08). Источник — решения владельца 19.08 (анкета)
и аудит 924 живых подсказок 20.08 (цитаты на настоящих клиентах).

ЛЕСТНИЦА ИСТОЧНИКОВ: решение владельца перекрывает прежнюю трактовку регламента.
Прежде «матрица» и «телефоны» лежали в REFUSE_AS_SOGLAS (удержание «уточню, смогу ли
взяться»), потому что регламент КЦ описывал их как «по согласованию». Анкета 19.08
решила иначе:
  В-003: матрица ЖК — ОТКАЗ СРАЗУ, без согласования и удержания;
         подсветка/инвертор (звук есть, картинки нет) остаются рабочей темой;
  В-004: ПЛАНШЕТЫ — согласование, ТЕЛЕФОНЫ — отказ (разделить в детекторе);
  В-018: по непрофилю отказ идёт сразу, номер до отказа не выпрашивается.

Живые цитаты, которые это чинит (аудит 20.08): на «повреждена матрица» бот отвечал
«давайте заеду, гляну и сразу скажу. Куда подъехать и номер ваш подскажите?» — и через
12 минут оператор отказывал у клиента на глазах.

Запуск: python3 analysis/test_batch3.py   (0 токенов)
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "brain"))
import prefilter  # noqa: E402

ok = bad = 0


def chk(label, cond):
    global ok, bad
    if cond:
        ok += 1
    else:
        bad += 1
        print("✗", label)


def вид(text):
    r = prefilter.check_refuse(text) or {}
    return r.get("kind"), r.get("sub"), (r.get("draft") or "")


# ── В-003: матрица ЖК — отказ сразу ──────────────────────────────────────────
for фраза in [
    "разбилась матрица на телевизоре, замените?",
    "экран телевизора треснул, можно поменять матрицу?",
    "Шлейф матрицы возможно восстановить?",
    "окно упало на ТВ Samsung 42, похоже что повреждена матрица, сколько стоит ремонт",
]:
    kind, sub, draft = вид(фраза)
    chk("матрица → отказ: %s" % фраза[:38], kind == "refuse" and sub == "матрица")
    chk("матрица без удержания: %s" % фраза[:30],
        "уточню" not in draft.lower() and "не обещаю" not in draft.lower())
    chk("матрица без выпрашивания номера: %s" % фраза[:30],
        "номер" not in draft.lower() and "подъехать" not in draft.lower())

# подсветка и инвертор — рабочая тема, отказ НЕ ставим (исключение из В-003)
for рабочая in [
    "звук есть, а изображения нет, тёмный экран",
    "поменять подсветку на телевизоре сколько стоит",
]:
    kind, sub, _ = вид(рабочая)
    chk("подсветка/инвертор остаются рабочими: %s" % рабочая[:34], sub != "матрица")

# ── В-004: планшеты — согласование, телефоны — отказ ─────────────────────────
for фраза in ["сколько стоит ремонт планшета ipad", "планшет не заряжается, почините?"]:
    kind, sub, _ = вид(фраза)
    chk("планшет → согласование: %s" % фраза[:34], kind == "soglas" and sub == "планшеты")

for фраза in ["ремонт телефона айфон 11 сколько", "смартфон не включается, возьмётесь?"]:
    kind, sub, draft = вид(фраза)
    chk("телефон → отказ: %s" % фраза[:34], kind == "refuse" and sub == "телефоны")
    chk("телефон без удержания: %s" % фраза[:30], "уточню" not in draft.lower())

# ── тексты отказов остаются живыми и короткими ──────────────────────────────
for sub in ("матрица", "телефоны"):
    варианты = prefilter.REFUSE_VARIANTS.get(sub) or []
    chk("варианты отказа «%s» существуют" % sub, len(варианты) >= 3)
    chk("варианты «%s» короткие (живой стиль)" % sub,
        all(len(v.replace("Здравствуйте\n", "")) <= 90 for v in варианты))

print("\nИТОГО: %d ок, %d провал" % (ok, bad))
sys.exit(1 if bad else 0)
