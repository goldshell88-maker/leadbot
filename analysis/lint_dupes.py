# -*- coding: utf-8 -*-
"""ЛИНТЕР РАЗДВОЕНИЙ: одно имя — одно определение на модуль.

ЗАЧЕМ. 24.08 подряд починены семь дефектов одного класса: правило описано списком в
одном месте, а второе место о нём не знает. Худший вид — когда оба списка носят ОДНО
имя: второе определение молча затирает первое при импорте, и половина правила
оказывается мертва, не подавая никаких признаков.

Так было с `_BREAKDOWN_RX` в brain/prefilter.py: бытовая половина («не сливает»,
«подтекает», «гудит») была мертва, и клиент с подтекающей стиральной машиной слышал
«Выезд бесплатный» вместо «Выезд и диагностика бесплатные». И с `_TV_RX` там же —
там повезло, копии совпадали.

ЧТО СЧИТАЕТСЯ РАЗДВОЕНИЕМ. Присваивание имени НА ВЕРХНЕМ УРОВНЕ модуля больше одного
раза. Перепривязка внутри функции сюда не попадает намеренно: ленивый кэш
(`global _X; _X = ...`) — законный приём, и запрещать его нечего.

Запуск:  python3 analysis/lint_dupes.py [каталог=brain]
Выход 0 — чисто, 1 — есть раздвоения. Стоит в pre-commit и в офлайн-регрессии.
"""
import ast
import collections
import io
import os
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ⚠ ИСКЛЮЧЕНИЯ — ТОЛЬКО ПОИМЁННО И С ПРИЧИНОЙ. Список пуст намеренно: пока он пуст,
# правило читается как правило. Если понадобится исключение — вписывать сюда парой
# «модуль:имя» и одной строкой, ПОЧЕМУ два определения здесь законны.
РАЗРЕШЕНО: dict[str, str] = {}


def раздвоения(путь):
    """[(имя, [строки])] — имена верхнего уровня, объявленные больше одного раза."""
    дерево = ast.parse(io.open(путь, encoding="utf-8").read())
    видано = collections.defaultdict(list)
    for узел in дерево.body:                       # ТОЛЬКО верхний уровень модуля
        цели = []
        if isinstance(узел, ast.Assign):
            цели = узел.targets
        elif isinstance(узел, ast.AnnAssign) and узел.value is not None:
            цели = [узел.target]
        for ц in цели:
            if isinstance(ц, ast.Name):
                видано[ц.id].append(узел.lineno)
    return [(имя, стр) for имя, стр in sorted(видано.items()) if len(стр) > 1]


def main():
    каталог = os.path.join(КОРЕНЬ, sys.argv[1] if len(sys.argv) > 1 else "brain")
    плохо = 0
    файлов = 0
    for файл in sorted(os.listdir(каталог)):
        if not файл.endswith(".py"):
            continue
        файлов += 1
        модуль = os.path.splitext(файл)[0]
        for имя, строки in раздвоения(os.path.join(каталог, файл)):
            ключ = "%s:%s" % (модуль, имя)
            if ключ in РАЗРЕШЕНО:
                continue
            плохо += 1
            print("РАЗДВОЕНИЕ  %s:%d — имя %s объявлено ещё и на строке(ах) %s"
                  % (файл, строки[-1], имя, ", ".join(str(x) for x in строки[:-1])))
            print("            Побеждает ПОСЛЕДНЕЕ; всё, что было только в предыдущих,")
            print("            мертво и не подаёт признаков. Сведите в одно определение.")
    print("=" * 60)
    print("Линтер раздвоений: %d файлов, раздвоений %d" % (файлов, плохо))
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
