import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter as p  # noqa: E402
import server as s  # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── 1. «МНЕ НУЖНО» ≠ «НЕ НУЖНО» (Воскресенск) ────────────────────")
rx = s._КЛИЕНТ_ЗАКРЫЛ_RX
chk("«Мне нужно хотя бы примерную цену» — НЕ закрытие",
    not rx.search("Мне нужно хотя бы примерную цену"))
chk("«Мне не нужно, спасибо» — закрытие", bool(rx.search("Мне не нужно, спасибо")))
chk("«не надо, уже нашли» — закрытие", bool(rx.search("не надо, уже нашли")))
chk("«спасибо, не надо» — закрытие", bool(rx.search("спасибо, не надо")))
chk("«уже вызвала мастера» — закрытие (сторож 29.08)",
    bool(rx.search("Уже вызвала мастера, спасибо")))
chk("«всё, спасибо» — закрытие (сторож 29.08)", bool(rx.search("всё, спасибо")))
chk("«я не передумал, жду вас» — НЕ закрытие", not rx.search("я не передумал, жду вас"))
chk("«передумала, не приезжайте» — закрытие", bool(rx.search("передумала, не приезжайте")))
chk("«точно не знаю, мне нужно уточнить» — НЕ закрытие",
    not rx.search("точно не знаю, мне нужно уточнить"))

print("── 2. МЕДИАПРИСТАВКИ (Раменское) ────────────────────────────────")
_боевое = "Здравствуйте. Вы apple tv ремонтируете? Там как я понимаю что-то с программой."
chk("боевая реплика: probe даёт вопрос", bool(p.media_stb_probe(_боевое, seed="x")))
chk("probe не обещает приём («сделаю/возьмусь» нет)",
    not p.re.search(r"\bсделаю\b|возьмусь|берусь",
                    p.media_stb_probe(_боевое, seed="x") or ""))
chk("«apple tv не включается» — соглас-класс, не вопрос",
    (p.check_soglasovanie("apple tv не включается, почините?") or {}).get("sub")
    == "ремонт медиаприставки")
chk("«прошить apple tv» — соглас-класс",
    (p.check_soglasovanie("нужно прошить apple tv") or {}).get("sub")
    == "ремонт медиаприставки")
chk("«настроить apple tv, слетела учётка» — мимо probe (приём, модель)",
    p.media_stb_probe("настроить apple tv, слетела учётка", seed="x") is None)
chk("«подключить андроид приставку к телевизору» — мимо probe",
    p.media_stb_probe("подключить андроид приставку к телевизору", seed="x") is None)
chk("«смарт приставка зависает» — соглас-класс",
    (p.check_soglasovanie("смарт приставка зависает на заставке") or {}).get("sub")
    == "ремонт медиаприставки")
chk("обычный телевизор — мимо probe",
    p.media_stb_probe("телевизор не включается", seed="x") is None)
chk("игровая консоль — мимо probe (свой класс)",
    p.media_stb_probe("ps5 ремонтируете?", seed="x") is None)
chk("пул probe ≥ 6 (несвязываемость аккаунтов)", len(p._MEDIA_PROBE_POOL) >= 6)
_разные = {p.media_stb_probe(_боевое, seed="seed%d" % i) for i in range(12)}
chk("ротация по зерну даёт ≥3 формулировки на 12 зёрен: %d" % len(_разные),
    len(_разные) >= 3)

# полный конвейер: боевая реплика Раменского
_res = s._run_relay_inner(
    [{"role": "client", "text": _боевое}],
    known={"visitor": "Иван", "city": "Раменское", "partner": "7",
           "title": "Ремонт телевизоров Sony"})
chk("конвейер: ответ есть, диалог у бота (не handoff)",
    bool(_res.get("reply")) and not _res.get("handoff"), str(_res.get("reply")))
chk("конвейер: в ответе нет обещания приёма",
    "сдела" not in (_res.get("reply") or "").lower()
    and "возьмусь" not in (_res.get("reply") or "").lower(), str(_res.get("reply")))
chk("конвейер: приветствие на первом касании",
    (_res.get("reply") or "").lower().startswith("здравствуйте"), str(_res.get("reply")))

# ремонт ясен → молчаливая передача полным конвейером
_res2 = s._run_relay_inner(
    [{"role": "client", "text": "Apple tv не включается, почините?"}],
    known={"visitor": "Иван", "city": "Раменское", "partner": "7"})
chk("конвейер: ясный ремонт приставки — молчание и передача",
    _res2.get("reply") == "" and _res2.get("handoff"), str(_res2)[:200])

print("── 3. ВЫЕЗД ТВ = ФОРМУЛА КП (Калуга) ────────────────────────────")
_тв_вопрос = "телевизор мерцает экран. сколько стоит выезд?"
_r, _ = p.enforce_callouts("Марку и модель подскажете?", _тв_вопрос,
                           prior_bot_text="Здравствуйте, да, работаю сегодня.",
                           first_reply=False)
chk("ТВ: «ничего не берём»/«бесплатный» без условия НЕ звучит",
    "ничего не берём" not in _r and not (
        "бесплатн" in _r.lower() and "1000" not in _r), _r)
chk("ТВ: формула КП с 1000 дописана", "1000" in _r, _r)
chk("ТВ: порядок железный — сначала «бесплатн», потом 1000",
    "1000" in _r and "бесплатн" in _r.lower()
    and _r.lower().find("бесплатн") < _r.find("1000"), _r)
_r723, _ = p.enforce_callouts("Марку подскажете?", _тв_вопрос,
                              prior_bot_text="Здравствуйте.", first_reply=False,
                              white=True)
chk("ТВ у партнёра 723: тоже формула с 1000", "1000" in _r723, _r723)
_бт, _ = p.enforce_callouts("Посмотрю на месте.",
                            "стиральная машина не отжимает. выезд платный?",
                            prior_bot_text="Здравствуйте.", first_reply=False)
chk("крупная БТ: выезд по-прежнему бесплатный, без 1000",
    ("бесплатн" in _бт.lower() or "ничего не берём" in _бт) and "1000" not in _бт, _бт)
# модель сама сказала «бесплатно» на ТВ — исправляющий гард дописывает условие
_фикс, _ = p.enforce_callouts("Выезд по городу бесплатный, посмотрю вашу плазму.",
                              "телевизор полосит, приедете?",
                              prior_bot_text="Здравствуйте.", first_reply=False)
chk("модельное «бесплатный» на ТВ получает условие про 1000", "1000" in _фикс, _фикс)

print("── 4. ПЛАНШЕТЫ И «АДРЕС ДО ПРОБЛЕМЫ» (Чита + ночной скрин) ──────")
_план = p.check_refuse("Здравствуйте. Планшеты айпады ремонтируете?")
chk("«Планшеты айпады ремонтируете?» — соглас (В-004)",
    bool(_план) and _план.get("kind") == "soglas" and _план.get("sub") == "планшеты",
    str(_план))
chk("«планшеты чините?» — соглас",
    (p.check_refuse("планшеты чините?") or {}).get("kind") == "soglas")
chk("«ремонт айпада сделаете» — соглас (классика, сторож)",
    (p.check_refuse("ремонт айпада сделаете?") or {}).get("kind") == "soglas")
chk("«купить планшет посоветуйте» — НЕ соглас",
    not p.check_refuse("посоветуйте какой планшет купить ребёнку"))
_рез = s._run_relay_inner(
    [{"role": "client", "text": "Здравствуйте. Планшеты айпады ремонтируете?"}],
    known={"visitor": "Елена", "city": "Чита", "partner": "7"})
chk("конвейер: планшеты с порога — молчание и передача",
    _рез.get("reply") == "" and _рез.get("handoff"), str(_рез)[:200])

# гард «адрес не раньше проблемы» — на МОДЕЛЬНУЮ реплику
_г = s._снять_адрес_без_проблемы("здравствуйте, да\nКуда нужно будет приехать?",
                                 False, direction="kp", prior_bot="", сид=7)
chk("адресный вопрос при неизвестной проблеме вырезан",
    not s._ADDRQ_RX.search(_г), _г)
chk("…и остаток реплики цел (вопрос о деле допишет воронка — гард стоит ДО неё)",
    _г.strip() == "здравствуйте, да", _г)
_г0 = s._снять_адрес_без_проблемы("Куда нужно будет приехать?",
                                  False, direction="kp", prior_bot="", сид=7)
chk("вопрос был всей репликой — на его месте вопрос о деле, не пустота",
    _г0.strip() and not s._ADDRQ_RX.search(_г0) and "?" in _г0, _г0)
_г2 = s._снять_адрес_без_проблемы("Принял. Подскажите адрес, куда подъехать?",
                                  True, direction="kp", prior_bot="", сид=7)
chk("проблема известна — адресный вопрос живёт",
    bool(s._ADDRQ_RX.search(_г2)), _г2)
_г3 = s._снять_адрес_без_проблемы(
    "Помогу. Куда подъехать? И что именно случилось, расскажите?",
    False, direction="kp", prior_bot="", сид=7)
chk("смешанная реплика: адрес ушёл, вопрос о поломке остался",
    not s._ADDRQ_RX.search(_г3) and "случилось" in _г3, _г3)

print("\nИтог: %d OK, %d FAIL" % (ok, bad))
sys.exit(1 if bad else 0)
