# -*- coding: utf-8 -*-
"""ВСЕ ГОТОВЫЕ ТЕКСТЫ ГОВОРЯТ ГОЛОСОМ ЧАСТНОГО МАСТЕРА.

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПРАВКА ПЯТИ СТРОК. Реплики модели чистит целый
конвейер: `enforce_callouts`, `_снять_обещание_мастера`, `_no_dash`. А готовые тексты
роутеров уходят клиенту НАПРЯМУЮ, минуя всё это, — и в них годами жило то самое, что
владелец 25.08 назвал «очень ужасной ошибкой»:

    prior_master  «Такое по переписке не разберу. Передам КОЛЛЕГЕ, он поднимет историю»
    cancel        «Принял, снимаю заявку. Передам МАСТЕРУ, чтобы освободил время»
    reschedule    «Понял, ПЕРЕДАМ, чтобы время сдвинули»
    no_show       «Сейчас выясню, ГДЕ МАСТЕР»
    discontent    «Понял вас. Передам КОЛЛЕГЕ, разберёмся»

Пять штук, и все — обращение от лица конторы, которой по легенде нет: бот работает
САМ, у него нет ни коллег, ни диспетчера, ни «мастера», которому можно передать.
Нашёл эталон на живом диалоге 26.08: «понял, передам, чтобы время сдвинули».

⚠ ПРОВЕРЯЕМ ВСЕ ПУЛЫ РАЗОМ, А НЕ ПЯТЬ ИСПРАВЛЕННЫХ СТРОК. Пулы дописывают каждую
неделю, и следующий автор снова напишет «передам коллеге» — правило должно ловить
новый текст само, иначе через месяц всё вернётся.

⚠ ПЕРЕДАЧА ЧЕЛОВЕКУ НИКУДА НЕ ДЕЛАСЬ. Её решает `notify`, а не слова в реплике:
диалог всё так же уходит оператору, меняется только ЛИЦО фразы.

Запуск: uv run python analysis/test_legend_pools.py
Офлайн, 0 токенов.
"""
import io
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import escalation                                       # noqa: E402
import prefilter                                        # noqa: E402
import server                                           # noqa: E402

ЧУЖОЙ_ГОЛОС = re.compile(
    r"переда(?:м|дим|ст)\b"                       # «передам», «передадим»
    r"|колле[гж]\w*"                              # коллега, коллеге, коллеги
    r"|где\s+мастер|мастер\w*\s+(?:освобод|свяж|перезвон|приед\w*\s+к\s+вам\s+вместо)"
    r"|наш\w*\s+(?:мастер|специалист|сотрудник|менеджер|диспетчер)"
    r"|мы\s+(?:перезвоним|свяжемся|приедем)"
    r"|наш[аейи]\s+компани|сервисн\w+\s+центр|наш\s+офис",
    re.IGNORECASE)

#: Что именно уходит клиенту. Служебные подписи для панели и CRM сюда не входят:
#: их читает смена, и «передам мастеру» там законно.
ПУЛЫ = [
    ("escalation.REPLIES", dict(escalation.REPLIES)),
    ("prefilter.JUNK_REPLIES", dict(getattr(prefilter, "JUNK_REPLIES", {}))),
    ("server._ОТПИСКА_НОЧЬ", dict(getattr(server, "_ОТПИСКА_НОЧЬ", {}))),
]
СПИСКИ = [(имя, getattr(server, имя, None)) for имя in
          ("_Q_ADDR", "_ВОПРОС_ПЛИТА", "_ВОПРОС_МОДЕЛЬ_ТВ", "_СОВЕТ_НЕ_ТРОГАТЬ",
           "_ХВОСТ_ПОДТВЕРЖУ", "_ЦЕНА_ПОЗЖЕ")]
СПИСКИ += [(имя, getattr(prefilter, имя, None)) for имя in
           ("PHONE_ASK_POOL", "SOGLAS_POOL", "ЧТО_СЛУЧИЛОСЬ_POOL",
            "PING_БЕЗ_НОМЕРА", "PING_БЕЗ_ОКНА")]

ошибки = []


def проверь(имя, условие, текст=""):
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + текст[:70]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


проверено = 0
print("готовые ответы роутеров")
for имя, пул in ПУЛЫ:
    if not пул:
        continue
    for ключ, текст in пул.items():
        if not isinstance(текст, str) or not текст.strip():
            continue
        проверено += 1
        m = ЧУЖОЙ_ГОЛОС.search(текст)
        проверь("%s[%s]" % (имя, ключ), not m, текст)

print("пулы воронки")
for имя, пул in СПИСКИ:
    if not пул:
        continue
    for текст in пул:
        if not isinstance(текст, str):
            continue
        проверено += 1
        проверь("%s: %s" % (имя, текст[:34]), not ЧУЖОЙ_ГОЛОС.search(текст), текст)

print("\nсам детектор ловит то, ради чего заведён")
for плохо in ("Понял, передам, чтобы время сдвинули",
              "Передам коллеге, он поднимет историю",
              "Сейчас выясню, где мастер",
              "Наш мастер свяжется с вами",
              "Мы перезвоним вам"):
    проверь("ловится: %s" % плохо[:38], bool(ЧУЖОЙ_ГОЛОС.search(плохо)))
for хорошо in ("Понял, перенесём. Уточню по своему графику и вернусь с подтверждением",
               "Принял, снимаю заявку. Время освобожу",
               "Подниму историю по вам и вернусь",
               "Могу сегодня к 19:00, удобно?"):
    проверь("не ложная тревога: %s" % хорошо[:34], not ЧУЖОЙ_ГОЛОС.search(хорошо))

print("\nпроверено готовых текстов: %d" % проверено)
if ошибки:
    print("ПРОВАЛЕНО: %d" % len(ошибки))
    sys.exit(1)
print("Все проверки пройдены")
