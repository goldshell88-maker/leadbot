import server as s                                      # noqa: E402

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:90]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


# геокодер в тесте не трогаем: он сетевой, а зерно от него не зависит
s.territory.map_profile = lambda *a, **k: None

_РУЛЕТКА_RX = re.compile(r"формулируй\s+его\s+ТАК:\s*«([^»]+)».*?вариант\s+№(\d)", re.S)


def оболочка(диалог, kr):
    """Тот самый блок «🎲 Оболочка этого ответа» из РЕАЛЬНОЙ сборки системного промпта."""
    блоки = s._build_system_blocks(диалог, kr, {}, диалог[-1].get("text", ""), "")
    for б in блоки:
        m = _РУЛЕТКА_RX.search(б.get("text") or "")
        if m:
            return m.group(1), m.group(2)
    return None, None


def диалог(текст, ходов_бота=0):
    d = [{"role": "client", "text": текст}]
    for i in range(ходов_бота):
        d.append({"role": "operator", "text": "Здравствуйте, помогу."})
        d.append({"role": "client", "text": "Хорошо"})
    return d


БАЗА = {"visitor": "Иван", "title": "Ремонт стиральных машин", "city": "Пермь",
        "direction": "bt", "persona": "p1"}

print("1. два разных клиента с одинаковым вопросом получают РАЗНЫЕ оболочки")
д = диалог("Здравствуйте, не крутит барабан")
a = оболочка(д, dict(БАЗА, visitor="Иван"))
b = оболочка(д, dict(БАЗА, visitor="Пётр"))
проверь("оболочка вообще нашлась в системном промпте", a[0] is not None, a)
проверь("разные клиенты → разные формулировки", a != b, "%s vs %s" % (a, b))

print("2. одно объявление, разные первые сообщения → разные оболочки")
c1 = оболочка(диалог("не крутит барабан"), БАЗА)
c2 = оболочка(диалог("течёт снизу"), БАЗА)
проверь("разный текст клиента → разная оболочка", c1 != c2, "%s vs %s" % (c1, c2))

print("3. внутри одного диалога оболочка меняется от хода к ходу")
h0 = оболочка(диалог("не крутит барабан", ходов_бота=0), БАЗА)
h1 = оболочка(диалог("не крутит барабан", ходов_бота=1), БАЗА)
h2 = оболочка(диалог("не крутит барабан", ходов_бота=2), БАЗА)
проверь("ход 1 и ход 2 звучат по-разному", h0 != h1, "%s vs %s" % (h0, h1))
проверь("ход 2 и ход 3 звучат по-разному", h1 != h2, "%s vs %s" % (h1, h2))

print("4. один клиент на двух наших аккаунтах — разные оболочки (несвязываемость)")
p1 = оболочка(д, dict(БАЗА, persona="p1"))
p2 = оболочка(д, dict(БАЗА, persona="p2"))
проверь("две персоны не выдают себя дословным совпадением", p1 != p2, "%s vs %s" % (p1, p2))

print("5. один и тот же ход одного диалога СТАБИЛЕН (иначе ответы плясали бы на ретраях)")
проверь("повторный вызов даёт то же самое", оболочка(д, БАЗА) == оболочка(д, БАЗА))

print("6. зерно не привязано ко времени")
исходник = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
тело = исходник[исходник.index("def _зерно_ответа"):]
тело = тело[:тело.index("\n# «Пластинка»")]
# ⚠ ДОКСТРОКУ ОТРЕЗАЕМ: в ней ЦИТИРУЕТСЯ прежний код со `time.time()`, и наивный
# поиск по всей функции краснел на собственном комментарии.
код = тело.split('"""')[2] if тело.count('"""') >= 2 else тело
проверь("в зерне нет time.time() — иначе всё вернётся к пятиминуткам",
        "time.time" not in код, код[:160])
проверь("зерно всё-таки считается от диалога", "sha256" in код and "ходов" in код, код[:160])

print("7. разброс по банку близок к равномерному на 300 диалогах")
import collections                                      # noqa: E402
счёт = collections.Counter()
for i in range(300):
    kr = dict(БАЗА, visitor="Клиент%d" % i)
    n = s._зерно_ответа(диалог("не крутит барабан"), kr) % len(s._LEAD_BANK)
    счёт[n] += 1
ожидание = 300.0 / len(s._LEAD_BANK)
перекос = max(abs(счёт.get(i, 0) - ожидание) for i in range(len(s._LEAD_BANK)))
проверь("ни один вариант не съедает банк (перекос %.0f при ожидании %.0f)"
        % (перекос, ожидание), перекос < ожидание * 0.6,
        dict(счёт))
проверь("задействован ВЕСЬ банк из %d формулировок" % len(s._LEAD_BANK),
        len(счёт) == len(s._LEAD_BANK), dict(счёт))

print("8. НИЖНЯЯ ГРАНИЦА ПУЛОВ: меньше шести вариантов — гарантированный повтор")
import prefilter as pf                                  # noqa: E402
МИНИМУМ = 6
#: Пулы, которым узость разрешена осознанно.
#:  • _TECH_WORDING — не пул реплик, а таблица замен формулировок.
#:  • REFUSE_HOOK_VARIANTS — МЁРТВЫЙ СПРАВОЧНИК: в `prefilter._refuse_text` прямо
#:    написано, что эти тексты клиенту больше не выдаются (решение заказчика 02.08
#:    «мы не будем никому отказывать»). Расширять то, что не уходит наружу, — работа
#:    впустую. ⚠ REFUSE_VARIANTS в исключения НЕ входит: он живой и уходит клиенту
#:    на окончательных отказах (газ, замок, матрица, скупка, телефоны).
#:  • server.CRM_ФИНАЛ — не пул реплик, а СПРАВОЧНИК СТАТУСОВ CRM: «Готов», «Отказ»,
#:    «Отмена Филиала», «Отмена КЦ», «Не оформлена». Их ровно пять, потому что столько
#:    их в CRM; добавить шестой ради круглого числа значит выдумать статус.
ИСКЛЮЧЕНИЯ = {"server._TECH_WORDING", "prefilter.REFUSE_HOOK_VARIANTS",
              "server.CRM_ФИНАЛ"}
узкие = []


def пулы_модуля(мод, имя_мод):
    """Списки фраз, включая ВЛОЖЕННЫЕ В СЛОВАРИ. ⚠ Первая редакция смотрела только
    списки верхнего уровня и пропустила `REFUSE_VARIANTS` — словарь из десяти пулов
    по три фразы, которые уходят клиенту на окончательных отказах."""
    for имя in dir(мод):
        v = getattr(мод, имя)
        if isinstance(v, dict):
            for ключ, вложенный in v.items():
                if isinstance(вложенный, (list, tuple)) and вложенный \
                        and all(isinstance(x, str) for x in вложенный):
                    yield "%s.%s[%s]" % (имя_мод, имя, ключ), вложенный, имя_мод + "." + имя
        else:
            yield "%s.%s" % (имя_мод, имя), v, "%s.%s" % (имя_мод, имя)


for полное, v, корень in [x for м, н in ((s, "server"), (pf, "prefilter"))
                          for x in пулы_модуля(м, н)]:
        if not (isinstance(v, (list, tuple)) and v and all(isinstance(x, str) for x in v)):
            continue
        if len(v) > 40 or any(len(x) < 3 for x in v):
            continue
        if sum(1 for x in v if " " in x) < max(1, len(v) // 2):
            continue                      # это словарь слов, а не пул реплик
        if полное in ИСКЛЮЧЕНИЯ or корень in ИСКЛЮЧЕНИЯ:
            continue
        if len(v) < МИНИМУМ:
            узкие.append("%s=%d" % (полное, len(v)))
проверь("все пулы реплик держат минимум %d вариантов" % МИНИМУМ,
        not узкие, ", ".join(узкие))

print("\nИТОГО: %d ок, %d провал" % (всего[0] - len(ошибки), len(ошибки)))
