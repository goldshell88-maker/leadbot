"""УНИКАЛЬНОСТЬ ОТВЕТОВ: два разных диалога не должны звучать одинаково.

Требование владельца 26.08: «бот никогда не должен вести два абсолютно одинаковых
диалога, у него должна быть 95 % уникальность его ответов, структур предложений».

ЧТО БЫЛО НЕ ТАК. Зерно вариативности («🎲 Оболочка этого ответа» в системном промпте)
считалось как `int(time.time() // 300) + сдвиг_персоны` — ОДНО значение на всех клиентов
внутри пятиминутки. Модель на одинаковый вход отвечает одинаково дословно (температура
у Sonnet 5 недоступна, её отклоняет API), поэтому вариативность целиком держится на
этом зерне. Двое разных людей с похожим вопросом на один аккаунт получали дословную
копию — ровно то, что владелец видит как «два одинаковых диалога».

ЗАМЕР ДО ПРАВКИ (4466 боевых реплик из analysis/answer_cache.jsonl):
  уникальных текстов          58,1 %
  уникальных первых предложений 32,6 %
  пять текстов дали 1324 повтора из 4466

⚠ ПРОВЕРЯЕМ ЧЕРЕЗ `_build_system_blocks`, А НЕ ТОЛЬКО ФУНКЦИЮ ЗЕРНА. Тест на голую
функцию оставался бы зелёным, даже если бы вызов из сборки промпта убрали совсем —
на этих граблях проект стоял уже шесть раз.

Запуск: uv run python analysis/test_unikalnost.py
Офлайн, 0 токенов.
"""
