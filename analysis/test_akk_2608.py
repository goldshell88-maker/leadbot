# -*- coding: utf-8 -*-
"""ПОДТВЕРЖДЕНИЯ И ЭХО: «понимаю, понял», пересказ проблемы, повтор названия за клиентом.

ВЛАДЕЛЕЦ 26.08, вечер: «бот цитирует проблемы и пишет "понимаю, понял", цитирует названия
и тд — похоже на робота, так люди не делают». Приложен снимок диалога по ТВ-приставке:

    клиент: Иии дальше не загружается
    бот   : понимаю, зависла на загрузке. Приставка какая, модель подскажете?
    клиент: [фото коробки SMUX BOX A1]
    бот   : смакс, понял
            Давайте подъеду, глянем что там с загрузкой …

ЧТО БЫЛО СЛОМАНО — ТРИ РАЗНЫЕ ВЕЩИ, И ГЛАВНАЯ ИЗ НИХ В ПРОМПТЕ:

1. Стадия КВАЛИФИКАЦИЯ прямым текстом требовала: «Подтверждай понимание («понял, это
   ремонтируется») — это втягивает». Модель делала ровно то, что просили.
2. `_ACK_ECHO_RX` не знал слова «понимаю» — самый частый вводный оборот модели.
3. Подтверждение в КОНЦЕ строки («смакс, понял») не ловилось ничем: оба правила якорны
   на начало реплики.

ЗАМЕР, А НЕ ВКУС — 45 516 боевых реплик операторов (analysis/LEARNING/avito_corpus.jsonl):
    реплика начинается с подтверждения          6,9 %   (у бота было 20,3 %)
    из них «хорошо» 84 %, «понял» 10 %          (у бота «понял» 45 из 45)
    «понимаю» 3 раза на 45 516, «понятно» 4, «ага» 0
    хвостовое «…, понял»                        0,61 %
Планка зависит от того, на что отвечаем: после согласия клиента 15,5 %, после телефона
или адреса 9,7 %, после описания поломки 7,3 %, в остальных ходах 5,4 %.

Запуск: uv run python analysis/test_akk_2608.py
Офлайн, 0 токенов (постпроцессор, модель не зовётся).
"""
import io
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:110]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


def через_все(reply, клиент, зерно=7):
    """Тот же порядок, что в боевой цепочке: эхо-ярлык → хвостовой акк → планка."""
    r = s._strip_ack_echo(reply, клиент)
    r = s._снять_хвостовой_акк(r)
    return s._планка_акка(r, клиент, зерно)


print("\n1. ДВА ПУЗЫРЯ СО СНИМКА ВЛАДЕЛЬЦА")
дано = "понимаю, зависла на загрузке. Приставка какая, модель подскажете?"
стало = через_все(дано, "Иии дальше не загружается")
проверь("«понимаю, зависла на загрузке» — пересказ снят", "зависла" not in стало.lower(), стало)
проверь("вопрос по делу остался", "модель" in стало.lower(), стало)

дано = "смакс, понял\nДавайте подъеду, глянем что там с загрузкой\nКуда подъехать?"
стало = через_все(дано, "SMUX BOX A1")
проверь("«смакс, понял» — название за клиентом не повторяем", "смакс" not in стало.lower(), стало)
проверь("действие бота уцелело", "подъеду" in стало.lower(), стало)

print("\n2. ЧЕГО РЕЗАТЬ НЕЛЬЗЯ")
дано = "Понял, подъеду завтра к 10. Адрес какой?"
стало = через_все(дано, "давайте завтра")
проверь("обещание с временем не схлопнулось", "завтра к 10" in стало, стало)
дано = "Завтра к 10, принял. Куда подъехать?"
проверь("подтверждение ДОГОВОРЁННОСТИ — не ярлык", через_все(дано, "давайте завтра к 10") == дано,
        через_все(дано, "давайте завтра к 10"))
проверь("«Хорошо.» одним словом остаётся: пустой пузырь клиент видит обрывом",
        s._планка_акка("Хорошо.", "да", 3) == "Хорошо.")
проверь("реплика без подтверждения не трогается",
        s._планка_акка("Куда подъехать?", "спб", 3) == "Куда подъехать?")

print("\n3. ПЛАНКА ДЕРЖИТ ЖИВУЮ ДОЛЮ, А НЕ ОБНУЛЯЕТ")
доля = {}
for ключ, клиент in (("согласие", "да, давайте"), ("контакт", "+7 900 000 00 00"),
                     ("поломка", "телевизор не включается"), ("прочее", "а вы где находитесь")):
    проверь("контекст «%s» распознан" % ключ, s._чем_отвечаем(клиент) == ключ, s._чем_отвечаем(клиент))
    оставили = sum(1 for i in range(600)
                   if s._планка_акка("Понял, подъеду посмотрю. Куда подъехать?", клиент, i)
                   .lower().startswith(("понял", "хорошо", "ок", "договорились", "отлично")))
    доля[ключ] = оставили / 600
    print("     доля подтверждений после «%s»: %.0f %%" % (ключ, доля[ключ] * 100))
проверь("после согласия подтверждают чаще, чем в прочих ходах", доля["согласие"] > доля["прочее"],
        доля)
проверь("подтверждение не исчезло совсем (живые 6,9 % от всех реплик)",
        all(0.15 < д < 0.90 for д in доля.values()), доля)

print("\n4. СЛОВО ПОДТВЕРЖДЕНИЯ — ПО ЖИВОМУ РАСПРЕДЕЛЕНИЮ, А НЕ ОДНО НА ВСЕХ")
слова = set()
for i in range(400):
    r = s._планка_акка("Понял, подъеду посмотрю. Куда подъехать?", "да, давайте", i)
    м = re.match(r"^(\w+)", r)
    if м and м.group(1).lower() in ("понял", "хорошо", "ок", "договорились", "отлично"):
        слова.add(м.group(1).lower())
проверь("бот не заперт на одном «понял»", len(слова) >= 2, слова)
проверь("«хорошо» — самое частое слово живых — в наборе есть", "хорошо" in слова, слова)
проверь("«понимаю» заменяется человеческим словом",
        not s._планка_акка("Понимаю, надо посмотреть на месте. Куда подъехать?", "да, давайте", 1)
        .lower().startswith("понимаю"))

print("\n5. ОДИН И ТОТ ЖЕ ХОД — ОДИН И ТОТ ЖЕ ОТВЕТ (иначе повтор доставки даст разный текст)")
проверь("планка детерминирована",
        s._планка_акка("Понял, подъеду. Куда?", "да", 5) == s._планка_акка("Понял, подъеду. Куда?", "да", 5))

print("\n6. ПРОВОДКА: без вызова в цепочке все проверки выше зелены впустую")
исходник = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
проверь("_снять_хвостовой_акк зовётся из цепочки",
        "reply = _снять_хвостовой_акк(reply)" in исходник)
проверь("_планка_акка зовётся из цепочки с последним словом клиента и зерном хода",
        "reply = _планка_акка(reply, last_client, _зерно_ответа(messages, kr))" in исходник)
# ⚠ ФРАЗА ОСТАЛАСЬ В КОММЕНТАРИИ НАД ПРАВКОЙ — И ЭТО ПРАВИЛЬНО: без неё через месяц
# никто не поймёт, что чинили. Проверяем, что она нигде не осталась КОДОМ.
живая = [n for n, л in enumerate(исходник.split("\n"), 1)
         if "Подтверждай понимание" in л and not л.lstrip().startswith("#")]
проверь("промпт квалификации больше не просит подтверждать понимание", not живая, живая)
# ⚠ ФОРМУЛИРОВКА УЖЕСТОЧЕНА 27.08 (снимок с кулером). Первая редакция звучала условно —
# «пересказывай только если добавляешь новое», — и модель воспользовалась оговоркой:
# «Кулер отвалился с процессора» после «кулер отпал». Ветка ВХОД всё это время держала
# ЖЁСТКИЙ запрет, и разница веток и была дырой. Проверяем смысл, а не дословную фразу.
_квал = исходник.split("СТАДИЯ КВАЛИФИКАЦИЯ", 1)
проверь("стадия квалификации вообще есть в промпте", len(_квал) == 2)
_текст = _квал[1][:800] if len(_квал) == 2 else ""
проверь("промпт квалификации запрещает пересказ БЕЗ оговорок",
        "НЕ ПЕРЕСКАЗЫВАЙ" in _текст and "только если" not in _текст, _текст[:200])
проверь("промпт квалификации запрещает повтор названия за клиентом",
        "не повторяй за ним" in _текст, _текст[:200])

print("\n" + "─" * 60)
print("проверок: %d, провалов: %d" % (всего[0], len(ошибки)))
for о in ошибки:
    print("  ПРОВАЛ:", о)
sys.exit(1 if ошибки else 0)
