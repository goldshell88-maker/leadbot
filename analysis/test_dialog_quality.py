# Строка «Ближайшее время приезда — „час-полтора“ (именно так и озвучивай)» уходила
# в системный промпт в ЛЮБОЙ час суток. В 21:15 это приказ пообещать приезд в 22:45
# при собственной планке приёма 21:30, в 03:00 — приезд в 04:30. Приказ невыполним
# в 12 часах суток из 24, и ровно на них приходится 35.7% заявок. Рядом, в том же
# абзаце, лежало правильное «завтра к 10:00-10:30» — два противоречащих указания.
def _промпт_часа(ч, город="Санкт-Петербург"):
    territory.city_localtime = _в_час(ч)
    try:
        return server._clock_note(city=город, direction="bt")
    finally:
        territory.city_localtime = _НАСТОЯЩИЕ_ЧАСЫ_ГОРОДА


