_РЕАЛЬНОЕ_ВРЕМЯ = time.localtime
_НАСТОЯЩИЕ_ЧАСЫ_ГОРОДА = territory.city_localtime


def _в_час(ч):
    """Подменяет часы, не трогая дату: 13 августа 2026, четверг.

    ⚠ ПОЧЕМУ НЕ time.localtime (найдено этапом 0 программы обучения 18.08).
    Тест подменял серверные часы и семь его проверок «проваливались» на
    исправном коде: с 15.08 бот берёт время ЧАСАМИ ГОРОДА КЛИЕНТА через
    territory.city_localtime (владелец во Владивостоке, +10 к Москве), а не
    часами машины. Подменять надо тот источник, которым код пользуется, —
    иначе тест сторожит дверь, в которую давно не ходят.
    """
    utc = calendar.timegm((2026, 8, 13, ч - 3, 30, 0, 3, 225, -1))   # Москва = UTC+3
    return lambda город="", now=None: _НАСТОЯЩИЕ_ЧАСЫ_ГОРОДА(город, utc)


def _обещанный_день(ч):
    territory.city_localtime = _в_час(ч)
    try:
        note = server._clock_note(city="Москва", direction="bt")
    finally:
        territory.city_localtime = _НАСТОЯЩИЕ_ЧАСЫ_ГОРОДА
    m = re.search(r"окно: «(\w+) к", note)
    return m.group(1) if m else "(окно не названо)"


