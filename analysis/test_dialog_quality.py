def _дописано(reply):
    """Что воронка приклеила к реплике (пусто — значит ничего)."""
    вышло = server._ensure_question(reply, has_addr=False, has_time=True, has_phone=True,
                                    prior_bot="", problem_known=True)
    return вышло[len(reply):].strip()


def _дописано_с(reply, slot, has_addr=False):
    """То же, но с заданным окном и уже собранным адресом — чтобы дошло до шага «время»."""
    вышло = server._ensure_question(reply, has_addr=has_addr, has_time=False, has_phone=True,
                                    prior_bot="", problem_known=True, slot_offer=slot)
    return вышло[len(reply):].strip()


def _окно_в_час(ч, город):
    """Какое окно воронка предложит в этот час в этом городе."""
    territory.city_localtime = _в_час(ч)
    try:
        return server._slot_offer(город, False, "", "bt", "")
    finally:
        territory.city_localtime = _НАСТОЯЩИЕ_ЧАСЫ_ГОРОДА


