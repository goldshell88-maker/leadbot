# -*- coding: utf-8 -*-
"""ТАВТОЛОГИЯ БОТА — НОЛЬ. Замер и гард.

ПОВОД. Просьба владельца 26.08: «проведи тест на тавтологию ответов бота и сделай так,
чтобы она была 0 %». Тавтология разложена на четыре ПРОВЕРЯЕМЫХ вида
(`analysis/tautology.py`), а не на ощущение «звучит криво».

ЗАМЕР ПО 1013 ЖИВЫМ РЕПЛИКАМ БОТА ИЗ БОЯ. Было 4,8 % реплик с тавтологией, и ВСЯ она
одного вида — самоповтор: «Выезд и диагностика 1000, при ремонте бесплатно» из хода в
ход, «Куда подъехать?» слово в слово. Внутренний повтор, эхо клиента и дубли
предложений держали прежние гарды и давали ровно ноль ещё до этой правки.

ЧТО ДЕЛАЕТ ГАРД. Повторное УТВЕРЖДЕНИЕ снимает (один раз сказано — услышано),
повторный ВОПРОС переодевает в другой вариант из пула (спросить второй раз законно,
незаконно спросить теми же словами), а если повтором оказалась ВСЯ реплика — отдаёт
пустоту и ведёт диалог к человеку: повторить себя хуже, чем промолчать.

⚠ ТЕКСТЫ СЦЕНАРИЯ ИЗ ЗАМЕРА ИСКЛЮЧЕНЫ: в ленте они под тем же префиксом, но пишет их
не мозг, а шаг сценария фиксированной строкой, и чинятся они в другом месте
(дожим выключен, текст исправлен миграцией панели).

⚠ КЛИЕНТ СПРОСИЛ — МОЛЧАТЬ НЕЛЬЗЯ НИ ПРИ КАКОМ ПОВТОРЕ. Стресс-набор поймал на этом:
клиент давил по цене и спросил «за приезд сколько?», а бот промолчал — его ответ
переиспользовал уже звучавшие слова. Повтор В ОТВЕТ НА ВОПРОС не тавтология, а ответ.

Запуск: uv run python analysis/test_tautology.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
sys.path.insert(0, os.path.join(КОРЕНЬ, "analysis"))
import server as s_                                     # noqa: E402
import tautology as T                                   # noqa: E402

ошибки = []


def проверь(имя, условие, чем=""):
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:80]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


ПРЕЖДЕ = ("Похоже на подсветку. Выезд и диагностика 1000, при ремонте бесплатно. "
          "Куда подъехать?")

print("повторное утверждение снимается")
_a = s_._снять_самоповтор("Понял. Выезд и диагностика 1000, при ремонте бесплатно. "
                         "Марку и модель подскажете?", ПРЕЖДЕ, 7)
проверь("цена второй раз не звучит", "диагностика" not in _a.lower(), _a)
проверь("новое остаётся", "модел" in _a.lower(), _a)

print("повтор через точку тоже ловится")
_b = s_._снять_самоповтор("Понял, похоже на подсветку. Выезд с диагностикой 1000, "
                         "при ремонте бесплатно. Куда подъехать?", ПРЕЖДЕ, 7)
проверь("четвёрка, перешагнувшая точку, снята",
        not T.повтор_себя(_b, [ПРЕЖДЕ]), T.повтор_себя(_b, [ПРЕЖДЕ]))

print("вся реплика — повтор: отдаём пустоту")
_c = s_._снять_самоповтор("Выезд и диагностика 1000, при ремонте бесплатно", ПРЕЖДЕ, 7)
проверь("пустая строка, а не вторая копия", _c.strip() == "", _c)

print("сид может прийти строкой — ход от этого не падает")
# ⚠ БОЕВОЙ ПУТЬ ПЕРЕДАЁТ СТРОКУ. `_соглас_сид` отдаёт «Иван|Ремонт ТВ|p3», а
# `_pick_unused` берёт остаток по модулю — строка роняла ход с TypeError, и реплика
# терялась. Поймано стресс-набором 26.08.
_c = s_._снять_самоповтор("Понял. Куда подъехать?", ПРЕЖДЕ, "Иван|Ремонт ТВ|p3")
проверь("строковый сид не роняет", isinstance(_c, str), _c)
_d = s_._снять_самоповтор("Понял. Куда подъехать?", ПРЕЖДЕ, 7)
проверь("числовой сид работает как прежде", isinstance(_d, str), _d)

print("новое не трогаем")
for т in ("Хорошо, буду завтра к 10:00", "Записал вас, до встречи",
          "Какая модель телевизора?"):
    проверь("не тронуто: %s" % т, s_._снять_самоповтор(т, ПРЕЖДЕ, 7) == т,
            s_._снять_самоповтор(т, ПРЕЖДЕ, 7))
проверь("без прошлого ничего не режем",
        s_._снять_самоповтор("Выезд и диагностика 1000", "", 7) == "Выезд и диагностика 1000")

print("гард стоит НА ПУТИ, а не рядом с ним")
_МSGS = [{"role": "client", "text": "Телевизор не включается"},
         {"role": "operator", "text": ПРЕЖДЕ},
         {"role": "client", "text": "Ага"}]
_KR = {"visitor": "", "city": "Москва", "direction": "кп", "title": ""}
_вых, *_ = s_._postprocess_reply(
    "Понял. Выезд и диагностика 1000, при ремонте бесплатно. Марку и модель подскажете?",
    _МSGS, dict(_KR), {}, False)
проверь("через _postprocess_reply повтор тоже снят",
        "диагностик" not in (_вых or "").lower(), _вых)

print("замер по всему живому корпусу подсказок")
всего = грязных = опустело = 0
for р, реч, прошлые in T.из_боя():
    всего += 1
    после = s_._снять_самоповтор(р, " \n".join(прошлые), 7,
                                 вопрос_клиента=реч.rstrip().endswith("?"))
    if not после.strip():
        опустело += 1
        continue
    if any(T.разбор(после, реч, прошлые)[в] for в in T.ВИДЫ):
        грязных += 1
проверь("реплик в замере около тысячи", всего > 900, всего)
проверь("тавтология = 0 %%: %d из %d" % (грязных, всего), грязных == 0)
# ⚠ ЦЕНА НОЛЯ НАЗВАНА ВСЛУХ И ОГРАНИЧЕНА. 2,4 % ходов бот отдаёт человеку вместо
# повтора: 1,1 % — реплика целиком была повтором, ещё 1,3 % — после чистки остался
# огрызок без шага («Понял.»), а это не ответ, а вежливый тупик. Оператор в обоих
# случаях получает диалог, а не бесполезную заметку. Потолок 3 % стоит здесь, чтобы
# следующая правка гарда не съела воронку молча.
проверь("цена ноля: опустело меньше 3 %% (%d из %d)" % (опустело, всего),
        опустело <= всего * 0.03)

print()
if ошибки:
    print("ПРОВАЛЕНО: %d" % len(ошибки))
    for e in ошибки:
        print("  -", e)
    sys.exit(1)
print("Все проверки пройдены")
