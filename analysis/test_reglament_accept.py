HOLD = re.compile(r"уточн|вернусь|чуть позже|согласов|передам|дам ответ", re.I)
ACCEPT = re.compile(r"да,?\s|помогу|берусь|соберу|повешу|поменяю|починю|настрою|сделаю|установлю|заменю|прочищу|"
                    r"могу\s+(?:помочь|подъехать|глянуть)|смогу\s+(?:помочь|подъехать)|подъеду|гляну", re.I)
REFUSE = re.compile(r"не\s*(?:помогу|беру|занимаюсь|смогу|делаю)|не\s*(?:наш|мой)\s*профиль|всего доброго", re.I)

rows, bad = [], []
for text, d, exp in CASES:
    r = server.run_relay([{"role": "client", "text": text}], known=kn(d))
    rep = r.get("reply") or ""
    ho = bool(r.get("handoff"))
    held = ho or bool(HOLD.search(rep))
    refused = bool(REFUSE.search(rep)) or bool(r.get("deflect"))
    accepted = bool(ACCEPT.search(rep)) and not held and not refused
    # вопрос-квалификатор без удержания/отказа = принятие по поведению (корпусный канон:
    # «Здравствуйте У вас она из какого материала?» — живой оператор без глагола принятия)
    engaged = "?" in rep and not held and not refused
    if exp == "soglas":
        ok = held and not accepted
    elif exp == "берём":
        ok = (accepted or engaged) and not held and not refused
    elif exp == "otkaz":
        ok = refused
    elif exp.startswith("озвучка:"):
        ok = exp.split(":")[1] in rep
    else:
        ok = True
    router = r.get("model") if "роутер" in (r.get("model") or "") else ""
    rows.append({"exp": exp, "text": text, "reply": rep, "held": held, "accepted": accepted,
                 "refused": refused, "router": router, "ok": ok})
    mark = "OK " if ok else "!! "
    print("%s[%-9s] %s" % (mark, exp, text[:52]))
    print("      %s %s" % (rep[:90], "["+router+"]" if router else ""))
    if not ok:
        bad.append({"exp": exp, "text": text, "reply": rep})

print("\n" + "=" * 50)
print("Верно: %d/%d | ПРОБЛЕМ: %d" % (sum(1 for x in rows if x["ok"]), len(rows), len(bad)))
print("\nОШИБКИ (бот принял согласование / соврал / не отказал):")
for b in bad:
    print("  • [%s] %s → %s" % (b["exp"], b["text"][:45], b["reply"][:70]))

