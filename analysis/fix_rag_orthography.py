# -*- coding: utf-8 -*-
"""ВЫПРЯМИТЕЛЬ ОРФОГРАФИИ В ПУЛЕ ЭТАЛОНОВ.

ЗАЧЕМ. Пул `brain/rag_examples.json` — это то, по чему бот равняет тон: живые ответы
операторов, отобранные из успешных диалогов. Вместе с интонацией он перенимает и ошибки.
Замер 24.08: 74 ответа с «в течении» и НИ ОДНОГО противовеса, 21 «что бы» вместо «чтобы»,
два «здраствуйте». Отбора по грамотности в петле нет ни на одном шаге.

⚠ ПРАВИМ ТОЛЬКО ОТВЕТ (`a`), НИКОГДА НЕ ВОПРОС (`q`). Вопрос — это речь КЛИЕНТА, и она
обязана остаться такой, как люди пишут на самом деле: по ней ищутся похожие ситуации, и
«причесав» её, мы перестанем находить живые обращения с опечатками.

Идемпотентен: второй прогон ничего не меняет. Запуск:
    python3 analysis/fix_rag_orthography.py            — показать, что будет исправлено
    python3 analysis/fix_rag_orthography.py --применить — записать
"""
import io
import json
import os
import re
import sys

ПУЛ = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "brain", "rag_examples.json")

# ⚠ КАЖДОЕ ПРАВИЛО — С ОГОВОРКОЙ, ГДЕ ОНО НЕ ДОЛЖНО СРАБАТЫВАТЬ.
ПРАВИЛА = (
    # «в течении часа» — предлог. Существительное («в течении реки») в чате про ремонт
    # не встречается вовсе: проверено, все 74 вхождения были о времени.
    (re.compile(r"\bв\s+течении\b", re.I), "в течение"),
    # союз «чтобы». Осторожно: «что бы вы ни делали» — законно, поэтому требуем
    # местоимение или отрицание сразу следом и НЕ трогаем оборот с «ни».
    (re.compile(r"\bчто\s+бы\b(?=\s+(?:я|вы|ты|мы|он|она|оно|они)\b(?!\s+ни\b))", re.I), "чтобы"),
    (re.compile(r"\bздраствуйте\b", re.I), "здравствуйте"),
    (re.compile(r"\bизвените\b", re.I), "извините"),
    (re.compile(r"\bпожалуста\b", re.I), "пожалуйста"),
    (re.compile(r"\bприйду\b", re.I), "приду"),
    # «по этому» вместо «поэтому». Не трогаем законное «по этому адресу/поводу/вопросу».
    (re.compile(r"\bпо\s+этому\b(?!\s+(?:адресу|поводу|вопросу|номеру|делу|телефону))", re.I),
     "поэтому"),
)


def выпрямить(текст):
    """Возвращает (исправленный текст, сколько правок)."""
    было = текст or ""
    правок = 0
    for rx, замена in ПРАВИЛА:
        было, n = rx.subn(lambda m, з=замена: _сохранить_регистр(m.group(0), з), было)
        правок += n
    return было, правок


def _сохранить_регистр(исходное, замена):
    """«В течении» → «В течение», а не «в течение»: начало предложения не ломаем."""
    return замена[0].upper() + замена[1:] if исходное[:1].isupper() else замена


def main():
    применить = "--применить" in sys.argv
    данные = json.load(io.open(ПУЛ, encoding="utf-8"))
    примеры = данные.get("examples") or []
    тронуто = всего = 0
    показано = 0
    for пример in примеры:
        новый, n = выпрямить(пример.get("a") or "")
        if not n:
            continue
        тронуто += 1
        всего += n
        if показано < 8:
            показано += 1
            print("  было: %s" % (пример.get("a") or "")[:96])
            print("  стало: %s" % новый[:96])
        пример["a"] = новый
    print("=" * 60)
    print("Пар в пуле: %d | тронуто: %d | правок: %d" % (len(примеры), тронуто, всего))
    if not применить:
        print("Это показ. Записать: python3 analysis/fix_rag_orthography.py --применить")
        return 0
    if тронуто:
        io.open(ПУЛ, "w", encoding="utf-8").write(
            json.dumps(данные, ensure_ascii=False, indent=1))
        print("Записано в %s" % ПУЛ)
    else:
        print("Править нечего — пул уже чист.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
