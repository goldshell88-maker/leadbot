# -*- coding: utf-8 -*-
"""РАЗБОР АДРЕСА: две дыры, найденные при проверке очереди CRM (28.08).

Повод — не догадка, а боевая очередь: в `data/crm_queue.jsonl` шесть заявок упали с
«город не найден в направлении», четыре из них по Петербургу. Территория CRM
выбирается по контуру карты, а карта ищет по РАЗОБРАННОМУ адресу — значит цена
промаха парсера здесь не «некрасивое поле», а потерянная заявка.

ДЫРА 1. Петербургские сокращения района. «12-я линия В.О., д. 5» не разбиралась
вовсе: между типом улицы и домом вставало «В.О.», и голова адреса не складывалась.
Карта при этом «12-я линия 5» находит и кладёт в контур «СПБ 1».

ДЫРА 2. Тип улицы справа отбрасывал ВЕСЬ разбор. Стоп-список содержит «улица» и
«проспект» — сами по себе они не название, и это верно. Но правило выбрасывало
голову целиком, стоило типу оказаться среди слов: «Вокзальная улица 5» → ни улицы,
ни дома, а дальше парсер отдавал обрывок «ица». По корпусу таких адресов 263, и
разбиралось из них 236 (90 %); теперь 263 (100 %).
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "brain"))
import server as s

ok = fail = 0


def проверить(имя, условие, факт=""):
    global ok, fail
    print(("  OK  " if условие else "  FAIL") + "  " + имя + ("" if условие else "  → " + str(факт)))
    if условие:
        ok += 1
    else:
        fail += 1


def разбор(адрес, город=""):
    р = s._parse_addr(адрес, город)
    return (р.get("street") or "", р.get("building") or "")


print("── ПЕТЕРБУРГСКИЕ СОКРАЩЕНИЯ РАЙОНА ──────────────────────────────")
for адрес, улица, дом in (("12-я линия В.О., д. 5", "12-я линия", "5"),
                          ("9-я линия ВО 11", "9-я линия", "11"),
                          ("12-я линия Васильевского острова 5", "12-я линия", "5"),
                          # ⚠ У ПРОСПЕКТОВ УТОЧНЕНИЕ — ЧАСТЬ НАЗВАНИЯ, А НЕ МУСОР. Большой,
                          # Малый и Средний проспекты есть И на Васильевском, И на Петроградской
                          # — это РАЗНЫЕ улицы на разных берегах. Мастер по «Большой проспект 36»
                          # без уточнения едет наугад. У ЛИНИЙ (выше) наоборот: они только на
                          # Васильевском, там «В.О.» ничего не различает и мешает разбору.
                          ("Большой проспект П.С. 36", "Большой проспект П.С.", "36"),
                          ("Большой проспект ПС 36", "Большой проспект ПС", "36"),
                          ("Малый проспект В.О. 9", "Малый проспект В.О.", "9")):
    проверить(адрес[:40], разбор(адрес, "Санкт-Петербург") == (улица, дом), разбор(адрес, "Санкт-Петербург"))

print("── ТИП УЛИЦЫ СПРАВА НЕ ОТБРАСЫВАЕТ РАЗБОР ───────────────────────")
for адрес, улица, дом in (("Вокзальная улица 5", "Вокзальная улица", "5"),
                          ("Восточная улица 7", "Восточная улица", "7"),
                          ("Итальянская улица 4", "Итальянская улица", "4"),
                          ("Садовая улица 1", "Садовая улица", "1"),
                          ("Большой проспект 36", "Большой проспект", "36")):
    проверить(адрес[:40], разбор(адрес) == (улица, дом), разбор(адрес))

print("── ПРЕЖНИЕ ФОРМЫ НЕ ПОСТРАДАЛИ ──────────────────────────────────")
for адрес, улица, дом in (("Невский проспект 24", "Невский проспект", "24"),
                          ("Ленина 5 кв 3", "Ленина", "5"),
                          ("ул Мира 7", "Мира", "7"),
                          ("Бухарестская, 86", "Бухарестская", "86"),
                          ("Совхозная 16", "Совхозная", "16")):
    проверить(адрес[:40], разбор(адрес) == (улица, дом), разбор(адрес))

print("── МУСОР АДРЕСОМ НЕ СТАНОВИТСЯ ──────────────────────────────────")
for мусор in ("домофон 45", "квартира 12", "этаж 3 подъезд 2"):
    проверить(мусор, разбор(мусор) == ("", ""), разбор(мусор))

print("── ТЕРРИТОРИЯ CRM ПО РАЗОБРАННОМУ АДРЕСУ ────────────────────────")
# ровно то, из-за чего падали заявки: без разбора территория не определяется
for адрес, ждём in (("12-я линия В.О., д. 5", True), ("Невский проспект 24", True)):
    т = s._территория_crm("kp", {"city": "Санкт-Петербург"}, {"address": адрес},
                          [{"role": "client", "text": "телевизор не включается, " + адрес}])
    проверить("территория по адресу %s" % адрес[:26], bool(т) == ждём, т)

print()
print("итог: ok=%d fail=%d" % (ok, fail))
sys.exit(1 if fail else 0)
