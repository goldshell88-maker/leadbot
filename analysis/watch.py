# -*- coding: utf-8 -*-
"""СМОТРЕТЬ ЗА БОТОМ ЖИВЬЁМ: клиент, оператор, бот и почему — одним экраном.

ЗАЧЕМ. В ленте панели видно только реплику. Здесь видно решение: на какой стадии
диалог, какой слой ответил, чего боту не хватает, и чем его ход отличается от хода
живого оператора — который на том же месте написал своё.

⚠ ЭТОТ ФАЙЛ НИЧЕГО НЕ ЗНАЕТ О БОТЕ И НЕ ИМПОРТИРУЕТ ЕГО. Он читает строки JSON и
рисует. Поэтому он запускается мгновенно, работает на другой машине и не может ничего
сломать: даже если бот на сервере обновится, смотрелка продолжит показывать поток.
Свои регексы сверки — сознательное дублирование: чинить сломанного бота его же
детектором нельзя.

КАК СМОТРЕТЬ

  живой бой (журнал на сервере бота):
      ssh leadchat-watch 'tail -n 20 -F /opt/leadbot/data/shadow.jsonl' \\
        | uv run python analysis/watch.py

  локально (то, что писал бот на этой машине):
      uv run python analysis/watch.py

  прогон по живым диалогам корпуса, без боя и без ожидания:
      uv run python analysis/replay.py 5 | uv run python analysis/watch.py

Ключи: --файл ПУТЬ · --последние N (сколько показать из хвоста) · --без-цвета
"""
import io
import json
import os
import re
import sys
import time

ЦВЕТ = ("--без-цвета" not in sys.argv) and (os.environ.get("NO_COLOR") is None)


def c(код, текст):
    return ("\033[%sm%s\033[0m" % (код, текст)) if ЦВЕТ else текст


СЕР, ЖИР, КРАС, ЗЕЛ, ЖЁЛТ, СИН, ГОЛ = "90", "1", "31", "32", "33", "34", "36"

# ── детекторы для сверки. Свои, намеренно не общие с ботом (см. шапку) ──
ОКНО = re.compile(r"(?:могу|подъеду|приеду|буду|заеду|подъехать)[^.!?\n]{0,40}"
                  r"(?:через\s+час|час[аоу]?[-\s]*полтора|сегодня|завтра|"
                  r"\bк\s*\d{1,2}\b|\d{1,2}[:.]\d{2})", re.IGNORECASE)
АДРЕС = re.compile(r"куда\s+(?:\w+\s+){0,3}(?:ехать|подъехать|приехать)|"
                   r"адрес\w*\s*(?:подскаж|напиш|скаж|какой|ваш)|"
                   r"по\s+какому\s+адресу|где\s+вы\s+наход|территориальн", re.IGNORECASE)
НОМЕР = re.compile(r"номер\s+(?:телефона|ваш|оставь|подскаж|напиш)|телефон\s*(?:ваш|оставь|подскаж)|"
                   r"оставьте\s+номер|скиньте\s+номер", re.IGNORECASE)
ЦЕНА = re.compile(r"\bот\s*\d{3,}|\d{3,}\s*(?:руб|р\b|₽)", re.IGNORECASE)
ВОПРОС = re.compile(r"\?")

МЕДИАНА_ЖИВЫХ = 39          # знаков, замер по 27 786 ходам операторов


def обрезать(t, n):
    t = " ".join((t or "").split())
    return t if len(t) <= n else t[:n - 1] + "…"


def признаки(t):
    return {"окно": bool(ОКНО.search(t or "")), "адрес": bool(АДРЕС.search(t or "")),
            "номер": bool(НОМЕР.search(t or "")), "цена": bool(ЦЕНА.search(t or "")),
            "вопрос": bool(ВОПРОС.search(t or ""))}


def сверка(бот, оператор):
    """Чем ход бота отличается от хода живого. Пусто — сравнивать не с чем."""
    if not (бот or "").strip() or not (оператор or "").strip():
        return []
    б, о = признаки(бот), признаки(оператор)
    строки = []
    for имя, слово in (("окно", "назвал время приезда"), ("адрес", "спросил адрес"),
                       ("номер", "попросил номер"), ("цена", "назвал цену"),
                       ("вопрос", "задал вопрос")):
        if б[имя] and о[имя]:
            строки.append(c(ЗЕЛ, "✓ оба ") + слово)
        elif б[имя] and not о[имя]:
            строки.append(c(ЖЁЛТ, "→ только бот ") + слово)
        elif о[имя] and not б[имя]:
            строки.append(c(КРАС, "← только оператор ") + слово)
    дл_б, дл_о = len(" ".join((бот or "").split())), len(" ".join((оператор or "").split()))
    знак = ЗЕЛ if дл_б <= max(дл_о, 60) else КРАС
    строки.append(c(знак, "длина %d против %d у живого (медиана %d)"
                    % (дл_б, дл_о, МЕДИАНА_ЖИВЫХ)))
    return строки


def строка(имя, текст, цвет, ширина=76):
    """Реплика с подписью слева и переносом по словам."""
    слова, строки, тек = (текст or "").split(), [], ""
    for w in слова:
        if len(тек) + len(w) + 1 > ширина:
            строки.append(тек)
            тек = w
        else:
            тек = (тек + " " + w).strip()
    if тек:
        строки.append(тек)
    if not строки:
        строки = [c(СЕР, "(пусто)")]
    out = [" %s  %s" % (c(цвет + ";1", имя.ljust(9)), строки[0])]
    out += ["            " + s for s in строки[1:]]
    return "\n".join(out)


def нарисовать(з):
    # ⚠ РИСУЕМ ТОЛЬКО СВОИ ЗАПИСИ. В ту же трубу попадает служебный журнал бота — он
    # тоже JSON, и без этой проверки смотрелка рисовала из него пустые карточки.
    if з.get("вид") != "ход":
        return
    шапка = " %s · %s · %s · %s " % (
        з.get("ts", "")[-8:], з.get("чат") or "?",
        з.get("город") or "город?", (з.get("направление") or "?").upper())
    print("\n" + c(ГОЛ, "═" * 3 + шапка + "═" * max(3, 86 - len(шапка))))
    if з.get("тема"):
        print(" " + c(СЕР, обрезать(з["тема"], 84)))
    if з.get("подсказка_до"):
        print(строка("БЫЛО", обрезать(з["подсказка_до"], 300), СЕР))
    print(строка("КЛИЕНТ", обрезать(з.get("клиент"), 400), ГОЛ))
    if з.get("оператор"):
        print(строка("ОПЕРАТОР", обрезать(з.get("оператор"), 400), ЗЕЛ))
    реплика = з.get("бот") or ""
    print(строка("БОТ", обрезать(реплика, 400) if реплика else "(промолчал)",
                 ЖЁЛТ if реплика else СЕР))
    хвост = []
    if з.get("стадия"):
        хвост.append(з["стадия"])
    if з.get("слой"):
        хвост.append(з["слой"])
    if з.get("мс") is not None:
        хвост.append("%d мс" % з["мс"])
    if хвост:
        print(строка("ПОЧЕМУ", " · ".join(хвост), СИН))
    if з.get("почему"):
        for кусок in str(з["почему"]).split("\n"):
            if кусок.strip():
                print("            " + c(СЕР, обрезать(кусок, 76)))
    метки = []
    if з.get("передал"):
        метки.append(c(КРАС, "→ человеку" + (": " + з["причина"] if з.get("причина") else "")))
    if з.get("заявка"):
        метки.append(c(ЗЕЛ, "★ заявка собрана"))
    if з.get("не_хватает"):
        метки.append(c(СЕР, "не хватает: " + ", ".join(з["не_хватает"])))
    for п in (з.get("пробелы") or []):
        метки.append(c(КРАС, "⚠ " + п))
    if метки:
        print("            " + "   ".join(метки))
    for s in сверка(реплика, з.get("оператор")):
        print("            " + s)
    sys.stdout.flush()


def хвост_файла(путь, последние):
    """tail -F своими руками: файл может ротироваться прямо во время просмотра."""
    while not os.path.exists(путь):
        print(c(СЕР, "жду появления %s …" % путь))
        time.sleep(2)
    f = io.open(путь, encoding="utf-8", errors="replace")
    строки = f.readlines()
    for s in строки[-последние:] if последние else []:
        да(s)
    f.seek(0, os.SEEK_END)
    инод = os.stat(путь).st_ino
    while True:
        s = f.readline()
        if s:
            да(s)
            continue
        time.sleep(0.4)
        try:
            if os.stat(путь).st_ino != инод:
                f.close()
                f = io.open(путь, encoding="utf-8", errors="replace")
                инод = os.stat(путь).st_ino
        except FileNotFoundError:
            pass


def да(s):
    s = (s or "").strip()
    if not s or not s.startswith("{"):
        return
    try:
        нарисовать(json.loads(s))
    except Exception:
        pass


def главное():
    последние = 10
    путь = None
    for i, a in enumerate(sys.argv):
        if a == "--последние" and i + 1 < len(sys.argv):
            последние = int(sys.argv[i + 1])
        if a == "--файл" and i + 1 < len(sys.argv):
            путь = sys.argv[i + 1]
    print(c(ЖИР, "смотрю за ботом. Ctrl+C — выход."))
    print(c(СЕР, "  %s — реплика клиента   %s — что написал живой оператор" %
            (c(ГОЛ, "КЛИЕНТ"), c(ЗЕЛ, "ОПЕРАТОР"))))
    print(c(СЕР, "  %s — что ответил бы бот   %s — на чём он это решил" %
            (c(ЖЁЛТ, "БОТ"), c(СИН, "ПОЧЕМУ"))))
    if not sys.stdin.isatty() and путь is None:
        for s in sys.stdin:                       # поток из ssh или из replay.py
            да(s)
        return 0
    корень = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    хвост_файла(путь or os.path.join(корень, "data", "shadow.jsonl"), последние)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(главное())
    except KeyboardInterrupt:
        print("\nвыход")
