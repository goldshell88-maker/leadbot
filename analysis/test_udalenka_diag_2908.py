# -*- coding: utf-8 -*-
"""ДВА ОБЕЩАНИЯ, КОТОРЫХ МЫ НЕ ДАЁМ (29.08, два боевых диалога).

1. УДАЛЁННАЯ РАБОТА (СПб, принтер). Клиент: «удалённо можно это сделать?» Бот:
   «Удалённо, да, могу подключиться сейчас. Установка от 500р». Слова владельца:
   «мы удалённо не работаем, работаем только на выезд». Правило в плейбуке было
   («дистанционно или выезд?» → «сам к вам подъеду»), гарда в коде не было.

2. ЦЕНА ОТДЕЛЬНОЙ ДИАГНОСТИКИ (Саратов, видеокарта). Клиент: «есть возможность
   проверить видеокарту? Сколько будет стоить». Бот: «Диагностика от 1000р».
   Слова владельца: «надо было озвучить от 500, так как это 7 партнёр; если бы был
   723 — то от 1000».

ДВЕ ФОРМУЛЫ ЦЕНЫ, И ПУТАТЬ ИХ НЕЛЬЗЯ:
  • нужен РЕМОНТ → «выезд и диагностика 1000 рублей, при выполнении работ бесплатно».
    Цифра 1000 здесь верна у любого партнёра — гард эту формулу обходит.
  • нужна ТОЛЬКО ДИАГНОСТИКА → «от 500» у партнёра 7, «от 1000» у 723.

ЧЕМ ПРОВЕРЕНО. Оба гарда прогнаны по 89 730 репликам живых операторов боевого
корпуса. У гарда удалёнки — НОЛЬ ложных срабатываний; у гарда цены — 9, и все девять
это настоящие цены отдельной диагностики. По дороге корпус вскрыл четыре ошибки в
самих гардах: приписанный отказ там, где обещания не было; окно отрицания в 16
символов вместо 32; «осмотр» внутри слова «пОСМОТРю»; и цена работы, принятая за
цену диагностики.

Запуск: uv run python analysis/test_udalenka_diag_2908.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── 1. УДАЛЁННО МЫ НЕ РАБОТАЕМ ───────────────────────────────────")
_боевой = ("Удалённо, да, могу подключиться сейчас. Установка от 500р, "
           "точнее скажу по факту. Телефон для связи оставите?")
_после = s._снять_обещание_удалёнки(_боевой)
chk("обещание удалёнки снято", "далённо, да" not in _после, _после[:60])
chk("на его месте — отказ словами мастера", "выезд" in _после.lower(), _после[:60])
chk("остальная реплика уцелела", "Телефон для связи оставите?" in _после, _после[:80])

chk("«могу подключиться через AnyDesk» снимается",
    "anydesk" not in s._снять_обещание_удалёнки("Могу подключиться через AnyDesk").lower())
chk("«дистанционно настрою» снимается",
    "астрою" not in s._снять_обещание_удалёнки("Дистанционно настрою вам принтер"))

print("── ЧЕСТНЫЙ ОТКАЗ ГАРД НЕ ЛОМАЕТ ─────────────────────────────────")
# ⚠ 79 реплик корпуса: «сейчас так дистанционно не смогу сказать, надо подъезжать».
# Это ПРЕДПИСАННЫЙ плейбуком ответ про цену — сломать его хуже, чем не чинить удалёнку.
for честный in ("Сейчас так дистанционно не смогу вам сказать, тут нужно подъезжать",
                "Не смогу вас сориентировать дистанционно",
                "нужно смотреть технику так несмогу вам дистанционно помочь",
                "как я могу дистанционно сказать цену",
                "Дистанционно не работаю, только на выезд",
                "Могу подъехать помочь, дистанционно не работаю"):
    chk("не тронут: «%s…»" % честный[:34], s._снять_обещание_удалёнки(честный) == честный,
        s._снять_обещание_удалёнки(честный)[:52])

chk("обычная реплика без удалёнки не трогается",
    s._снять_обещание_удалёнки("Здравствуйте, да, могу помочь с драйвером")
    == "Здравствуйте, да, могу помочь с драйвером")

print("── «УДАЛЁННЫЕ» — ЭТО ЕЩЁ И СТЁРТЫЕ ──────────────────────────────")
# ⚠ НАЙДЕНО ЭКЗАМЕНОМ ПО ЖИВЫМ ФОРМУЛИРОВКАМ КОРПУСА. Клиенты спрашивают «переносите
# удалённые приложения?», «восстановите удалённые фото?» — это законная работа, которую
# мы делаем НА ВЫЕЗДЕ. Первая версия гарда отвечала на неё «я только на выезд работаю»
# и теряла заказ. Отличаем по предмету: у стёртого он есть, у удалённой работы — нет.
for законная in ("Да, могу восстановить удалённые приложения",
                 "Да, перенос удалённых приложений сделаю",
                 "Восстановлю удалённые фото, подъеду посмотрю",
                 "Удалённые файлы можно попробовать вернуть, подъеду посмотрю",
                 "Настрою печать с телефона удалённо по WiFi"):
    chk("не тронута: «%s…»" % законная[:34],
        s._снять_обещание_удалёнки(законная) == законная,
        s._снять_обещание_удалёнки(законная)[:52])

print("── 2. ЦЕНА ДИАГНОСТИКИ ПО ПАРТНЁРУ ──────────────────────────────")
chk("ставка партнёра 7 — 500", s.диагностика_ценник("7") == 500)
chk("ставка партнёра 723 — 1000", s.диагностика_ценник("723") == 1000)
chk("незнакомый партнёр — как 7", s.диагностика_ценник("740") == 500)
chk("партнёра нет — как 7", s.диагностика_ценник(None) == 500)

_саратов = "Хорошо, бывает такое при сборке. Диагностика от 1000р. Куда подъехать?"
chk("боевой случай: партнёру 7 ставим 500",
    "500" in s._поправить_цену_диагностики(_саратов, "7"),
    s._поправить_цену_диагностики(_саратов, "7")[:60])
chk("тому же тексту партнёру 723 не трогаем",
    s._поправить_цену_диагностики(_саратов, "723") == _саратов)
chk("партнёру 723 поднимаем с 500 до 1000",
    "1000" in s._поправить_цену_диагностики("Диагностика от 500р", "723"))
chk("остальная реплика уцелела",
    "Куда подъехать?" in s._поправить_цену_диагностики(_саратов, "7"))

print("── ФОРМУЛУ ВЫЕЗДА ГАРД ОБХОДИТ ──────────────────────────────────")
# ⚠ 141 реплика корпуса такого вида. В ней 1000 верна у ЛЮБОГО партнёра: это про выезд,
# который при работах бесплатен, а не про отдельную диагностику.
for формула in ("Выезд и диагностика для вас бесплатны при выполнении работ. "
                "А если откажетесь — 1000 рублей",
                "стоимость выезда и диагностики 1000 рублей\nв случае ремонта бесплатно",
                "выезд и диагностика будет 1000р в случае продолжения работ",
                "Могу сегодня приехать, диагностика 1000 рублей стоит, при ремонте бесплатно"):
    chk("не тронута: «%s…»" % формула[:32],
        s._поправить_цену_диагностики(формула, "7") == формула,
        s._поправить_цену_диагностики(формула, "7")[:56])

print("── ЦЕНА РАБОТЫ — НЕ ЦЕНА ДИАГНОСТИКИ ────────────────────────────")
# Эти четыре вскрыты прогоном по корпусу: гард честно портил цену РЕМОНТА.
for работа in ("Подберем после осмотра, от 1000р работа такая",
               "Я не могу обещать пока не осмотрю, от 1500р работа",
               "Точно скажу на месте, когда посмотрю — обычно такой ремонт от 1500.",
               "смотрите, я тут так посмотрел, где примерно от 8000р у вас ремонт выйдет"):
    chk("не тронута: «%s…»" % работа[:34],
        s._поправить_цену_диагностики(работа, "7") == работа,
        s._поправить_цену_диагностики(работа, "7")[:56])

print("── ГАРДЫ ЖИВЫЕ ──────────────────────────────────────────────────")
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
chk("удалёнка вызывается из воронки", "reply = _снять_обещание_удалёнки(reply," in _ИСХ)
chk("цена вызывается из воронки", "reply = _поправить_цену_диагностики(reply," in _ИСХ)
chk("цена берёт партнёра из карточки", '_поправить_цену_диагностики(reply, (kr or {}).get("partner")' in _ИСХ)

print("=" * 50)
print("Удалёнка и цена диагностики (29.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
