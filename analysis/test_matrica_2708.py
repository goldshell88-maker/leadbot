# -*- coding: utf-8 -*-
"""БОТ РАЗВЕРНУЛСЯ НА 180° И ЧУТЬ НЕ СЛИЛ ЗАЯВКУ: «Да, занимаюсь» → «матрицами не занимаюсь».

ВЛАДЕЛЕЦ 27.08 со снимком (Иван, Крымск, объявление «Ремонт и настройка компьютеров»):
«бот чуть не слил заявку, я пытался её как-то спасти».

    13:36 клиент: Заменой матрицы на ноутбуках занимаетесь?
    13:38 БОТ   : Да, занимаюсь. Какая модель ноутбука?
    13:38 клиент: ASUS Laptop X570ZD
    13:39 БОТ   : Хорошо, ASUS X570ZD. Экран разбит или потёк?      ← повтор модели за клиентом
    13:40 БОТ   : Понял, подъеду гляну. Куда приехать надо?
    13:41 БОТ   : … Могу через два, два с половиной часа … Номер ваш оставьте
    13:41 клиент: Меня интересует цена замены матрицы
    13:42 БОТ   : матрицами не занимаюсь                             ← разворот на 180°
    13:42 клиент: Понял, спасибо                                     ← клиент прощался
    13:42 ОПЕРАТОР спасает: «С заменой матрицы могу помочь»

ПЕРВЫЙ ДЕФЕКТ — ОТКАЗ ЗАБЫЛ ПРЕДМЕТ РАБОТЫ. Исключение в `check_refuse` написано верно:
«матрица-отказ — про ТВ; экран НОУТБУКА и МОНОБЛОКА меняем». Оно и сработало на первой
реплике — там было слово «ноутбуках». Но отказ считается по ПОСЛЕДНЕЙ реплике клиента, а
в «Меня интересует цена замены матрицы» прибора уже нет: клиент назвал его один раз, пять
реплик назад. Исключение испарилось, осталась голая подстрока «матриц» — и шаблон ТВ-отказа.

⚠ КОНТЕКСТ УМЕЕТ ТОЛЬКО СНИМАТЬ ОТКАЗ. Симметрия («раз ноутбук помним, давайте и телевизор
помнить») была бы ошибкой: тогда «настроить телевизор» из первой реплики похоронило бы
ноутбучную матрицу из десятой. Ложный отказ выбрасывает живой лид, пропущенный — всего лишь
доходит до человека.

ВТОРОЙ ДЕФЕКТ — «Хорошо, ASUS X570ZD». Анти-эхо не срезало модель, потому что защищало
фрагменты с цифрами (чтобы не схлопнуть «Понял, подъеду завтра к 10»). Под то же описание
подходит и обозначение модели. Различаем по склейке: во времени и цене число стоит само по
себе, в модели вклеено между букв.

Запуск: uv run python analysis/test_matrica_2708.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter as pf                                  # noqa: E402
import server as s                                      # noqa: E402

ошибки = []
всего = [0]


def проверь(имя, условие, чем=""):
    всего[0] += 1
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:110]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


РЕЧЬ = ("Добрый день Заменой матрицы на ноутбуках занимаетесь? ASUS Laptop X570ZD "
        "Просто горит серым и всё Изображение не выдаёт Если через HDMI подключать к внешке, "
        "то работает Бесплатно это? Я точно знаю, что это матрица")

print("\n1. САМ СНИМОК: отказ помнит, что речь про ноутбук")
for посл in ("Меня интересует цена замены матрицы", "Я точно знаю, что это матрица",
             "Сколько будет стоить матрица?"):
    проверь("«%s» — отказа нет" % посл[:44], pf.check_refuse(посл, РЕЧЬ) is None,
            (pf.check_refuse(посл, РЕЧЬ) or {}).get("draft"))
проверь("а без контекста отказ был бы (так и случилось в бою)",
        pf.check_refuse("Меня интересует цена замены матрицы") is not None)
проверь("первая реплика с прибором и раньше проходила",
        pf.check_refuse("Заменой матрицы на ноутбуках занимаетесь?") is None)

print("\n2. ТВ-ОТКАЗ ОСТАЛСЯ ЗАКОННЫМ — ради него правило и заводили")
тв = "У телевизора samsung разбит экран, полосы по всей матрице"
проверь("разбитая матрица телевизора — отказ", pf.check_refuse(тв) is not None)
проверь("и с контекстом того же диалога — тоже отказ",
        pf.check_refuse("нужна замена матрицы", тв) is not None)
проверь("монитор по-прежнему не отказ",
        pf.check_refuse("матрицу на мониторе поменять") is None)

print("\n3. КОНТЕКСТ НЕ СОЗДАЁТ ОТКАЗОВ, ТОЛЬКО СНИМАЕТ")
# телевизор в ранней реплике не должен хоронить ноутбучную матрицу в поздней
смешанный = "Здравствуйте, телевизор настроить надо. А ещё у ноутбука матрицу поменять"
проверь("«телевизор настроить» + «ноутбуку матрицу» — не отказ",
        pf.check_refuse("у ноутбука матрицу поменять", смешанный) is None,
        (pf.check_refuse("у ноутбука матрицу поменять", смешанный) or {}).get("draft"))
проверь("пустой контекст ничего не ломает",
        pf.check_refuse("матрицу на ноутбуке поменять", "") is None)
проверь("контекст None не роняет разбор",
        pf.check_refuse("здравствуйте", None) is None)

print("\n4. МОДЕЛЬ ТЕХНИКИ ЗА КЛИЕНТОМ НЕ ПОВТОРЯЕМ")
проверь("«Хорошо, ASUS X570ZD» — модель срезана",
        "X570ZD" not in s._strip_ack_echo("Хорошо, ASUS X570ZD. Экран разбит или потёк?",
                                          "ASUS Laptop X570ZD"),
        s._strip_ack_echo("Хорошо, ASUS X570ZD. Экран разбит или потёк?", "ASUS Laptop X570ZD"))
проверь("«Хорошо, Samsung UE43» — тоже",
        "UE43" not in s._strip_ack_echo("Хорошо, Samsung UE43. Что с ним?",
                                        "телевизор Samsung UE43"))
проверь("вопрос по делу после среза остался",
        "?" in s._strip_ack_echo("Хорошо, ASUS X570ZD. Экран разбит или потёк?", "ASUS Laptop X570ZD"))

print("\n5. ВРЕМЯ И ЦЕНУ РЕЗАТЬ ПО-ПРЕЖНЕМУ НЕЛЬЗЯ (ради чего гард и стоял)")
для_беречь = [
    ("Понял, подъеду завтра к 10. Адрес какой?", "давайте завтра", "завтра к 10"),
    ("Понял, 1000 рублей выйдет. Куда подъехать?", "сколько стоит", "1000"),
    ("Понял, через 2 часа буду. Адрес?", "когда сможете", "2 часа"),
    ("Понял, к 10:30 подъеду. Куда?", "во сколько", "10:30"),
]
for r, кл, кусок in для_беречь:
    проверь("«%s» уцелело" % кусок, кусок in s._strip_ack_echo(r, кл), s._strip_ack_echo(r, кл))
проверь("число внутри слова числом не считается (X570ZD)",
        not s._ЗНАЧАЩЕЕ_ЧИСЛО_RX.search("ASUS X570ZD"))
проверь("отдельно стоящее число считается", bool(s._ЗНАЧАЩЕЕ_ЧИСЛО_RX.search("завтра к 10")))

print("\n6. ПОДСКАЗКА МОДЕЛИ ЗНАЛА ТЕ ЖЕ ГАРДЫ — ТЕПЕРЬ ЗНАЕТ")
проверь("модели не советуют отказать в ноутбучной матрице",
        pf.refuse_topic("Меня интересует цена замены матрицы", РЕЧЬ) is None,
        pf.refuse_topic("Меня интересует цена замены матрицы", РЕЧЬ))
проверь("а по ТВ подсказка осталась",
        pf.refuse_topic("телевизор упал, разбит экран") == "матрица")
# ⚠ КОНТЕКСТНЫЕ ГАРДЫ ПОДСКАЗКУ ГАСИТЬ НЕ ДОЛЖНЫ — в этом её работа (EDGE-03).
проверь("газ рядом со столешницей модель по-прежнему предупреждают",
        pf.refuse_topic("а можете вырезать в столешнице отверстие под мойку и газовую панель?") == "газ")
проверь("но шаблоном такую смесь не гасим",
        pf.check_refuse("а можете вырезать в столешнице отверстие под мойку и газовую панель?") is None)

print("\n7. ФОРМУЛА ВЫЕЗДА: срез диагностики не должен ломать фразу")
_речь_ремонт = ("Заменой матрицы на ноутбуках занимаетесь? Просто горит серым и всё "
                "Изображение не выдаёт Если через HDMI подключать к внешке, то работает")
_формула = "Выезд и диагностика для вас будут бесплатны при выполнении работ"
проверь("на ремонтной заявке «диагностика» остаётся на месте",
        pf._drop_diagnostics_on_install(_формула, _речь_ремонт) == _формула,
        pf._drop_diagnostics_on_install(_формула, _речь_ремонт))
_чистый_монтаж = pf._drop_diagnostics_on_install(_формула, "Нужно повесить телевизор на стену и подключить")
проверь("на чистом монтаже диагностика убрана", "диагностик" not in _чистый_монтаж, _чистый_монтаж)
проверь("и фраза осталась согласованной («будут бесплатны» при одном подлежащем — брак)",
        "будут бесплатны" not in _чистый_монтаж, _чистый_монтаж)
проверь("«горит серым» опознано симптомом", bool(pf._СИМПТОМ_RX.search("просто горит серым и всё")))
проверь("«изображение не выдаёт» — тоже", bool(pf._СИМПТОМ_RX.search("изображение не выдаёт")))

print("\n8. РЕГЛАМЕНТ ВЫУЧИЛ ТО, ЧТО ОПЕРАТОР ГОВОРИЛ ВЖИВУЮ")
# Владелец: «проанализируй и мои ответы тоже, чтобы бот был готов к такому». Ниже — его же
# формулировки из этого диалога, перенесённые в регламент дословно по смыслу.
_промпт = io.open(os.path.join(КОРЕНЬ, "brain", "prompt.py"), encoding="utf-8").read()
проверь("матрицу меняют, а не ремонтируют — правило есть",
        "МАТРИЦУ НЕ РЕМОНТИРУЮТ" in _промпт)
проверь("слово «не занимаюсь» прямо запрещено", "не произноси «не занимаюсь»" in _промпт)
проверь("цену матрицы вслепую называть нельзя", "ЦЕНУ МАТРИЦЫ ВСЛЕПУЮ НЕ НАЗЫВАЙ" in _промпт)
проверь("обещание «подберу под вашу модель» убрано",
        "подберу под вашу модель, гляну крепление" not in _промпт)
проверь("возражение про диагностику отработано",
        "ЗАЧЕМ ДИАГНОСТИКА" in _промпт and "искать один в один" in _промпт)
проверь("выезд идёт вместе с диагностикой — сказано",
        "выезд идёт вместе" in _промпт)
проверь("скриншот с маркетплейса — не фото поломки",
        "СКРИНШОТ КАРТОЧКИ ТОВАРА" in _промпт)
проверь("монитор больше не назван отказной темой вместе с ТВ",
        "это про ЖК ТВ,\nНЕ про ноутбуки и НЕ про мониторы" in _промпт)

print("\n9. ОСТАЛЬНОЕ ИЗ ТОГО ЖЕ РАЗБОРА")
проверь("«компьютер» опознаётся предметом КП (так называется объявление)",
        bool(pf._LAPTOP_RX.search("ремонт и настройка компьютеров")))
проверь("заголовок объявления один снимает отказ по матрице",
        pf.check_refuse("меня интересует цена замены матрицы",
                        "Иван · Ремонт и настройка компьютеров / Выезд мастера на дом") is None)
проверь("но объявление про телевизоры отказ сохраняет",
        pf.check_refuse("телевизор разбит, матрица", "Ремонт телевизоров") is not None)
проверь("«Бесплатно это?» — вопрос о цене", s._клиент_спросил_цену("Бесплатно это?"))
проверь("«выезд платный?» — тоже", s._клиент_спросил_цену("выезд платный?"))
проверь("а своя же фраза бота о бесплатном выезде вопросом не считается",
        not s._клиент_спросил_цену("Выезд и диагностика для вас бесплатны при выполнении работ"))
проверь("хвостовой акк тоже различает модель и время",
        s._снять_хвостовой_акк("X570ZD, понял\nДавайте подъеду") == "Давайте подъеду",
        s._снять_хвостовой_акк("X570ZD, понял\nДавайте подъеду"))
проверь("а договорённость со временем в хвосте не режется",
        s._снять_хвостовой_акк("Завтра к 10, принял\nБуду").startswith("Завтра"))
проверь("модель техники контактом не считается", s._чем_отвечаем("ASUS Laptop X570ZD") == "прочее")
проверь("телефон контактом остался", s._чем_отвечаем("89001234567") == "контакт")
проверь("адрес — тоже", s._чем_отвечаем("Ленина 5 кв 12") == "контакт")

print("\n10. ПРОВОДКА")
исходник = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
разбор = io.open(os.path.join(КОРЕНЬ, "brain", "prefilter.py"), encoding="utf-8").read()
проверь("отказ принимает речь клиента", "def check_refuse(text, предмет=\"\")" in разбор)
проверь("исключение по ноутбуку смотрит в накопленную речь",
        "_LAPTOP_RX.search(предмет_t)" in разбор)
проверь("исключение по монитору — тоже", "_MONITOR_RX.search(предмет_t)" in разбор)
проверь("ТВ проверяется по ПОСЛЕДНЕЙ реплике: контекст не создаёт отказов",
        разбор.count("not _TV_RX.search(t)") >= 2)
проверь("боевой путь передаёт речь клиента", "check_refuse(last_client, речь_клиента)" in исходник)
проверь("подсказка модели — тоже", "check_refuse(last, blob)" in исходник)
проверь("основание сверки — тоже",
        'check_refuse(last_client or "", client_all or "")' in исходник)
проверь("гард цифр различает модель и время",
        "_ЗНАЧАЩЕЕ_ЧИСЛО_RX.search(frag)" in исходник)
проверь("подсказка модели получает речь клиента", "refuse_topic(last, blob)" in исходник)
проверь("гарды вынесены в одно место", "def _гард_снимает_отказ(" in разбор)
проверь("предметный гард отделён от контекстного", "def _не_тот_предмет(" in разбор)
проверь("подсказка зовёт предметный гард",
        "if _не_тот_предмет(kind, t, предмет_t):" in разбор)
проверь("срез диагностики спрашивает общий список симптомов",
        "or _СИМПТОМ_RX.search(t)" in разбор)
проверь("заголовок объявления доходит до предмета",
        '(known or {}).get("title")' in исходник and "речь_клиента = (речь_клиента" in исходник)
проверь("контакт опознаётся телефоном и адресом, а не наличием цифр",
        "prefilter.phones_in(т) or _ADDR_RX.search(т)" in исходник)
проверь("хвостовой акк зовёт тот же цифровой критерий",
        "_ЗНАЧАЩЕЕ_ЧИСЛО_RX.search(ярлык)" in исходник)

print("\n" + "─" * 60)
print("проверок: %d, провалов: %d" % (всего[0], len(ошибки)))
for о in ошибки:
    print("  ПРОВАЛ:", о)
sys.exit(1 if ошибки else 0)
