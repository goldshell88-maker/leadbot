# -*- coding: utf-8 -*-
"""БОЕВЫЕ ДИАЛОГИ 29.08: часть дня клиента и floor чужого направления.

Первые часы работы бота после включения дали два дефекта, которых не поймал ни один
из тридцати офлайн-тестов.

1. ЧАСТЬ ДНЯ (Курск). Клиент: «Союзная. Но во второй половине дня». Бот: «Могу сегодня
   к 10:00-10:30, удобно вам будет?» — предложил утро в ответ на просьбу о второй
   половине. Часть дня считалась от ТЕКУЩЕГО времени города, а пожелание клиента не
   смотрелось вовсе.

2. FLOOR ЧУЖОГО НАПРАВЛЕНИЯ (Курск). Клиент спросил цену переустановки Windows с Office
   и чистки от пыли, бот ответил «вместе от 1500». Это floor МНЧ (сборка мебели); прайс
   КП по каждой из этих работ — 2000. Корректор цен пропустил цифру НАМЕРЕННО: 1500
   числится законной ступенью лестницы, и он не знает, что ступень чужая.
   Слова владельца: «Почему от полутора?»

Запуск: uv run python analysis/test_boy_2908.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402
import price_book as pb                                 # noqa: E402

ok = bad = 0


def chk(имя, услов, факт=""):
    global ok, bad
    if услов:
        ok += 1
        print("  OK    %s" % имя)
    else:
        bad += 1
        print("  FAIL  %s  %s" % (имя, факт))


print("── ЧАСТЬ ДНЯ, О КОТОРОЙ ПРОСИЛ КЛИЕНТ ───────────────────────────")
_живой = s._слот_под_пожелание("Могу сегодня к 10:00-10:30, удобно вам будет?",
                               "Союзная. Но во второй половине дня")
chk("утро больше не предлагается", "10:00" not in _живой, _живой)
chk("окно ушло во вторую половину", "14:00" in _живой, _живой)
chk("остальная реплика цела", "удобно вам будет" in _живой, _живой)

for реплика, речь, ждём in (
        ("Могу к 11:00, удобно?", "можно вечером?", "18:00"),
        ("Могу к 09:00?", "после обеда удобнее", "14:00"),
        ("Могу к 20:00?", "можно с утра?", "10:00")):
    r = s._слот_под_пожелание(реплика, речь)
    chk("«%s» → %s" % (речь[:24], ждём), ждём in r, r)

print("── КОГДА НЕ ТРОГАЕМ ─────────────────────────────────────────────")
# окно уже в нужной части дня
chk("верное окно не переставляем",
    s._слот_под_пожелание("Могу к 15:00?", "во второй половине дня") == "Могу к 15:00?")
# ⚠ ЧАС, НАЗВАННЫЙ САМИМ КЛИЕНТОМ, — ЭТО УЖЕ СОГЛАСИЕ, А НЕ НАШЕ ПРЕДЛОЖЕНИЕ
# ⚠ ПРИМЕР ОБЯЗАН БЫТЬ ВНЕ ДИАПАЗОНА, ИНАЧЕ ПРОВЕРКА ПУСТАЯ. Первая редакция брала
# «в 10:00 утром»: десять и так попадает в утро (10-12), и защита «час клиента» ничего
# не решала — диверсия против неё прошла молча. Тринадцать во «вторую половину» (14-18)
# не попадает, и без защиты его бы переставили на 14:00.
chk("час клиента не правим, даже вне его же диапазона",
    s._слот_под_пожелание("Могу к 13:00, удобно?", "во второй половине дня, давайте в 13:00")
    == "Могу к 13:00, удобно?",
    s._слот_под_пожелание("Могу к 13:00, удобно?", "во второй половине дня, давайте в 13:00"))
chk("без пожелания ничего не меняем",
    s._слот_под_пожелание("Могу к 11:00?", "холодильник не морозит") == "Могу к 11:00?")
chk("пустая реплика не роняет", s._слот_под_пожелание("", "вечером") == "")

_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
print("── FLOOR ЧУЖОГО НАПРАВЛЕНИЯ ─────────────────────────────────────")
# ⚠ ПРОВЕРКИ ПЕРЕЕХАЛИ В test_boy2_2908 ВМЕСТЕ С РЕШЕНИЕМ (29.08). Здесь стоял
# `_floor_своего_направления`: он заменял floor МНЧ прайсовой ценой СРАЗУ, то есть
# прыгал через ступень «от 1000», которую владелец назвал первой — «для 723 сначала
# озвучка от 1000, потом, если есть фиксированные, фиксированный, но по правилам
# отработки возражений». Функция удалена, работу делает `_планка_озвучки`.
chk("правка, прыгавшая через ступень, удалена",
    "_floor_своего_направления" not in _ИСХ)
chk("работу делает планка озвучки", "_планка_озвучки(reply, client_all" in _ИСХ)

print("── ОБА ГАРДА ЖИВЫЕ ──────────────────────────────────────────────")
# ⚠ ГЛАВНЫЙ УРОК СЕССИИ: правило, которое никто не зовёт, не работает.
_ИСХ = io.open(os.path.join(КОРЕНЬ, "brain", "server.py"), encoding="utf-8").read()
chk("слот под пожелание вызывается", "reply = _слот_под_пожелание(reply" in _ИСХ)
# ⚠ ПРОВЕРКА СНЯТА ВМЕСТЕ С ФУНКЦИЕЙ (29.08). `_floor_своего_направления` заменял
# floor МНЧ прайсовой ценой сразу — то есть прыгал через ступень «от 1000», которую
# владелец назвал первой: «для 723 сначала озвучка от 1000, потом, если есть
# фиксированные, фиксированный — но по правилам отработки возражений». Работу делает
# `_планка_озвучки`, и проверки на неё стоят в test_boy2_2908.
chk("правка, прыгавшая через ступень, удалена",
    "_floor_своего_направления" not in _ИСХ)
chk("оба стоят после воронки",
    _ИСХ.find("_слот_под_пожелание(reply") > _ИСХ.find("_ensure_question(_split_greeting_bubble"))

print("── ЗОВ ЧЕЛОВЕКА НА РАБОТЕ, КОТОРУЮ МЫ БЕРЁМ ────────────────────")
# Боевой диалог 29.08, Рязань. Клиент: «Подскажите примерную стоимость перепрошивки.
# Телевизор dexp». Бот ответил по существу и передал диалог менеджеру. В промпте есть
# правило «ТВ-ПРИСТАВКИ: их ремонт и прошивка = согласование», а про прошивку САМОГО
# телевизора правила не было — модель прочитала «прошивка ТВ» и решила, что это оно.
# Слова владельца: «Прошивку телевизоров мы принимаем». Прайс КП: прошивка ТВ = 2500.
chk("прошивка телевизора — зов снимаем",
    s._ложный_зов_человека(True, "model_handoff",
                           "Подскажите примерную стоимость перепрошивки. Телевизор dexp"))
# ⚠ ОКНО ЧЕРЕЗ ТОЧКУ ОБЯЗАТЕЛЬНО: предмет назван отдельным предложением, и запрет
# точки внутри окна рвал совпадение ровно на боевой фразе.
chk("предмет через точку тоже виден",
    s._ложный_зов_человека(True, "model_handoff", "перепрошивка. телевизор"))
chk("прошивка телевизора одной фразой",
    s._ложный_зов_человека(True, "model_handoff", "перепрошивка телевизора"))

print("── А ВОТ ЭТО ТРОГАТЬ НЕЛЬЗЯ ────────────────────────────────────")
for h, c, т, что in ((True, "model_handoff", "прошить тв-приставку", "приставка — согласование"),
                     (True, "model_handoff", "прошивка playstation", "консоль — согласование"),
                     (True, "model_handoff", "прошивка телевизора и приставки", "смесь — не трогаем"),
                     (True, "refuse", "перепрошивка телевизора", "отказ по регламенту"),
                     (True, "soglas", "перепрошивка телевизора", "согласование по регламенту"),
                     (False, "model_handoff", "перепрошивка телевизора", "зова и не было"),
                     (True, "model_handoff", "холодильник не морозит", "чужая тема")):
    chk("%s" % что, not s._ложный_зов_человека(h, c, т))

print("── ГАРД ЖИВОЙ ──────────────────────────────────────────────────")
chk("снятие вызывается из suggest_reply", "_ложный_зов_человека(result.get(" in _ИСХ)
chk("снимается и handoff, и причина",
    'result["handoff"] = False' in _ИСХ and 'result["notify_reason"] = None' in _ИСХ)
chk("снятие пишется в журнал", "leadbot.handoff.снят_ложный" in _ИСХ)
_ПР = io.open(os.path.join(КОРЕНЬ, "brain", "prompt.py"), encoding="utf-8").read()
chk("правило есть и в промпте", "ПРОШИВКА САМОГО ТЕЛЕВИЗОРА" in _ПР)

print("=" * 50)
print("Боевые диалоги (29.08): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
