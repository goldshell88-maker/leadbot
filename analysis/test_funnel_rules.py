# ⚠ ЛОЖНОЕ «ВРЕМЯ НАЗВАНО» СТОИТ ДОРОЖЕ ПРОПУСКА: бот перестаёт предлагать окно вовсе,
# и запись не рождается. Цены, сроки гарантии и габариты временем не являются. Приветствие
