# на вопрос «выезжаете и сможете сегодня?» получил четыре строки — окно, адрес
# и номер разом. Замер по кэшу боевых ответов: сама модель трёх вопросов не задаёт
# ни разу (0 из 3669), значит третий элемент всегда приходит из кода.
_MSGS_ДВА = [
    {"role": "client", "text": "вы работаете с чисткой ноутбука от газировки? И сколько будет стоить?"},
    {"role": "operator", "text": "Здравствуйте, да, нужно приезжать смотреть объемы"},
    {"role": "client", "text": "Выезжаете на канонерский остров? И сможете ли сегодня?"},
]
_KR_ДВА = {"visitor": "", "city": "Санкт-Петербург", "direction": "kp", "title": "",
           "persona": "", "partner": "", "white": False}

for _имя, _модель, _добор in (
    # ровно та реплика, что ушла в бою: окно и адрес уже спрошены — третьего не бывает
    ("окно+адрес", "да, выезжаю\nМогу сегодня, через час-полтора удобно?\n"
                   "По адресу подскажите, куда к вам подъехать (квартира, подъезд, этаж)?", False),
    # ⚠ ОЖИДАНИЕ ПО «ТОЛЬКО ОКНО» ПЕРЕВЁРНУТО 26.08 — ПРАВИЛОМ ВЛАДЕЛЬЦА, НЕ ЗАМЕРОМ.
    # Раньше здесь стояло True: «окно названо — добери номер тем же сообщением» (+13,2
    # п.п., этап 2). Теперь работает более старшее правило: «чтобы предложить время, мы
    # должны знать адрес» — обещание «час-полтора» верно только в черте города, а где
    # клиент, бот не знает. Поэтому на реплике с окном И БЕЗ известного адреса вторым
    # элементом идёт АДРЕС, а не номер.
    # Номер не потерян, а отложен на ход: по живому корпусу Авито его цена с ходом
    # РАСТЁТ — 45,9 % на первом, 51,1 % на втором, 74,0 % на третьем и позже.
    # Как только адрес известен, добор номера возвращается — случай ниже это и держит.
    ("только окно", "да, выезжаю\nМогу сегодня, через час-полтора удобно?", False),
    ("только адрес", "да, выезжаю\nАдрес подскажете?", True),
    ("дело без просьб", "да, чищу от залития, это обычная работа", True),
):
    _вых, *_ = server._postprocess_reply(_модель, _MSGS_ДВА, dict(_KR_ДВА), {}, False)
    _вых = _вых or ""
    _добавлен = _вых.lower().count("номер") > _модель.lower().count("номер")
    chk("два элемента [%s]: номер добран=%s" % (_имя, _добор), _добавлен == _добор)
    chk("два элемента [%s]: просьб не больше двух" % _имя,
        server._просьб_данных(_вых) <= server._МАКС_ПРОСЬБ)

# АДРЕС УЖЕ ИЗВЕСТЕН — добор номера к окну возвращается, как и был
_MSGS_АДРЕС = _MSGS_ДВА[:2] + [
    {"role": "client", "text": "Канонерский остров, Двинская 14, кв 9"},
]
_вых_а, *_ = server._postprocess_reply(
    "да, выезжаю\nМогу сегодня, через час-полтора удобно?",
    _MSGS_АДРЕС, dict(_KR_ДВА), {}, False)
chk("адрес известен: к окну добирается номер", "номер" in (_вых_а or "").lower())
chk("адрес известен: повторно адрес не просим",
    not server._ADDRQ_RX.search(_вых_а or ""))

# счётчик считает именно ЭЛЕМЕНТЫ, а не знаки вопроса
chk("счётчик: окно+адрес = 2",
    server._просьб_данных("Могу через час-полтора удобно?\nАдрес подскажете?") == 2)
chk("счётчик: одно дело = 0", server._просьб_данных("да, чищу от залития") == 0)

# ── 10. ВОПРОС ПО ТИПУ ЗАПРОСА, А НЕ ПО НАПРАВЛЕНИЮ (находка 23.08) ──────────
# Клиент: «возможна ли у Вас установка приложений на айфон, которых нет в app store?
# И по стоимости?» Бот: «Здравствуйте. Как давно это началось?» — спросил про давность
# несуществующей поломки. Job-пулы в коде были, но отдавались ровно при direction=="mnc",
# то есть КП, БТ, ТВ и пустое направление обслуживали ЛЮБОЙ запрос поломочными вопросами.
# Замер: 200 хвостов из 200 на этой реплике пришли из поломочного пула.
_УСЛУГИ = ["возможна ли у Вас установка приложений на айфон, которых нет в app store?",
           "установить Windows на ноутбук", "нужно шкаф собрать",
           "повесить телевизор на стену", "установить смеситель", "заменить розетку",
           "надо люстру повесить", "подключить стиральную машину", "настроить роутер",
           "натяжной потолок снять и обратно поставить"]
_ПОЛОМКИ = ["не морозит", "стиралка течёт", "экран разбит", "полосы на экране",
            "гудит при отжиме", "висит на логотипе", "перестал холодить",
            "телевизор не показывает",
            # ⚠ СМЕШАННЫЕ: работа названа, но симптом сильнее — это ремонт, а не монтаж
            "поставил новую посудомойку, теперь не сливает",
            "установил кондиционер, а он не включается"]
for _t in _УСЛУГИ:
    chk("услуга опознана: " + _t[:34], prefilter.job_stated(_t))
for _t in _ПОЛОМКИ:
    chk("поломка не услуга: " + _t[:34], not prefilter.job_stated(_t))

# ...и главное — поведение: на услуге поломочных вопросов не бывает вовсе
_ПОЛОМОЧНЫЕ = ("случилось", "поломк", "не так", "давно это началось", "сломалось", "произошло")
for _t in ("возможна ли у Вас установка приложений на айфон?", "установить Windows на ноутбук"):
    _хвосты = set()
    for _i in range(40):
        _хвосты.add(server._ensure_question("Здравствуйте", False, False, False,
                                            problem_known=True, first_reply=True, direction="",
                                            seed="к%d" % _i, job=prefilter.job_stated(_t)))
    chk("на услуге нет вопроса о поломке: " + _t[:30],
        not any(w in h.lower() for h in _хвосты for w in _ПОЛОМОЧНЫЕ))
# ...а на поломке — наоборот, вопрос обязан быть про поломку
_хвосты_п = {server._ensure_question("Здравствуйте", False, False, False, problem_known=True,
                                     first_reply=True, direction="bt", seed="к%d" % _i,
                                     job=prefilter.job_stated("не морозит холодильник"))
             for _i in range(40)}
chk("на поломке вопрос про поломку",
    any(w in h.lower() for h in _хвосты_п for w in _ПОЛОМОЧНЫЕ))

# ── 11. САМАЯ КРУПНАЯ ОДИНОЧНАЯ ДОПИСКА (замер 24.08) ───────────────────────
# strip_logistics приписывала ОДНУ вшитую фразу «Что у вас случилось?» в 11,6% ходов —
# по объёму как вся воронка, и вариантов у неё было ноль. Каждая девятая реплика бота
# заканчивалась слово в слово одинаково, на всех аккаунтах сразу.
_ВАР = {prefilter.strip_logistics("да, помогу", seed="к%d|о%d|p%d" % (i, i % 11, i % 9))
        for i in range(120)}
chk("пул «что случилось» разнообразен", len(_ВАР) >= 4)
chk("ни один вариант не забирает больше трети",
    max(sum(1 for i in range(300)
            if prefilter.strip_logistics("да, помогу", seed="к%d" % i) == в)
        for в in _ВАР) / 300 < 0.34)
chk("внутри диалога формулировка стабильна",
    len({prefilter.strip_logistics("да, помогу", seed="один|и|тот|же") for _ in range(20)}) == 1)
# ⚠ КАЖДЫЙ ВАРИАНТ — ВОПРОС: по знаку «?» решает и сама функция, и воронка ниже.
chk("все варианты пула — вопросы", all("?" in в for в in prefilter.ЧТО_СЛУЧИЛОСЬ_POOL))
# ⚠ И НЕЙТРАЛЬНЫ ПО ПРЕДМЕТУ: «что случилось с техникой» нелепо на мебели и сантехнике,
# а МНЧ — пятая часть потока.
chk("ни один вариант не называет предмет",
    all(not any(w in в.lower() for w in ("техник", "прибор", "аппарат"))
        for в in prefilter.ЧТО_СЛУЧИЛОСЬ_POOL))
# ...и работа функции не изменилась: логистику по-прежнему режет
chk("логистика по-прежнему вырезается",
    "куда" not in prefilter.strip_logistics("да, помогу. Куда подъехать?", seed="к1").lower())

print("=" * 60)
print("Правила воронки (этап 2): %d/%d" % (ok, ok + bad))
sys.exit(1 if bad else 0)
