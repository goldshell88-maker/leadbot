# Этап 2: в дыре «окно есть, телефона нет» (1405 диалогов) оператор НЕ ПРОСИЛ номер
# вообще в 71.3% случаев (1002). Лид теряется не на отказе клиента, а на незаданном
# вопросе. Прямая просьба номера — приём с наибольшим устойчивым подъёмом: +13.2 п.п.
# к лиду [+11.3;+15.1], значим внутри КАЖДОГО из шести диспетчеров.
def _номер_дописан(reply, hp=False, pa_cnt=0, early=False):
    return server._добрать_номер(reply, hp=hp, pa_cnt=pa_cnt, early=early)


