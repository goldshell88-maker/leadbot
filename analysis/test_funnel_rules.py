# ⚠ ПРОВЕРЯЕМ СМЫСЛ ПО ВСЕМУ ПУЛУ, А НЕ ОДНО СЛОВО У ОДНОГО ВАРИАНТА (24.08).
# Раньше здесь стояло «в ответе есть слово „объём“» — это работало, пока ветка отдавала
# ровно одну фразу. Замер показал, чем это обошлось: `_снять_переспрос` заменил вопрос в
# 527 репликах из 3956, и 98,5% замен — одна строка «Марку и модель подскажите?». Она же
# стала концовкой 572 реплик (14,5%), хотя модель написала её лишь 95 раз. Теперь ветка
# отдаёт пул, и проверка обязана держать СМЫСЛ на КАЖДОМ варианте, а не форму на одном.
_СИДЫ = ["клиент%d|объявление%d|p%d" % (i, i % 7, i % 9) for i in range(60)]


def _все_шаги(направление, речь):
    return {server._снять_переспрос("Что у вас случилось?", True, направление, речь, seed=сид)
            for сид in _СИДЫ}


_техника = _все_шаги("bt", "не морозит холодильник")
chk("техника: пул разнообразен", len(_техника) >= 4)
chk("техника: КАЖДЫЙ вариант спрашивает марку или модель",
    all(("марк" in ш.lower() or "модел" in ш.lower()) for ш in _техника))
chk("техника: каждый вариант — вопрос", all("?" in ш for ш in _техника))
# ⚠ ЗНАК ВОПРОСА ТУТ НЕСУЩИЙ, А НЕ КОСМЕТИКА: по нему воронка ниже решает, дописывать ли
# СВОЙ вопрос. Шаг без «?» собрал бы поверх себя второй вопрос — ровно та перегруженность,
# ради которой пул и заведён. Тире запрещено стилевым слоем, а он к этому месту уже отработал.
for _имя, _пул in (("техника", server._ШАГ_ТЕХНИКА), ("точки", server._ШАГ_ТОЧКИ),
                   ("адрес", server._Q_ADDR)):
    chk("%s: все варианты пула — вопросы" % _имя, all("?" in в for в in _пул))
    chk("%s: в пуле нет тире" % _имя, all("—" not in в and " - " not in в for в in _пул))

_точки = _все_шаги("mnc", "нужно поставить розетку на кухне")
chk("электрика: пул разнообразен", len(_точки) >= 4)
chk("электрика: КАЖДЫЙ вариант спрашивает объём",
    all(any(w in ш.lower() for w in ("объём", "точек", "мест", "штук")) for ш in _точки))

_встреча = _все_шаги("mnc", "собрать шкаф из икеи")
chk("прочие работы: шаг к встрече, а не «сколько точек»",
    all("точек" not in ш.lower() for ш in _встреча))
chk("прочие работы: КАЖДЫЙ вариант спрашивает, куда приехать",
    all(any(w in ш.lower() for w in ("куда", "адрес", "территориальн")) for ш in _встреча))

# ⚠ И ГЛАВНОЕ, РАДИ ЧЕГО ПУЛ: ни одна формулировка не должна забирать себе большинство.
# До правки одна фраза забирала 98,5% замен и становилась концовкой каждой седьмой реплики.
_счёт = {}
for сид in ["к%d|о%d|p%d" % (i, i % 11, i % 9) for i in range(300)]:
    ш = server._снять_переспрос("Что у вас случилось?", True, "bt",
                                "не морозит холодильник", seed=сид)
    _счёт[ш] = _счёт.get(ш, 0) + 1
chk("ни один вариант не забирает больше трети",
    max(_счёт.values()) / sum(_счёт.values()) < 0.34)
# ...и внутри ОДНОГО диалога формулировка не пляшет: сид один — ответ один
chk("внутри диалога формулировка стабильна",
    len({server._снять_переспрос("Что у вас случилось?", True, "bt",
                                 "не морозит", seed="один|и|тот|же") for _ in range(20)}) == 1)
chk("задача НЕ названа — вопрос остаётся",
    "случилось" in server._снять_переспрос("Здравствуйте, что у вас случилось?",
                                           False, "").lower())
chk("осмысленный вопрос не трогаем",
    "марку" in server._снять_переспрос("да, возьмусь. Марку и модель подскажите?",
                                       True, "bt").lower())

# ── 7. РЕПЛИКА ПРО ФОТО — ОТВЕТ ПРО ФОТО, А НЕ ДИАГНОЗ ───────────────────────
# Клиент: «Фото не могу отправить пока вы не ответите (». Бот в бою: «похоже на
