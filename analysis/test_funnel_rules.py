# ── 2. ПИНГ НЕСЁТ СЛЕДУЮЩИЙ ШАГ, А НЕ ГОЛОЕ «АКТУАЛЬНО?» ─────────────────────
# Этап 2: 2029 диалогов у живых заканчиваются пингом «актуально?/в силе?» — это
# дешёвая замена работе. Подъём даёт не пинг, а конкретика: просьба номера +13.2 п.п.,
# вопрос про модель +7.5, «куда подъехать» +7.3.
def _пинг(есть_телефон, есть_окно, ключ="chat1|msg1"):
    return channel.ping_text(есть_телефон=есть_телефон, есть_окно=есть_окно, ключ=ключ)


