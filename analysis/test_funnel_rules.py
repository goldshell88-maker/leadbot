# ── 5. СОГЛАСУЕМАЯ ТЕМА: фраза из регламента вместо выдуманной ───────────────
# «По графику сверюсь» в регламенте НЕТ: согласование уходит «в чат филиала».
# По числам это худшая формулировка: отклик 47.5% против 90.9%, телефон 2.2%
