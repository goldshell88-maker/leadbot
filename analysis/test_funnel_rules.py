chk("без жалобы на фото ответ не трогаем",
    "контакт отошёл" in server._ответ_про_фото("контакт отошёл, гляну", "не включается", "bt"))

# ── 8. КЛИЕНТ НАЗВАЛ ВРЕМЯ — ВТОРОЕ ОКНО НЕ ПРЕДЛАГАЕМ (находка 23.08) ───────
# _TIME_RX отвечает на вопрос «время клиент уже назвал?». Он знал «сегодня/завтра/
# утром/вечером», но не знал ДНЕЙ НЕДЕЛИ и диапазонов часов. Замер: 10 форм из 24
