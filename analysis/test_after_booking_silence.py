# -*- coding: utf-8 -*-
"""ЗАЯВКА СОБРАНА — ДАЛЬШЕ БОТ МОЛЧИТ И ЖДЁТ ОПЕРАТОРА.

СЛОВО ВЛАДЕЛЬЦА 26.08, дословно: «если понятно, что заявка создана, на последующие
сообщения можно не отвечать и ждать, когда диалог примет оператор».

ЧТО БЫЛО НЕ ТАК. Роутер эскалации стоит ВЫШЕ заслона первичности и потому обходил его.
Эталон на живой выборке поймал два таких хода:

    клиент: «Здравствуйте, сегодня все в силе?»
    бот:    «Уточню по времени и вернусь к вам»          ← визит уже назначен

    клиент: «Я сегодня не успеваю, перенесем на завтра»
    бот:    «понял, перенесём. Уточню по своему графику»  ← то же самое

Мостик задумывался, чтобы клиент не висел в тишине. Но после записи тишина и есть
правильный ответ: время двигает тот, у кого график, а бот его не видит.

⚠ ЧЕЛОВЕКА ЗОВЁМ ПО-ПРЕЖНЕМУ. Молчание касается ТОЛЬКО текста клиенту: `notify_human`
остаётся, иначе диалог просто потеряется в очереди.

⚠ ДО ЗАПИСИ МОСТИК ОСТАЁТСЯ. Клиент, который спрашивает статус, НЕ договорившись о
визите, — это другой случай: там молчание читается как игнор.

Запуск: uv run python analysis/test_after_booking_silence.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

KR = {"visitor": "", "city": "Москва", "direction": "бт", "title": ""}
ошибки = []


def проверь(имя, условие, чем=""):
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:70]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


def ход(msgs):
    return s.run_relay([dict(m) for m in msgs], known=dict(KR))


ЗАПИСАН = [
    {"role": "client", "text": "Стиральная машина не отжимает"},
    {"role": "operator", "text": "здравствуйте, помогу. Куда подъехать?"},
    {"role": "client", "text": "Ленина 12, кв 5"},
    {"role": "operator", "text": "Записал вас на сегодня к 17:00, буду у вас"},
]

print("после записи — тишина")
for реплика in ("Здравствуйте, сегодня все в силе?",
                "Я сегодня не успеваю, перенесем на завтра я отпишусь!",
                "А во сколько точно приедете?"):
    r = ход(ЗАПИСАН + [{"role": "client", "text": реплика}])
    проверь("молчит на «%s»" % реплика[:36], not (r.get("reply_text") or "").strip(),
            r.get("reply_text"))
    проверь("но человека зовёт: «%s»" % реплика[:30], bool(r.get("notify_human")))

print("оператор уже ведёт разговор — тоже молчим (тот же заслон первичности)")
ЧУЖОЙ = [
    {"role": "client", "text": "Сколько стоит заменить подсветку на тв?"},
    {"role": "operator", "text": "Добрый\nот 500р\nпо адресу какому?"},
    {"role": "client", "text": "Сингапай"},
    {"role": "operator", "text": "улица и номер дома"},
    {"role": "client", "text": "Я пока интересуюсь, приблизительная цена нужна"},
    {"role": "operator", "text": "я написал вам сразу"},
    {"role": "client", "text": "Я сегодня не успеваю, перенесем на завтра я отпишусь!"},
]
r = ход(ЧУЖОЙ)
проверь("молчит в чужом диалоге без всякой записи",
        not (r.get("reply_text") or "").strip(), r.get("reply_text"))
проверь("и там человека зовёт", bool(r.get("notify_human")))

print("до записи мостик остаётся: молчание там читается как игнор")
БЕЗ_ЗАПИСИ = [
    {"role": "client", "text": "Стиралка не отжимает"},
    {"role": "operator", "text": "здравствуйте, помогу. Что случилось?"},
    {"role": "client", "text": "Сегодня все в силе?"},
]
r = ход(БЕЗ_ЗАПИСИ)
проверь("на тот же вопрос БЕЗ записи мостик остаётся",
        bool((r.get("reply_text") or "").strip()), r.get("reply_text"))

print("сам детектор записи")
проверь("«Записал вас на сегодня» — запись",
        bool(s._ВИЗИТ_НАЗНАЧЕН_RX.search("Записал вас на сегодня к 17:00")))
проверь("«буду у вас» — запись", bool(s._ВИЗИТ_НАЗНАЧЕН_RX.search("буду у вас в 17:00")))
проверь("«я у вас был» записью не считается",
        not s._ВИЗИТ_НАЗНАЧЕН_RX.search("вчера я у вас был, всё сделал"))
проверь("обсуждение без записи — не запись",
        not s._ВИЗИТ_НАЗНАЧЕН_RX.search("могу подъехать, когда вам удобно?"))

print()
if ошибки:
    print("ПРОВАЛЕНО: %d" % len(ошибки))
    for e in ошибки:
        print("  -", e)
    sys.exit(1)
print("Все проверки пройдены")
