# -*- coding: utf-8 -*-
"""Три правки по замеру, принятые владельцем 26.08 («сделай так, как будет лучше»).

Все три — не вкусовые: у каждой есть число, которое её оправдывает, и число, которое
показывает результат.

1. ПОТОЛОК ДЛИНЫ 110 ЗНАКОВ. Гнаться за медианой живых (39) бессмысленно: длину боту
   дают шаги воронки — окно и адрес, — а это самые ценные ходы. Зато на краю есть обрыв.
   Замер по живому корпусу Авито, самая крупная клетка (первый ход, клиент спросил цену,
   оператор ушёл от ответа, 1928 ходов) — доля ОТВЕТИВШИХ клиентов:
       ≤40 → 79,9 %   41–70 → 80,1 %   71–110 → 75,0 %   >110 → 68,2 % [59,0–76,1]
   До 110 разницы нет, выше — минус 12 пунктов, интервалы не пересекаются.
   У бота было >110 в 20 % ходов против 6 % у живых — втрое чаще. Стало 6 %.

2. ЦИФРА ЦЕНЫ НА ПЕРВОМ ХОДЕ, КОГДА НЕ СПРАШИВАЛИ. Первый ход с названной ценой даёт
   14,6 % до телефона при базе «без шага» 27,9 %. Но ТОЛЬКО когда не спрашивали: если
   спросили, цена нейтральна на первом ходе (20,7 % против базы 20,2 %) и ЛУЧШЕ ухода от
   ответа на втором (27,6 % против 20,9 %). Живой случай: «видеокарты ремонтируете?» →
   «берусь. Что с ней случилось? Ремонт видеокарты от 5000».

3. НОМЕР ВПЕРЁД АДРЕСА В ВОРОНКЕ. Разбор эталона: бот 23 раза добирал адрес и 9 раз
   номер, живой оператор — 1 и 1. Цена добавки против того же хода «без шага»:
       «номер» +23,6 п.п.        «адрес» +0,1 п.п.  ← ноль
   Адрес в одиночку не стоит ничего, и это подтверждено дважды: Авито 29,4 % при базе
   27,9 %, Jivo 13,1 % при базе 11,7 %.

Запуск: uv run python analysis/test_decisions_2608.py
Офлайн, 0 токенов.
"""
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import server as s                                      # noqa: E402

ошибки = []


def проверь(имя, условие, чем=""):
    print(("  ✓ " if условие else "  ✗ ") + имя + (("  → " + str(чем)[:80]) if not условие else ""))
    if not условие:
        ошибки.append(имя)


def дл(t):
    return len(" ".join((t or "").split()))


print("1. потолок длины: режем воду, не шаг")
ДЛИННАЯ = ("Понял, звук есть, изображения нет, похоже на подсветку, это чиним. "
           "Цену скажу точно после осмотра, по подсветке многое зависит от диодов. "
           "По какому адресу вы находитесь?")
_a = s._подрезать_длину(ДЛИННАЯ)
проверь("влезли в потолок", дл(_a) <= s._ПРЕДЕЛ_ДЛИНЫ, дл(_a))
проверь("вопрос-шаг остался", "?" in _a, _a)
проверь("приём работы остался", "чиним" in _a or "подсветк" in _a, _a)
проверь("вода снята", "диодов" not in _a, _a)

_b = s._подрезать_длину("Здравствуйте помогу со всем этим. Расценю на месте под вашу задачу, "
                        "объём разный у каждой позиции. Могу через час-полтора, удобно вам "
                        "будет? По какому адресу вы находитесь?")
проверь("окно не режем даже ради потолка", bool(s._ОКНО_В_РЕПЛИКЕ_RX.search(_b)), _b)
проверь("и адрес не режем", bool(s._ADDRQ_RX.search(_b)), _b)

for короткая in ("Да, помогу", "Здравствуйте, да, помогу с телевизором. Что именно случилось?"):
    проверь("короткую не трогаем: %s" % короткая[:40],
            s._подрезать_длину(короткая) == короткая)
_c = s._подрезать_длину("Записал вас на сегодня к 17:00, буду у вас, до встречи, "
                        "подтвержу перед выездом обязательно, чтобы вы никуда не ушли зря")
проверь("финал записи не режем", bool(s._BOOKED_REPLY_RX.search(_c)), _c)
проверь("пустоту не отдаём", s._подрезать_длину("а" * 300).strip() != "")

print("2. цифра цены без вопроса — только на первом ходе")
проверь("незваная цифра снята",
        "5000" not in s._снять_незваную_цену(
            "здравствуйте берусь. Что с ней случилось? Ремонт видеокарты от 5000",
            "Здравствуйте, видеокарты ремонтируете?", True))
проверь("остальное осталось",
        "случилось" in s._снять_незваную_цену(
            "здравствуйте берусь. Что с ней случилось? Ремонт видеокарты от 5000",
            "Здравствуйте, видеокарты ремонтируете?", True))
проверь("спросил про цену — не трогаем",
        "2000" in s._снять_незваную_цену("Чистка от 2000, точнее на месте",
                                         "Сколько примерно будет стоить почистка?", True))
проверь("«сколько это стоит» тоже считается вопросом",
        "1500" in s._снять_незваную_цену("Сборка от 1500", "Сколько это стоит?", True))
проверь("«бесплатно» не сумма — оставляем",
        "бесплатн" in s._снять_незваную_цену("сделаю. Выезд по городу для вас бесплатный",
                                             "Проблема с телевизором", True))
проверь("не первый ход — не трогаем",
        "5000" in s._снять_незваную_цену("Ремонт от 5000", "Ремонтируете?", False))
проверь("реплика из одной цены не пустеет",
        s._снять_незваную_цену("Ремонт видеокарты от 5000", "Ремонтируете?", True).strip() != "")

print("4. все три стоят НА ПУТИ, а не рядом с ним")
# ⚠ ЭТОТ РАЗДЕЛ ОБЯЗАТЕЛЕН. Дважды за сегодня я писал тест на функцию, снимал её вызов
# из конвейера — и тест оставался зелёным. Проверяем через `_postprocess_reply`, то есть
# ровно тем путём, которым реплика идёт в бою.
_KR = {"visitor": "", "city": "Москва", "direction": "кп", "title": ""}
_ПЕРВЫЙ = [{"role": "client", "text": "Здравствуйте, видеокарты ремонтируете?"}]
_вых3, *_ = s._postprocess_reply(
    "здравствуйте берусь. Что с ней случилось? Ремонт видеокарты от 5000",
    _ПЕРВЫЙ, dict(_KR), {}, True)
проверь("проводка: незваная цена снята конвейером", "5000" not in (_вых3 or ""), _вых3)

_ДЛИННЫЙ = [{"role": "client", "text": "Телевизор не показывает, звук есть"},
            {"role": "operator", "text": "здравствуйте, что случилось?"},
            {"role": "client", "text": "Изображения нет совсем"}]
_вых4, *_ = s._postprocess_reply(
    "Понял, звук есть, изображения нет, похоже на подсветку, это чиним. "
    "Цену скажу точно после осмотра, по подсветке многое зависит от диодов и от "
    "конструктива, тут заранее не угадаешь никак. По какому адресу вы находитесь?",
    _ДЛИННЫЙ, dict(_KR), {}, False)
# ⚠ ПОТОЛОК — НЕ ГИЛЬОТИНА. Если после снятия ВСЕЙ воды реплика всё ещё длинная,
# значит длину дают шаги (приём работы + вопрос), а их резать нельзя. Поэтому проводку
# проверяем по тому, что вода СНЯТА и текст стал короче, а не по числу на выходе.
проверь("проводка: вода снята конвейером",
        "диодов" not in (_вых4 or "") and "конструктив" not in (_вых4 or ""), _вых4)
проверь("проводка: реплика стала заметно короче", дл(_вых4) < 160,
        "%d знаков: %s" % (дл(_вых4), _вых4))

print("3. время известно — сначала адрес (инверсия 30.08)")
# ⚠ ИНВЕРСИЯ 30.08 (обучение на живом корпусе + слово владельца: «чтобы предложить
# время, мы должны знать адрес»). Прежний сторож 26.08 требовал номер первым (замер
# +23,6 п.п.), но правило 30.08 главнее: при обещанном времени адрес идёт вперёд —
# без него договорённость о времени слепая (вдруг клиент вне территории). Тот же
# порядок охраняет test_addr_before_time («номер уступает место адресу»).
_вых = s._ensure_question("да, помогу", has_addr=False, has_time=True, has_phone=False,
                          prior_bot="", problem_known=True, direction="кп", seed="x",
                          slot_offer="через час-полтора")
проверь("воронка просит адрес первым, когда время уже обещано",
        bool(s._ADDRQ_RX.search(_вых)), _вых)
_вых2 = s._ensure_question("да, помогу", has_addr=False, has_time=True, has_phone=True,
                           prior_bot="", problem_known=True, direction="кп", seed="x",
                           slot_offer="через час-полтора")
проверь("номер нельзя (правило трёх сообщений) — тогда адрес",
        bool(s._ADDRQ_RX.search(_вых2)), _вых2)

print()
if ошибки:
    print("ПРОВАЛЕНО: %d" % len(ошибки))
    for e in ошибки:
        print("  -", e)
    sys.exit(1)
print("Все проверки пройдены")
