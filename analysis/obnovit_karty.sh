#!/bin/sh
# Ежедневное обновление территорий филиалов с карт Яндекса.
#
# ⚠ ЗАЧЕМ РАСПИСАНИЕ. Владелец правит карты в Конструкторе постоянно, а выгрузку запускали
# руками — и никто не запускал. 27.08 проверка показала: карты КП и МНЧ правлены 20.08, файл
# бота был от 15.08. За эти дни бот не знал нового контура «ЛЮБЕРЦЫ» на МНЧ и обещал Видному,
# Одинцову, Гатчине и Кронштадту приезд ВДВОЕ быстрее, чем едет филиал.
#
# ⚠ ЗАПУСКАТЬ ТОЛЬКО НА СЕРВЕРЕ. С машины владельца yandex.ru недоступен (проверено: SSL-таймаут),
# и документированная команда там просто не отработает.
#
# Сама выгрузка отказывается записывать файл, если контуров подозрительно мало или направление
# пустое, — то есть худшее, что может случиться, это «territории остались вчерашними».
# ⚠ ИМЯ ПЕРЕМЕННОЙ ЛАТИНИЦЕЙ: на сервере /bin/sh это dash, и кириллическое имя
# он не принимает вовсе — «ЖУРНАЛ=…: not found» на первой же строке.
set -e
cd /opt/leadbot
LOG=/var/log/leadbot-karty.log
{
  echo "=== $(date '+%Y-%m-%d %H:%M:%S') обновление карт"
  python3 analysis/fetch_filial_zones.py 2>&1 | grep -vE "^   (city|satellite|outside)" || true
  echo
} >> "$LOG" 2>&1
# перезапуск нужен: zones() держит файл в памяти процесса и сама его не перечитывает
if systemctl is-active --quiet leadbot; then
  systemctl restart leadbot
  echo "  бот перезапущен, карты перечитаны" >> "$LOG"
fi
