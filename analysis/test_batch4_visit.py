# -*- coding: utf-8 -*-
"""ПАЧКА 4, часть 6 — ДЕНЬ НЕДЕЛИ В ЗАЯВКЕ (Э4, 21.08).

`_visit_from_reply` понимает только «сегодня / завтра / послезавтра». Между тем
плейбук сам велит называть день недели: «клиент говорит "на этой неделе" → НЕ
записывай размыто: конкретизируй ближайший подходящий день ("в субботу к 11")»,
и живой случай в разделе про запись — «Во вторник к 17:00-17:30 удобно?».

Что происходило: реплика «в субботу к 11:00» не совпадала ни с одним днём из
трёх, разбор уходил в запасную ветку «час без дня = СЕГОДНЯ», и в заявку уезжала
сегодняшняя дата. Клиенту обещана суббота, филиалу назначен вторник — промах до
шести суток, и виноватым остаётся мастер, который не приехал.

Запуск: uv run python analysis/test_batch4_visit.py   (0 токенов)
"""
import io
import os
import sys
import time

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "brain"))
import server      # noqa: E402
import territory   # noqa: E402

ok = bad = 0


def chk(label, cond):
    global ok, bad
    if cond:
        ok += 1
    else:
        bad += 1
        print("✗", label)


ГОРОД = "Москва"
СЕЙЧАС = territory.city_localtime(ГОРОД)
ДНИ = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]


def ждём(сдвиг):
    b = time.mktime((СЕЙЧАС.tm_year, СЕЙЧАС.tm_mon, СЕЙЧАС.tm_mday, 12, 0, 0, 0, 0, -1)) + сдвиг * 86400
    d = time.localtime(b)
    return "%02d-%02d-%04d" % (d.tm_mday, d.tm_mon, d.tm_year)


# ── прежнее поведение не сломано ────────────────────────────────────────────
for текст, сдвиг, час in [
    ("Хорошо, буду у вас сегодня к 17:00", 0, "17:00"),
    ("Сегодня уже занято, могу завтра к 11:00", 1, "11:00"),
    ("Давайте послезавтра к 9:30", 2, "09:30"),
]:
    д, ч = server._visit_from_reply(текст, ГОРОД)
    chk("прежнее: %s" % текст[:38], д == ждём(сдвиг) and ч == час)

# ── день недели считается по календарю ──────────────────────────────────────
for сдвиг_дней in range(7):
    цель = (СЕЙЧАС.tm_wday + сдвиг_дней) % 7
    имя = ДНИ[цель]
    падеж = {"среда": "среду", "пятница": "пятницу", "суббота": "субботу"}.get(имя, имя)
    д, ч = server._visit_from_reply("Давайте в %s к 14:00" % падеж, ГОРОД)
    chk("«в %s» → +%d дней" % (падеж, сдвиг_дней), д == ждём(сдвиг_дней) and ч == "14:00")

# обратный порядок слов
цель = (СЕЙЧАС.tm_wday + 3) % 7
падеж = {"среда": "среду", "пятница": "пятницу", "суббота": "субботу"}.get(ДНИ[цель], ДНИ[цель])
д, _ = server._visit_from_reply("Подъеду к 10:00 в %s" % падеж, ГОРОД)
chk("обратный порядок: «к 10:00 в %s»" % падеж, д == ждём(3))

# ── день недели не сваливается в «сегодня» даже без пары ────────────────────
цель = (СЕЙЧАС.tm_wday + 2) % 7
падеж = {"среда": "среду", "пятница": "пятницу", "суббота": "субботу"}.get(ДНИ[цель], ДНИ[цель])
д, ч = server._visit_from_reply("Во %s буду. Время к 16:00 подойдёт?" % падеж, ГОРОД) \
    if падеж.startswith("в") else server._visit_from_reply(
        "В %s буду. Время к 16:00 подойдёт?" % падеж, ГОРОД)
chk("день и час в разных предложениях — день не теряется", д == ждём(2))

# ── ничего не названо — по-прежнему пусто ───────────────────────────────────
д, ч = server._visit_from_reply("Приеду, посмотрю и скажу", ГОРОД)
chk("нет времени — нет даты", (д, ч) == ("", ""))

print("\nИТОГО: %d ок, %d провал" % (ok, bad))
sys.exit(1 if bad else 0)
