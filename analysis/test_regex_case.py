# -*- coding: utf-8 -*-
"""Предметные регексы не зависят от регистра: люди пишут с большой буквы.

НАХОДКА 26.08. `_TV_RX`, `_BT_BIG_RX`, `_KP_RX`, `_MNC_RX` были собраны БЕЗ
`re.IGNORECASE`, а заглавных литералов в их шаблонах нет ни одного — то есть регистр
ничего не различал, он просто терял слова. Живой диалог, с которого всё началось:
«Тв lg не переключает дальше, просто горит логотип» — `problem_stated` отвечала False,
и бот вырезал из своего ответа адрес и время, а вместо них дописывал «Что у вас
случилось?» человеку, который только что всё написал.

ЗАМЕР ПО 30 428 ЖИВЫМ ДИАЛОГАМ: `_TV_RX` не видел предмет в 611 (2,0 %), `_KP_RX` в
386, `_MNC_RX` в 215, `_BT_BIG_RX` в 99; итог по `problem_stated` — 406 диалогов
(1,3 %), где бот считал, что поломка не названа.

⚠ ПРОВЕРЯЕМ ПРИЧИНУ, А НЕ СЛЕДСТВИЕ. Тест на одну фразу «Телевизор» прошёл бы и
после того, как кто-нибудь допишет `.lower()` в одном вызывающем месте из шести.
Поэтому здесь проверяется флаг самого регекса и отсутствие заглавных букв в шаблоне:
пока литералы строчные, IGNORECASE обязателен, иначе слово теряется.

Запуск: uv run python analysis/test_regex_case.py
Офлайн, 0 токенов.
"""
import io
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(КОРЕНЬ, "brain"))
import prefilter as p                                   # noqa: E402

ПРЕДМЕТНЫЕ = ("_TV_RX", "_BT_BIG_RX", "_KP_RX", "_MNC_RX", "_PROBLEM_KNOWN_RX", "_РАБОТА_RX")
ошибки = []


def проверь(имя, условие):
    print(("  ✓ " if условие else "  ✗ ") + имя)
    if not условие:
        ошибки.append(имя)


print("флаги регексов")
for имя in ПРЕДМЕТНЫЕ:
    rx = getattr(p, имя)
    заглавные = re.findall(r"[A-ZА-ЯЁ]", rx.pattern)
    проверь("%s: без учёта регистра" % имя, bool(rx.flags & re.IGNORECASE))
    проверь("%s: в шаблоне нет заглавных литералов" % имя, not заглавные)

print("живые фразы, на которых это ловилось")
ЖИВЫЕ = [
    "Тв lg не переключает дальше, просто горит логотип",
    "Телевизор сони. Тарелка приставка МТС. После включения выходит на экран",
    "Принтер Pantum bm 2302",
    "Роутер хуавей ах1",
    "Щиток в квартире",
    "Холодильник Атлант",
    "ПК не включается",
    "Люстру повесить",
]
for т in ЖИВЫЕ:
    проверь("поломка названа: %s" % т[:44], p.problem_stated(т))

print("не ломаем обратное: болтовня по-прежнему пустая")
for т in ("Здравствуйте", "Вы бот?", "Добрый день!", "А вы кто"):
    проверь("не поломка: %s" % т, not p.problem_stated(т))

print()
if ошибки:
    print("ПРОВАЛЕНО: %d" % len(ошибки))
    for e in ошибки:
        print("  -", e)
    sys.exit(1)
print("Все проверки пройдены")
