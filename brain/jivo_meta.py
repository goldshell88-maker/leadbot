# -*- coding: utf-8 -*-
"""РАЗБОР СЛУЖЕБНОЙ МЕТКИ JIVO: партнёр, «белый» аккаунт, код источника, направление.

Jivo показывает в шапке диалога строку вида
    Авито • 🛑 ! Парт - 723 БЕЛЫЙ / Ист - Б3 МНЧ ! 🛑 - Мастер на час с выездом…
и она же приходит в вебхуке отдельной «страницей» (`payload.page.url`), рядом с настоящей
ссылкой на объявление Avito.

Зачем это боту:
  • ПАРТНЁР решает деньги. У 723 («белые» аккаунты) свои правила: «за услугу от 1000»,
    «выезд и диагностика 1000», и прямой запрет уходить от вопроса стоимости — то есть
    наша лестница с уводом без цифры там НЕ применяется. У партнёра 7 — наши обычные правила.
  • НАПРАВЛЕНИЕ в метке («Б3 МНЧ», «В71 БТ», «С82 КП») надёжнее, чем угадывание по заголовку
    объявления: заказчик проставляет его сам.

Живой поток (замер по 50 МБ сырых вебхуков): партнёр 7 — большинство, 723 БЕЛЫЙ — 305 диалогов,
плюс 340, 748, 007. Форматы метки гуляют: «Парт»/«Партнер», «/» или «!» как разделитель,
пробел перед «КП» иногда пропадает («С77 КП!»), номер бывает с нулями («007»).
"""
import re

# «! Парт - 723 БЕЛЫЙ / Ист - Б3 МНЧ !» либо «! Партнер - 7 ! Ист - С96 КП !»
_LABEL_RX = re.compile(r"парт(?:н[её]р)?\s*[-–—:]\s*(\d{1,4})\s*([А-Яа-яЁё]*)", re.I)
# до закрывающего «!»; «/» НЕ ограничитель — иначе у аккаунтов «С75 БТ/МНЧ» терялось
# второе направление, и двунаправленный источник выглядел как чисто БТ
_SOURCE_RX = re.compile(r"ист(?:очник)?\s*[-–—:]\s*([^!]+)", re.I)
_WHITE_RX = re.compile(r"бел\w*", re.I)
# направление в хвосте кода источника: «Б3 МНЧ», «В71 БТ», «C82 КП!», «С75 БТ/МНЧ»
_DIR_RX = re.compile(r"\b(КП|МНЧ|БТ)\b", re.I)

DIRECTION_MAP = {"кп": "kp", "мнч": "mnc", "бт": "bt"}


def parse_label(text):
    """Разбор одной метки. Возвращает dict или None, если это не метка."""
    t = (text or "")
    m = _LABEL_RX.search(t)
    if not m:
        return None
    partner = m.group(1).lstrip("0") or "0"          # «007» → «7»
    white = bool(_WHITE_RX.search(m.group(2) or "")) or bool(
        _WHITE_RX.search(t[m.end():m.end() + 12]))
    src = ""
    ms = _SOURCE_RX.search(t)
    if ms:
        src = re.sub(r"[\s!]+$", "", ms.group(1)).strip()
    dirs = [DIRECTION_MAP[d.lower()] for d in _DIR_RX.findall(src or t)
            if d.lower() in DIRECTION_MAP]
    return {"partner": partner, "white": white, "source": src,
            "directions": dirs, "direction": dirs[0] if len(dirs) == 1 else ""}


def from_pages(pages):
    """Ищем метку среди «страниц» визита (там же лежит и настоящая ссылка на объявление)."""
    for p in (pages or []):
        if not p:
            continue
        got = parse_label(p if isinstance(p, str) else str(p))
        if got:
            return got
    return None


def is_white(meta):
    """«Белый» аккаунт партнёра 723 — там подчёркнуто вежливое общение и свои цены."""
    return bool(meta) and (meta.get("partner") == "723" or meta.get("white"))
