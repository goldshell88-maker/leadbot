# -*- coding: utf-8 -*-
"""RAG-подсказка: на сообщение клиента подтягиваем ближайшие ЖИВЫЕ эталонные пары
«клиент → лучший ответ» из brain/rag_examples.json (BM25, чистый stdlib, 0 зависимостей).

Пул собирается analysis/build_rag_pool.py (успешные диалоги корпуса + правки заказчика
со страницы /review как «золото» — золото получает бонус в ранжировании)."""
import os
import re
import json
import math
import threading

_HERE = os.path.dirname(os.path.abspath(__file__))
_PATH = os.path.join(_HERE, "rag_examples.json")
_LOCK = threading.Lock()
_INDEX = None
_INDEX_MTIME = 0.0   # автоперечитка пула при изменении файла (ТЗ 3.5): пересобрали
_NB_MTIME = 0.0      # rag_examples.json / intent_nb.json — рестарт сервера не нужен


def _mtime(path):
    try:
        return os.path.getmtime(path)
    except OSError:
        return 0.0

_TOKEN_RX = re.compile(r"[а-яёa-z0-9]{3,}")
_STEM = 5


def _tokens(text):
    return [w[:_STEM] for w in _TOKEN_RX.findall((text or "").lower())]


def _build():
    try:
        data = json.load(open(_PATH, encoding="utf-8"))
    except Exception:
        return {"docs": [], "df": {}, "avgdl": 1.0}
    docs = []
    df = {}
    for ex in data.get("examples", []):
        toks = _tokens(ex.get("q", ""))
        if not toks:
            continue
        tf = {}
        for t in toks:
            tf[t] = tf.get(t, 0) + 1
        for t in tf:
            df[t] = df.get(t, 0) + 1
        docs.append({"tf": tf, "len": len(toks), "ex": ex})
    avgdl = sum(d["len"] for d in docs) / max(1, len(docs))
    return {"docs": docs, "df": df, "avgdl": avgdl}


def _index():
    global _INDEX, _INDEX_MTIME
    with _LOCK:
        m = _mtime(_PATH)
        if _INDEX is None or m != _INDEX_MTIME:
            _INDEX = _build()
            _INDEX_MTIME = m
        return _INDEX


def reload_index():
    global _INDEX
    with _LOCK:
        _INDEX = None


# ---- собственная NLU: наивный Байес-классификатор интента реплики (обучен на нашем корпусе,
# analysis/train_intent_nb.py). Связка NLU+LLM: NLU понимает ТИП реплики и направляет RAG-поиск. ----
_NB_PATH = os.path.join(_HERE, "intent_nb.json")
_NB = None


def _nb():
    global _NB, _NB_MTIME
    with _LOCK:
        m = _mtime(_NB_PATH)
        if _NB is None or m != _NB_MTIME:
            try:
                _NB = json.load(open(_NB_PATH, encoding="utf-8"))
            except Exception:
                _NB = {}
            _NB_MTIME = m
        return _NB


def classify_intent(text):
    """(класс, уверенность 0..1) или (None, 0) — своя NLU-модель, 0 внешних зависимостей."""
    nb = _nb()
    if not nb:
        return None, 0.0
    toks = _tokens(text)
    if not toks:
        return None, 0.0
    priors, vocab, fallback = nb["priors"], nb["vocab"], nb["fallback"]
    scores = dict(priors)
    for t in toks:
        row = vocab.get(t)
        for c in scores:
            scores[c] += (row.get(c) if row else None) or fallback[c]
    best = max(scores, key=scores.get)
    mx = scores[best]
    Z = sum(math.exp(v - mx) for v in scores.values())
    return best, 1.0 / Z


def retrieve(query, k=3, min_score=1.5):
    """Топ-k эталонов. BM25 + NLU-буст класса + золото заказчика ×1.3."""
    idx = _index()
    docs, df, avgdl = idx["docs"], idx["df"], idx["avgdl"]
    if not docs:
        return []
    n = len(docs)
    q = _tokens(query)
    if not q:
        return []
    icls, iconf = classify_intent(query)
    k1, b = 1.4, 0.6
    scored = []
    for d in docs:
        s = 0.0
        for t in q:
            f = d["tf"].get(t)
            if not f:
                continue
            idf = math.log(1.0 + (n - df[t] + 0.5) / (df[t] + 0.5))
            s += idf * f * (k1 + 1) / (f + k1 * (1 - b + b * d["len"] / avgdl))
        if s <= 0:
            continue
        if d["ex"].get("src") == "gold":
            s *= 1.3
        elif str(d["ex"].get("src") or "").startswith("этап7"):
            # ⚠ ДОКАЗАННЫЕ ПРИЁМЫ (этап 7 программы обучения). Это не «ещё примеры», а
            # четыре приёма, прошедшие ворота этапа 3: подъём к заявке с 95% интервалом
            # не через ноль, n≥30, значимость ВНУТРИ каждого диспетчера. Без веса они
            # тонули: 160 новых против 3980 старых не выигрывают лексическое сходство,
            # и замер до/после показал ровно нулевую разницу — пополнение было мёртвым.
            # Вес меньше золота владельца (1.3): его правки всё равно главнее.
            s *= 1.25
        elif d["ex"].get("src") == "dump":
            # Материал из чужой выгрузки (31 мастер) — расширяет покрытие там, где своих
            # примеров мало, но НЕ должен вытеснять наши. Всплывает, только если заметно
            # лучше подходит лексически. Сравнение до/после 31.07 показало: без штрафа
            # он местами подменял хорошие наши ответы более общими.
            s *= 0.75
        if icls and iconf >= 0.55 and d["ex"].get("class") == icls:
            s *= 1.15                                  # мягкий буст докам того же интента
        scored.append((s, d["ex"]))
    scored.sort(key=lambda x: -x[0])
    out, seen_a = [], set()
    for s, ex in scored:
        if s < min_score:
            break
        a5 = ex["a"][:60]
        if a5 in seen_a:
            continue
        seen_a.add(a5)
        out.append(ex)
        if len(out) >= k:
            break
    return out


# ⚠ ЛЮБОЕ число от трёх знаков, а не только «от NNN» и «NNN р». Прежний регекс не видел цифру в
# словесной обёртке («услуга в 1000 обойдётся», «1500 будет стоить», «Первичный осмотр 500»,
# «выезд и диагностика 2500») — и на ПЕРВОМ ценовом ходе пример подсовывал модели готовую сумму,
# схлопывая лестницу заказчика в один шаг. Время под него не попадает: ни «10:30», ни «11-11:30»,
# ни «к 12 часам» не дают трёх цифр подряд.
_DIGIT_REPLY_RX = re.compile(r"\d{3,}")
# «выезд бесплатный» — не цифра, поэтому гард цен его не видел, и на ценовые вопросы (в т.ч. по КП/ТВ,
# где выезд ПЛАТНЫЙ — 1000 с диагностикой) в примерах всплывало ложное коммерческое условие.
# Формулу показываем, только когда клиент сам заговорил о выезде/приезде/вызове/диагностике.
_FREE_VISIT_RX = re.compile(r"выезд.{0,25}бесплатн|бесплатн\w*.{0,15}выезд", re.IGNORECASE)
_VISIT_ASKED_RX = re.compile(r"выезд|приезд|приед|вызов|диагностик|осмотр", re.IGNORECASE)


#: ⚠ ПДн ЧУЖИХ КЛИЕНТОВ В ПРИМЕРАХ (найдено 21.08, разбор слепых зон).
#: rag_examples.json собран из живых диалогов: в нём лежали 14 «голых» 10-значных
#: телефонов и сотни адресов. note_for подставляет примеры в system КАЖДОГО хода,
#: то есть чужие ПДн уезжали в модель при каждом обращении. Прежняя маска ловила
#: только «+7…/8…»; десять цифр подряд проходили насквозь, адреса — вовсе.
#:
#: Маскируем ДВАЖДЫ: при сборке базы (analysis/mask_rag_pii.py) и здесь, на выдаче.
#: База пополняется, и один рубеж однажды забудут.
#:
#: Главная опасность маски — сожрать деловой текст: «Мойке 30 см», «Хайер 43 дюйма»,
#: «максимум 2000₽», «выезд 1000 рублей». Поэтому три прохода с разной строгостью.
_PII_PHONE_RX = re.compile(
    r"(?<!\d)(?:(?:\+?7|8)[\s\-()]*)?\d{3}[\s\-()]*\d{3}[\s\-()]*\d{2}[\s\-()]*\d{2}(?!\d)")
_PII_BARE_RX = re.compile(r"(?<!\d)\d{10,11}(?!\d)")

#: За номером дома не бывает единицы измерения — главный отсекатель ложных.
#: Однобуквенные единицы (м, г, л, р, в) берём ТОЛЬКО строчными: заглавная «В» —
#: это литера дома («пер. Д 11 В»), а не вольты.
_PII_UNIT = (r"см|мм|метр\w*|км|кг|гр|литр\w*|шт|штук\w*|руб\w*|тыс|"
             r"дюйм\w*|градус\w*|минут\w*|мин|час\w*|дн\w*|день|год\w*|лет|"
             r"вольт|ватт|вт|мл|куб|розет\w*|точ\w*")
_NE_UNIT = r"(?!\s*(?i:" + _PII_UNIT + r")\b)(?!\s*(?-i:м|г|л|р|в|шт)\b)"
_NE_UNIT_AMB = (r"(?!\s*(?i:" + _PII_UNIT.replace(r"|метр\w*", "") + r")\b)"
                + r"(?!\s*(?-i:м|г|л|р|шт)\b)")
#: «выезд 1000» и «код 123» — не адреса: маркер, приклеенный справа к букве, ложный.
#: А вот цифра слева («12кв.15», «1подьезд 37») — это номер дома, прилипший к маркеру.
_NE_БУКВА = r"(?<![а-яёА-ЯЁa-zA-Z])"
#: «под 10ку», «дом 5ый» — числительное, а не адрес. Прочие слипшиеся буквы
#: («подъезд 1эт», «этаж 318кв») наоборот означают продолжение адреса.
_NE_ЧИСЛИТ = r"(?!(?i:ку|ти|ый|ой|ая|ое|ым|го)\b)"
_НОМЕР_ДОМА = (r"\s*\.?\s*\d{1,4}(?!\d)(?:-[а-я]{1,2}\b|[а-я]\b)?(?:\s*/\s*\d+)?"
               + _NE_ЧИСЛИТ)

#: ПРОХОД 1а — улица и её родня. Тип улицы сказан прямо, поэтому число за ним —
#: всегда дом, и проверять единицы не нужно: «Проспект 50 лет Октября» иначе
#: не маскировался («лет» читалось единицей времени).
_PII_ADDR_RX = re.compile(
    _NE_БУКВА
    + r"(?:ул\.?|улиц\w*|пр-т|пр\.?|проспект|проезд|пер\.?|переул\w*|бульвар|шоссе|"
      r"мкр\.?|мкрн|микр\.?|микрорайон|наб\.?|набережная|тупик|аллея|линия)"
    + _НОМЕР_ДОМА,
    re.IGNORECASE)

#: ПРОХОД 1б — двусмысленные маркеры: «д», «под», «кв», «этаж» бывают предлогом
#: и сокращением. Здесь единицы проверяем: «под 45 градусов» — не подъезд.
_PII_ADDR_AMB_RX = re.compile(
    _NE_БУКВА
    + r"(?:д\.?|дом|зд\.?|корп\.?|корпус|кв\.?|квартир\w*|"
      r"подъезд|подьезд|под[’ʼ']езд|под\.?|пд\.?|этаж)"
    + _НОМЕР_ДОМА + _NE_UNIT_AMB,
    re.IGNORECASE)

#: ПРОХОД 2 — топоним со СВОИМ номером дома без маркера: «Рябиновая 14», «Южная 18к2».
#: Предохранители: номер похож на дом (две цифры либо дробь/литера), справа не единица
#: и не «.30» (время «После 18.30»), слева не техника и не ходовое слово.
#: IGNORECASE тут НЕ ставим: он обнуляет требование заглавной буквы, и под маску уходит
#: любое «слово + число» — проверено, «диагностика 1000 рублей» → «<адрес>0 рублей».
_PII_NOTSTREET = {
    "телевизор", "телевизора", "холодильник", "холодильника", "машина", "машинка",
    "плита", "плиты", "духовка", "духовки", "зеркало", "мойка", "мойке", "мойку",
    "раковина", "стиральная", "посудомоечная", "микроволновка", "варочная",
    "кондиционер", "котёл", "котел", "бойлер", "ноутбук", "монитор", "планшет",
    "модель", "цена", "цену", "стоимость", "ремонт", "диагональ", "серия",
    "сегодня", "завтра", "около", "примерно", "нужно", "итого", "всего",
    "минимум", "максимум", "порядка", "сумма", "выезд", "диагностика",
    "после", "часов", "числа", "время", "адрес",
}
_NE_ДЕНЬГИ = r"(?!\s*(?:₽|%|\d))(?![.:]\d)"
_PII_STREET_RX = re.compile(
    r"\b([А-ЯЁ][а-яё\-]{3,})\s+(\d{1,3}\s*/\s*\d+|\d{1,3}\s*к\s*\d+|\d{2,3}[а-я]?|\d{1,3}[а-я])"
    + _NE_ДЕНЬГИ + _NE_UNIT)

#: ПРОХОД 3 — свободная форма, но ТОЛЬКО при адресном контексте рядом.
#: «Сосновая 5, кв 14, под.2» и «Полевая,17 под.4» проходом 2 не берутся: дом
#: однозначный или отделён запятой. Ослаблять шаблон везде — резать деловой текст,
#: поэтому ослабляем там, где адрес уже виден: квартира, подъезд, этаж, домофон.
_PII_CONTEXT_RX = re.compile(
    r"<адрес>|(?i:" + _NE_БУКВА + r"(?:кв\.?|квартир\w*|подъезд|подьезд|под\.|пд|этаж|"
    r"домофон|ориентир|адрес|дом\b|корпус|подъехать|приезжайте))")
_PII_LOOSE_RX = re.compile(
    r"\b([А-ЯЁ][а-яё\-]{3,})[\s,]+(\d{1,3}(?:\s*[/к]\s*\d+)?[а-я]?)"
    + _NE_ДЕНЬГИ + _NE_UNIT)
#: «луговая52к3» — улица, слипшаяся с домом
_PII_GLUED_RX = re.compile(r"\b([А-Яа-яЁё][а-яё\-]{3,})(\d{1,3}(?:[к/]\d+)?[а-я]?)\b")

#: Прибирание за маской: россыпь меток схлопывается в одну, осиротевшее слово-маркер
#: и прилипший слева номер дома убираются — иначе читать невозможно.
_PII_GLUE_RX = re.compile(r"(?:<адрес>[\s,.;/\-]*)+<адрес>")
_PII_TAIL_RX = re.compile(
    r"\b(?:ул\.?|улиц\w*|дом|кв\.?|квартир\w*|подъезд|подьезд|этаж)\s*(?=<адрес>)",
    re.IGNORECASE)
_PII_ORPHAN_RX = re.compile(r"(?<!\d)\d{1,3}\s*(?=<адрес>)")


def _street_sub(m):
    return "<адрес>" if m.group(1).lower() not in _PII_NOTSTREET else m.group(0)


def mask_pii(text):
    """Убирает из текста телефоны и адреса, оставляя суть обращения.

    Цену, размер и модель НЕ трогаем: маскируются только номера телефонов
    (в любом формате, включая десять цифр подряд) и адресные конструкции.
    """
    t = str(text or "")
    t = _PII_PHONE_RX.sub("<номер>", t)
    t = _PII_BARE_RX.sub("<номер>", t)
    t = _PII_ADDR_RX.sub("<адрес>", t)
    t = _PII_ADDR_AMB_RX.sub("<адрес>", t)
    t = _PII_STREET_RX.sub(_street_sub, t)
    if _PII_CONTEXT_RX.search(t):
        t = _PII_LOOSE_RX.sub(_street_sub, t)
        t = _PII_GLUED_RX.sub(_street_sub, t)
    t = _PII_TAIL_RX.sub("", t)
    t = _PII_ORPHAN_RX.sub("", t)
    for _ in range(3):                      # «<адрес> <адрес> <адрес>» → «<адрес>»
        t = _PII_GLUE_RX.sub("<адрес>", t)
    return re.sub(r"[ \t]{2,}", " ", t).strip()


def note_for(last_client, k=2, avoid_price_digits=False, direction="", white=False):
    # k=2 (было 3, ТЗ 3.5): двух эталонов хватает для вариативности тона, третий добавлял
    # ~80 тк некэшируемого входа на ход (~1 400 ₽/мес @868). Живая проба после смены — зелёная.
    """Готовый system-блок с примерами (или пустая строка). avoid_price_digits=True на
    ПЕРВОМ ценовом ходе: примеры с цифрами не показываем, чтобы не ломали лестницу заказчика.

    direction/white — направление диалога и «белый» партнёр 723. «Выезд по городу бесплатный» —
    формула МНЧ у партнёра 7; в КП, БТ и на белом действует «выезд и диагностика 1000, при
    выполнении работ бесплатно». Пул этого не различает и различать не может: в паре
    «Выезд платный?» → «выезд по городу бесплатный» предмета нет, и fix_known_slips из
    build_rag_pool её не чинит, — значит режем на ВЫДАЧЕ, где направление уже известно."""
    visit_asked = bool(_VISIT_ASKED_RX.search(last_client or ""))
    # ⚠ ФОРМУЛА «ПРИ ОТКАЗЕ 1000» ЖИВЁТ ТОЛЬКО НА КП (слово владельца 18.08; здесь код
    # отстал от него на сутки). Раньше сюда входило и БТ — значит на бытовой технике из
    # примеров вырезалась ПРАВИЛЬНАЯ бесплатная формула, и модель училась говорить про
    # 1000 там, где выезд бесплатный. Белый партнёр 723 — отдельный случай, у него
    # формула обязательна и в МНЧ.
    paid_visit = bool(white) or (direction or "").lower() == "kp"
    exs = retrieve(last_client,
                   k=k + (3 if (avoid_price_digits or not visit_asked or paid_visit) else 0))
    if avoid_price_digits:
        exs = [e for e in exs if not _DIGIT_REPLY_RX.search(e["a"])]
    if not visit_asked:
        exs = [e for e in exs if not _FREE_VISIT_RX.search(e["a"])]
    elif paid_visit:
        # формулу оставляем только в ПОЛНОМ виде — с условием про 1000 при отказе от работ
        exs = [e for e in exs if not _FREE_VISIT_RX.search(e["a"]) or "1000" in e["a"]]
    exs = exs[:k]
    if not exs:
        return ""
    lines = ["ЖИВЫЕ ПРИМЕРЫ ПОХОЖИХ СИТУАЦИЙ (возьми ХОД и ТОН, перефразируй под контекст, дословно "
             "не копируй). ⚠ Жёсткие правила выше (лестница цены, запреты, озвучки) ГЛАВНЕЕ примеров — "
             "если пример им противоречит, следуй правилам:"]
    for ex in exs:
        tag = " [эталон заказчика]" if ex.get("src") == "gold" else ""
        lines.append("• К: «%s» → О%s: «%s»"
                     % (mask_pii(ex["q"])[:150], tag, mask_pii(ex["a"])[:200]))
    return "\n".join(lines)
