def _has(rx, t):
    return bool(rx.search(t or ""))


def detect(last_client, all_client_text="", bot_history="", booked=False, known=None):
    """Признак эскалации в последней реплике клиента → {reason, reply, silent} или None.

    last_client   — последняя реплика (по ней решаем);
    all_client_text — вся речь клиента (для контекста «была ли заявка»);
    bot_history   — прежние реплики бота (обещали ли мы приезд);
    booked        — заявка уже создана/подтверждена;
    known         — контекст канала: booked / lead_id / has_lead, если канал их знает.

    Порядок внутри детектора — от самого дорогого к самому дешёвому: сначала то, что
    грозит деньгами и репутацией, потом организационное."""
    t = delatin((last_client or "").strip())
    if not t:
        return None
    # ЗАМОК: есть ли в этом диалоге запись. Четыре признака ниже без него не срабатывают —
    # именно он, а не сужение регексов, отсекает «перенести розетку», «вы где находитесь»
    # и «на 12 августа может мастер приехать» (разбор 50 эскалаций 12.08).
    booked_state = bool(booked) or visit_state(all_client_text or last_client,
                                               bot_history, known)

    # 1. Предыдущий мастер — РАНЬШЕ претензии: «прошлый мастер деньги взял» формально
    # попадает и под претензию, но это другой случай. Мы не знаем, наш это был мастер или
    # чужой, и обязаны не давать гарантий по непроверенному факту — а претензия молчит.
    if _has(_PRIOR_MASTER_RX, t):
        return _mk("prior_master")
    # 2. Претензия. Деньги и порча — самоочевидны (платить было за что). Оценочные
    # «некачественно», «халтура» — только при записи: без неё это рассказ о ЧУЖОЙ работе
    # и обычно новая заявка («в общежитии некачественно сделано, трубы забиты»).
    if (_has(_CLAIM_HARD_RX, t) and not _has(_CLAIM_NEGATED_RX, t)
            and not _has(_FEAR_QUESTION_RX, t)) \
            or (_has(_CLAIM_SOFT_RX, t) and booked_state):
        return _mk("claim")
    # 3. Срыв визита — раньше статуса: «мастер не приехал» это уже не вопрос, а инцидент.
    # Сам оборот доказывает, что визит назначали, поэтому замок здесь не нужен.
    if _has(_NO_SHOW_RX, t) or (_has(_NO_SHOW_SOFT_RX, t) and booked_state):
        return _mk("no_show")
    # 4. Отказ от заявки
    if (_has(_CANCEL_RX, t) or (_has(_CANCEL_SOFT_RX, t) and booked_state)) \
            and not _has(_CANCEL_ELSEWHERE_RX, t):
        return _mk("cancel")
    # 5. Перенос. Переносят ВРЕМЯ, а не предмет: «перенести розетку» это монтаж.
    # Однозначный оборот («перенесите визит») сам доказывает, что визит есть, — он проходит
    # без замка. Мягкий («давайте лучше завтра») — только при записи, иначе это выбор слота.
    _resched_core = (_has(_RESCHEDULE_CORE_RX, t) and not _has(_MOVE_OBJECT_RX, t)
                     and not _has(_MEASURE_RX, t)
                     and (_has(_TIME_WORD_RX, t) or _has(_VISIT_WORD_RX, t)))
    if _resched_core or _has(_RESCHEDULE_HARD_RX, t) \
            or (_has(_RESCHEDULE_SOFT_RX, t) and booked_state):
        return _mk("reschedule")
    # 6. Статус визита. «Будем вас ждать» — подтверждение, а не вопрос; «вы где находитесь» —
    # гео-вопрос новичка; «может мастер приехать 12-го» — запрос слота, а не статус.
    if not _has(_WAIT_CONFIRM_RX, t) and not _has(_GEO_QUESTION_RX, t) \
            and not _has(_SLOT_REQUEST_RX, t) and (
            _has(_STATUS_HARD_RX, t) or (_has(_STATUS_SOFT_RX, t) and booked_state)):
        return _mk("status")
    # 7. Недовольство: агрессия ЛИБО недовольство по уже сделанной работе.
    # Ругань рядом с названием техники адресована технике: «ноутбук тупой какой-то».
    if (_has(_AGGRESSION_RX, t) and not _has(_TECH_NEAR_RX, t)) \
            or (_has(_AFTER_WORK_RX, t) and _negative(t) and booked_state):
        return _mk("discontent")
    return None


_VISIT_RX = re.compile(r"запис\w*|подъед\w*|приед\w*|буду\s*у\s*вас|\bк\s*\d{1,2}[:.]\d{2}|"
                       r"договорил\w*\s*(?:на|о)\s", re.IGNORECASE)
_NEG_RX = re.compile(r"не\s*работает|хуже|плохо|недоволен|недовольна|возмут|безобраз|"
                     r"так\s*и\s*не|опять|снова\s*слома", re.IGNORECASE)


def _visit_discussed(ctx):
    return bool(_VISIT_RX.search(ctx or ""))


def _negative(t):
    return bool(_NEG_RX.search(t or ""))


def _mk(reason):
    return {"reason": reason, "label": REASONS[reason],
            "reply": REPLIES.get(reason, ""), "silent": reason in SILENT}


def event(reason, note=""):
    """Событие эскалации для ответа и журнала. Одна форма на всех потребителей."""
    return {"reason": reason, "label": REASONS.get(reason, reason),
            "deadline_min": deadline_min(reason), "note": (note or "")[:200]}
