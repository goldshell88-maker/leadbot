# ── латиница ────────────────────────────────────────────────────────────────
# В корпусе люди регулярно пишут по-русски латиницей («kholodilnik ne rabotaet»,
# «otmenite zayavku»). Для детекторов это тот же текст, поэтому приводим его к кириллице.
# Только когда кириллицы в реплике НЕТ вовсе: иначе покалечим марки (LG, Bosch, Haier).
_TRANSLIT = [("shch", "щ"), ("sch", "щ"), ("yo", "ё"), ("zh", "ж"), ("kh", "х"), ("ts", "ц"),
             ("ch", "ч"), ("sh", "ш"), ("yu", "ю"), ("ya", "я"), ("ye", "е"),
             ("a", "а"), ("b", "б"), ("v", "в"), ("g", "г"), ("d", "д"), ("e", "е"),
             ("z", "з"), ("i", "и"), ("j", "й"), ("k", "к"), ("l", "л"), ("m", "м"),
             ("n", "н"), ("o", "о"), ("p", "п"), ("r", "р"), ("s", "с"), ("t", "т"),
             ("u", "у"), ("f", "ф"), ("h", "х"), ("c", "ц"), ("y", "ы"), ("w", "в"),
             ("x", "кс"), ("q", "к"), ("'", ""), ("`", "")]
_CYR_RX = re.compile(r"[а-яё]", re.IGNORECASE)
_LAT_RX = re.compile(r"[a-z]{3,}", re.IGNORECASE)


def delatin(text):
    """Латиница-по-русски → кириллица. Приблизительно: нам нужны попадания регексов,
    а не красивый текст, поэтому «skolko» превращается в «сколко» и это нормально —
    детекторы ниже написаны терпимо к мягкому знаку."""
    t = text or ""
    if _CYR_RX.search(t) or not _LAT_RX.search(t):
        return t
    low = t.lower()
    for a, b in _TRANSLIT:
        low = low.replace(a, b)
    return low


