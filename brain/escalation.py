# Четыре признака — статус, перенос, срыв визита и претензия к нашей работе — предполагают,
# что запись УЖЕ существует. Запирать их на словах бессмысленно: «перенести выключатель» и
# «перенести визит» отличаются не формулировкой, а тем, есть ли что переносить. Отсюда замок.
#
# ⚠ ДВА КЛЮЧА, И ВТОРОЙ ОБЯЗАТЕЛЕН. Историю чата бот видит по-разному: свой канал Авито даёт
# 50 последних сообщений (переживает разрыв, потому что тянется у Авито), а LeadChat присылает
# ПОСЛЕДНИЕ ДЕСЯТЬ (context_messages, дефолт 10) — запись, сделанная пятнадцатью репликами
# раньше, туда просто не попадёт. Поэтому кроме следов в истории смотрим на то, что от истории
# не зависит: телефон клиента, признак заявки от вызывающей стороны и ссылку самого клиента
# на договорённость («у нас запись на 11»).
_CLOCK_RX = re.compile(r"\b\d{1,2}[:.]\d{2}\b|\bк\s*\d{1,2}\b(?!\s*(?:метр|км|кг))")
_BOOKED_BOT_RX = re.compile(r"запис(?:ал|ала|ываю|ал\s*вас)|запишу\s*вас|буду\s*у\s*вас|"
                            r"подъеду\s*(?:сегодня|завтра|к\s*\d)", re.IGNORECASE)
# клиент сам ссылается на существующую договорённость — работает даже без нашей истории
_CLIENT_REFS_BOOKING_RX = re.compile(
    r"у\s*(?:нас|меня)\s*(?:сегодня\s*|завтра\s*)?запис|договорил\w*\s*(?:на|с\s*вами)|"
    r"должен\s*был\s*(?:прие|подъе|быть)|записыва\w*\s*(?:меня|нас)|"
    r"мастер\s*(?:должен|обещал|приезжал|приходил)|вы\s*(?:же\s*)?обещали|"
    r"(?:ваш|наш)\s*мастер\s*(?:был|приезжал|приходил|сделал)|"
    # работа уже была: клиент сам это говорит, и это тоже доказательство записи —
    # ключ, который работает даже когда историю чата нам не показали
    r"после\s*ремонта|уже\s*(?:чинили|ремонтировали|приезжал|делали)|"
    r"пришлось\s*переделыв|неделю\s*назад\s*чинили|вчера\s*(?:чинили|приезжал)",
    re.IGNORECASE)


def visit_state(client_all="", bot_history="", known=None):
    """Есть ли в этом диалоге признаки уже существующей записи или заявки."""
    known = known or {}
    if known.get("booked") or known.get("lead_id") or known.get("has_lead"):
        return True                              # прямой признак от канала — самый надёжный
    bh = delatin(bot_history or "")
    if _BOOKED_BOT_RX.search(bh) or _CLOCK_RX.search(bh):
        return True                              # мы уже назначали или предлагали время
    ca = delatin(client_all or "")
    if _CLIENT_REFS_BOOKING_RX.search(ca):
        return True                              # клиент ссылается на договорённость
    # ⚠ ТЕЛЕФОН — НЕ ДОКАЗАТЕЛЬСТВО ЗАПИСИ (аудит 18.08, critical). Номер бот
    # выпрашивает САМ на стадии добора данных: клиент даёт его и тут же
    # спрашивает «когда приедете?» — самый обычный оборот свежего лида. Пока
    # телефон стоял в признаках, этот замок открывался, мягкие ветки статуса и
    # переноса срабатывали без всякой записи, и лид уходил человеку с
    # «Уточню по времени и вернусь к вам» вместо предложенного окна. Ровно то,
    # что запрещает комментарий 13.08 двумя абзацами выше.
    return False


