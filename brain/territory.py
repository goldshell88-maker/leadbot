def city_localtime(city, now=None):
    # Локальные часы КЛИЕНТА: time.struct_time его города (для тестов свой now).
    import time as _t
    base = now if now is not None else _t.time()
    return _t.gmtime(base + city_tz_offset(city) * 3600)

