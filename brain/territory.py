    # ГОРОДА НЕТ В СПРАВОЧНИКЕ ЭТОГО НАПРАВЛЕНИЯ: филиал заявку не выполнит, идём на согласование
    if far_trip_ctx and no_filial(city, far_trip_ctx.get("direction", "")):
        return {"lead": "два, два с половиной часа", "urgent": "в течение двух часов",
                "earliest": "11:00", "latest": "21:30", "needs_approval": True,
                "zone": "в этом направлении филиала в городе нет (%s)" % city}
    if _norm(city) in SETTLEMENT_CITIES:      # город, принимаемый по правилам населённого пункта
        return {"lead": "два, два с половиной часа", "urgent": "в течение двух часов",
                "earliest": "11:00", "latest": "21:30", "needs_approval": True,
                "zone": "населённый пункт (приём как за чертой города)"}
