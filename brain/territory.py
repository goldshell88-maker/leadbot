def _near36_index():
    """Название населённого пункта → {филиал: км}.

    ⚠ Именно СЛОВАРЬ филиалов, а не «ближайший». Тёзок в России очень много (Ивановское,
    Чёрная, Отрадное), и если хранить одну пару, то «село Ивановское» из пермского диалога
    сматчится с подмосковным Ивановским и даст приём вместо согласования."""
    global _NEAR36_INDEX
    if _NEAR36_INDEX is None:
        idx = {}
        for filial, d in (near36().get("filials") or {}).items():
            for s in d.get("settlements") or []:
                n = _norm(s.get("name"))
                if not n:
                    continue
                by = idx.setdefault(n, {})
                km = s.get("km", 999)
                if filial not in by or km < by[filial]:
                    by[filial] = km
        _NEAR36_INDEX = idx
    return _NEAR36_INDEX


def far_trip(client_text="", city="", direction="", topic_text=""):
    """Клиент в зоне дальнего выезда КП (≤36 км от основного филиала)?

    Возвращает (филиал, км) либо None. Работает ТОЛЬКО для КП — так велел заказчик.
    """
    try:
        import filials
        if not filials.far_trip_allowed(direction):
            return None
        # ⚠ У ГОРОДА МОЖЕТ НЕ БЫТЬ ДАЛЬНЕГО ВЫЕЗДА ВОВСЕ (правило владельца 27.08 по Белгороду:
        # «заявки за территорией принимаются по согласованию с филиалом»). Радиус 36 км там не
        # применяется ни при каких условиях — за чертой города решает филиал, а не расстояние.
        if filials.no_far_trip(city, direction):
            return None
    except Exception:
        return None
    # ⚠ ГОРОД С КОНТУРОМ — ИСКЛЮЧЕНИЕ. «Все города, у которых есть кастомная разметка, принимаются
    # строго по ней, вне этой разметки будет согласование» (правило заказчика 01.08.2026).
    # Радиус 36 км там неприменим: территорию задаёт контур, а не расстояние до филиала.
    if city_has_map(city, direction):
        return None
    # ⚠ ТВ — ИСКЛЮЧЕНИЕ (правило заказчика 01.08.2026): «для ТВ нет дальнего выезда, ТВ принимается
    # либо на спутник, либо на основной филиал». ТВ — сквозная тема: он идёт во все три
    # направления по одному регламенту, поэтому метка «КП» сама по себе права на 36 км не даёт.
    try:
        import prefilter
        if prefilter._TV_RX.search(((topic_text or "") + " " + (client_text or "")).lower()):
            return None
    except Exception:
        pass
    data = filial_coords()
    if not data:
        return None
    limit = 36
    try:
        limit = filials.FAR_TRIP_KM
    except Exception:
        pass
    # 1) точно: координаты адреса против центров филиалов
    try:
        import geocode
        pt = geocode.geocode((client_text or "").strip(), city)
    except Exception:
        pt = None
    if pt:
        best = None
        for filial, d in data.items():
            if d.get("lat") is None:
                continue
            km = _haversine_km(pt[0], pt[1], d["lat"], d["lon"])
            if best is None or km < best[1]:
                best = (filial, km)
        # ⚠ Пустая выборка (все филиалы «строго по карте») — не выдаём ложный дальний выезд
        if best is None:
            return None
        if best and best[1] <= limit:
            return best[0], round(best[1], 1)
        if best:
            return None                      # координаты есть и они ДАЛЬШЕ 36 км — вопрос закрыт
    # 2) ЗАПАСНОЙ ПУТЬ — только когда геокодер промолчал: клиент сам назвал населённый пункт.
    #
    # ⚠ ИМЯ ИЗ СПИСКА ИСКАТЬ ПО ВСЕМУ ТЕКСТУ НЕЛЬЗЯ. Замер по корпусу (6347 диалогов) показал,
    # что среди 11 712 названий в зоне 36 км полно обычных русских слов: деревня «Добрый»
    # совпадала с «Добрый день» в 35 диалогах, плюс «Новый», «Новая», «Красное», «Старая»,
    # «Северный», «Чёрная», «16 км». Такой лид получил бы приём вместо согласования — то есть
    # заявку, которую филиал не выполнит. Поэтому имя засчитываем ТОЛЬКО сразу за маркером
    # населённого пункта, как люди и пишут: «Село Дрокино», «деревня Концово», «СНТ Восход».
    #
    # ⚠ И ВТОРОЕ: имя обязано принадлежать ФИЛИАЛУ ЭТОГО ЖЕ ДИАЛОГА. Тёзок в России очень много
    # («село Ивановское», «Чёрная», «Отрадное» есть у десятков филиалов), и без этой сверки
    # пермский лид получал бы приём по подмосковному однофамильцу.
    own = {_norm(city)}
    try:
        import filials as _f
        _par = _f.satellite_of(city, direction)
        if _par:
            own.add(_norm(_par))
    except Exception:
        pass
    if not city:
        return None                          # не с чем сверять — на приём не отпускаем
    for m in _NAMED_SETTLEMENT_RX.finditer(client_text or ""):
        by = _near36_index().get(_norm(m.group(1))) or {}
        for filial, km in by.items():
            if _norm(filial) in own:
                return filial, km
    return None


def _haversine_km(a_lat, a_lon, b_lat, b_lon):
    import math
    r = 6371.0088
    p1, p2 = math.radians(a_lat), math.radians(b_lat)
    dp, dl = math.radians(b_lat - a_lat), math.radians(b_lon - a_lon)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(h))


def city_profile_from_map(city, direction=""):
    """Что карта говорит о ГОРОДЕ целиком, без привязки к точке клиента.

    ⚠ ДВА РАЗНЫХ ВОПРОСА, И ПУТАТЬ ИХ НЕЛЬЗЯ. «Где клиент» без адреса не узнать никак. А «что
    карта говорит про этот город» — узнать можно и без адреса: у Адлера один контур «АДЛЕР ЗА
    2,5 ЧАСА», и время приёма это городской факт, а не точечный.
    Отдаём ответ, ТОЛЬКО если все контуры города согласны между собой: у Петербурга их четыре
    с разными правилами, и «город целиком» там не определён — значит и врать не будем.
    """
    if not city:
        return None
    имена = {_norm(city)}
    try:
        import filials
        имена |= filials.имена_города(city)
    except Exception:
        pass
    свои = [a for a in ((zones() or {}).get("areas") or [])
            if (not direction or a.get("direction") == direction)
            and _norm(a.get("city")) in имена and a.get("zone") != "outside"]
    if not свои:
        return None
    зоны = {a.get("zone") for a in свои}
    сроки = {a.get("lead") for a in свои}
    if len(зоны) > 1 or len(сроки) > 1:
        return None                       # контуры спорят — городского ответа нет
    a = свои[0]
    return {"city": city, "direction": a.get("direction") or direction, "name": a.get("name") or "",
            "zone": a.get("zone") or "city", "lead": a.get("lead"),
            "earliest": a.get("earliest"), "msk": bool(a.get("msk")),
            # ⚠ ПОМЕТКА ОБЯЗАТЕЛЬНА: этот профиль про ГОРОД, а не про точку клиента, и
            # потребитель должен уметь их различать — см. slot_profile.
            "по_городу": True}


def map_profile(city, client_text, direction=""):
    """Профиль территории ПО КАРТЕ (или None, если карта этот адрес не покрывает).

    ⚠ Зачем отдельно от resolve(): resolve сводит богатый ответ карты к одному булеву «за чертой»,
    и всё остальное — зона «спутник», «ЗА 3 Часа», московский столбец прайса — терялось.
    Клиент из контура «СЕРПУХОВ (ЗА 2-2.5)» получал обещание «час-полтора» (находка TERR-2).
    """
    loc = locate_by_text(client_text, city, direction)
    if loc and loc.get("zone") != "unknown":
        return loc
    # ⚠ АДРЕСА НЕТ — НО ГОРОД МЫ ЗНАЕМ. Точку клиента без адреса не выдумываем, а вот правило
    # приёма самого города карта даёт и так: у Адлера один контур «АДЛЕР ЗА 2,5 ЧАСА», и без
    # этого ответа бот обещал бы Адлеру час-полтора по умолчанию справочника.
    return city_profile_from_map(city, direction)


def slot_profile_from_map(loc):
    """Карта → тот же словарь, что отдаёт slot_profile, чтобы вызывающий код не различал источник."""
    if not loc:
        return None
    zone = loc.get("zone")
    lead = loc.get("lead") or "час-полтора"
    early = loc.get("earliest") or "10:00"
    urgent = "в течение часа" if lead.startswith("час") else (
        "в течение трёх часов" if lead.startswith("три") else "в течение двух часов")
    if zone == "outside":
        human = "вне размеченной территории филиала (%s)" % (loc.get("name") or "по согласованию")
    elif zone == "satellite":
        human = "город-спутник по карте (%s)" % (loc.get("name") or loc.get("city") or "")
    else:
        human = "черта города по карте (%s)" % (loc.get("name") or loc.get("city") or "")
    # ⚠ СПУТНИК ИЗ СПРАВОЧНИКА ЗАКАЗЧИКА ПЕРЕБИВАЕТ УМОЛЧАНИЕ КАРТЫ ПО ВРЕМЕНИ.
    # Карта решает, ПРИНИМАЕМ ли мы точку (контур — это территория), но время она задаёт не всегда:
    # у контура «ХИМКИ» на карте МНЧ времени в названии нет, и парсер ставит «час-полтора», тогда
    # как в списках заказчика Химки — СПУТНИК Москвы, то есть два-два с половиной часа и с 11:00.
    # Явную метку («ПРИНИМАЕМ ЗА 2,5 ЧАСА») это не трогает: там zone уже satellite.
    if zone == "city" and lead == "час-полтора":
        try:
            import filials
            if filials.satellite_of(loc.get("city"), loc.get("direction")):
                lead, early, urgent = ("два, два с половиной часа", "11:00", "в течение двух часов")
                human = "город-спутник по справочнику, в контуре карты (%s)" % (
                    loc.get("name") or loc.get("city") or "")
        except Exception:
            pass
    return {"lead": lead, "urgent": urgent, "earliest": early, "latest": "21:30",
            "needs_approval": zone == "outside", "zone": human, "source": "карта",
            "msk": bool(loc.get("msk"))}


def note(city, outside_city=False, loc=None, far_trip_ctx=None, lead_ok=True, window=""):
    """Короткая строка для системного промпта — что можно и за сколько на этой территории.

    ⚠ lead_ok — ВЫПОЛНИМ ЛИ «ближайший приезд» ПРЯМО СЕЙЧАС (правка 24.08). Раньше строка
    «Ближайшее время приезда — „час-полтора“ (именно так и озвучивай)» уходила в промпт в
    ЛЮБОЙ час суток. В 21:15 это приказ пообещать приезд в 22:45 при собственной планке
    приёма 21:30, а в 03:00 — приезд в 04:30. Приказ невыполним в 12 часах суток из 24, и
    ровно на эти часы приходится 35.7% заявок.
    Хуже того, в том же абзаце системы рядом лежало правильное «завтра к 10:00-10:30» из
    `_clock_note`: два противоречащих указания в одном месте, и модель слушала первое.

    Решать здесь, внутри territory, нельзя: развилка «через сколько» против «к какому часу»
    живёт в `server._slot_state`, и вторая её копия разъехалась бы с первой. Поэтому вызывающий
    передаёт готовый ответ: lead_ok=False плюс `window` — то самое окно, которое надо озвучить.
    """
    closed = is_closed(city)
    if closed:
        return ("ТЕРРИТОРИЯ: %s — %s. ЗАЯВКИ НА ЭТОТ ГОРОД НЕ ПРИНИМАЮТСЯ. Клиенту ничего не "
                "обещай, время не называй: ответь «по графику сверюсь и чуть позже дам ответ», "
                "возьми номер и поставь handoff_to_human=true." % (city, closed))
    p = slot_profile(city, outside_city, loc, far_trip_ctx)
    col = price_column(city)
    # ⚠ ГОРОД НЕИЗВЕСТЕН — НЕ УТВЕРЖДАЕМ НИЧЕГО. Раньше при пустом городе сюда уходило
    # «ТЕРРИТОРИЯ: черта города … Город региональный — цены по базовому столбцу»: два УТВЕРЖДЕНИЯ
    # про зону и про деньги при полном незнании, где клиент. По корпусу это 18.6% потока
    # (ссылка без города: объявление открыто из профиля). Спрашивать город запрещено, поэтому
    # честный ход — не обещать время и не называть столбец, а вести к адресу.
    if not city and not loc:
        return ("ТЕРРИТОРИЯ: город из объявления НЕ ИЗВЕСТЕН. Не утверждай, что клиент в черте "
                "города, и НЕ называй конкретных сумм из прайса — столбец зависит от города. "
                "Город НЕ спрашивай (запрет плейбука): веди к адресу — из него всё станет ясно. "
                "Про время говори осторожно: «подъеду, как освобожусь, давайте подберём окно».")
    bits = ["ТЕРРИТОРИЯ: %s%s." % (p["zone"], (" (%s)" % city) if city else "")]
    if p["needs_approval"]:
        bits.append("Клиент ВНЕ черты города — заявку сам НЕ подтверждай: это согласование "
                    "с филиалом независимо от источника. Собери адрес и номер, скажи «по графику "
                    "сверюсь и вернусь с ответом», handoff_to_human=true. Про километры и "
                    "платность выезда не заговаривай.")
    elif outside_city and p["zone"].startswith("дальний выезд"):
        # правило заказчика 01.08.2026: на КП это ПРИНИМАЕМАЯ заявка, а не согласование
        bits.append("Клиент за чертой города, но филиал рядом — заявку принимай САМ, согласование "
                    "не нужно. Про километры и платность выезда клиенту не говори: это наша "
                    "внутренняя мерка.")
    if lead_ok:
        bits.append("Ближайшее время приезда — «%s» (именно так и озвучивай). Самая ранняя заявка на "
                    "%s, самая поздняя на %s; раньше или позже — только через человека."
                    % (p["lead"], p["earliest"], p["latest"]))
        bits.append("Клиент торопит («срочно», «сейчас») → «Буду у вас %s, постараюсь как можно "
                    "раньше»." % p["urgent"])
    else:
        # ЧАС УЖЕ НЕ ТОТ. «Через час-полтора» сейчас означало бы приезд позже самой поздней
        # заявки (или посреди ночи), поэтому предлагать надо КОНКРЕТНОЕ окно, а не срок.
        bits.append("⛔ «%s» СЕЙЧАС НЕ ОЗВУЧИВАЙ: приезд через этот срок выйдет позже самой "
                    "поздней заявки (%s). Ближайшее выполнимое окно — «%s», его и предлагай."
                    % (p["lead"], p["latest"], window or "по графику сверюсь и вернусь с ответом"))
        bits.append("Клиент торопит («срочно», «сейчас») → приезд немедленно НЕ обещай: "
                    "«%s удобно вам будет?». Нужен выезд раньше — только через человека."
                    % (window or "ближайшее окно уточню"))
    if col == "msk":
        bits.append("Город МОСКОВСКИЙ — все цены бери из МОСКОВСКОГО столбца прайса (он в скобках "
                    "«МСК»), региональные суммы тут занижены.")
    else:
        bits.append("Город региональный — цены по базовому столбцу прайса, «МСК»-суммы НЕ называй.")
    return " ".join(bits)
