def _norm(city):
    return (city or "").strip().lower().replace("ё", "е")


_MAP_CITIES = {}


def _split_city_name(name):
    """«Электросталь-Ногинск» → {электросталь-ногинск, электросталь, ногинск}.

    Заказчик подписывает один контур на два города, а клиент приходит из объявления ОДНОГО
    из них — иначе половина составного контура осталась бы «не размеченной»."""
    out = set()
    n = _norm(name)
    if not n:
        return out
    out.add(n)
    for part in re.split(r"[-–—/]", n):
        part = part.strip()
        if len(part) > 3:
            out.add(part)
    return out


def cities_on_map(direction=""):
    """Города, у которых есть СВОЙ КОНТУР на карте этого направления.

    ⚠ ПРАВИЛО ЗАКАЗЧИКА 01.08.2026, дословно: «все города, у которых есть кастомная разметка,
    принимаются СТРОГО по ней, вне этой разметки будет согласование». То есть контур — это и
    есть территория филиала, и правило дальнего выезда 36 км к таким городам НЕ применяется:
    клиент в 20 км от филиала, но вне контура — согласование, а не дальний выезд.
    Границы КП, МНЧ и БТ разные, поэтому набор считается ПО НАПРАВЛЕНИЮ."""
    key = (direction or "").lower()
    if key not in _MAP_CITIES:
        out = set()
        for a in ((zones() or {}).get("areas") or []):
            if key and a.get("direction") != key:
                continue
            out |= _split_city_name(a.get("city"))
        # ⚠ ИМЕНА С КАРТЫ РАСКРЫВАЕМ В ИМЕНА СПРАВОЧНИКА. «Спб» с контура должен находиться и
        # как «Санкт-Петербург», иначе набор городов карты и набор городов справочника никогда
        # не пересекутся — а именно на этом пересечении держится правило «строго по контуру».
        try:
            import filials
            for имя in list(out):
                out |= filials.имена_города(имя)
        except Exception:
            pass
        _MAP_CITIES[key] = out
    return _MAP_CITIES[key]


def city_has_map(city, direction=""):
    """У города есть размеченный контур → принимаем строго по нему.

    ⚠ СРАВНИВАЕМ ПО ВСЕМ ИМЕНАМ ГОРОДА, А НЕ ПО ОДНОМУ. Карта подписана так, как удобно
    владельцу («СПБ 1», «СПБ3»), справочник и карточка говорят «Санкт-Петербург» — и семь
    контуров Петербурга на трёх картах были боту недоступны (проверено 27.08). Словарь имён
    живёт в `filials.имена_города`: там же составные контуры на два города.
    """
    на_карте = cities_on_map(direction)
    if _norm(city) in на_карте:
        return True
    try:
        import filials
        return bool(filials.имена_города(city) & на_карте)
    except Exception:
        return False


def _msk_from_map():
    """Города с пометкой «(МСК)» прямо на карте заказчика — источник правды по столбцу прайса.

    ⚠ СОСТАВНЫЕ ИМЕНА КОНТУРОВ РАЗБИРАЕМ НА ЧАСТИ. Заказчик подписывает один контур на два
    города — «Электросталь-Ногинск (МСК)», «Раменское-Жуковский (МСК)», — а клиент приходит
    из объявления ОДНОГО из них. Без разбора Ногинск и Жуковский получали РЕГИОНАЛЬНЫЙ столбец
    прайса, то есть заниженную цену и спор на месте.
    """
    out = set()
    for a in ((zones() or {}).get("areas") or []):
        if not (a.get("msk") and a.get("city")):
            continue
        name = _norm(a["city"])
        out.add(name)
        for part in re.split(r"[-–—/]", name):
            part = part.strip()
            if len(part) > 3:
                out.add(part)
    return out


def price_column(city):
    """'msk' — московский столбец прайса, 'region' — базовый.

    Приоритет у карты: если контур помечен «(МСК)», город московский. Статический список
    остаётся запасным — он работает, пока карты не выгружены."""
    c = _norm(city)
    return "msk" if (c in _msk_from_map() or c in {_norm(x) for x in MSK_FILIAL}) else "region"


_SPEECH_MSK_RX = None


def price_column_from_speech(text):
    """Столбец прайса по городу, ПРОЗВУЧАВШЕМУ В РЕЧИ, — для диалогов с пустой карточкой.

    ⚠ Карточка объявления пуста у четверти диалогов (в ссылке-мессенджере Avito города
    физически нет — server.py об этом честно пишет клиентскому блоку), а столбец прайса
    выбирался ТОЛЬКО по карточке: москвич, назвавший город в переписке, получал
    региональные цены, и корректор «чинил» верную московскую сумму модели вниз.
    Аудит 15.08.

    Вопрос здесь ровно один — московская сеть или нет, поэтому ищем по ЗАКРЫТОМУ набору
    городов сети (карта + статический список), целыми словами, с той же нормализацией,
    что у price_column. Не нашли — «region», как и было: ошибиться «в регион» безопасно,
    это прежнее поведение.
    """
    global _SPEECH_MSK_RX
    if not (text or "").strip():
        return "region"
    if _SPEECH_MSK_RX is None:
        names = _msk_from_map() | {_norm(x) for x in MSK_FILIAL}
        alts = sorted({_declined(n) for n in names if len(n) >= 4}, key=len, reverse=True)
        _SPEECH_MSK_RX = re.compile(
            r"(?<![а-яa-z0-9])(?:%s)(?![а-яa-z0-9])" % "|".join(a for a in alts if a)
        ) if alts else re.compile(r"(?!x)x")
    return "msk" if _SPEECH_MSK_RX.search(_norm(text)) else "region"


def _declined(name):
    """Шаблон имени города со СКЛОНЕНИЯМИ: клиенты пишут «в Химках», «в Подольске»,
    а набор городов — в именительном. Окончания перечислены ЯВНО, а не жадным хвостом:
    жадный хвост ловил бы «посадку» на «Посаде» и «видно» на «Видном».
    У многословных («Сергиев Посад») склоняется последний токен — по нему и ищем."""
    last = name.split()[-1].split("-")[-1]
    if len(last) < 4:
        return re.escape(name)  # короткое — только точная форма, без вольностей
    if last.endswith(("ки", "щи", "цы", "ши")):      # Химки, Мытищи → в Химках, из Мытищ
        return re.escape(last[:-1]) + r"(?:и|ах|ам|ами)?"
    if last.endswith("ое"):                          # Видное → в Видном (голое «видно» не наше)
        return re.escape(last[:-2]) + r"(?:ое|ом|ого|ому)"
    if last.endswith(("а", "я")):                    # Истра, Балашиха → в Истре
        return re.escape(last[:-1]) + r"(?:а|я|е|и|у|ю|ой|ей)"
    if last.endswith("о"):                           # Домодедово → в Домодедове
        return re.escape(last[:-1]) + r"(?:о|е|а|у)"
    # согласная: Подольск, Серпухов, Клин → в Подольске, под Серпуховом
    return re.escape(last) + r"(?:а|е|у|ом|ым)?"


_CITY_RULES = {}


def map_city_rules(direction=""):
    """Правила приёма, написанные заказчиком МЕТКОЙ на карте: {город: {lead, earliest, mark}}.

    ⚠ Метки — второй способ, которым заказчик задаёт время, и до 01.08.2026 бот их не видел
    вовсе (виджет карты их не отдаёт, они есть только на странице карт). Из них берутся
    «КЛИН ЗА 2,5 ЧАСА», «КРОНШТАДТ ЗА 2,5 ЧАСА», «ГАТЧИНА ЗА 2.5 ЧАСА» — города без своего контура.
    Города, у которых контур ЕСТЬ, сюда не попадают: их точно решает карта, а правило по имени
    только огрубило бы ответ (у Сочи собственный контур «СОЧИ ЗА 1,5 ЧАСА»)."""
    key = (direction or "").lower()
    if key not in _CITY_RULES:
        out = {}
        for r in ((zones() or {}).get("city_rules") or []):
            if key and (r.get("direction") or "").lower() != key:
                continue
            c = _norm(r.get("city"))
            if not c or city_has_map(c, key):
                continue
            cur = out.get(c)
            if cur is None or _LEAD_RANK.get(r.get("lead"), 0) > _LEAD_RANK.get(cur["lead"], 0):
                out[c] = {"lead": r.get("lead"), "earliest": r.get("earliest") or "11:00",
                          "mark": r.get("mark")}
        _CITY_RULES[key] = out
    return _CITY_RULES[key]


_LEAD_RANK = {"час-полтора": 1, "два, два с половиной часа": 2, "три часа": 3}


