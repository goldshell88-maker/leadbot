# -*- coding: utf-8 -*-
"""ТЕНЕВОЙ ЖУРНАЛ: что написал клиент, что ответил оператор, что ответил бы бот и почему.

ЗАЧЕМ. Владелец не пускает бота в бой и видит только его реплику в ленте. По одной
реплике нельзя понять, ПОЧЕМУ она такая: какой слой её решил, на какой стадии воронки
диалог, чего боту не хватает и чем его ход отличается от хода живого оператора. Этот
файл делает решение видимым: одна строка JSON на каждый ход, и её можно смотреть живьём
`tail -F`, как консольный лог.

⚠ ЖУРНАЛ НЕ ИМЕЕТ ПРАВА УРОНИТЬ ХОД. Любая ошибка записи гасится: наблюдение не стоит
ни одного потерянного ответа клиенту. По той же причине здесь нет сети и нет блокировок
между процессами — только дозапись в конец файла, которую ОС делает атомарно для
коротких строк.

⚠ ПЕРСОНАЛЬНОЕ НЕ ПИШЕМ ЛИШНЕГО. В журнал идут тексты переписки — они и так лежат в
базе панели, — но телефон в реплике клиента маскируется: файл смотрят с ноутбука, и
он живёт дольше диалога.

Выключается `LEADBOT_SHADOW=0`. Файл — `data/shadow.jsonl`, ротация по размеру.
"""
import io
import json
import os
import re
import time

_КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ФАЙЛ = os.environ.get("LEADBOT_SHADOW_FILE") or os.path.join(_КОРЕНЬ, "data", "shadow.jsonl")
ПРЕДЕЛ = int(os.environ.get("LEADBOT_SHADOW_MAX_MB", "20")) * 1024 * 1024
ВКЛЮЧЁН = os.environ.get("LEADBOT_SHADOW", "1") not in ("0", "нет", "off")

_ТЕЛЕФОН = re.compile(r"(?:(?:\+?7|8)[\s\-()]*)?\d{3}[\s\-()]*\d{3}[\s\-()]*\d{2}[\s\-()]*\d{2}(?!\d)")


def маска(текст):
    """Телефон в журнал не пишем: последние четыре цифры оставляем для узнавания."""
    def _з(m):
        цифры = re.sub(r"\D", "", m.group(0))
        return "тел…" + цифры[-4:] if len(цифры) >= 4 else "тел…"
    return _ТЕЛЕФОН.sub(_з, текст or "")


def _ротация():
    try:
        if os.path.exists(ФАЙЛ) and os.path.getsize(ФАЙЛ) > ПРЕДЕЛ:
            старый = ФАЙЛ + ".1"
            if os.path.exists(старый):
                os.remove(старый)
            os.replace(ФАЙЛ, старый)
    except Exception:
        pass


def пиши(**поля):
    """Одна строка журнала. Ничего не возвращает и ничего не бросает."""
    if not ВКЛЮЧЁН:
        return
    try:
        поля.setdefault("ts", time.strftime("%Y-%m-%dT%H:%M:%S"))
        os.makedirs(os.path.dirname(ФАЙЛ), exist_ok=True)
        _ротация()
        with io.open(ФАЙЛ, "a", encoding="utf-8") as f:
            f.write(json.dumps(поля, ensure_ascii=False) + "\n")
    except Exception:
        pass


def ход(messages, known, res, out=None, ms=None, стадия="", источник="leadchat"):
    """Собрать и записать ход. Всё, что может отсутствовать, отсутствует молча."""
    if not ВКЛЮЧЁН:
        return
    try:
        msgs = [m for m in (messages or []) if (m.get("text") or "").strip()]
        клиент = next((m["text"] for m in reversed(msgs) if m.get("role") == "client"), "")
        свои = list((known or {}).get("prior_self") or [])
        # ⚠ «ЧТО ОТПРАВИЛ ОПЕРАТОР ВМЕСТО МОЕЙ ПОДСКАЗКИ» — ПРИБЛИЖЕНИЕ, И ЭТО ЧЕСТНО.
        # Подсказки приходят отдельным полем без отметок времени, поэтому сопоставить их
        # с репликами оператора по часам нельзя. Берём последнюю реплику оператора в
        # переписке: если подсказка уже была, именно она и стоит на её месте. Ошибка
        # возможна там, где оператор писал дважды подряд, — сверка это подпишет.
        оператор = ""
        if свои:
            оператор = next((m["text"] for m in reversed(msgs)
                             if m.get("role") != "client"), "")
        реплика = (res or {}).get("reply_text") or (res or {}).get("reply") or ""
        # ⚠ ПРОБЕЛЫ ВХОДА НАЗЫВАЕМ ВСЛУХ. Первый же боевой ход 26.08 пришёл без города
        # и без объявления — а без города бот не имеет права называть окно, и самый
        # сильный ход воронки (26,0 % против базы 11,7 % по 23 159 первым ходам) просто
        # не случается. В ответе это выглядит как «бот вяло отвечает», хотя виноват вход.
        пробелы = []
        if not (known or {}).get("city"):
            пробелы.append("нет города — окно назвать нельзя")
        if not (known or {}).get("title"):
            пробелы.append("нет объявления — направление неизвестно")
        пиши(вид="ход",
             источник=источник,
             чат=str((known or {}).get("key") or (known or {}).get("chat_id") or ""),
             город=(known or {}).get("city") or "",
             направление=(known or {}).get("direction") or "",
             тема=((known or {}).get("title") or "")[:80],
             клиент=маска(клиент)[:600],
             оператор=маска(оператор)[:600],
             подсказка_до=маска(свои[-1])[:600] if свои else "",
             бот=маска(реплика)[:600],
             стадия=стадия,
             слой=(res or {}).get("model") or "",
             почему=(res or {}).get("note") or "",
             передал=bool((res or {}).get("notify_human") or (res or {}).get("handoff")),
             причина=((res or {}).get("escalation") or {}).get("reason") or "",
             не_хватает=list((res or {}).get("missing") or []),
             заявка=bool((res or {}).get("lead_ready")),
             # ⚠ ВИД ЗАЯВКИ, А НЕ ТОЛЬКО ФАКТ (26.08): «полная» и «прозвон» требуют от
             # человека разных действий, и по журналу их надо различать без чтения кода.
             вид_заявки=((res or {}).get("lead") or {}).get("вид") or "",
             пробелы=пробелы,
             ходов=len(msgs),
             мс=ms)
    except Exception:
        pass
