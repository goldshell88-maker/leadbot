def kp_price_block():
    """Прайс КП для третьей ступени лестницы. Московской колонки у КП нет — суммы едины."""
    rows = "; ".join(
        "%s %d" % (label, price_for(key)) for label, key in _KP_BLOCK_ITEMS if price_for(key)
    )
    return (
        "ПРАЙС КП (третья ступень лестницы — клиент требует точную сумму; правило лестницы "
        "в разделе 6): " + rows + ". Видеокарта/пайка ЖК — от 5000, приставки — от 1500 "
        "(эти два озвучиваются сами, правило раздела 6 в силе). Числа не выдумывай: чего "
        "нет в списке — «по месту скажу»."
    )


def price_for(name, msk=False):
    """Каноническая сумма работы (или None, если такой работы в прайсе нет)."""
    for n, reg, m, _rs, _ms, _rx in TABLE:
        if n == name:
            return (m if (msk and m) else reg)
    return None


def _allowed(entry, msk):
    name, reg, m, rs, ms, _rx = entry
    if msk and m:
        return ms, m
    return rs, reg


def _с_начала_слова(rx, t):
    """Первое совпадение шаблона, начинающееся с начала слова. Нет такого — None.

    Хвост слова не проверяем: шаблоны прайса — основы и обязаны брать падежи
    («смеситель», «смесителя»). Проверяется только левая граница.
    """
    for m in rx.finditer(t or ""):
        i = m.start()
        if i == 0 or not (t[i - 1].isalpha()):
            return m
    return None


