#: ⚠ ПРИМЕТА ИЩЕТСЯ С НАЧАЛА СЛОВА, А НЕ ПОДСТРОКОЙ ГДЕ ПОПАЛО (замер 26.08).
#: Здесь стоял голый `t.find(w)`, и на 9742 живых первых сообщениях он дал 7027 попаданий
#: ВНУТРЬ чужих слов. Два из них массовые и оба портили «Вид работ» в карточке CRM:
#:     «тв»   — 6369 раз, из них 5548 внутри слова «здравствуйте» (здравс-ТВ-уйте);
#:     «кран» — 608 раз внутри «экран»: телевизор с битым экраном уезжал в сантехнику.
#: Тот же класс, что «соо-ТВ-етственно» и «\bсколько» внутри «скол», которые проект уже ловил.
#: Хвост слова не запрещаем — приметы это ОСНОВЫ и обязаны брать падежи («кран», «краны»).
_НАЧАЛО_СЛОВА = r"(?<![а-яa-z])"
#: Аббревиатуре хвост запрещён отдельно: «\bтв» без этого ловит «твой» и «твёрдый».
_ЦЕЛЫМ_СЛОВОМ = {"тв"}
#: Слова, которые начинаются с приметы, но предметом не являются. Собраны замером по
#: живому корпусу, а не придуманы: без них правка меняла бы один ложный ответ на другой.
_НЕ_ПРЕДМЕТ = {
    "плит": r"плитк",                       # плитка это отделка, а не плита
    "стол": r"столь|столк|столб|столов[аоы]",   # «столько», «столкнул», «столб», «столовая»
    "кран": r"крайн",                       # опечатка «крайне» в «кран» не превращается
}
_ПРИМЕТА_RX = {}
for _слова, _к in КАТЕГОРИИ:
    for _w in _слова:
        _ядро = re.escape(_w.replace("ё", "е"))
        _хвост = r"(?![а-яa-z])" if _w in _ЦЕЛЫМ_СЛОВОМ else ""
        _ПРИМЕТА_RX[_w] = re.compile(_НАЧАЛО_СЛОВА + _ядро + _хвост)
_НЕ_ПРЕДМЕТ_RX = {k: re.compile(_НАЧАЛО_СЛОВА + v) for k, v in _НЕ_ПРЕДМЕТ.items()}


def objects_in(text):
    """Названные предметы (по порядку появления) — запасной источник тем для заявки.

    Отвечает на вопрос «о чём вообще речь», когда в прайсе точной работы нет:
    «отремонтировать кровать» прайсу неизвестно, а предмет назван прямо.
    Возвращает ПРИМЕТУ, а не категорию: примета точнее и в справочнике CRM
    сначала пробуется она (см. crm.build_patch).
    """
    t = (text or "").lower().replace("ё", "е")
    найдено = []
    for слова, _категория in КАТЕГОРИИ:
        for w in слова:
            m = _ПРИМЕТА_RX[w].search(t)
            if not m:
                continue
            стоп = _НЕ_ПРЕДМЕТ_RX.get(w)
            if стоп and стоп.match(t, m.start()):
                continue
            найдено.append((m.start(), w))
            break
    найдено.sort()
    return [w for _i, w in найдено]


#: Позиции прайса, которых в справочнике «Вид работ» не бывает: это плата, а не работа.
_НЕ_ВИД_РАБОТ = frozenset({"выезд и диагностика"})


def with_categories(темы):
    """Темы + их категории справочника CRM, приметы первыми.

    ⚠ РАСШИРЯЕМ ЗДЕСЬ, А НЕ У ПОТРЕБИТЕЛЯ. Потребителей два и живут они в РАЗНЫХ
    языках: серверный crm.build_patch (Python) и расширение Chrome (offscreen.js).
    У расширения своей копии словаря нет и быть не должно — иначе правка примет
    доедет до одного и не доедет до другого. Раскрываем один раз, в лиде, и оба
    получают готовый список.

    Приметы идут ПЕРЕД категориями: если в справочнике города есть точная позиция
    («Кровать»), она должна выиграть у общей («Мебель»).
    """
    # ⚠ СБОР ЗА ВЫЕЗД — НЕ ВИД РАБОТ (замер очереди 26.08). В карточки уезжала тема
    # «выезд и диагностика», и расширение честно искало её в справочнике «Вид работ»:
    # такой позиции там нет и быть не может — это плата, а не работа. Она вставала
    # ПЕРВОЙ в списке тем и съедала попытку у настоящего предмета («ванна»).
    out = [т for т in (темы or []) if т not in _НЕ_ВИД_РАБОТ]
    for тема in list(out):
        нт = (тема or "").lower().replace("ё", "е")
        for слова, категория in КАТЕГОРИИ:
            if any(w.replace("ё", "е") in нт for w in слова) and категория not in out:
                out.append(категория)
    return out


def _anchor_for(reply, pos, prev_end, fallback):
    """Чья это цена: ищем последний якорь работы в отрезке ОТ ПРЕДЫДУЩЕЙ ЦЕНЫ до текущей.

    Окно «±N символов» здесь не годится — реплика бывает короче окна, и тогда к цене
    «рядом» оказываются сразу два якоря (урок сессии 39k, смешанные заявки)."""
    seg = reply[prev_end:pos]
    best, best_pos = None, -1
    сколько = 0
    for entry in TABLE:
        for m in entry[5].finditer(seg):
            сколько += 1
            if m.start() > best_pos:
                best, best_pos = entry, m.start()
    # ⚠ НЕОДНОЗНАЧНОСТЬ НЕ ПРАВИМ (аудит регламента 18.08). При перечислении
    # «сифон и смеситель поменяю: от 2500 и от 3000» в отрезок до ПЕРВОЙ суммы
    # попадали ОБЕ работы, брался последний якорь — и верная цена сифона
    # поднималась до цены смесителя: клиент получал две одинаковые суммы.
    # Две работы в отрезке = мы не знаем, чья это цена; молчаливая правка
    # верной цены дороже пропуска.
    if сколько > 1:
        return None
    return best or fallback


_ОБЪЁМ_RX = re.compile(r"(\d+(?:[.,]\d+)?)\s*(?:гб|гига|gb)|(терабайт|\bтб\b|\btb\b)", re.IGNORECASE)


def _объём_больше_10гб(t):
    for m in _ОБЪЁМ_RX.finditer(t or ""):
        if m.group(2):
            return True                       # терабайты — заведомо больше
        try:
            if float(m.group(1).replace(",", ".")) > 10:
                return True
        except ValueError:
            continue
    return False


def enforce_price_whitelist(reply, client_text="", msk=False):
    """Строгий белый список: сумма в реплике обязана совпадать с прайсом своей работы.

    Возвращает (исправленная_реплика, [список правок]). Число, которое не удалось привязать
    ни к одной работе, НЕ трогаем — молча выдумывать замену опаснее, чем оставить как есть;
    такие случаи попадают в отчёт вызывающего кода.
    """
    r = reply or ""
    if not r:
        return r, []
    # ⚠ ЗАПАСНОЙ ЯКОРЬ ПО РЕЧИ КЛИЕНТА ОТМЕНЁН (аудит 18.08, critical).
    #
    # Он брал единственную тему прайса из слов клиента и вешал её на ЛЮБУЮ
    # сумму, которую не удалось привязать к работе в самой реплике, — включая
    # работы, которых в таблице нет вовсе. Живой прогон: клиент «собрать кухню
    # и зеркало повесить», бот «Соберу кухню, работа 6000 руб» → клиенту
    # уходило «Соберу кухню, работа 1000 руб» (якорь «зеркало»). Занижение
    # в 5-10 раз на сборке кухни, шкафа, натяжном потолке: мастер на месте
    # такую цену не подтвердит — ровно та беда, ради которой файл и написан.
    #
    # Докстринг обещает верное поведение: «Число, которое не удалось привязать
    # ни к одной работе, НЕ трогаем» — теперь код это и делает, а непривязанная
    # сумма уходит в notes вызывающему («непривязанная сумма»).
    fallback = None

    out, notes, prev_end, shift = [], [], 0, 0
    pieces, last = [], 0
    for m in MONEY_RX.finditer(r):
        raw = (m.group(1) or m.group(2) or m.group(3) or "").replace(" ", "").replace("\u00a0", "")
        try:
            val = int(raw)
        except (TypeError, ValueError):
            continue
        # ⚠ СТУПЕНЬ ЛЕСТНИЦЫ ЖИВА ТОЛЬКО С «ОТ» (решение 30.08 по хвосту №9 аудита).
        # Правило 01.08 писано про «от N» — открытую нижнюю границу второго шага;
        # ГОЛОЕ «N руб» — это фикс, и он обязан сверяться с прайсом позиции: «сифон
        # поменяю, 2000» уходил клиенту при прайсе 1000, течь в обе стороны на любой
        # фикс-позиции. Урок 12.08 не нарушен: «ванна от 800» и «фурнитура от 1000»
        # по-прежнему неприкосновенны — у них есть «от».
        # «от» захвачен самим MONEY_RX (первая альтернатива): признак — группа 1
        _от = bool(m.group(1)) or bool(
            re.search(r"от\s*$", r[max(0, m.start() - 4):m.start()], re.IGNORECASE))
        if val in LADDER_FLOORS and _от:
            prev_end = m.end()
            continue
        if val in LADDER_FLOORS:
            _e = _anchor_for(r, m.start(), prev_end, fallback)
            if _e is None:
                prev_end = m.end()        # ступень без якоря — прежнее поведение
                continue
            _разреш, _кан = _allowed(_e, msk)
            if val in _разреш:
                prev_end = m.end()
                continue
            # голый фикс не из прайса позиции — правится ниже общим путём
            entry = _e
            g = 1 if m.group(1) else (2 if m.group(2) else 3)
            _s, _e2 = m.span(g)
            pieces.append((_s, _e2, str(_кан)))
            notes.append(("%s (голый фикс): %d -> %d" % (entry[0], val, _кан), val))
            prev_end = m.end()
            continue
        entry = _anchor_for(r, m.start(), prev_end, fallback)
        prev_end = m.end()
        if entry is None:
            notes.append(("непривязанная сумма", val))
            continue
        # ⚠ ПЕРЕНОС БОЛЬШЕ 10 ГБ — ЦЕНА НЕ ИЗ ПРАЙСА, И РЕЗАТЬ ЕЁ НЕЛЬЗЯ (сверка
        # регламента 30.08, №3): 1500 в прайсе дано только «до 10 гб», а корректор
        # переписывал «500 гб за 4000» в 1500 — многочасовая работа в минус.
        if entry[0] == "перенос данных" and _объём_больше_10гб(client_text):
            notes.append(("перенос >10 гб: сумма не проверяется", val))
            continue
        allowed, canon = _allowed(entry, msk)
        if val in allowed:
            continue
        # цена не из прайса → правим на прайсовую
        g = 1 if m.group(1) else (2 if m.group(2) else 3)
        s, e = m.span(g)
        pieces.append((s, e, str(canon)))
        notes.append(("%s: %d -> %d" % (entry[0], val, canon), val))

    if not pieces:
        return r, notes
    res, last = [], 0
    for s, e, new in pieces:
        res.append(r[last:s])
        res.append(new)
        last = e
    res.append(r[last:])
    return "".join(res), notes
